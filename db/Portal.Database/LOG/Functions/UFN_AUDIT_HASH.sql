-- 감사 로그 한 행의 해시. 적재(USP_AUDIT_WRITE)와 무결성 점검(USP_AUDIT_VERIFY_EXEC)이 같은 식을 쓰도록 한 곳에 둔다.
-- NULL과 빈 문자열을 구분하려고 NULL은 U+2400으로 바꾸고, 필드 사이는 U+241E로 구분한다.
CREATE FUNCTION [LOG].[UFN_AUDIT_HASH] (
  @P_PREV_HASH   BINARY(32),
  @P_LOG_DT      DATETIME2(3),
  @P_USER_ID     VARCHAR(30),
  @P_TABLE_NM    VARCHAR(100),
  @P_ACTION_CD   CHAR(1),
  @P_ROW_KEY     NVARCHAR(200),
  @P_BEFORE_JSON NVARCHAR(MAX),
  @P_AFTER_JSON  NVARCHAR(MAX),
  @P_CLIENT_IP   VARCHAR(45)
)
RETURNS TABLE
AS
RETURN
  SELECT CAST(HASHBYTES('SHA2_256',
           @P_PREV_HASH + CAST(CONCAT(
             CONVERT(NVARCHAR(30), @P_LOG_DT, 126), NCHAR(9246),
             ISNULL(CAST(@P_USER_ID AS NVARCHAR(30)), NCHAR(9216)), NCHAR(9246),
             CAST(@P_TABLE_NM AS NVARCHAR(100)), NCHAR(9246),
             CAST(@P_ACTION_CD AS NVARCHAR(1)), NCHAR(9246),
             @P_ROW_KEY, NCHAR(9246),
             ISNULL(@P_BEFORE_JSON, NCHAR(9216)), NCHAR(9246),
             ISNULL(@P_AFTER_JSON, NCHAR(9216)), NCHAR(9246),
             ISNULL(CAST(@P_CLIENT_IP AS NVARCHAR(45)), NCHAR(9216))
           ) AS VARBINARY(MAX))) AS BINARY(32)) AS [ROW_HASH];
