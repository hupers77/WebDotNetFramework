-- 접근 기록 한 행의 해시. 적재(USP_ACCESS_LOG_WRITE)와 무결성 점검(USP_ACCESS_LOG_VERIFY_EXEC)이 같은 식을 쓴다.
-- NULL은 U+2400, 필드 구분은 U+241E (UFN_AUDIT_HASH와 같은 규칙).
CREATE FUNCTION [LOG].[UFN_ACCESS_HASH] (
  @P_PREV_HASH    BINARY(32),
  @P_LOG_DT       DATETIME2(3),
  @P_LOG_USER_ID  VARCHAR(30),
  @P_PROGRAM_ID   VARCHAR(30),
  @P_FUNC_CD      VARCHAR(20),
  @P_HTTP_METHOD  VARCHAR(10),
  @P_REQUEST_PATH VARCHAR(400),
  @P_STATUS_CODE  SMALLINT,
  @P_ELAPSED_MS   INT,
  @P_CLIENT_IP    VARCHAR(45),
  @P_TRACE_ID     VARCHAR(64)
)
RETURNS TABLE
AS
RETURN
  SELECT CAST(HASHBYTES('SHA2_256',
           @P_PREV_HASH + CAST(CONCAT(
             CONVERT(NVARCHAR(30), @P_LOG_DT, 126), NCHAR(9246),
             ISNULL(CAST(@P_LOG_USER_ID AS NVARCHAR(30)), NCHAR(9216)), NCHAR(9246),
             ISNULL(CAST(@P_PROGRAM_ID AS NVARCHAR(30)), NCHAR(9216)), NCHAR(9246),
             ISNULL(CAST(@P_FUNC_CD AS NVARCHAR(20)), NCHAR(9216)), NCHAR(9246),
             CAST(@P_HTTP_METHOD AS NVARCHAR(10)), NCHAR(9246),
             CAST(@P_REQUEST_PATH AS NVARCHAR(400)), NCHAR(9246),
             CAST(@P_STATUS_CODE AS NVARCHAR(10)), NCHAR(9246),
             CAST(@P_ELAPSED_MS AS NVARCHAR(12)), NCHAR(9246),
             ISNULL(CAST(@P_CLIENT_IP AS NVARCHAR(45)), NCHAR(9216)), NCHAR(9246),
             ISNULL(CAST(@P_TRACE_ID AS NVARCHAR(64)), NCHAR(9216))
           ) AS VARBINARY(MAX))) AS BINARY(32)) AS [ROW_HASH];
