-- 개인정보 접속기록 한 행의 해시. 적재(USP_PII_ACCESS_LOG_WRITE)와 무결성 점검(USP_PII_ACCESS_LOG_VERIFY_EXEC)이 같은 식을 쓴다.
-- NULL은 U+2400, 필드 구분은 U+241E (UFN_AUDIT_HASH와 같은 규칙).
CREATE FUNCTION [LOG].[UFN_PII_HASH] (
  @P_PREV_HASH   BINARY(32),
  @P_LOG_DT      DATETIME2(3),
  @P_USER_ID     VARCHAR(30),
  @P_PROGRAM_ID  VARCHAR(30),
  @P_ACTION_CD   VARCHAR(10),
  @P_TARGET_DESC NVARCHAR(500),
  @P_REASON      NVARCHAR(500),
  @P_CLIENT_IP   VARCHAR(45)
)
RETURNS TABLE
AS
RETURN
  SELECT CAST(HASHBYTES('SHA2_256',
           @P_PREV_HASH + CAST(CONCAT(
             CONVERT(NVARCHAR(30), @P_LOG_DT, 126), NCHAR(9246),
             CAST(@P_USER_ID AS NVARCHAR(30)), NCHAR(9246),
             CAST(@P_PROGRAM_ID AS NVARCHAR(30)), NCHAR(9246),
             CAST(@P_ACTION_CD AS NVARCHAR(10)), NCHAR(9246),
             ISNULL(@P_TARGET_DESC, NCHAR(9216)), NCHAR(9246),
             ISNULL(@P_REASON, NCHAR(9216)), NCHAR(9246),
             ISNULL(CAST(@P_CLIENT_IP AS NVARCHAR(45)), NCHAR(9216))
           ) AS VARBINARY(MAX))) AS BINARY(32)) AS [ROW_HASH];
