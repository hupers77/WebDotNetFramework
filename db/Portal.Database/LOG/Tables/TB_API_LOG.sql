-- 외부 API 요청/응답 기록 (민감 필드는 마스킹해 저장)
CREATE TABLE [LOG].[TB_API_LOG] (
  [LOG_ID]         BIGINT IDENTITY(1,1) NOT NULL,
  [LOG_DT]         DATETIME2(3)   NOT NULL CONSTRAINT [DF_TB_API_LOG_LOG_DT] DEFAULT (SYSUTCDATETIME()),
  [DIRECTION_CD]   VARCHAR(3)     NOT NULL,             -- IN/OUT
  [CLIENT_ID]      VARCHAR(50)    NULL,
  [HTTP_METHOD]    VARCHAR(10)    NOT NULL,
  [URL]            VARCHAR(1000)  NOT NULL,
  [STATUS_CODE]    SMALLINT       NULL,
  [ELAPSED_MS]     INT            NULL,
  [REQUEST_BODY]   NVARCHAR(MAX)  NULL,
  [RESPONSE_BODY]  NVARCHAR(MAX)  NULL,
  [TRACE_ID]       VARCHAR(64)    NULL,
  CONSTRAINT [PK_TB_API_LOG] PRIMARY KEY CLUSTERED ([LOG_DT], [LOG_ID])
    WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT])
);
