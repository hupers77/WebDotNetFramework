-- 데이터 변경 기록: 변경 전/후 값을 JSON으로 남긴다 (10년 보관, 삭제 불가)
CREATE TABLE [LOG].[TB_AUDIT_LOG] (
  [LOG_ID]         BIGINT IDENTITY(1,1) NOT NULL,
  [LOG_DT]         DATETIME2(3)   NOT NULL CONSTRAINT [DF_TB_AUDIT_LOG_LOG_DT] DEFAULT (SYSUTCDATETIME()),
  [USER_ID]        VARCHAR(30)    NULL,
  [TABLE_NM]       VARCHAR(100)   NOT NULL,             -- FW.TB_CODE
  [ACTION_CD]      CHAR(1)        NOT NULL,             -- I/U/D
  [ROW_KEY]        NVARCHAR(200)  NOT NULL,             -- 'USER_STAT|ACTIVE'
  [BEFORE_JSON]    NVARCHAR(MAX)  NULL,
  [AFTER_JSON]     NVARCHAR(MAX)  NULL,
  [CLIENT_IP]      VARCHAR(45)    NULL,
  [PREV_HASH]      BINARY(32)     NOT NULL,             -- 직전 행의 ROW_HASH (해시 체인, 위·변조 검증)
  [ROW_HASH]       BINARY(32)     NOT NULL,
  CONSTRAINT [PK_TB_AUDIT_LOG] PRIMARY KEY CLUSTERED ([LOG_DT], [LOG_ID])
    WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT])
);
GO
CREATE INDEX [IX_TB_AUDIT_LOG_TABLE] ON [LOG].[TB_AUDIT_LOG] ([TABLE_NM], [LOG_DT])
  WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT]);
