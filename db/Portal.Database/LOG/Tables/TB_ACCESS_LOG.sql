-- 화면·API 접근 기록 (10년 보관). 응답 후 비동기 큐로 일괄 적재한다
CREATE TABLE [LOG].[TB_ACCESS_LOG] (
  [LOG_ID]         BIGINT IDENTITY(1,1) NOT NULL,
  [LOG_DT]         DATETIME2(3)   NOT NULL CONSTRAINT [DF_TB_ACCESS_LOG_LOG_DT] DEFAULT (SYSUTCDATETIME()),
  [USER_ID]        VARCHAR(30)    NULL,
  [PROGRAM_ID]     VARCHAR(30)    NULL,
  [FUNC_CD]        VARCHAR(20)    NULL,
  [HTTP_METHOD]    VARCHAR(10)    NOT NULL,
  [REQUEST_PATH]   VARCHAR(400)   NOT NULL,             -- 쿼리 문자열 제외 (민감 값 기록 방지)
  [STATUS_CODE]    SMALLINT       NOT NULL,
  [ELAPSED_MS]     INT            NOT NULL,
  [CLIENT_IP]      VARCHAR(45)    NULL,
  [TRACE_ID]       VARCHAR(64)    NULL,
  [PREV_HASH]      BINARY(32)     NOT NULL,             -- 직전 행의 ROW_HASH (해시 체인, 위·변조 검증)
  [ROW_HASH]       BINARY(32)     NOT NULL,
  CONSTRAINT [PK_TB_ACCESS_LOG] PRIMARY KEY CLUSTERED ([LOG_DT], [LOG_ID])
    WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT])
);
GO
CREATE INDEX [IX_TB_ACCESS_LOG_USER] ON [LOG].[TB_ACCESS_LOG] ([USER_ID], [LOG_DT])
  WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT]);
