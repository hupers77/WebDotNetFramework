-- 예상하지 못한 오류 (LOG.ERROR_RETENTION_DAYS 보관). 화면에는 TRACE_ID만 보여준다
CREATE TABLE [LOG].[TB_ERROR_LOG] (
  [LOG_ID]         BIGINT IDENTITY(1,1) NOT NULL,
  [LOG_DT]         DATETIME2(3)   NOT NULL CONSTRAINT [DF_TB_ERROR_LOG_LOG_DT] DEFAULT (SYSUTCDATETIME()),
  [TRACE_ID]       VARCHAR(64)    NULL,
  [USER_ID]        VARCHAR(30)    NULL,
  [REQUEST_PATH]   VARCHAR(400)   NULL,
  [SOURCE]         VARCHAR(200)   NULL,
  [MESSAGE]        NVARCHAR(2000) NOT NULL,
  [DETAIL]         NVARCHAR(MAX)  NULL,
  CONSTRAINT [PK_TB_ERROR_LOG] PRIMARY KEY CLUSTERED ([LOG_DT], [LOG_ID])
    WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT])
);
GO
CREATE INDEX [IX_TB_ERROR_LOG_TRACE] ON [LOG].[TB_ERROR_LOG] ([TRACE_ID])
  WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT]);
