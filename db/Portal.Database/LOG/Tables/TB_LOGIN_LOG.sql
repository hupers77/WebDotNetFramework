-- 로그인·로그아웃 기록 (10년 보관)
CREATE TABLE [LOG].[TB_LOGIN_LOG] (
  [LOG_ID]         BIGINT IDENTITY(1,1) NOT NULL,
  [LOG_DT]         DATETIME2(3)   NOT NULL CONSTRAINT [DF_TB_LOGIN_LOG_LOG_DT] DEFAULT (SYSUTCDATETIME()),
  [USER_ID]        VARCHAR(30)    NULL,                 -- 존재하지 않는 ID로 시도하면 입력값(최대 30자)
  [LOGIN_RESULT_CD] VARCHAR(20)   NOT NULL,             -- 공통코드 LOGIN_RESULT
  [AUTH_METHOD_CD] VARCHAR(10)    NOT NULL,             -- FORM/FORM_MFA/AD/AD_LDAP
  [CLIENT_IP]      VARCHAR(45)    NULL,
  [USER_AGENT]     NVARCHAR(300)  NULL,
  [SESSION_HASH]   CHAR(64)       NULL,
  [PREV_HASH]      BINARY(32)     NOT NULL,             -- 직전 행의 ROW_HASH (해시 체인, 위·변조 검증)
  [ROW_HASH]       BINARY(32)     NOT NULL,
  CONSTRAINT [PK_TB_LOGIN_LOG] PRIMARY KEY CLUSTERED ([LOG_DT], [LOG_ID])
    WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT])
);
GO
CREATE INDEX [IX_TB_LOGIN_LOG_USER] ON [LOG].[TB_LOGIN_LOG] ([USER_ID], [LOG_DT])
  WITH (DATA_COMPRESSION = PAGE) ON [PS_LOG_MONTH] ([LOG_DT]);
