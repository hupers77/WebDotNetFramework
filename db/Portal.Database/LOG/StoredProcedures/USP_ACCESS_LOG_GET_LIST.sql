-- 화면·API 접근 기록 조회 (목록 SP 표준 템플릿). 프로그램: LOG_ACCESS_INQ
-- 기간은 UTC [@P_FROM_DT, @P_TO_DT) 이고 31일까지. 데이터 범위가 전체면 모든 행(로그인 전 요청 포함),
-- 아니면 범위 안 계정의 기록만 본다. @P_ERROR_YN = 'Y'면 응답 코드 400 이상만.
-- 결과셋 1: 목록(최근 순), 결과셋 2: 전체 건수
CREATE PROCEDURE [LOG].[USP_ACCESS_LOG_GET_LIST]
  @P_FROM_DT         DATETIME2(3),
  @P_TO_DT           DATETIME2(3),
  @P_TARGET_USER_ID  VARCHAR(30)  = NULL,
  @P_PROGRAM_ID      VARCHAR(30)  = NULL,
  @P_ERROR_YN        CHAR(1)      = NULL,
  @P_IP              VARCHAR(45)  = NULL,
  @P_PAGE_NO         INT          = 1,
  @P_PAGE_SIZE       INT          = 50,
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_FROM_DT IS NULL OR @P_TO_DT IS NULL OR @P_TO_DT <= @P_FROM_DT OR DATEDIFF(HOUR, @P_FROM_DT, @P_TO_DT) > 31 * 24
    THROW 50003, 'MSG.LOG_PERIOD', 1;

  DECLARE @ALL CHAR(1) = (SELECT [ALL_YN] FROM [FW].[UFN_DATA_SCOPE_ALL](@P_USER_ID, 'LOG_ACCESS_INQ'));
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 1000 THEN 1000 ELSE @P_PAGE_SIZE END;

  SELECT A.[LOG_ID], A.[LOG_DT], A.[USER_ID], A.[PROGRAM_ID], A.[FUNC_CD], A.[HTTP_METHOD], A.[REQUEST_PATH],
         A.[STATUS_CODE], A.[ELAPSED_MS], A.[CLIENT_IP], A.[TRACE_ID]
    FROM [LOG].[TB_ACCESS_LOG] A
   WHERE A.[LOG_DT] >= @P_FROM_DT AND A.[LOG_DT] < @P_TO_DT
     AND (@P_TARGET_USER_ID IS NULL OR A.[USER_ID] = @P_TARGET_USER_ID)
     AND (@P_PROGRAM_ID IS NULL OR A.[PROGRAM_ID] = @P_PROGRAM_ID)
     AND (@P_ERROR_YN IS NULL OR @P_ERROR_YN = 'N' OR A.[STATUS_CODE] >= 400)
     AND (@P_IP IS NULL OR A.[CLIENT_IP] = @P_IP)
     AND (@ALL = 'Y' OR EXISTS (SELECT 1 FROM [FW].[TB_USER] U
                                  JOIN [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'LOG_ACCESS_INQ') S ON S.[COMPANY_CD] = U.[COMPANY_CD]
                                 WHERE U.[USER_ID] = A.[USER_ID] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID])))
   ORDER BY A.[LOG_DT] DESC, A.[LOG_ID] DESC
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [LOG].[TB_ACCESS_LOG] A
   WHERE A.[LOG_DT] >= @P_FROM_DT AND A.[LOG_DT] < @P_TO_DT
     AND (@P_TARGET_USER_ID IS NULL OR A.[USER_ID] = @P_TARGET_USER_ID)
     AND (@P_PROGRAM_ID IS NULL OR A.[PROGRAM_ID] = @P_PROGRAM_ID)
     AND (@P_ERROR_YN IS NULL OR @P_ERROR_YN = 'N' OR A.[STATUS_CODE] >= 400)
     AND (@P_IP IS NULL OR A.[CLIENT_IP] = @P_IP)
     AND (@ALL = 'Y' OR EXISTS (SELECT 1 FROM [FW].[TB_USER] U
                                  JOIN [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'LOG_ACCESS_INQ') S ON S.[COMPANY_CD] = U.[COMPANY_CD]
                                 WHERE U.[USER_ID] = A.[USER_ID] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID])))
  OPTION (RECOMPILE);
END
