-- 화면·API 접근 기록 일괄 적재. 웹서버의 접근 기록 큐가 호출한다(사용자별 값은 행에 들어 있다).
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [LOG].[USP_ACCESS_LOG_WRITE]
  @P_ROWS       [LOG].[TVP_ACCESS_LOG] READONLY,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @PREV_HASH BINARY(32), @ROW_HASH BINARY(32), @LAST_ID BIGINT, @CNT INT = 0;
  DECLARE @SEQ INT, @LOG_DT DATETIME2(3), @LOG_USER_ID VARCHAR(30), @PROGRAM_ID VARCHAR(30), @FUNC_CD VARCHAR(20),
          @HTTP_METHOD VARCHAR(10), @REQUEST_PATH VARCHAR(400), @STATUS_CODE SMALLINT, @ELAPSED_MS INT,
          @ROW_IP VARCHAR(45), @TRACE_ID VARCHAR(64);

  BEGIN TRAN;

  SELECT @PREV_HASH = [LAST_HASH]
    FROM [LOG].[TB_LOG_CHAIN] WITH (UPDLOCK, HOLDLOCK)
   WHERE [TABLE_NM] = 'LOG.TB_ACCESS_LOG';

  IF @PREV_HASH IS NULL
    THROW 50090, 'MSG.SYSTEM_ERROR', 1;

  -- 해시 체인은 행마다 직전 해시가 필요하므로 배치 순서대로 한 행씩 넣는다 (배치 크기는 웹서버가 제한)
  SELECT @SEQ = MIN([SEQ_NO]) FROM @P_ROWS;
  WHILE @SEQ IS NOT NULL
  BEGIN
    SELECT @LOG_DT = [LOG_DT], @LOG_USER_ID = [USER_ID], @PROGRAM_ID = [PROGRAM_ID], @FUNC_CD = [FUNC_CD],
           @HTTP_METHOD = [HTTP_METHOD], @REQUEST_PATH = [REQUEST_PATH], @STATUS_CODE = [STATUS_CODE],
           @ELAPSED_MS = [ELAPSED_MS], @ROW_IP = [CLIENT_IP], @TRACE_ID = [TRACE_ID]
      FROM @P_ROWS
     WHERE [SEQ_NO] = @SEQ;

    SELECT @ROW_HASH = H.[ROW_HASH]
      FROM [LOG].[UFN_ACCESS_HASH](@PREV_HASH, @LOG_DT, @LOG_USER_ID, @PROGRAM_ID, @FUNC_CD, @HTTP_METHOD, @REQUEST_PATH, @STATUS_CODE, @ELAPSED_MS, @ROW_IP, @TRACE_ID) H;

    INSERT INTO [LOG].[TB_ACCESS_LOG]
      ([LOG_DT], [USER_ID], [PROGRAM_ID], [FUNC_CD], [HTTP_METHOD], [REQUEST_PATH], [STATUS_CODE], [ELAPSED_MS], [CLIENT_IP], [TRACE_ID], [PREV_HASH], [ROW_HASH])
    VALUES
      (@LOG_DT, @LOG_USER_ID, @PROGRAM_ID, @FUNC_CD, @HTTP_METHOD, @REQUEST_PATH, @STATUS_CODE, @ELAPSED_MS, @ROW_IP, @TRACE_ID, @PREV_HASH, @ROW_HASH);

    SET @LAST_ID = SCOPE_IDENTITY();
    SET @PREV_HASH = @ROW_HASH;
    SET @CNT += 1;
    SELECT @SEQ = MIN([SEQ_NO]) FROM @P_ROWS WHERE [SEQ_NO] > @SEQ;
  END

  IF @CNT > 0
    UPDATE [LOG].[TB_LOG_CHAIN]
       SET [LAST_LOG_ID] = @LAST_ID, [LAST_HASH] = @PREV_HASH
     WHERE [TABLE_NM] = 'LOG.TB_ACCESS_LOG';

  COMMIT;

  SELECT @CNT AS [AFFECTED_CNT];
END
