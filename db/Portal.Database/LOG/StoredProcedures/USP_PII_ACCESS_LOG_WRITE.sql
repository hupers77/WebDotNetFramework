-- 개인정보 접속기록 적재 (조회 VIEW, 다운로드 DOWNLOAD, 마스킹 해제 UNMASK). 화면 Service가 개인정보를 돌려주기 전에 부른다(IPiiAccessLog).
-- 다운로드와 마스킹 해제는 사유가 있어야 한다. 대상(@P_TARGET_DESC)에는 건수·조건만 넣고 개인정보 원문은 넣지 않는다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [LOG].[USP_PII_ACCESS_LOG_WRITE]
  @P_PROGRAM_ID   VARCHAR(30),
  @P_ACTION_CD    VARCHAR(10),
  @P_TARGET_DESC  NVARCHAR(500) = NULL,
  @P_REASON       NVARCHAR(500) = NULL,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_REASON = NULLIF(LTRIM(RTRIM(@P_REASON)), N'');

  IF @P_USER_ID IS NULL OR @P_ACTION_CD NOT IN ('VIEW', 'DOWNLOAD', 'UNMASK')
     OR NOT EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM] WHERE [PROGRAM_ID] = @P_PROGRAM_ID)
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  IF @P_ACTION_CD IN ('DOWNLOAD', 'UNMASK') AND (@P_REASON IS NULL OR LEN(@P_REASON) < 2)
    THROW 50005, 'MSG.PII_REASON_REQUIRED', 1;

  DECLARE @LOG_DT DATETIME2(3) = SYSUTCDATETIME();
  DECLARE @PREV_HASH BINARY(32);
  DECLARE @ROW_HASH BINARY(32);

  BEGIN TRAN;

  SELECT @PREV_HASH = [LAST_HASH]
    FROM [LOG].[TB_LOG_CHAIN] WITH (UPDLOCK, HOLDLOCK)
   WHERE [TABLE_NM] = 'LOG.TB_PII_ACCESS_LOG';

  IF @PREV_HASH IS NULL
    THROW 50090, 'MSG.SYSTEM_ERROR', 1;

  SELECT @ROW_HASH = H.[ROW_HASH]
    FROM [LOG].[UFN_PII_HASH](@PREV_HASH, @LOG_DT, @P_USER_ID, @P_PROGRAM_ID, @P_ACTION_CD, @P_TARGET_DESC, @P_REASON, @P_CLIENT_IP) H;

  INSERT INTO [LOG].[TB_PII_ACCESS_LOG]
    ([LOG_DT], [USER_ID], [PROGRAM_ID], [ACTION_CD], [TARGET_DESC], [REASON], [CLIENT_IP], [PREV_HASH], [ROW_HASH])
  VALUES
    (@LOG_DT, @P_USER_ID, @P_PROGRAM_ID, @P_ACTION_CD, @P_TARGET_DESC, @P_REASON, @P_CLIENT_IP, @PREV_HASH, @ROW_HASH);

  UPDATE [LOG].[TB_LOG_CHAIN]
     SET [LAST_LOG_ID] = SCOPE_IDENTITY(), [LAST_HASH] = @ROW_HASH
   WHERE [TABLE_NM] = 'LOG.TB_PII_ACCESS_LOG';

  COMMIT;

  SELECT 1 AS [AFFECTED_CNT];
END
