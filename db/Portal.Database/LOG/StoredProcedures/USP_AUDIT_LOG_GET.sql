-- 데이터 변경 기록 한 건 (변경 전후 JSON 포함). 프로그램: LOG_AUDIT_INQ
-- @P_LOG_DT는 목록에서 받은 값으로, 월 파티션을 바로 찾는 데 쓴다. 데이터 범위가 전체가 아니면 0행.
-- 결과: LOG_ID, LOG_DT, USER_ID, TABLE_NM, ACTION_CD, ROW_KEY, BEFORE_JSON, AFTER_JSON, CLIENT_IP
CREATE PROCEDURE [LOG].[USP_AUDIT_LOG_GET]
  @P_LOG_ID     BIGINT,
  @P_LOG_DT     DATETIME2(3),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT A.[LOG_ID], A.[LOG_DT], A.[USER_ID], A.[TABLE_NM], A.[ACTION_CD], A.[ROW_KEY], A.[BEFORE_JSON], A.[AFTER_JSON], A.[CLIENT_IP]
    FROM [LOG].[TB_AUDIT_LOG] A
   WHERE A.[LOG_DT] = @P_LOG_DT AND A.[LOG_ID] = @P_LOG_ID
     AND (SELECT [ALL_YN] FROM [FW].[UFN_DATA_SCOPE_ALL](@P_USER_ID, 'LOG_AUDIT_INQ')) = 'Y';
END
