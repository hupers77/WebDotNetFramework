-- 로그인 기록 조회 (목록 SP 표준 템플릿). 프로그램: LOG_ACCESS_INQ
-- 기간은 UTC [@P_FROM_DT, @P_TO_DT) 이고 31일까지. 데이터 범위가 전체면 모든 행(없는 ID로 시도한 기록 포함),
-- 아니면 범위 안 계정의 기록만 본다. 계정 이름 등 개인정보는 돌려주지 않는다(ID·IP만).
-- 결과셋 1: 목록(최근 순), 결과셋 2: 전체 건수
CREATE PROCEDURE [LOG].[USP_LOGIN_LOG_GET_LIST]
  @P_FROM_DT         DATETIME2(3),
  @P_TO_DT           DATETIME2(3),
  @P_TARGET_USER_ID  VARCHAR(30)  = NULL,
  @P_RESULT_CD       VARCHAR(20)  = NULL,
  @P_IP              VARCHAR(45)  = NULL,
  @P_PAGE_NO         INT          = 1,
  @P_PAGE_SIZE       INT          = 50,
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_FROM_DT IS NULL OR @P_TO_DT IS NULL OR @P_TO_DT <= @P_FROM_DT OR DATEDIFF(HOUR, @P_FROM_DT, @P_TO_DT) > 31 * 24
    THROW 50003, 'MSG.LOG_PERIOD', 1;

  DECLARE @ALL CHAR(1) = (SELECT [ALL_YN] FROM [FW].[UFN_DATA_SCOPE_ALL](@P_USER_ID, 'LOG_ACCESS_INQ'));
  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 1000 THEN 1000 ELSE @P_PAGE_SIZE END;

  SELECT L.[LOG_ID], L.[LOG_DT], L.[USER_ID], L.[LOGIN_RESULT_CD],
         COALESCE(RL.[CODE_NM], RD.[CODE_NM], L.[LOGIN_RESULT_CD]) AS [LOGIN_RESULT_NM],
         L.[AUTH_METHOD_CD], L.[CLIENT_IP], L.[USER_AGENT]
    FROM [LOG].[TB_LOGIN_LOG] L
    LEFT JOIN [FW].[TB_CODE_LANG] RL ON RL.[GROUP_CD] = 'LOGIN_RESULT' AND RL.[CODE] = L.[LOGIN_RESULT_CD] AND RL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] RD ON RD.[GROUP_CD] = 'LOGIN_RESULT' AND RD.[CODE] = L.[LOGIN_RESULT_CD] AND RD.[LANG_CD] = @DEFAULT_LANG
   WHERE L.[LOG_DT] >= @P_FROM_DT AND L.[LOG_DT] < @P_TO_DT
     AND (@P_TARGET_USER_ID IS NULL OR L.[USER_ID] = @P_TARGET_USER_ID)
     AND (@P_RESULT_CD IS NULL OR L.[LOGIN_RESULT_CD] = @P_RESULT_CD)
     AND (@P_IP IS NULL OR L.[CLIENT_IP] = @P_IP)
     AND (@ALL = 'Y' OR EXISTS (SELECT 1 FROM [FW].[TB_USER] U
                                  JOIN [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'LOG_ACCESS_INQ') S ON S.[COMPANY_CD] = U.[COMPANY_CD]
                                 WHERE U.[USER_ID] = L.[USER_ID] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID])))
   ORDER BY L.[LOG_DT] DESC, L.[LOG_ID] DESC
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [LOG].[TB_LOGIN_LOG] L
   WHERE L.[LOG_DT] >= @P_FROM_DT AND L.[LOG_DT] < @P_TO_DT
     AND (@P_TARGET_USER_ID IS NULL OR L.[USER_ID] = @P_TARGET_USER_ID)
     AND (@P_RESULT_CD IS NULL OR L.[LOGIN_RESULT_CD] = @P_RESULT_CD)
     AND (@P_IP IS NULL OR L.[CLIENT_IP] = @P_IP)
     AND (@ALL = 'Y' OR EXISTS (SELECT 1 FROM [FW].[TB_USER] U
                                  JOIN [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'LOG_ACCESS_INQ') S ON S.[COMPANY_CD] = U.[COMPANY_CD]
                                 WHERE U.[USER_ID] = L.[USER_ID] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID])))
  OPTION (RECOMPILE);
END
