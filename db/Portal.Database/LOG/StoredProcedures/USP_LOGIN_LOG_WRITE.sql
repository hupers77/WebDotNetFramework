-- 로그인·로그아웃 기록 적재. 인증 SP(FW.USP_AUTH_*)가 같은 트랜잭션 안에서 호출한다.
-- 로그인 전에는 @P_USER_ID가 비어 있으므로 대상 계정은 @P_LOGIN_USER_ID로 받는다(없는 ID면 입력값을 30자까지).
CREATE PROCEDURE [LOG].[USP_LOGIN_LOG_WRITE]
  @P_LOGIN_USER_ID   VARCHAR(30),
  @P_LOGIN_RESULT_CD VARCHAR(20),
  @P_AUTH_METHOD_CD  VARCHAR(10),
  @P_USER_AGENT      NVARCHAR(300) = NULL,
  @P_SESSION_HASH    CHAR(64)      = NULL,
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @LOG_DT DATETIME2(3) = SYSUTCDATETIME();
  DECLARE @PREV_HASH BINARY(32);
  DECLARE @ROW_HASH BINARY(32);

  BEGIN TRAN;

  SELECT @PREV_HASH = [LAST_HASH]
    FROM [LOG].[TB_LOG_CHAIN] WITH (UPDLOCK, HOLDLOCK)
   WHERE [TABLE_NM] = 'LOG.TB_LOGIN_LOG';

  IF @PREV_HASH IS NULL
    THROW 50090, 'MSG.SYSTEM_ERROR', 1;

  SELECT @ROW_HASH = H.[ROW_HASH]
    FROM [LOG].[UFN_LOGIN_HASH](@PREV_HASH, @LOG_DT, @P_LOGIN_USER_ID, @P_LOGIN_RESULT_CD, @P_AUTH_METHOD_CD, @P_CLIENT_IP, @P_USER_AGENT, @P_SESSION_HASH) H;

  INSERT INTO [LOG].[TB_LOGIN_LOG]
    ([LOG_DT], [USER_ID], [LOGIN_RESULT_CD], [AUTH_METHOD_CD], [CLIENT_IP], [USER_AGENT], [SESSION_HASH], [PREV_HASH], [ROW_HASH])
  VALUES
    (@LOG_DT, @P_LOGIN_USER_ID, @P_LOGIN_RESULT_CD, @P_AUTH_METHOD_CD, @P_CLIENT_IP, @P_USER_AGENT, @P_SESSION_HASH, @PREV_HASH, @ROW_HASH);

  UPDATE [LOG].[TB_LOG_CHAIN]
     SET [LAST_LOG_ID] = SCOPE_IDENTITY(), [LAST_HASH] = @ROW_HASH
   WHERE [TABLE_NM] = 'LOG.TB_LOGIN_LOG';

  COMMIT;
END
