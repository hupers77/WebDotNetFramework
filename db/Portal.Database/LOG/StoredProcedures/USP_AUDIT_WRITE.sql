-- 데이터 변경 감사 로그 적재. 변경 SP가 같은 트랜잭션 안에서 호출한다(설계서 8장).
CREATE PROCEDURE [LOG].[USP_AUDIT_WRITE]
  @P_TABLE_NM     VARCHAR(100),
  @P_ACTION_CD    CHAR(1),
  @P_ROW_KEY      NVARCHAR(200),
  @P_BEFORE_JSON  NVARCHAR(MAX) = NULL,
  @P_AFTER_JSON   NVARCHAR(MAX) = NULL,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @LOG_DT DATETIME2(3) = SYSUTCDATETIME();
  DECLARE @PREV_HASH BINARY(32);
  DECLARE @ROW_HASH BINARY(32);

  BEGIN TRAN;

  -- 체인 머리를 잠가 같은 테이블 로그의 적재 순서를 직렬화한다 (체인 머리 행은 초기 데이터가 만든다)
  SELECT @PREV_HASH = [LAST_HASH]
    FROM [LOG].[TB_LOG_CHAIN] WITH (UPDLOCK, HOLDLOCK)
   WHERE [TABLE_NM] = 'LOG.TB_AUDIT_LOG';

  IF @PREV_HASH IS NULL
    THROW 50090, 'MSG.SYSTEM_ERROR', 1;

  SELECT @ROW_HASH = H.[ROW_HASH]
    FROM [LOG].[UFN_AUDIT_HASH](@PREV_HASH, @LOG_DT, @P_USER_ID, @P_TABLE_NM, @P_ACTION_CD, @P_ROW_KEY, @P_BEFORE_JSON, @P_AFTER_JSON, @P_CLIENT_IP) H;

  INSERT INTO [LOG].[TB_AUDIT_LOG]
    ([LOG_DT], [USER_ID], [TABLE_NM], [ACTION_CD], [ROW_KEY], [BEFORE_JSON], [AFTER_JSON], [CLIENT_IP], [PREV_HASH], [ROW_HASH])
  VALUES
    (@LOG_DT, @P_USER_ID, @P_TABLE_NM, @P_ACTION_CD, @P_ROW_KEY, @P_BEFORE_JSON, @P_AFTER_JSON, @P_CLIENT_IP, @PREV_HASH, @ROW_HASH);

  UPDATE [LOG].[TB_LOG_CHAIN]
     SET [LAST_LOG_ID] = SCOPE_IDENTITY(), [LAST_HASH] = @ROW_HASH
   WHERE [TABLE_NM] = 'LOG.TB_AUDIT_LOG';

  COMMIT;
END
