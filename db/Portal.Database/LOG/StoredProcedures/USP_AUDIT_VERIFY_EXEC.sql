-- 감사 로그 해시 체인 무결성 점검 (월별 배치 JOB_LOG_INTEGRITY, 보안 감사 화면). 프로그램: LOG_AUDIT_INQ
-- 결과: 점검 건수와 처음 깨진 LOG_ID(없으면 NULL). 행 내용 변경, 중간 행 삭제, 순서 조작을 잡는다.
CREATE PROCEDURE [LOG].[USP_AUDIT_VERIFY_EXEC]
  @P_FROM_DT    DATETIME2(3),
  @P_TO_DT      DATETIME2(3),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  WITH [CHECKED] AS (
    SELECT A.[LOG_ID], A.[PREV_HASH], A.[ROW_HASH],
           LAG(A.[ROW_HASH]) OVER (ORDER BY A.[LOG_ID]) AS [EXPECTED_PREV],
           H.[ROW_HASH] AS [RECALC_HASH]
      FROM [LOG].[TB_AUDIT_LOG] A
     CROSS APPLY [LOG].[UFN_AUDIT_HASH](A.[PREV_HASH], A.[LOG_DT], A.[USER_ID], A.[TABLE_NM], A.[ACTION_CD], A.[ROW_KEY], A.[BEFORE_JSON], A.[AFTER_JSON], A.[CLIENT_IP]) H
     WHERE A.[LOG_DT] >= @P_FROM_DT
       AND A.[LOG_DT] < @P_TO_DT
  )
  SELECT COUNT(*) AS [CHECKED_CNT],
         MIN(CASE WHEN [ROW_HASH] <> [RECALC_HASH]
                    OR ([EXPECTED_PREV] IS NOT NULL AND [PREV_HASH] <> [EXPECTED_PREV])
                  THEN [LOG_ID] END) AS [BROKEN_LOG_ID]
    FROM [CHECKED];
END
