-- 데이터 변경 기록이 있는 테이블 이름 (조회 조건 선택지). 프로그램: LOG_AUDIT_INQ
-- 테이블·일시 인덱스(IX_TB_AUDIT_LOG_TABLE)만 읽는다. 데이터 범위가 전체가 아니면 0행.
-- 결과: TABLE_NM (이름 순)
CREATE PROCEDURE [LOG].[USP_AUDIT_TABLE_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT DISTINCT A.[TABLE_NM]
    FROM [LOG].[TB_AUDIT_LOG] A WITH (INDEX ([IX_TB_AUDIT_LOG_TABLE]))
   WHERE (SELECT [ALL_YN] FROM [FW].[UFN_DATA_SCOPE_ALL](@P_USER_ID, 'LOG_AUDIT_INQ')) = 'Y'
   ORDER BY A.[TABLE_NM];
END
