-- 접근 기록 해시 체인 무결성 점검 (월별 배치 JOB_LOG_INTEGRITY, 보안 감사 화면). 프로그램: LOG_ACCESS_INQ
-- 결과: 점검 건수와 처음 깨진 LOG_ID(없으면 NULL).
CREATE PROCEDURE [LOG].[USP_ACCESS_LOG_VERIFY_EXEC]
  @P_FROM_DT    DATETIME2(3),
  @P_TO_DT      DATETIME2(3),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  WITH [CHECKED] AS (
    SELECT A.[LOG_ID], A.[PREV_HASH], A.[ROW_HASH],
           LAG(A.[ROW_HASH]) OVER (ORDER BY A.[LOG_ID]) AS [EXPECTED_PREV],
           H.[ROW_HASH] AS [RECALC_HASH]
      FROM [LOG].[TB_ACCESS_LOG] A
     CROSS APPLY [LOG].[UFN_ACCESS_HASH](A.[PREV_HASH], A.[LOG_DT], A.[USER_ID], A.[PROGRAM_ID], A.[FUNC_CD], A.[HTTP_METHOD], A.[REQUEST_PATH], A.[STATUS_CODE], A.[ELAPSED_MS], A.[CLIENT_IP], A.[TRACE_ID]) H
     WHERE A.[LOG_DT] >= @P_FROM_DT
       AND A.[LOG_DT] < @P_TO_DT
  )
  SELECT COUNT(*) AS [CHECKED_CNT],
         MIN(CASE WHEN [ROW_HASH] <> [RECALC_HASH]
                    OR ([EXPECTED_PREV] IS NOT NULL AND [PREV_HASH] <> [EXPECTED_PREV])
                  THEN [LOG_ID] END) AS [BROKEN_LOG_ID]
    FROM [CHECKED];
END
