-- 첨부 파일 한 건 (다운로드·삭제 전 확인용). 저장 경로는 FileService만 쓴다.
-- 협력사 사용자는 자기 회사 묶음이나 공유 묶음(SHARE_YN = 'Y')의 파일만 받을 수 있고, 아니면 0행이다.
-- 결과: FILE_ID, FILE_GROUP_ID, PROGRAM_ID, COMPANY_CD, SHARE_YN, ORG_FILE_NM, FILE_EXT, FILE_SIZE, STORED_PATH, CONTENT_HASH, REG_ID
CREATE PROCEDURE [FW].[USP_FILE_GET]
  @P_FILE_ID    BIGINT,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT F.[FILE_ID], F.[FILE_GROUP_ID], G.[PROGRAM_ID], G.[COMPANY_CD], G.[SHARE_YN],
         F.[ORG_FILE_NM], F.[FILE_EXT], F.[FILE_SIZE], F.[STORED_PATH], F.[CONTENT_HASH], F.[REG_ID]
    FROM [FW].[TB_FILE] F
    JOIN [FW].[TB_FILE_GROUP] G ON G.[FILE_GROUP_ID] = F.[FILE_GROUP_ID]
    JOIN [FW].[TB_USER] U ON U.[USER_ID] = @P_USER_ID AND U.[USER_STAT_CD] = 'ACTIVE'
   WHERE F.[FILE_ID] = @P_FILE_ID
     AND F.[DEL_YN] = 'N'
     AND (U.[USER_TYPE_CD] <> 'PARTNER' OR G.[COMPANY_CD] = U.[COMPANY_CD] OR G.[SHARE_YN] = 'Y');
END
