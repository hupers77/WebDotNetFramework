-- 레포트 일괄 저장 (등록·수정·삭제). 프로그램: RPT_REPORT_MGT
-- @P_ROWS_JSON: [{rowStat(I/U/D), reportId, dataSp, templateView, paramsJson, orientCd(P/L), approvalYn, totalYn, maxRows, useYn, rowVer(16진수; U·D 필수)}]
-- 규칙: 레포트 ID는 사용 중인 프로그램 ID여야 하고 만든 뒤 바꿀 수 없다. 데이터 SP는 '스키마.USP_RPT_대상_GET_LIST' 형식이고 실제로 있어야 한다.
--       양식 뷰 이름은 영문·숫자·밑줄만(화면에서 뷰가 있는지도 확인). 이미 만든 요청(TB_REPORT_RUN)이 있으면 지울 수 없고 사용 안 함으로 바꾼다.
-- 수정·삭제는 조회 때의 ROW_VER와 같아야 한다. 변경 내용은 감사 로그에 남긴다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_REPORT_SAVE]
  @P_ROWS_JSON  NVARCHAR(MAX),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF ISJSON(@P_ROWS_JSON) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @R TABLE (
    [ROW_STAT] CHAR(1), [REPORT_ID] VARCHAR(30) PRIMARY KEY, [DATA_SP] VARCHAR(128), [TEMPLATE_VIEW] VARCHAR(50), [PARAMS_JSON] NVARCHAR(2000),
    [ORIENT_CD] CHAR(1), [APPROVAL_YN] CHAR(1), [TOTAL_YN] CHAR(1), [MAX_ROWS] INT, [USE_YN] CHAR(1), [ROW_VER] BINARY(8));
  INSERT INTO @R
  SELECT [rowStat], [reportId], LTRIM(RTRIM([dataSp])), NULLIF(LTRIM(RTRIM([templateView])), ''), NULLIF(LTRIM(RTRIM([paramsJson])), N''),
         ISNULL([orientCd], 'P'), ISNULL([approvalYn], 'N'), ISNULL([totalYn], 'N'), ISNULL([maxRows], 5000), ISNULL([useYn], 'Y'), CONVERT(BINARY(8), [rowVer], 2)
    FROM OPENJSON(@P_ROWS_JSON) WITH (
      [rowStat] CHAR(1), [reportId] VARCHAR(30), [dataSp] VARCHAR(128), [templateView] VARCHAR(50), [paramsJson] NVARCHAR(2000),
      [orientCd] CHAR(1), [approvalYn] CHAR(1), [totalYn] CHAR(1), [maxRows] INT, [useYn] CHAR(1), [rowVer] VARCHAR(16));

  IF NOT EXISTS (SELECT 1 FROM @R)
    THROW 50005, 'MSG.NO_CHANGES', 1;
  IF EXISTS (SELECT 1 FROM @R WHERE [ROW_STAT] NOT IN ('I', 'U', 'D') OR [REPORT_ID] IS NULL OR [REPORT_ID] COLLATE Latin1_General_BIN LIKE '%[^A-Z0-9_]%'
                                  OR ([ROW_STAT] IN ('U', 'D') AND [ROW_VER] IS NULL))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R
              WHERE [ROW_STAT] IN ('I', 'U')
                AND ([DATA_SP] IS NULL OR [DATA_SP] COLLATE Latin1_General_BIN LIKE '%[^A-Za-z0-9_.]%' OR [DATA_SP] NOT LIKE '[A-Z]%.USP[_]RPT[_]%[_]GET[_]LIST'
                     OR LEN([DATA_SP]) - LEN(REPLACE([DATA_SP], '.', '')) <> 1
                     OR ([TEMPLATE_VIEW] IS NOT NULL AND [TEMPLATE_VIEW] COLLATE Latin1_General_BIN LIKE '%[^A-Za-z0-9_]%')
                     OR ([PARAMS_JSON] IS NOT NULL AND ISJSON([PARAMS_JSON]) <> 1)
                     OR [ORIENT_CD] NOT IN ('P', 'L') OR [APPROVAL_YN] NOT IN ('Y', 'N') OR [TOTAL_YN] NOT IN ('Y', 'N') OR [USE_YN] NOT IN ('Y', 'N')
                     OR [MAX_ROWS] NOT BETWEEN 1 AND 100000))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R WHERE [ROW_STAT] IN ('I', 'U') AND OBJECT_ID([DATA_SP], 'P') IS NULL)
    THROW 50004, 'MSG.REPORT_SP_NOT_FOUND', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = R.[REPORT_ID]
              WHERE R.[ROW_STAT] = 'I' AND (P.[PROGRAM_ID] IS NULL OR P.[USE_YN] <> 'Y'))
    THROW 50004, 'MSG.NOT_FOUND', 1;
  IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_REPORT] T ON T.[REPORT_ID] = R.[REPORT_ID] WHERE R.[ROW_STAT] = 'I')
    THROW 50001, 'MSG.DUP_REPORT', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_REPORT] T ON T.[REPORT_ID] = R.[REPORT_ID] WHERE R.[ROW_STAT] IN ('U', 'D') AND T.[REPORT_ID] IS NULL)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @CNT INT = 0, @N INT, @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_REPORT] T WITH (UPDLOCK) ON T.[REPORT_ID] = R.[REPORT_ID]
                WHERE R.[ROW_STAT] IN ('U', 'D') AND T.[ROW_VER] <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_REPORT_RUN] U ON U.[REPORT_ID] = R.[REPORT_ID] WHERE R.[ROW_STAT] = 'D')
      THROW 50001, 'MSG.REPORT_IN_USE', 1;

    SET @BEFORE = (SELECT T.[REPORT_ID], T.[DATA_SP], T.[TEMPLATE_VIEW], T.[PARAMS_JSON], T.[ORIENT_CD], T.[APPROVAL_YN], T.[TOTAL_YN], T.[MAX_ROWS], T.[USE_YN]
                     FROM [FW].[TB_REPORT] T JOIN @R R ON R.[REPORT_ID] = T.[REPORT_ID] FOR JSON PATH);

    INSERT INTO [FW].[TB_REPORT] ([REPORT_ID], [DATA_SP], [TEMPLATE_VIEW], [PARAMS_JSON], [ORIENT_CD], [APPROVAL_YN], [TOTAL_YN], [MAX_ROWS], [USE_YN], [REG_ID], [UPD_ID])
    SELECT [REPORT_ID], [DATA_SP], [TEMPLATE_VIEW], [PARAMS_JSON], [ORIENT_CD], [APPROVAL_YN], [TOTAL_YN], [MAX_ROWS], [USE_YN], @P_USER_ID, @P_USER_ID
      FROM @R WHERE [ROW_STAT] = 'I';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    UPDATE T
       SET T.[DATA_SP] = R.[DATA_SP], T.[TEMPLATE_VIEW] = R.[TEMPLATE_VIEW], T.[PARAMS_JSON] = R.[PARAMS_JSON], T.[ORIENT_CD] = R.[ORIENT_CD],
           T.[APPROVAL_YN] = R.[APPROVAL_YN], T.[TOTAL_YN] = R.[TOTAL_YN], T.[MAX_ROWS] = R.[MAX_ROWS], T.[USE_YN] = R.[USE_YN],
           T.[UPD_ID] = @P_USER_ID, T.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_REPORT] T JOIN @R R ON R.[REPORT_ID] = T.[REPORT_ID]
     WHERE R.[ROW_STAT] = 'U';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    DELETE T FROM [FW].[TB_REPORT] T JOIN @R R ON R.[REPORT_ID] = T.[REPORT_ID] WHERE R.[ROW_STAT] = 'D';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    SET @AFTER = (SELECT R.[ROW_STAT], R.[REPORT_ID], R.[DATA_SP], R.[TEMPLATE_VIEW], R.[PARAMS_JSON], R.[ORIENT_CD], R.[APPROVAL_YN], R.[TOTAL_YN], R.[MAX_ROWS], R.[USE_YN]
                    FROM @R R FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_REPORT', @P_ACTION_CD = 'U', @P_ROW_KEY = N'REPORT',
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
