-- 사용자 정보·역할 저장 (저장 SP 표준 템플릿). 프로그램: SYS_USER_MGT
-- 이름, 상태(ACTIVE/LOCKED/DORMANT/RETIRED), 계정 사용 기한, 직접 부여 역할(@P_ROLE_IDS: JSON 배열, 이 목록이 되도록 더하고 뺀다)을 저장한다.
-- 규칙: 자기 자신의 상태·역할은 바꿀 수 없다. 역할은 COMPANY_TYPE_CD가 비었거나 사용자 회사 유형과 같은 것만 줄 수 있다
--       (협력사 사용자에게 본사 역할 금지). SYS_ADMIN 역할을 주고 빼는 것과 SYS_ADMIN 사용자를 고치는 것은 SYS_ADMIN만 한다.
-- 상태를 사용 외로 바꾸면 그 사용자의 세션은 다음 요청에서 끊긴다(세션 확인 SP). 역할·상태가 바뀌면 권한 캐시(AUTH)를 갱신한다.
-- 동시성: 조회 때 받은 ROW_VER와 같아야 한다. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_USER_SAVE]
  @P_TARGET_USER_ID  VARCHAR(30),
  @P_ROW_VER         BINARY(8),
  @P_USER_NM         NVARCHAR(100),
  @P_USER_STAT_CD    VARCHAR(10),
  @P_ACCOUNT_END_DT  DATE          = NULL,
  @P_ROLE_IDS        NVARCHAR(MAX) = N'[]',
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_USER_NM = NULLIF(LTRIM(RTRIM(@P_USER_NM)), N'');
  IF @P_USER_NM IS NULL OR ISJSON(@P_ROLE_IDS) <> 1 OR LEFT(LTRIM(@P_ROLE_IDS), 1) <> '['
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @WANT TABLE ([ROLE_ID] VARCHAR(30) PRIMARY KEY);
  INSERT INTO @WANT ([ROLE_ID]) SELECT DISTINCT CAST([value] AS VARCHAR(30)) FROM OPENJSON(@P_ROLE_IDS);

  DECLARE @CALLER_SYS_ADMIN BIT = IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) WHERE [ROLE_ID] = 'SYS_ADMIN'), 1, 0);
  DECLARE @OLD_STAT VARCHAR(10), @OLD_VER BINARY(8), @COMPANY_TYPE VARCHAR(10);
  DECLARE @ADDED TABLE ([ROLE_ID] VARCHAR(30));
  DECLARE @REMOVED TABLE ([ROLE_ID] VARCHAR(30));
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    SELECT @OLD_STAT = U.[USER_STAT_CD], @OLD_VER = U.[ROW_VER], @COMPANY_TYPE = C.[COMPANY_TYPE_CD]
      FROM [FW].[TB_USER] U WITH (UPDLOCK, HOLDLOCK)
      JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
     WHERE U.[USER_ID] = @P_TARGET_USER_ID;

    IF @OLD_STAT IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @OLD_VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @P_USER_STAT_CD <> @OLD_STAT AND @P_USER_STAT_CD NOT IN ('ACTIVE', 'LOCKED', 'DORMANT', 'RETIRED')
      THROW 50005, 'MSG.INVALID_INPUT', 1;
    IF EXISTS (SELECT 1 FROM @WANT W LEFT JOIN [FW].[TB_ROLE] R ON R.[ROLE_ID] = W.[ROLE_ID] WHERE R.[ROLE_ID] IS NULL)
      THROW 50005, 'MSG.INVALID_INPUT', 1;

    INSERT INTO @ADDED ([ROLE_ID])
    SELECT W.[ROLE_ID] FROM @WANT W
     WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] UR WHERE UR.[USER_ID] = @P_TARGET_USER_ID AND UR.[ROLE_ID] = W.[ROLE_ID]);
    INSERT INTO @REMOVED ([ROLE_ID])
    SELECT UR.[ROLE_ID] FROM [FW].[TB_USER_ROLE] UR WITH (UPDLOCK)
     WHERE UR.[USER_ID] = @P_TARGET_USER_ID AND NOT EXISTS (SELECT 1 FROM @WANT W WHERE W.[ROLE_ID] = UR.[ROLE_ID]);

    DECLARE @ROLES_CHANGED BIT = IIF(EXISTS (SELECT 1 FROM @ADDED) OR EXISTS (SELECT 1 FROM @REMOVED), 1, 0);
    DECLARE @STAT_CHANGED BIT = IIF(@P_USER_STAT_CD <> @OLD_STAT, 1, 0);

    IF @P_TARGET_USER_ID = @P_USER_ID AND (@ROLES_CHANGED = 1 OR @STAT_CHANGED = 1)
      THROW 50003, 'MSG.USER_SELF_CHANGE', 1;
    IF @CALLER_SYS_ADMIN = 0
       AND (EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] WHERE [USER_ID] = @P_TARGET_USER_ID AND [ROLE_ID] = 'SYS_ADMIN')
            OR EXISTS (SELECT 1 FROM @ADDED WHERE [ROLE_ID] = 'SYS_ADMIN'))
      THROW 50003, 'MSG.USER_SYS_ADMIN_ONLY', 1;
    IF EXISTS (SELECT 1 FROM @ADDED A JOIN [FW].[TB_ROLE] R ON R.[ROLE_ID] = A.[ROLE_ID]
                WHERE R.[USE_YN] <> 'Y' OR (R.[COMPANY_TYPE_CD] IS NOT NULL AND R.[COMPANY_TYPE_CD] <> @COMPANY_TYPE))
      THROW 50003, 'MSG.USER_ROLE_TYPE', 1;

    SET @BEFORE = (SELECT U.[USER_NM], U.[USER_STAT_CD], U.[ACCOUNT_END_DT],
                          (SELECT STRING_AGG([ROLE_ID], ',') WITHIN GROUP (ORDER BY [ROLE_ID]) FROM [FW].[TB_USER_ROLE] WHERE [USER_ID] = U.[USER_ID]) AS [ROLE_IDS]
                     FROM [FW].[TB_USER] U WHERE U.[USER_ID] = @P_TARGET_USER_ID
                     FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);

    UPDATE [FW].[TB_USER]
       SET [USER_NM] = @P_USER_NM, [USER_STAT_CD] = @P_USER_STAT_CD, [ACCOUNT_END_DT] = @P_ACCOUNT_END_DT,
           [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
     WHERE [USER_ID] = @P_TARGET_USER_ID;

    DELETE UR FROM [FW].[TB_USER_ROLE] UR JOIN @REMOVED D ON D.[ROLE_ID] = UR.[ROLE_ID] WHERE UR.[USER_ID] = @P_TARGET_USER_ID;
    INSERT INTO [FW].[TB_USER_ROLE] ([USER_ID], [ROLE_ID], [REG_ID], [UPD_ID])
    SELECT @P_TARGET_USER_ID, [ROLE_ID], @P_USER_ID, @P_USER_ID FROM @ADDED;

    SET @AFTER = (SELECT U.[USER_NM], U.[USER_STAT_CD], U.[ACCOUNT_END_DT],
                         (SELECT STRING_AGG([ROLE_ID], ',') WITHIN GROUP (ORDER BY [ROLE_ID]) FROM [FW].[TB_USER_ROLE] WHERE [USER_ID] = U.[USER_ID]) AS [ROLE_IDS]
                    FROM [FW].[TB_USER] U WHERE U.[USER_ID] = @P_TARGET_USER_ID
                    FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_TARGET_USER_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    IF @ROLES_CHANGED = 1 OR @STAT_CHANGED = 1
      UPDATE [FW].[TB_CACHE_VERSION]
         SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME()
       WHERE [CACHE_KEY] = 'AUTH';

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT];
END
