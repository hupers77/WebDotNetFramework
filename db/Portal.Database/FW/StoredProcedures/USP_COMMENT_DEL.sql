-- 댓글 삭제 (표시만 한다). 프로그램: 게시판의 프로그램 (DELETE는 애플리케이션이 확인)
-- 작성자 본인 또는 관리자(@P_MANAGER_YN)만.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_COMMENT_DEL]
  @P_COMMENT_ID   BIGINT,
  @P_ROW_VER      BINARY(8),
  @P_POST_ID      BIGINT,
  @P_MANAGER_YN   CHAR(1)     = 'N',
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_MANAGER_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @VER BINARY(8), @WRITER VARCHAR(30);

  BEGIN TRY
    BEGIN TRAN;

    SELECT @VER = C.[ROW_VER], @WRITER = C.[WRITER_ID]
      FROM [FW].[TB_POST_COMMENT] C WITH (UPDLOCK, HOLDLOCK)
     WHERE C.[COMMENT_ID] = @P_COMMENT_ID AND C.[POST_ID] = @P_POST_ID AND C.[DEL_YN] = 'N'
       AND EXISTS (SELECT 1 FROM [FW].[UFN_POST_VISIBLE](@P_USER_ID, @P_MANAGER_YN) V WHERE V.[POST_ID] = C.[POST_ID]);

    IF @WRITER IS NULL OR (@WRITER <> @P_USER_ID AND @P_MANAGER_YN = 'N')
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;

    UPDATE [FW].[TB_POST_COMMENT] SET [DEL_YN] = 'Y', [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME() WHERE [COMMENT_ID] = @P_COMMENT_ID;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT];
END
