-- 위젯 데이터: 최근 7일에 올라온 공지사항 수 (숫자 카드). 글 보기 규칙은 목록 화면과 같다(UFN_POST_VISIBLE, 관리자 아님).
-- 위젯 SP 공통 결과 열: LABEL, VALUE, TEXT, LINK, DT
CREATE PROCEDURE [FW].[USP_WIDGET_NOTICE_NEW]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT CAST(NULL AS NVARCHAR(100)) AS [LABEL], CAST(COUNT(*) AS DECIMAL(18, 2)) AS [VALUE],
         CAST(NULL AS NVARCHAR(200)) AS [TEXT], CAST(NULL AS VARCHAR(200)) AS [LINK], CAST(NULL AS DATETIME2(0)) AS [DT]
    FROM [FW].[TB_POST] P
    JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, 'N') V ON V.[POST_ID] = P.[POST_ID]
   WHERE P.[BOARD_CD] = 'Notice' AND P.[ROOT_POST_ID] = P.[POST_ID] AND P.[REG_DT] >= DATEADD(DAY, -7, SYSUTCDATETIME());
END
