-- 공통코드 그룹 목록 (목록 SP 표준 템플릿). 프로그램: SYS_CODE_MGT
-- 결과셋 1: 목록, 결과셋 2: 전체 건수. 명칭은 사용자 언어 → 기본 언어 → 관리용 기본명 순으로 대체한다.
CREATE PROCEDURE [FW].[USP_CODE_GROUP_GET_LIST]
  @P_KEYWORD    NVARCHAR(100) = NULL,
  @P_PAGE_NO    INT           = 1,
  @P_PAGE_SIZE  INT           = 50,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT G.[GROUP_CD],
         COALESCE(L.[GROUP_NM], LD.[GROUP_NM], G.[GROUP_NM]) AS [GROUP_NM],
         G.[SYSTEM_YN], G.[ALLOW_ADD_YN],
         G.[ATTR1_NM], G.[ATTR2_NM], G.[ATTR3_NM], G.[ATTR4_NM], G.[ATTR5_NM],
         G.[USE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_CODE] C WHERE C.[GROUP_CD] = G.[GROUP_CD]) AS [CODE_CNT]
    FROM [FW].[TB_CODE_GROUP] G
    LEFT JOIN [FW].[TB_CODE_GROUP_LANG] L  ON L.[GROUP_CD] = G.[GROUP_CD] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_GROUP_LANG] LD ON LD.[GROUP_CD] = G.[GROUP_CD] AND LD.[LANG_CD] = @DEFAULT_LANG
   WHERE (@P_KEYWORD IS NULL OR G.[GROUP_CD] LIKE @P_KEYWORD + '%' OR L.[GROUP_NM] LIKE '%' + @P_KEYWORD + '%' OR LD.[GROUP_NM] LIKE '%' + @P_KEYWORD + '%')
   ORDER BY G.[SORT_NO], G.[GROUP_CD]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_CODE_GROUP] G
    LEFT JOIN [FW].[TB_CODE_GROUP_LANG] L  ON L.[GROUP_CD] = G.[GROUP_CD] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_GROUP_LANG] LD ON LD.[GROUP_CD] = G.[GROUP_CD] AND LD.[LANG_CD] = @DEFAULT_LANG
   WHERE (@P_KEYWORD IS NULL OR G.[GROUP_CD] LIKE @P_KEYWORD + '%' OR L.[GROUP_NM] LIKE '%' + @P_KEYWORD + '%' OR LD.[GROUP_NM] LIKE '%' + @P_KEYWORD + '%')
  OPTION (RECOMPILE);
END
