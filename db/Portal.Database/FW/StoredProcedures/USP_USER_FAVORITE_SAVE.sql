-- 본인 즐겨찾기 추가·해제. 같은 요청을 여러 번 보내도 결과가 같다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_USER_FAVORITE_SAVE]
  @P_MENU_ID      INT,
  @P_FAVORITE_YN  CHAR(1),
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_USER_ID IS NULL OR @P_FAVORITE_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF @P_FAVORITE_YN = 'Y' AND NOT EXISTS (SELECT 1 FROM [FW].[TB_MENU] WHERE [MENU_ID] = @P_MENU_ID AND [USE_YN] = 'Y' AND [MENU_TYPE_CD] <> 'FOLDER')
    THROW 50004, 'MSG.NOT_FOUND', 1;

  IF @P_FAVORITE_YN = 'Y'
  BEGIN
    INSERT INTO [FW].[TB_USER_FAVORITE] ([USER_ID], [MENU_ID], [SORT_NO], [REG_ID], [UPD_ID])
    SELECT @P_USER_ID, @P_MENU_ID,
           ISNULL((SELECT MAX([SORT_NO]) FROM [FW].[TB_USER_FAVORITE] WHERE [USER_ID] = @P_USER_ID), 0) + 10,
           @P_USER_ID, @P_USER_ID
     WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_USER_FAVORITE] WHERE [USER_ID] = @P_USER_ID AND [MENU_ID] = @P_MENU_ID);
  END
  ELSE
  BEGIN
    DELETE FROM [FW].[TB_USER_FAVORITE] WHERE [USER_ID] = @P_USER_ID AND [MENU_ID] = @P_MENU_ID;
  END

  SELECT @@ROWCOUNT AS [AFFECTED_CNT];
END
