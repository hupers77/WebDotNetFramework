-- 현재 사용자(@P_USER_ID)의 권한 원천 데이터. 평가(SYS_ADMIN 전체 허용, 역할 허용 합집합, 사용자 GRANT 추가·DENY 우선)는
-- 애플리케이션의 PermissionEvaluator가 한다(설계서 6장). 로그인 시와 캐시 버전(AUTH)이 바뀔 때 읽는다.
-- 결과 1: 유효 역할 ROLE_ID, DATA_SCOPE_CD
-- 결과 2: 역할 기능 권한 PROGRAM_ID, FUNC_CD (사용 중인 프로그램만, 중복 제거)
-- 결과 3: 사용자 예외 권한 PROGRAM_ID, FUNC_CD, GRANT_TYPE (유효기간 안)
CREATE PROCEDURE [FW].[USP_AUTH_GET_PERMISSION]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @ROLES TABLE ([ROLE_ID] VARCHAR(30) PRIMARY KEY, [DATA_SCOPE_CD] VARCHAR(10));
  INSERT INTO @ROLES SELECT [ROLE_ID], [DATA_SCOPE_CD] FROM [FW].[UFN_USER_ROLES](@P_USER_ID);

  SELECT [ROLE_ID], [DATA_SCOPE_CD] FROM @ROLES ORDER BY [ROLE_ID];

  SELECT DISTINCT RF.[PROGRAM_ID], RF.[FUNC_CD]
    FROM @ROLES R
    JOIN [FW].[TB_ROLE_PROGRAM_FUNC] RF ON RF.[ROLE_ID] = R.[ROLE_ID]
    JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = RF.[PROGRAM_ID]
   WHERE P.[USE_YN] = 'Y'
   ORDER BY RF.[PROGRAM_ID], RF.[FUNC_CD];

  SELECT UF.[PROGRAM_ID], UF.[FUNC_CD], RTRIM(UF.[GRANT_TYPE]) AS [GRANT_TYPE]
    FROM [FW].[TB_USER_PROGRAM_FUNC] UF
    JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = UF.[PROGRAM_ID]
    JOIN [FW].[TB_USER] U ON U.[USER_ID] = UF.[USER_ID]
   WHERE UF.[USER_ID] = @P_USER_ID
     AND UF.[END_DT] >= CAST(GETDATE() AS DATE)
     AND P.[USE_YN] = 'Y'
     AND U.[USER_STAT_CD] = 'ACTIVE'
   ORDER BY UF.[PROGRAM_ID], UF.[FUNC_CD];
END
