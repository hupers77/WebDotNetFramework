-- 로그인 성공 처리: 실패 횟수·잠금 초기화, 중복 로그인 정책 적용, 세션 생성, 로그인 로그 기록.
-- 세션 키는 애플리케이션이 만든 무작위 값의 SHA-256(64자 16진수)만 받는다. 원문은 쿠키에만 있다.
-- 중복 로그인(SESSION.CONCURRENT_POLICY): KICK_OLD = 기존 세션 종료(KICKED), DENY_NEW = 새 로그인 거부, ALLOW = 허용
-- 결과: EXPIRE_DT, KICKED_CNT
CREATE PROCEDURE [FW].[USP_AUTH_LOGIN_SUCCESS_EXEC]
  @P_LOGIN_USER_ID  VARCHAR(30),
  @P_SESSION_HASH   CHAR(64),
  @P_AUTH_METHOD_CD VARCHAR(10),
  @P_USER_AGENT     NVARCHAR(300) = NULL,
  @P_USER_ID        VARCHAR(30),
  @P_LANG_CD        VARCHAR(5),
  @P_CLIENT_IP      VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_SESSION_HASH IS NULL OR @P_SESSION_HASH LIKE '%[^0-9a-f]%' OR LEN(@P_SESSION_HASH) <> 64
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_USER] WHERE [USER_ID] = @P_LOGIN_USER_ID)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @IDLE_MINUTES INT = ISNULL(TRY_CAST((SELECT [CONFIG_VAL] FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'SESSION.IDLE_MINUTES') AS INT), 30);
  DECLARE @POLICY VARCHAR(10) = ISNULL((SELECT CAST([CONFIG_VAL] AS VARCHAR(10)) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'SESSION.CONCURRENT_POLICY'), 'KICK_OLD');
  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @EXPIRE_DT DATETIME2(0) = DATEADD(MINUTE, @IDLE_MINUTES, @NOW);
  DECLARE @KICKED_CNT INT = 0;

  BEGIN TRY
    BEGIN TRAN;

    -- 사용자 행을 먼저 갱신(잠금)해 같은 사용자의 동시 로그인을 직렬화한다
    UPDATE [FW].[TB_USER]
       SET [LOGIN_FAIL_CNT] = 0, [LOCK_YN] = 'N', [LOCK_DT] = NULL, [LAST_LOGIN_DT] = @NOW
     WHERE [USER_ID] = @P_LOGIN_USER_ID;

    IF @POLICY = 'DENY_NEW'
       AND EXISTS (SELECT 1 FROM [FW].[TB_USER_SESSION]
                    WHERE [USER_ID] = @P_LOGIN_USER_ID AND [END_DT] IS NULL AND [EXPIRE_DT] > @NOW)
      THROW 50010, 'AUTH.CONCURRENT_DENIED', 1;

    IF @POLICY = 'KICK_OLD'
    BEGIN
      UPDATE [FW].[TB_USER_SESSION]
         SET [END_DT] = @NOW, [END_REASON_CD] = 'KICKED', [UPD_ID] = @P_LOGIN_USER_ID, [UPD_DT] = @NOW
       WHERE [USER_ID] = @P_LOGIN_USER_ID AND [END_DT] IS NULL AND [EXPIRE_DT] > @NOW;
      SET @KICKED_CNT = @@ROWCOUNT;
    END

    INSERT INTO [FW].[TB_USER_SESSION]
      ([SESSION_ID], [USER_ID], [LOGIN_DT], [LAST_ACCESS_DT], [EXPIRE_DT], [CLIENT_IP], [USER_AGENT], [AUTH_METHOD_CD], [REG_ID], [UPD_ID])
    VALUES
      (@P_SESSION_HASH, @P_LOGIN_USER_ID, @NOW, @NOW, @EXPIRE_DT, @P_CLIENT_IP, @P_USER_AGENT, @P_AUTH_METHOD_CD, @P_LOGIN_USER_ID, @P_LOGIN_USER_ID);

    EXEC [LOG].[USP_LOGIN_LOG_WRITE]
      @P_LOGIN_USER_ID = @P_LOGIN_USER_ID, @P_LOGIN_RESULT_CD = 'SUCCESS', @P_AUTH_METHOD_CD = @P_AUTH_METHOD_CD,
      @P_USER_AGENT = @P_USER_AGENT, @P_SESSION_HASH = @P_SESSION_HASH,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @EXPIRE_DT AS [EXPIRE_DT], @KICKED_CNT AS [KICKED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
