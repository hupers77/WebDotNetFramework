-- 메일 발송 결과 기록. 성공하면 SENT, 실패하면 @P_MAX_TRY회까지 @P_RETRY_MINUTES × 시도 횟수 뒤에 다시 보내고, 넘으면 FAILED.
-- SENT·FAILED로 끝나면 받는 주소와 치환값을 지운다(개인정보 최소 보관). 오류 메시지에는 주소를 넣지 않는다(호출하는 쪽 책임).
-- 발송 작업이 가져간(SENDING) 행만 바꾼다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_MSG_QUEUE_RESULT_EXEC]
  @P_MSG_ID         BIGINT,
  @P_SENT_YN        CHAR(1),
  @P_ERROR_MSG      NVARCHAR(500) = NULL,
  @P_MAX_TRY        INT = 3,
  @P_RETRY_MINUTES  INT = 5,
  @P_USER_ID        VARCHAR(30) = NULL,
  @P_LANG_CD        VARCHAR(5),
  @P_CLIENT_IP      VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_SENT_YN NOT IN ('Y', 'N') OR @P_MAX_TRY < 1 OR @P_RETRY_MINUTES < 0
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();

  UPDATE [FW].[TB_MSG_QUEUE]
     SET [STAT_CD] = CASE WHEN @P_SENT_YN = 'Y' THEN 'SENT' WHEN [TRY_CNT] >= @P_MAX_TRY THEN 'FAILED' ELSE 'READY' END,
         [SENT_DT] = CASE WHEN @P_SENT_YN = 'Y' THEN @NOW END,
         [NEXT_TRY_DT] = CASE WHEN @P_SENT_YN = 'N' THEN DATEADD(MINUTE, @P_RETRY_MINUTES * [TRY_CNT], @NOW) ELSE [NEXT_TRY_DT] END,
         [ERROR_MSG] = CASE WHEN @P_SENT_YN = 'N' THEN LEFT(@P_ERROR_MSG, 500) END,
         [TO_EMAIL_ENC] = CASE WHEN @P_SENT_YN = 'Y' OR [TRY_CNT] >= @P_MAX_TRY THEN NULL ELSE [TO_EMAIL_ENC] END,
         [PARAMS_JSON] = CASE WHEN @P_SENT_YN = 'Y' OR [TRY_CNT] >= @P_MAX_TRY THEN NULL ELSE [PARAMS_JSON] END,
         [LOCK_DT] = NULL, [UPD_DT] = @NOW
   WHERE [MSG_ID] = @P_MSG_ID
     AND [STAT_CD] = 'SENDING';

  SELECT @@ROWCOUNT AS [AFFECTED_CNT];
END
