-- 회사 등록·수정 (저장 SP 표준 템플릿). 프로그램: SYS_COMPANY_MGT
-- @P_ROW_VER가 NULL이면 등록, 있으면 수정. 등록은 협력사만 하고 회사 코드는 P0001부터 차례로 부여한다(@P_COMPANY_CD는 무시).
-- 본사는 초기 데이터 한 건이다.
-- 규칙: 회사 유형은 바꿀 수 없다. 본사는 사용 안 함·계약 종료일을 둘 수 없다. 협력사는 사업자등록번호가 있어야 하고,
--       다른 협력사와 같으면 안 된다(하이픈·공백 무시, 가입 신청이 사업자등록번호로 회사를 찾으므로).
-- 계약 종료일을 바꾸면 그 회사 협력사 계정 중 사용 기한이 이전 계약 종료일과 같던 계정(이전 값이 없었으면 기한이 없던 계정)의
-- 기한도 새 계약 종료일로 바꾼다(승인할 때 계약 종료일을 기한으로 넣으므로). 따로 기한을 정한 계정은 그대로 둔다.
-- 그중 기한이 지나 만료(EXPIRED, JOB_PARTNER_EXPIRE)된 계정은 새 계약 종료일이 오늘 이후(또는 없음)면 다시 사용(ACTIVE)으로 돌린다(계약 연장).
-- 사업자등록번호 정리와 허용 IP 형식 검사는 애플리케이션이 한다. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT(바뀐 회사 1 + 기한을 바꾼 계정 수), NEW_KEY(회사 코드)
CREATE PROCEDURE [FW].[USP_COMPANY_SAVE]
  @P_COMPANY_CD       VARCHAR(10)    = NULL,
  @P_ROW_VER          BINARY(8)      = NULL,
  @P_COMPANY_NM       NVARCHAR(100),
  @P_COMPANY_TYPE_CD  VARCHAR(10),
  @P_BIZ_REG_NO       VARCHAR(20)    = NULL,
  @P_ALLOW_IP_LIST    VARCHAR(1000)  = NULL,
  @P_CONTRACT_END_DT  DATE           = NULL,
  @P_SORT_NO          INT            = 0,
  @P_USE_YN           CHAR(1),
  @P_USER_ID          VARCHAR(30),
  @P_LANG_CD          VARCHAR(5),
  @P_CLIENT_IP        VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_COMPANY_NM = NULLIF(LTRIM(RTRIM(@P_COMPANY_NM)), N'');
  SET @P_BIZ_REG_NO = NULLIF(LTRIM(RTRIM(@P_BIZ_REG_NO)), '');
  SET @P_ALLOW_IP_LIST = NULLIF(LTRIM(RTRIM(@P_ALLOW_IP_LIST)), '');
  DECLARE @BIZ_KEY VARCHAR(20) = REPLACE(REPLACE(@P_BIZ_REG_NO, '-', ''), ' ', '');

  -- 입력 검증 (트랜잭션 전)
  IF (@P_ROW_VER IS NOT NULL AND NULLIF(LTRIM(RTRIM(@P_COMPANY_CD)), '') IS NULL) OR @P_COMPANY_NM IS NULL
     OR @P_COMPANY_TYPE_CD NOT IN ('HQ', 'PARTNER') OR @P_USE_YN NOT IN ('Y', 'N') OR @P_SORT_NO < 0
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF @P_COMPANY_TYPE_CD = 'HQ' AND (@P_USE_YN = 'N' OR @P_CONTRACT_END_DT IS NOT NULL)
    THROW 50003, 'MSG.COMPANY_HQ_RULE', 1;
  IF @P_COMPANY_TYPE_CD = 'PARTNER' AND NULLIF(@BIZ_KEY, '') IS NULL
    THROW 50005, 'MSG.COMPANY_BIZ_REQUIRED', 1;

  DECLARE @CNT INT = 0;
  DECLARE @OLD_TYPE VARCHAR(10), @OLD_VER BINARY(8), @OLD_END DATE;
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX), @USERS_BEFORE NVARCHAR(MAX);
  DECLARE @MOVED TABLE ([USER_ID] VARCHAR(30), [OLD_END] DATE, [OLD_STAT] VARCHAR(10));

  BEGIN TRY
    BEGIN TRAN;

    IF @P_ROW_VER IS NULL
    BEGIN
      IF @P_COMPANY_TYPE_CD <> 'PARTNER'
        THROW 50003, 'MSG.COMPANY_HQ_RULE', 1;

      -- 다음 협력사 코드 (P + 4자리 일련번호, 9999를 넘으면 자리수가 늘어난다). 동시에 등록해도 겹치지 않게 잠근다
      DECLARE @SEQ INT = 1 + ISNULL((SELECT MAX(TRY_CAST(SUBSTRING([COMPANY_CD], 2, 9) AS INT))
                                       FROM [FW].[TB_COMPANY] WITH (UPDLOCK, HOLDLOCK)
                                      WHERE [COMPANY_CD] LIKE 'P[0-9][0-9][0-9][0-9]%'
                                        AND SUBSTRING([COMPANY_CD], 2, 9) NOT LIKE '%[^0-9]%'), 0);
      SET @P_COMPANY_CD = 'P' + IIF(@SEQ < 10000, RIGHT('0000' + CAST(@SEQ AS VARCHAR(9)), 4), CAST(@SEQ AS VARCHAR(9)));
      IF EXISTS (SELECT 1 FROM [FW].[TB_COMPANY] WHERE [COMPANY_CD] = @P_COMPANY_CD)
        THROW 50001, 'MSG.DUP_CODE', 1;
    END
    ELSE
    BEGIN
      SELECT @OLD_TYPE = [COMPANY_TYPE_CD], @OLD_VER = [ROW_VER], @OLD_END = [CONTRACT_END_DT]
        FROM [FW].[TB_COMPANY] WITH (UPDLOCK, HOLDLOCK)
       WHERE [COMPANY_CD] = @P_COMPANY_CD;

      IF @OLD_TYPE IS NULL
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @OLD_VER <> @P_ROW_VER
        THROW 50002, 'MSG.CONCURRENCY', 1;
      IF @OLD_TYPE <> @P_COMPANY_TYPE_CD
        THROW 50003, 'MSG.COMPANY_TYPE_FIXED', 1;
    END

    IF @P_COMPANY_TYPE_CD = 'PARTNER'
       AND EXISTS (SELECT 1 FROM [FW].[TB_COMPANY] WITH (UPDLOCK, HOLDLOCK)
                    WHERE [COMPANY_TYPE_CD] = 'PARTNER' AND [COMPANY_CD] <> @P_COMPANY_CD
                      AND REPLACE(REPLACE([BIZ_REG_NO], '-', ''), ' ', '') = @BIZ_KEY)
      THROW 50001, 'MSG.COMPANY_BIZ_DUP', 1;

    IF @P_ROW_VER IS NULL
    BEGIN
      INSERT INTO [FW].[TB_COMPANY]
        ([COMPANY_CD], [COMPANY_NM], [COMPANY_TYPE_CD], [BIZ_REG_NO], [ALLOW_IP_LIST], [CONTRACT_END_DT], [SORT_NO], [USE_YN], [REG_ID], [UPD_ID])
      VALUES
        (@P_COMPANY_CD, @P_COMPANY_NM, @P_COMPANY_TYPE_CD, @P_BIZ_REG_NO, @P_ALLOW_IP_LIST, @P_CONTRACT_END_DT, @P_SORT_NO, @P_USE_YN, @P_USER_ID, @P_USER_ID);
      SET @CNT = 1;
    END
    ELSE
    BEGIN
      SET @BEFORE = (SELECT [COMPANY_NM], [BIZ_REG_NO], [ALLOW_IP_LIST], [CONTRACT_END_DT], [SORT_NO], [USE_YN]
                       FROM [FW].[TB_COMPANY] WHERE [COMPANY_CD] = @P_COMPANY_CD
                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);

      UPDATE [FW].[TB_COMPANY]
         SET [COMPANY_NM] = @P_COMPANY_NM, [BIZ_REG_NO] = @P_BIZ_REG_NO, [ALLOW_IP_LIST] = @P_ALLOW_IP_LIST,
             [CONTRACT_END_DT] = @P_CONTRACT_END_DT, [SORT_NO] = @P_SORT_NO, [USE_YN] = @P_USE_YN,
             [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
       WHERE [COMPANY_CD] = @P_COMPANY_CD;
      SET @CNT = 1;

      -- 계약 종료일을 따라가던 협력사 계정의 사용 기한을 함께 옮긴다
      IF @P_COMPANY_TYPE_CD = 'PARTNER' AND ISNULL(@OLD_END, '9999-12-31') <> ISNULL(@P_CONTRACT_END_DT, '9999-12-31')
      BEGIN
        UPDATE [FW].[TB_USER]
           SET [ACCOUNT_END_DT] = @P_CONTRACT_END_DT, [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
        OUTPUT INSERTED.[USER_ID], DELETED.[ACCOUNT_END_DT], DELETED.[USER_STAT_CD] INTO @MOVED
         WHERE [COMPANY_CD] = @P_COMPANY_CD
           AND [USER_TYPE_CD] = 'PARTNER'
           AND ISNULL([ACCOUNT_END_DT], '9999-12-31') = ISNULL(@OLD_END, '9999-12-31');
        SET @CNT += @@ROWCOUNT;

        -- 계약을 연장했으면 기한이 지나 만료된 계정을 다시 쓸 수 있게 한다
        IF ISNULL(@P_CONTRACT_END_DT, '9999-12-31') >= CAST(GETDATE() AS DATE) AND @P_USE_YN = 'Y'
          UPDATE U
             SET [USER_STAT_CD] = 'ACTIVE', [STAT_CHG_DT] = SYSUTCDATETIME()
            FROM [FW].[TB_USER] U
            JOIN @MOVED M ON M.[USER_ID] = U.[USER_ID]
           WHERE U.[USER_STAT_CD] = 'EXPIRED';
      END
    END

    SET @AFTER = (SELECT [COMPANY_CD], [COMPANY_NM], [COMPANY_TYPE_CD], [BIZ_REG_NO], [ALLOW_IP_LIST], [CONTRACT_END_DT], [SORT_NO], [USE_YN]
                    FROM [FW].[TB_COMPANY] WHERE [COMPANY_CD] = @P_COMPANY_CD
                    FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @ACTION CHAR(1) = IIF(@P_ROW_VER IS NULL, 'I', 'U');
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_COMPANY', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @P_COMPANY_CD,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    IF EXISTS (SELECT 1 FROM @MOVED)
    BEGIN
      SET @USERS_BEFORE = (SELECT [USER_ID], [OLD_END] AS [ACCOUNT_END_DT], [OLD_STAT] AS [USER_STAT_CD] FROM @MOVED ORDER BY [USER_ID] FOR JSON PATH, INCLUDE_NULL_VALUES);
      DECLARE @USERS_AFTER NVARCHAR(MAX) = (SELECT U.[USER_ID], U.[ACCOUNT_END_DT], U.[USER_STAT_CD]
                                              FROM [FW].[TB_USER] U JOIN @MOVED M ON M.[USER_ID] = U.[USER_ID]
                                             ORDER BY U.[USER_ID] FOR JSON PATH, INCLUDE_NULL_VALUES);
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_COMPANY_CD,
        @P_BEFORE_JSON = @USERS_BEFORE, @P_AFTER_JSON = @USERS_AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT], @P_COMPANY_CD AS [NEW_KEY];
END
