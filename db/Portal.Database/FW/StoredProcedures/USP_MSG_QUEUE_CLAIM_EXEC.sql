-- 메일 발송 작업(JOB_MAIL_SEND)이 보낼 메시지를 가져간다. 가져간 행은 SENDING으로 바꿔 다른 작업이 다시 가져가지 않게 한다.
-- 작업이 멈춰 SENDING에 머문 행은 @P_LOCK_MINUTES가 지나면 다시 가져가고, 이미 @P_MAX_TRY회 시도했으면 FAILED로 끝낸다.
-- 가져갈 때마다 시도 횟수를 올린다.
-- 받는 사람 언어의 템플릿 문구가 없으면 기본 언어 문구를 준다. 템플릿을 쓰지 않게 되었으면 실패로 끝낸다.
-- 결과: MSG_ID, TEMPLATE_ID, TO_EMAIL_ENC, LANG_CD, PARAMS_JSON, TRY_CNT, SUBJECT, BODY
CREATE PROCEDURE [FW].[USP_MSG_QUEUE_CLAIM_EXEC]
  @P_BATCH_SIZE    INT = 20,
  @P_LOCK_MINUTES  INT = 10,
  @P_MAX_TRY       INT = 3,
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_BATCH_SIZE NOT BETWEEN 1 AND 100 OR @P_LOCK_MINUTES < 1 OR @P_MAX_TRY < 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP 1 [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  DECLARE @CLAIMED TABLE ([MSG_ID] BIGINT PRIMARY KEY);

  BEGIN TRY
    BEGIN TRAN;

    -- 멈춘 작업이 마지막 시도였던 행은 다시 보내지 않는다
    UPDATE [FW].[TB_MSG_QUEUE] WITH (ROWLOCK, READPAST)
       SET [STAT_CD] = 'FAILED', [TO_EMAIL_ENC] = NULL, [PARAMS_JSON] = NULL, [LOCK_DT] = NULL,
           [ERROR_MSG] = N'SEND_INTERRUPTED', [UPD_DT] = @NOW
     WHERE [STAT_CD] = 'SENDING' AND [LOCK_DT] < DATEADD(MINUTE, -@P_LOCK_MINUTES, @NOW) AND [TRY_CNT] >= @P_MAX_TRY;

    -- 다른 작업이 잠근 행은 건너뛴다 (READPAST)
    UPDATE TOP (@P_BATCH_SIZE) Q
       SET [STAT_CD] = 'SENDING', [LOCK_DT] = @NOW, [TRY_CNT] = Q.[TRY_CNT] + 1, [UPD_DT] = @NOW
    OUTPUT INSERTED.[MSG_ID] INTO @CLAIMED
      FROM [FW].[TB_MSG_QUEUE] Q WITH (ROWLOCK, READPAST, UPDLOCK)
     WHERE Q.[CHANNEL_CD] = 'MAIL'
       AND ((Q.[STAT_CD] = 'READY' AND Q.[NEXT_TRY_DT] <= @NOW)
         OR (Q.[STAT_CD] = 'SENDING' AND Q.[LOCK_DT] < DATEADD(MINUTE, -@P_LOCK_MINUTES, @NOW)));

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT Q.[MSG_ID], Q.[TEMPLATE_ID], Q.[TO_EMAIL_ENC], Q.[LANG_CD], Q.[PARAMS_JSON], Q.[TRY_CNT],
         ISNULL(L.[SUBJECT], D.[SUBJECT]) AS [SUBJECT], ISNULL(L.[BODY], D.[BODY]) AS [BODY]
    FROM @CLAIMED C
    JOIN [FW].[TB_MSG_QUEUE] Q ON Q.[MSG_ID] = C.[MSG_ID]
    JOIN [FW].[TB_MSG_TEMPLATE] T ON T.[TEMPLATE_ID] = Q.[TEMPLATE_ID] AND T.[USE_YN] = 'Y' AND T.[MAIL_YN] = 'Y'
    LEFT JOIN [FW].[TB_MSG_TEMPLATE_LANG] L ON L.[TEMPLATE_ID] = Q.[TEMPLATE_ID] AND L.[LANG_CD] = Q.[LANG_CD]
    LEFT JOIN [FW].[TB_MSG_TEMPLATE_LANG] D ON D.[TEMPLATE_ID] = Q.[TEMPLATE_ID] AND D.[LANG_CD] = @DEFAULT_LANG
   WHERE ISNULL(L.[BODY], D.[BODY]) IS NOT NULL
   ORDER BY Q.[MSG_ID];

  -- 템플릿을 쓰지 않게 되었거나 문구가 없는 행은 보내지 않고 끝낸다 (주소·치환값도 지운다)
  UPDATE Q
     SET [STAT_CD] = 'FAILED', [TO_EMAIL_ENC] = NULL, [PARAMS_JSON] = NULL, [LOCK_DT] = NULL,
         [ERROR_MSG] = N'TEMPLATE_UNAVAILABLE', [UPD_DT] = @NOW
    FROM [FW].[TB_MSG_QUEUE] Q
    JOIN @CLAIMED C ON C.[MSG_ID] = Q.[MSG_ID]
   WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_MSG_TEMPLATE] T
                      WHERE T.[TEMPLATE_ID] = Q.[TEMPLATE_ID] AND T.[USE_YN] = 'Y' AND T.[MAIL_YN] = 'Y'
                        AND EXISTS (SELECT 1 FROM [FW].[TB_MSG_TEMPLATE_LANG] L
                                     WHERE L.[TEMPLATE_ID] = T.[TEMPLATE_ID] AND L.[LANG_CD] IN (Q.[LANG_CD], @DEFAULT_LANG)));
END
