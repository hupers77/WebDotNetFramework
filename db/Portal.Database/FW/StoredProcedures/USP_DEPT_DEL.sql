-- 부서 삭제 (삭제 SP 표준 템플릿). 프로그램: SYS_DEPT_MGT
-- 잘못 만든 부서만 지운다. 하위 부서나 소속 계정(상태와 관계없이)이 있거나 AD 동기화 부서면 지우지 않는다
-- (조직 개편은 사용 안 함으로 바꿔 기록을 남긴다). 부서 역할도 함께 지우고 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_DEPT_DEL]
  @P_DEPT_ID     VARCHAR(20),
  @P_ROW_VER     BINARY(8),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @COMPANY VARCHAR(10), @VER BINARY(8), @AD_PATH NVARCHAR(400);

  BEGIN TRY
    BEGIN TRAN;

    SELECT @COMPANY = D.[COMPANY_CD], @VER = D.[ROW_VER], @AD_PATH = D.[AD_OU_PATH]
      FROM [FW].[TB_DEPT] D WITH (UPDLOCK, HOLDLOCK)
     WHERE D.[DEPT_ID] = @P_DEPT_ID
       AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'SYS_DEPT_MGT') S WHERE S.[COMPANY_CD] = D.[COMPANY_CD]);

    IF @COMPANY IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @AD_PATH IS NOT NULL
      THROW 50003, 'MSG.DEPT_AD_MANAGED', 1;
    IF EXISTS (SELECT 1 FROM [FW].[TB_DEPT] WITH (UPDLOCK, HOLDLOCK) WHERE [PARENT_DEPT_ID] = @P_DEPT_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_USER] WITH (UPDLOCK, HOLDLOCK) WHERE [DEPT_ID] = @P_DEPT_ID)
      THROW 50003, 'MSG.DEPT_IN_USE', 1;

    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT D.[DEPT_ID], D.[COMPANY_CD], D.[PARENT_DEPT_ID], D.[DEPT_NM], D.[SORT_NO], D.[USE_YN],
                                            (SELECT [ROLE_ID], [INHERIT_YN] FROM [FW].[TB_DEPT_ROLE] WHERE [DEPT_ID] = D.[DEPT_ID] ORDER BY [ROLE_ID] FOR JSON PATH) AS [ROLES]
                                       FROM [FW].[TB_DEPT] D WHERE D.[DEPT_ID] = @P_DEPT_ID
                                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);

    DELETE FROM [FW].[TB_DEPT_ROLE] WHERE [DEPT_ID] = @P_DEPT_ID;
    DELETE FROM [FW].[TB_DEPT] WHERE [DEPT_ID] = @P_DEPT_ID;

    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_DEPT', @P_ACTION_CD = 'D', @P_ROW_KEY = @P_DEPT_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = NULL,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT];
END
