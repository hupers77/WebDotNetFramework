-- 첨부 정리 작업(JOB_TEMP_CLEANUP)이 지울 파일을 찾는다:
--   삭제 표시(DEL_YN = 'Y')한 지 FILE.DELETED_KEEP_DAYS(기본 30일)가 지난 파일,
--   올린 지 하루가 지나도 업무 저장으로 확정되지 않은 묶음(CONFIRM_YN = 'N')의 파일.
-- 결과: FILE_ID, STORED_PATH
CREATE PROCEDURE [FW].[USP_FILE_CLEANUP_GET_LIST]
  @P_BATCH_SIZE    INT = 500,
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_BATCH_SIZE NOT BETWEEN 1 AND 5000
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @KEEP_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'FILE.DELETED_KEEP_DAYS'), 30);

  SELECT TOP (@P_BATCH_SIZE) F.[FILE_ID], F.[STORED_PATH]
    FROM [FW].[TB_FILE] F
    JOIN [FW].[TB_FILE_GROUP] G ON G.[FILE_GROUP_ID] = F.[FILE_GROUP_ID]
   WHERE (F.[DEL_YN] = 'Y' AND F.[UPD_DT] < DATEADD(DAY, -@KEEP_DAYS, @NOW))
      OR (G.[CONFIRM_YN] = 'N' AND G.[REG_DT] < DATEADD(DAY, -1, @NOW))
   ORDER BY F.[FILE_ID];
END
