-- 회사 목록 (목록 SP 표준 템플릿). 프로그램: SYS_COMPANY_MGT
-- 검색어는 회사 코드·회사명·사업자등록번호(하이픈·공백 무시) 일부. 사용자 수는 그 회사 소속 계정 수(상태 무관).
-- 결과셋 1: 목록(본사 먼저, 정렬 순서, 회사명 순), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_COMPANY_GET_LIST]
  @P_KEYWORD          NVARCHAR(100) = NULL,
  @P_COMPANY_TYPE_CD  VARCHAR(10)   = NULL,
  @P_USE_YN           CHAR(1)       = NULL,
  @P_PAGE_NO          INT           = 1,
  @P_PAGE_SIZE        INT           = 50,
  @P_USER_ID          VARCHAR(30),
  @P_LANG_CD          VARCHAR(5),
  @P_CLIENT_IP        VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  DECLARE @BIZ_KEY VARCHAR(100) = NULLIF(REPLACE(REPLACE(CAST(@P_KEYWORD AS VARCHAR(100)), '-', ''), ' ', ''), '');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT C.[COMPANY_CD], C.[COMPANY_NM], C.[COMPANY_TYPE_CD],
         COALESCE(TL.[CODE_NM], TD.[CODE_NM], C.[COMPANY_TYPE_CD]) AS [COMPANY_TYPE_NM],
         C.[BIZ_REG_NO], C.[ALLOW_IP_LIST], C.[CONTRACT_END_DT], C.[SORT_NO], C.[USE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_USER] U WHERE U.[COMPANY_CD] = C.[COMPANY_CD]) AS [USER_CNT],
         C.[UPD_ID], C.[UPD_DT], C.[ROW_VER]
    FROM [FW].[TB_COMPANY] C
    LEFT JOIN [FW].[TB_CODE_LANG] TL ON TL.[GROUP_CD] = 'COMPANY_TYPE' AND TL.[CODE] = C.[COMPANY_TYPE_CD] AND TL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] TD ON TD.[GROUP_CD] = 'COMPANY_TYPE' AND TD.[CODE] = C.[COMPANY_TYPE_CD] AND TD.[LANG_CD] = @DEFAULT_LANG
   WHERE (@P_KEYWORD IS NULL OR C.[COMPANY_CD] LIKE '%' + @P_KEYWORD + '%' OR C.[COMPANY_NM] LIKE '%' + @P_KEYWORD + '%'
          OR (@BIZ_KEY IS NOT NULL AND REPLACE(REPLACE(C.[BIZ_REG_NO], '-', ''), ' ', '') LIKE '%' + @BIZ_KEY + '%'))
     AND (@P_COMPANY_TYPE_CD IS NULL OR C.[COMPANY_TYPE_CD] = @P_COMPANY_TYPE_CD)
     AND (@P_USE_YN IS NULL OR C.[USE_YN] = @P_USE_YN)
   ORDER BY CASE WHEN C.[COMPANY_TYPE_CD] = 'HQ' THEN 0 ELSE 1 END, C.[SORT_NO], C.[COMPANY_NM], C.[COMPANY_CD]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_COMPANY] C
   WHERE (@P_KEYWORD IS NULL OR C.[COMPANY_CD] LIKE '%' + @P_KEYWORD + '%' OR C.[COMPANY_NM] LIKE '%' + @P_KEYWORD + '%'
          OR (@BIZ_KEY IS NOT NULL AND REPLACE(REPLACE(C.[BIZ_REG_NO], '-', ''), ' ', '') LIKE '%' + @BIZ_KEY + '%'))
     AND (@P_COMPANY_TYPE_CD IS NULL OR C.[COMPANY_TYPE_CD] = @P_COMPANY_TYPE_CD)
     AND (@P_USE_YN IS NULL OR C.[USE_YN] = @P_USE_YN)
  OPTION (RECOMPILE);
END
