-- 작업 실행을 시작한다: 작업을 잠그고(RUNNING_YN) 실행 이력 행을 만든다. 실행할 차례가 아니거나 다른 Worker가 이미 가져갔으면 결과가 없다.
-- 예약 실행이면 다음 예약 시각을 @P_NEXT_RUN_DT(Worker가 주기로 계산한 값)로 바꾼다. 수동 실행은 예약 시각을 건드리지 않는다.
-- 멈춘 실행(잠근 지 TIMEOUT_MIN 지남)을 넘겨받으면 그 이력은 FAILED(INTERRUPTED)로 끝낸다.
-- 결과: HIST_ID, RUN_TYPE_CD, RUN_USER_ID
CREATE PROCEDURE [FW].[USP_JOB_START_EXEC]
  @P_JOB_ID        VARCHAR(30),
  @P_NEXT_RUN_DT   DATETIME2(0) = NULL,
  @P_HOST_NM       VARCHAR(64) = NULL,
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @CLAIMED TABLE ([RUN_TYPE_CD] VARCHAR(10), [RUN_USER_ID] VARCHAR(30), [PREV_HIST_ID] BIGINT, [WAS_RUNNING] CHAR(1));
  DECLARE @HIST_ID BIGINT;

  BEGIN TRY
    BEGIN TRAN;

    UPDATE [FW].[TB_JOB] WITH (UPDLOCK, ROWLOCK)
       SET [RUNNING_YN] = 'Y', [LOCK_DT] = @NOW, [RUN_REQ_YN] = 'N', [RUN_REQ_ID] = NULL,
           [NEXT_RUN_DT] = CASE WHEN [NEXT_RUN_DT] IS NULL OR [NEXT_RUN_DT] <= @NOW THEN @P_NEXT_RUN_DT ELSE [NEXT_RUN_DT] END,
           [UPD_DT] = @NOW
    OUTPUT CASE WHEN deleted.[RUN_REQ_YN] = 'Y' THEN 'MANUAL' ELSE 'SCHEDULE' END, deleted.[RUN_REQ_ID], deleted.[LAST_HIST_ID], deleted.[RUNNING_YN]
      INTO @CLAIMED
     WHERE [JOB_ID] = @P_JOB_ID
       AND [USE_YN] = 'Y'
       AND ([RUNNING_YN] = 'N' OR [LOCK_DT] < DATEADD(MINUTE, -[TIMEOUT_MIN], @NOW))
       AND ([RUN_REQ_YN] = 'Y' OR [NEXT_RUN_DT] <= @NOW);

    IF EXISTS (SELECT 1 FROM @CLAIMED)
    BEGIN
      UPDATE H
         SET [RESULT_CD] = 'FAILED', [END_DT] = @NOW, [RESULT_MSG] = N'INTERRUPTED'
        FROM [FW].[TB_JOB_HIST] H
        JOIN @CLAIMED C ON C.[PREV_HIST_ID] = H.[HIST_ID] AND C.[WAS_RUNNING] = 'Y'
       WHERE H.[RESULT_CD] = 'RUNNING';

      INSERT INTO [FW].[TB_JOB_HIST] ([JOB_ID], [RUN_TYPE_CD], [RUN_USER_ID], [HOST_NM], [START_DT], [RESULT_CD])
      SELECT @P_JOB_ID, [RUN_TYPE_CD], [RUN_USER_ID], @P_HOST_NM, @NOW, 'RUNNING' FROM @CLAIMED;

      SET @HIST_ID = SCOPE_IDENTITY();

      UPDATE [FW].[TB_JOB] SET [LAST_HIST_ID] = @HIST_ID, [LAST_RUN_DT] = @NOW WHERE [JOB_ID] = @P_JOB_ID;
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @HIST_ID AS [HIST_ID], [RUN_TYPE_CD], [RUN_USER_ID] FROM @CLAIMED WHERE @HIST_ID IS NOT NULL;
END
