-- 송신 대상 목록 (관리 화면). 프로그램: SYS_API_OUTBOUND_MGT
-- 결과셋 1: 대상(키순, 비밀값은 설정 여부만), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_API_OUTBOUND_ADMIN_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT O.[TARGET_KEY], O.[TARGET_NM], O.[BASE_URL], O.[AUTH_TYPE_CD], O.[AUTH_HEADER], O.[AUTH_USER],
         CASE WHEN O.[AUTH_SECRET_ENC] IS NULL THEN 'N' ELSE 'Y' END AS [SECRET_YN],
         O.[TIMEOUT_SEC], O.[RETRY_COUNT], O.[ALLOW_PRIVATE_YN], O.[USE_YN], O.[UPD_ID], O.[UPD_DT], O.[ROW_VER]
    FROM [FW].[TB_API_OUTBOUND] O
   ORDER BY O.[TARGET_KEY];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_API_OUTBOUND];
END
