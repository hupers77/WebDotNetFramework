-- 송신 대상 한 건 (송신 클라이언트용; 암호화된 비밀값 포함이라 화면에서는 부르지 않는다). 없으면 0행
CREATE PROCEDURE [FW].[USP_API_OUTBOUND_GET]
  @P_TARGET_KEY VARCHAR(30),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT [TARGET_KEY], [BASE_URL], [AUTH_TYPE_CD], [AUTH_HEADER], [AUTH_USER], [AUTH_SECRET_ENC],
         [TIMEOUT_SEC], [RETRY_COUNT], [ALLOW_PRIVATE_YN], [USE_YN]
    FROM [FW].[TB_API_OUTBOUND]
   WHERE [TARGET_KEY] = @P_TARGET_KEY;
END
