-- 조회자 목록 (READER_YN 게시판의 관리자 기능). 프로그램: 게시판의 프로그램 (UPDATE는 애플리케이션이 확인)
-- 결과: USER_ID, USER_NM, COMPANY_CD, FIRST_DT, LAST_DT, READ_CNT (처음 본 순서)
CREATE PROCEDURE [FW].[USP_POST_READER_GET_LIST]
  @P_POST_ID     BIGINT,
  @P_BOARD_CD    VARCHAR(30),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_POST] P JOIN [FW].[TB_BOARD] B ON B.[BOARD_CD] = P.[BOARD_CD]
                  WHERE P.[POST_ID] = @P_POST_ID AND P.[BOARD_CD] = @P_BOARD_CD AND P.[DEL_YN] = 'N' AND B.[READER_YN] = 'Y')
    THROW 50004, 'MSG.NOT_FOUND', 1;

  SELECT R.[USER_ID], U.[USER_NM], U.[COMPANY_CD], R.[FIRST_DT], R.[LAST_DT], R.[READ_CNT]
    FROM [FW].[TB_POST_READ] R
    JOIN [FW].[TB_USER] U ON U.[USER_ID] = R.[USER_ID]
   WHERE R.[POST_ID] = @P_POST_ID
   ORDER BY R.[FIRST_DT], R.[USER_ID];
END
