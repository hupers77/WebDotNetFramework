-- 레포트 백그라운드 생성을 요청한다(대기열에 넣는다). 요청자의 회사·유형은 사용자 테이블에서 읽는다.
-- 사용 중인 레포트가 아니면 MSG.NOT_FOUND, 요청자의 진행 중(대기·실행) 요청이 5건이면 RPT.RUN_LIMIT.
-- 프로그램: 레포트 프로그램 (PDF는 PRINT, 엑셀은 EXPORT를 화면이 확인한다)
-- 결과: AFFECTED_CNT, NEW_KEY(RUN_ID)
CREATE PROCEDURE [FW].[USP_REPORT_RUN_SAVE]
  @P_REPORT_ID    VARCHAR(30),
  @P_FORMAT_CD    VARCHAR(5),
  @P_PARAMS_JSON  NVARCHAR(2000),
  @P_REASON       NVARCHAR(200) = NULL,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_USER_ID IS NULL OR @P_FORMAT_CD NOT IN ('PDF', 'EXCEL') OR ISJSON(@P_PARAMS_JSON) = 0
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_REPORT] R JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = R.[REPORT_ID]
                  WHERE R.[REPORT_ID] = @P_REPORT_ID AND R.[USE_YN] = 'Y' AND P.[USE_YN] = 'Y')
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @RUN_ID BIGINT;

  BEGIN TRY
    BEGIN TRAN;

    -- 같은 사용자의 동시 요청이 한도를 넘지 않게 사용자 행을 잠근 채로 센다
    DECLARE @COMPANY_CD VARCHAR(10), @USER_TYPE_CD VARCHAR(10);
    SELECT @COMPANY_CD = [COMPANY_CD], @USER_TYPE_CD = [USER_TYPE_CD]
      FROM [FW].[TB_USER] WITH (UPDLOCK, ROWLOCK)
     WHERE [USER_ID] = @P_USER_ID;

    IF @COMPANY_CD IS NULL
      THROW 50005, 'MSG.INVALID_INPUT', 1;

    IF (SELECT COUNT(*) FROM [FW].[TB_REPORT_RUN] WHERE [REQ_USER_ID] = @P_USER_ID AND [STATUS_CD] IN ('QUEUED', 'RUNNING')) >= 5
      THROW 52004, 'RPT.RUN_LIMIT', 1;

    INSERT INTO [FW].[TB_REPORT_RUN] ([REPORT_ID], [FORMAT_CD], [PARAMS_JSON], [REASON], [REQ_USER_ID], [REQ_COMPANY_CD], [REQ_USER_TYPE_CD], [REQ_LANG_CD])
    VALUES (@P_REPORT_ID, @P_FORMAT_CD, @P_PARAMS_JSON, @P_REASON, @P_USER_ID, @COMPANY_CD, @USER_TYPE_CD, @P_LANG_CD);

    SET @RUN_ID = SCOPE_IDENTITY();
    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT], CAST(@RUN_ID AS VARCHAR(20)) AS [NEW_KEY];
END
