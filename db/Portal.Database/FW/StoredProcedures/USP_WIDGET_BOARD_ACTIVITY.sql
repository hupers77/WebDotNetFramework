-- 위젯 데이터: 최근 30일 게시판별 새 글 수 (막대 차트). 사용자가 읽기(READ) 권한을 가진 사용 중인 게시판만 보인다.
-- 권한 평가 규칙은 UFN_FUNC_USERS·PermissionEvaluator와 같다(유효 역할, SYS_ADMIN, 역할 허용 또는 사용자 GRANT, 사용자 DENY 제외).
-- 글 수는 볼 수 있는 원글만 센다(UFN_POST_VISIBLE, 관리자 아님). 게시판 이름은 화면 언어 → 기본 언어 → 코드 순.
-- 위젯 SP 공통 결과 열: LABEL(게시판 이름), VALUE(글 수), TEXT, LINK(게시판 주소), DT
CREATE PROCEDURE [FW].[USP_WIDGET_BOARD_ACTIVITY]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @ROLES TABLE ([ROLE_ID] VARCHAR(30) NOT NULL PRIMARY KEY);
  INSERT INTO @ROLES ([ROLE_ID]) SELECT DISTINCT [ROLE_ID] FROM [FW].[UFN_USER_ROLES](@P_USER_ID);
  DECLARE @ADMIN BIT = IIF(EXISTS (SELECT 1 FROM @ROLES WHERE [ROLE_ID] = 'SYS_ADMIN'), 1, 0);
  DECLARE @TODAY DATE = CAST(GETDATE() AS DATE);
  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  WITH [READABLE] AS (
    SELECT B.[BOARD_CD], B.[SORT_NO]
      FROM [FW].[TB_BOARD] B
      JOIN [FW].[TB_PROGRAM] PG ON PG.[PROGRAM_ID] = B.[PROGRAM_ID] AND PG.[USE_YN] = 'Y'
     WHERE B.[USE_YN] = 'Y'
       AND EXISTS (SELECT 1 FROM @ROLES)
       AND (@ADMIN = 1
            OR ((EXISTS (SELECT 1 FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF JOIN @ROLES R ON R.[ROLE_ID] = RF.[ROLE_ID]
                          WHERE RF.[PROGRAM_ID] = B.[PROGRAM_ID] AND RF.[FUNC_CD] = 'READ')
                 OR EXISTS (SELECT 1 FROM [FW].[TB_USER_PROGRAM_FUNC] G
                             WHERE G.[USER_ID] = @P_USER_ID AND G.[PROGRAM_ID] = B.[PROGRAM_ID] AND G.[FUNC_CD] = 'READ'
                               AND G.[GRANT_TYPE] = 'GRANT' AND G.[END_DT] >= @TODAY))
                AND NOT EXISTS (SELECT 1 FROM [FW].[TB_USER_PROGRAM_FUNC] D
                                 WHERE D.[USER_ID] = @P_USER_ID AND D.[PROGRAM_ID] = B.[PROGRAM_ID] AND D.[FUNC_CD] = 'READ'
                                   AND D.[GRANT_TYPE] = 'DENY' AND D.[END_DT] >= @TODAY)))
  ),
  [CNT] AS (
    SELECT P.[BOARD_CD], COUNT(*) AS [POST_CNT]
      FROM [FW].[TB_POST] P
      JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, 'N') V ON V.[POST_ID] = P.[POST_ID]
     WHERE P.[ROOT_POST_ID] = P.[POST_ID] AND P.[REG_DT] >= DATEADD(DAY, -30, SYSUTCDATETIME())
     GROUP BY P.[BOARD_CD]
  )
  SELECT CAST(COALESCE(L.[BOARD_NM], DL.[BOARD_NM], R.[BOARD_CD]) AS NVARCHAR(100)) AS [LABEL],
         CAST(ISNULL(C.[POST_CNT], 0) AS DECIMAL(18, 2)) AS [VALUE],
         CAST(NULL AS NVARCHAR(200)) AS [TEXT], CAST('/Board/' + R.[BOARD_CD] AS VARCHAR(200)) AS [LINK], CAST(NULL AS DATETIME2(0)) AS [DT]
    FROM [READABLE] R
    LEFT JOIN [CNT] C ON C.[BOARD_CD] = R.[BOARD_CD]
    LEFT JOIN [FW].[TB_BOARD_LANG] L ON L.[BOARD_CD] = R.[BOARD_CD] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_BOARD_LANG] DL ON DL.[BOARD_CD] = R.[BOARD_CD] AND DL.[LANG_CD] = @DEFAULT_LANG
   ORDER BY R.[SORT_NO], R.[BOARD_CD];
END
