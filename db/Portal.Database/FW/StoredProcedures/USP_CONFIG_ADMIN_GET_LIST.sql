-- 설정 관리 화면 목록 (목록 SP 표준 템플릿). 프로그램: SYS_CONFIG_MGT
-- 결과셋 1: 목록, 결과셋 2: 전체 건수. SECRET 값은 내보내지 않고 입력 여부(SECRET_SET_YN)만 알려 준다.
-- 정렬: 설정 분류 코드(CONFIG_CATEGORY)의 정렬 순서 → 설정 키.
CREATE PROCEDURE [FW].[USP_CONFIG_ADMIN_GET_LIST]
  @P_CATEGORY_CD  VARCHAR(20)   = NULL,
  @P_KEYWORD      NVARCHAR(100) = NULL,
  @P_PAGE_NO      INT           = 1,
  @P_PAGE_SIZE    INT           = 50,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT C.[CONFIG_KEY],
         CASE WHEN C.[ENC_YN] = 'Y' THEN NULL ELSE C.[CONFIG_VAL] END AS [CONFIG_VAL],
         CASE WHEN C.[ENC_YN] = 'Y' AND C.[CONFIG_VAL] IS NOT NULL THEN 'Y' ELSE 'N' END AS [SECRET_SET_YN],
         C.[VAL_TYPE_CD], C.[CATEGORY_CD], C.[DESCRIPTION], C.[RESTART_YN],
         C.[UPD_ID], C.[UPD_DT], C.[ROW_VER]
    FROM [FW].[TB_CONFIG] C
    LEFT JOIN [FW].[TB_CODE] K ON K.[GROUP_CD] = 'CONFIG_CATEGORY' AND K.[CODE] = C.[CATEGORY_CD]
   WHERE (@P_CATEGORY_CD IS NULL OR C.[CATEGORY_CD] = @P_CATEGORY_CD)
     AND (@P_KEYWORD IS NULL OR C.[CONFIG_KEY] LIKE '%' + @P_KEYWORD + '%' OR C.[DESCRIPTION] LIKE '%' + @P_KEYWORD + '%')
   ORDER BY ISNULL(K.[SORT_NO], 2147483647), C.[CONFIG_KEY]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_CONFIG] C
   WHERE (@P_CATEGORY_CD IS NULL OR C.[CATEGORY_CD] = @P_CATEGORY_CD)
     AND (@P_KEYWORD IS NULL OR C.[CONFIG_KEY] LIKE '%' + @P_KEYWORD + '%' OR C.[DESCRIPTION] LIKE '%' + @P_KEYWORD + '%')
  OPTION (RECOMPILE);
END
