-- 배치 작업 설정 저장 (저장 SP 표준 템플릿). 프로그램: SYS_JOB_MGT
-- 작업 추가·삭제와 실행 대상(유형·대상)은 바꾸지 않는다(초기 데이터·배포가 관리). 주기·제한 시간·사용 여부·설명만 바꾼다.
-- 주기 식은 애플리케이션이 검사해서 넘긴다. 주기를 바꾸거나 다시 사용으로 바꾸면 다음 실행 시각을 비워 Worker가 새로 계산하게 한다
-- (멈춰 있던 동안의 예약이 바로 실행되지 않게).
-- 동시성: 조회 때 받은 EDIT_VER와 같아야 한다. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_JOB_SAVE]
  @P_JOB_ID       VARCHAR(30),
  @P_EDIT_VER     INT,
  @P_CRON_EXPR    VARCHAR(100) = NULL,
  @P_TIMEOUT_MIN  INT,
  @P_USE_YN       CHAR(1),
  @P_DESCRIPTION  NVARCHAR(500) = NULL,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_TIMEOUT_MIN NOT BETWEEN 1 AND 1440 OR @P_USE_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @CHANGED TABLE (
    [OLD_CRON] VARCHAR(100), [OLD_TIMEOUT] INT, [OLD_USE_YN] CHAR(1), [OLD_DESC] NVARCHAR(500),
    [NEW_CRON] VARCHAR(100), [NEW_TIMEOUT] INT, [NEW_USE_YN] CHAR(1), [NEW_DESC] NVARCHAR(500));

  BEGIN TRY
    BEGIN TRAN;

    IF NOT EXISTS (SELECT 1 FROM [FW].[TB_JOB] WITH (UPDLOCK) WHERE [JOB_ID] = @P_JOB_ID)
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF NOT EXISTS (SELECT 1 FROM [FW].[TB_JOB] WHERE [JOB_ID] = @P_JOB_ID AND [EDIT_VER] = @P_EDIT_VER)
      THROW 50002, 'MSG.CONCURRENCY', 1;

    UPDATE [FW].[TB_JOB]
       SET [NEXT_RUN_DT] = CASE WHEN ISNULL([CRON_EXPR], '') <> ISNULL(@P_CRON_EXPR, '') OR ([USE_YN] = 'N' AND @P_USE_YN = 'Y') THEN NULL ELSE [NEXT_RUN_DT] END,
           [CRON_EXPR] = @P_CRON_EXPR, [TIMEOUT_MIN] = @P_TIMEOUT_MIN, [USE_YN] = @P_USE_YN, [DESCRIPTION] = @P_DESCRIPTION,
           [EDIT_VER] += 1, [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
    OUTPUT DELETED.[CRON_EXPR], DELETED.[TIMEOUT_MIN], DELETED.[USE_YN], DELETED.[DESCRIPTION],
           INSERTED.[CRON_EXPR], INSERTED.[TIMEOUT_MIN], INSERTED.[USE_YN], INSERTED.[DESCRIPTION]
      INTO @CHANGED
     WHERE [JOB_ID] = @P_JOB_ID;

    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT [OLD_CRON] AS [CRON_EXPR], [OLD_TIMEOUT] AS [TIMEOUT_MIN], [OLD_USE_YN] AS [USE_YN], [OLD_DESC] AS [DESCRIPTION]
                                       FROM @CHANGED FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @AFTER NVARCHAR(MAX) = (SELECT [NEW_CRON] AS [CRON_EXPR], [NEW_TIMEOUT] AS [TIMEOUT_MIN], [NEW_USE_YN] AS [USE_YN], [NEW_DESC] AS [DESCRIPTION]
                                      FROM @CHANGED FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_JOB', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_JOB_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT];
END
