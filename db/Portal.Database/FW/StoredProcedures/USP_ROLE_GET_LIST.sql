-- 역할 목록 (역할 관리 화면과 역할별 권한 화면의 왼쪽 목록). 프로그램: SYS_ROLE_MGT, SYS_ROLE_AUTH_MGT
-- 결과: ROLE_ID, ROLE_NM, DESCRIPTION, COMPANY_TYPE_CD, DATA_SCOPE_CD, SYSTEM_YN, SORT_NO, USE_YN, FUNC_CNT(사용 중 프로그램의 부여 기능 수),
--       USER_CNT(직접 부여한 계정 수), DEPT_CNT(부여한 부서 수), IN_USE_YN(계정·부서·AD 그룹·위임 중 하나라도 부여됨),
--       MY_ROLE_YN(현재 사용자가 지금 가진 역할), UPD_ID, UPD_DT, ROW_VER
CREATE PROCEDURE [FW].[USP_ROLE_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT R.[ROLE_ID], R.[ROLE_NM], R.[DESCRIPTION], R.[COMPANY_TYPE_CD], R.[DATA_SCOPE_CD], R.[SYSTEM_YN], R.[SORT_NO], R.[USE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = RF.[PROGRAM_ID]
           WHERE RF.[ROLE_ID] = R.[ROLE_ID] AND P.[USE_YN] = 'Y') AS [FUNC_CNT],
         (SELECT COUNT(DISTINCT UR.[USER_ID]) FROM [FW].[TB_USER_ROLE] UR WHERE UR.[ROLE_ID] = R.[ROLE_ID]) AS [USER_CNT],
         (SELECT COUNT(DISTINCT DR.[DEPT_ID]) FROM [FW].[TB_DEPT_ROLE] DR WHERE DR.[ROLE_ID] = R.[ROLE_ID]) AS [DEPT_CNT],
         IIF(EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] X WHERE X.[ROLE_ID] = R.[ROLE_ID])
             OR EXISTS (SELECT 1 FROM [FW].[TB_DEPT_ROLE] X WHERE X.[ROLE_ID] = R.[ROLE_ID])
             OR EXISTS (SELECT 1 FROM [FW].[TB_AD_GROUP_ROLE] X WHERE X.[ROLE_ID] = R.[ROLE_ID])
             OR EXISTS (SELECT 1 FROM [FW].[TB_ROLE_DELEGATE] X WHERE X.[ROLE_ID] = R.[ROLE_ID]), 'Y', 'N') AS [IN_USE_YN],
         IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) M WHERE M.[ROLE_ID] = R.[ROLE_ID]), 'Y', 'N') AS [MY_ROLE_YN],
         R.[UPD_ID], R.[UPD_DT], R.[ROW_VER]
    FROM [FW].[TB_ROLE] R
   ORDER BY R.[SORT_NO], R.[ROLE_ID];
END
