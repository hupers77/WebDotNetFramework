-- 역할 목록 (역할별 권한 화면의 왼쪽 목록). 프로그램: SYS_ROLE_AUTH_MGT
-- 결과: ROLE_ID, ROLE_NM, DESCRIPTION, COMPANY_TYPE_CD, DATA_SCOPE_CD, SYSTEM_YN, USE_YN, FUNC_CNT(사용 중 프로그램의 부여 기능 수),
--       MY_ROLE_YN(현재 사용자가 지금 가진 역할), ROW_VER
CREATE PROCEDURE [FW].[USP_ROLE_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT R.[ROLE_ID], R.[ROLE_NM], R.[DESCRIPTION], R.[COMPANY_TYPE_CD], R.[DATA_SCOPE_CD], R.[SYSTEM_YN], R.[USE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = RF.[PROGRAM_ID]
           WHERE RF.[ROLE_ID] = R.[ROLE_ID] AND P.[USE_YN] = 'Y') AS [FUNC_CNT],
         IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) M WHERE M.[ROLE_ID] = R.[ROLE_ID]), 'Y', 'N') AS [MY_ROLE_YN],
         R.[ROW_VER]
    FROM [FW].[TB_ROLE] R
   ORDER BY R.[SORT_NO], R.[ROLE_ID];
END
