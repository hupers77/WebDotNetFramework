-- 협력사 계정 가입 신청 (로그인 전 화면). 비밀번호 규칙·이메일 형식은 애플리케이션이 확인하고 해시·암호문만 넘긴다.
-- 회사는 사업자등록번호로 찾는다: 사용 중이고 계약 기간 안인 협력사 한 곳이어야 한다(없으면 담당 부서에 회사 등록을 요청한다).
-- 희망 ID는 기존 계정, 처리 대기 중인 신청과 겹칠 수 없다(대소문자 구분 없음).
-- 승인 권한(SYS_PARTNER_APPROVE:APPROVE)이 있는 사용자에게 TPL_PARTNER_SIGNUP_REQ 알림(포털·메일)을 같은 트랜잭션으로 보낸다.
-- 결과: AFFECTED_CNT, NEW_KEY(신청 번호)
CREATE PROCEDURE [FW].[USP_PARTNER_JOIN_SAVE]
  @P_BIZ_REG_NO   VARCHAR(20),
  @P_REQ_USER_ID  VARCHAR(30),
  @P_USER_NM      NVARCHAR(100),
  @P_EMAIL_ENC    VARBINARY(512),
  @P_PWD_HASH     VARBINARY(64),
  @P_PWD_SALT     VARBINARY(16),
  @P_USER_ID      VARCHAR(30)   = NULL,
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @BIZ_NO VARCHAR(20) = REPLACE(REPLACE(LTRIM(RTRIM(@P_BIZ_REG_NO)), '-', ''), ' ', '');
  DECLARE @TODAY DATE = CAST(GETDATE() AS DATE);
  DECLARE @COMPANY_CD VARCHAR(10), @COMPANY_CNT INT, @REQ_ID BIGINT;

  IF NULLIF(@BIZ_NO, '') IS NULL OR NULLIF(LTRIM(RTRIM(@P_REQ_USER_ID)), '') IS NULL OR NULLIF(LTRIM(RTRIM(@P_USER_NM)), N'') IS NULL
     OR @P_EMAIL_ENC IS NULL OR DATALENGTH(@P_PWD_HASH) <> 64 OR DATALENGTH(@P_PWD_SALT) <> 16
     OR NOT EXISTS (SELECT 1 FROM [FW].[TB_LANG] WHERE [LANG_CD] = @P_LANG_CD AND [USE_YN] = 'Y')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  SELECT @COMPANY_CD = MIN([COMPANY_CD]), @COMPANY_CNT = COUNT(*)
    FROM [FW].[TB_COMPANY]
   WHERE REPLACE(REPLACE([BIZ_REG_NO], '-', ''), ' ', '') = @BIZ_NO
     AND [COMPANY_TYPE_CD] = 'PARTNER'
     AND [USE_YN] = 'Y'
     AND ([CONTRACT_END_DT] IS NULL OR [CONTRACT_END_DT] >= @TODAY);

  IF @COMPANY_CNT <> 1
    THROW 50005, 'MSG.JOIN_COMPANY_NOT_FOUND', 1;

  BEGIN TRY
    BEGIN TRAN;

    -- 같은 ID로 동시에 들어온 신청이 둘 다 통과하지 않도록 범위 잠금으로 확인한다
    IF EXISTS (SELECT 1 FROM [FW].[TB_USER] WITH (UPDLOCK, HOLDLOCK) WHERE [USER_ID] = LTRIM(RTRIM(@P_REQ_USER_ID)))
       OR EXISTS (SELECT 1 FROM [FW].[TB_PARTNER_JOIN_REQ] WITH (UPDLOCK, HOLDLOCK)
                   WHERE [USER_ID] = LTRIM(RTRIM(@P_REQ_USER_ID)) AND [REQ_STAT_CD] = 'REQUESTED')
      THROW 50001, 'MSG.JOIN_ID_TAKEN', 1;

    INSERT INTO [FW].[TB_PARTNER_JOIN_REQ]
      ([COMPANY_CD], [USER_ID], [USER_NM], [EMAIL_ENC], [LANG_CD], [PWD_HASH], [PWD_SALT], [REG_ID], [UPD_ID])
    VALUES
      (@COMPANY_CD, LTRIM(RTRIM(@P_REQ_USER_ID)), LTRIM(RTRIM(@P_USER_NM)), @P_EMAIL_ENC, @P_LANG_CD, @P_PWD_HASH, @P_PWD_SALT,
       LTRIM(RTRIM(@P_REQ_USER_ID)), LTRIM(RTRIM(@P_REQ_USER_ID)));
    SET @REQ_ID = SCOPE_IDENTITY();

    -- 감사 로그에는 이메일·비밀번호를 남기지 않는다
    DECLARE @AFTER NVARCHAR(MAX) = (SELECT @REQ_ID AS [REQ_ID], @COMPANY_CD AS [COMPANY_CD], LTRIM(RTRIM(@P_REQ_USER_ID)) AS [USER_ID],
                                           'REQUESTED' AS [REQ_STAT_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    DECLARE @ROW_KEY NVARCHAR(200) = CAST(@REQ_ID AS NVARCHAR(20));
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_PARTNER_JOIN_REQ', @P_ACTION_CD = 'I', @P_ROW_KEY = @ROW_KEY,
      @P_BEFORE_JSON = NULL, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = NULL, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    -- 승인 담당자 알림 (신청자 이름·이메일은 넣지 않는다)
    DECLARE @PARAMS NVARCHAR(4000) = (SELECT C.[COMPANY_NM], LTRIM(RTRIM(@P_REQ_USER_ID)) AS [USER_ID]
                                        FROM [FW].[TB_COMPANY] C WHERE C.[COMPANY_CD] = @COMPANY_CD
                                         FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    DECLARE @TO_USER_ID VARCHAR(30);
    DECLARE APPROVERS CURSOR LOCAL FAST_FORWARD FOR
      SELECT [USER_ID] FROM [FW].[UFN_FUNC_USERS]('SYS_PARTNER_APPROVE', 'APPROVE');
    OPEN APPROVERS;
    FETCH NEXT FROM APPROVERS INTO @TO_USER_ID;
    WHILE @@FETCH_STATUS = 0
    BEGIN
      EXEC [FW].[USP_MSG_QUEUE_SAVE] @P_TEMPLATE_ID = 'TPL_PARTNER_SIGNUP_REQ', @P_TO_USER_ID = @TO_USER_ID, @P_PARAMS_JSON = @PARAMS,
           @P_RESULT_YN = 'N', @P_USER_ID = NULL, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
      FETCH NEXT FROM APPROVERS INTO @TO_USER_ID;
    END
    CLOSE APPROVERS;
    DEALLOCATE APPROVERS;

    COMMIT;

    SELECT 1 AS [AFFECTED_CNT], CAST(@REQ_ID AS VARCHAR(20)) AS [NEW_KEY];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
