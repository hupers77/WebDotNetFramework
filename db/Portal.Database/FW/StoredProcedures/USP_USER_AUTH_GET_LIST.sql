-- 사용자 한 명의 예외 권한 (사용자별 예외 권한 화면). 프로그램: SYS_USER_AUTH_MGT
-- 대상은 현재 사용자의 데이터 범위(UFN_DATA_SCOPE) 안이어야 한다(밖이면 결과 1이 0행).
-- 결과 1: USER_ID, USER_NM, COMPANY_NM, COMPANY_TYPE_CD, USER_STAT_CD, SYS_ADMIN_YN(대상이 시스템 관리자), SELF_YN(대상이 나), VERSION(동시성 확인용)
-- 결과 2: 사용 중인 프로그램 × 프로그램이 쓰는 기능마다 PROGRAM_ID, PROGRAM_NM, OPEN_SCOPE_CD, GRANTABLE_YN(대상 회사 유형에 열린 화면),
--         FUNC_CD, ROLE_YN(대상의 유효 역할이 이미 허용), GRANT_TYPE(GRANT/DENY/NULL), END_DT
CREATE PROCEDURE [FW].[USP_USER_AUTH_GET_LIST]
  @P_TARGET_USER_ID  VARCHAR(30),
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @COMPANY_TYPE VARCHAR(10);
  SELECT @COMPANY_TYPE = C.[COMPANY_TYPE_CD]
    FROM [FW].[TB_USER] U
    JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
   WHERE U.[USER_ID] = @P_TARGET_USER_ID
     AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'SYS_USER_AUTH_MGT') S
                 WHERE S.[COMPANY_CD] = U.[COMPANY_CD] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID]));

  SELECT U.[USER_ID], U.[USER_NM], C.[COMPANY_NM], C.[COMPANY_TYPE_CD], U.[USER_STAT_CD],
         IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](U.[USER_ID]) R WHERE R.[ROLE_ID] = 'SYS_ADMIN')
             OR EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] R WHERE R.[USER_ID] = U.[USER_ID] AND R.[ROLE_ID] = 'SYS_ADMIN'), 'Y', 'N') AS [SYS_ADMIN_YN],
         IIF(U.[USER_ID] = @P_USER_ID, 'Y', 'N') AS [SELF_YN],
         V.[VERSION]
    FROM [FW].[TB_USER] U
    JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
   CROSS APPLY [FW].[UFN_USER_AUTH_VERSION](U.[USER_ID]) V
   WHERE U.[USER_ID] = @P_TARGET_USER_ID AND @COMPANY_TYPE IS NOT NULL;

  SELECT P.[PROGRAM_ID], P.[PROGRAM_NM], S.[OPEN_SCOPE_CD],
         IIF(S.[OPEN_SCOPE_CD] = 'ALL' OR (@COMPANY_TYPE = 'HQ' AND S.[OPEN_SCOPE_CD] = 'EMP')
             OR (@COMPANY_TYPE = 'PARTNER' AND S.[OPEN_SCOPE_CD] = 'PARTNER'), 'Y', 'N') AS [GRANTABLE_YN],
         F.[FUNC_CD],
         IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_TARGET_USER_ID) R
                       JOIN [FW].[TB_ROLE_PROGRAM_FUNC] RF ON RF.[ROLE_ID] = R.[ROLE_ID]
                      WHERE RF.[PROGRAM_ID] = F.[PROGRAM_ID] AND RF.[FUNC_CD] = F.[FUNC_CD]), 'Y', 'N') AS [ROLE_YN],
         UF.[GRANT_TYPE], UF.[END_DT]
    FROM [FW].[TB_PROGRAM_FUNC] F
    JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = F.[PROGRAM_ID]
    JOIN [FW].[UFN_PROGRAM_SCOPE]() S ON S.[PROGRAM_ID] = P.[PROGRAM_ID]
    LEFT JOIN [FW].[TB_CODE] C ON C.[GROUP_CD] = 'FUNC_CD' AND C.[CODE] = F.[FUNC_CD]
    LEFT JOIN [FW].[TB_USER_PROGRAM_FUNC] UF ON UF.[USER_ID] = @P_TARGET_USER_ID AND UF.[PROGRAM_ID] = F.[PROGRAM_ID] AND UF.[FUNC_CD] = F.[FUNC_CD]
   WHERE P.[USE_YN] = 'Y' AND @COMPANY_TYPE IS NOT NULL
   ORDER BY P.[MODULE_CD], P.[PROGRAM_ID], ISNULL(C.[SORT_NO], 9999), F.[FUNC_CD];
END
