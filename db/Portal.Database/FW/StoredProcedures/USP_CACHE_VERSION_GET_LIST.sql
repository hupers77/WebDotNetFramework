-- 캐시 버전 목록. 웹서버가 주기적으로(기본 5초) 호출해 바뀐 키의 메모리 캐시를 비운다.
CREATE PROCEDURE [FW].[USP_CACHE_VERSION_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT [CACHE_KEY], [VERSION_NO]
    FROM [FW].[TB_CACHE_VERSION]
   ORDER BY [CACHE_KEY];
END
