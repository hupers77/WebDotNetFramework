-- 2단계 인증 이메일 인증번호 발급(저장). 번호는 애플리케이션이 만들어 해시만 넘기고, 메일은 애플리케이션이 보낸다.
-- 로그인 도중이라 @P_USER_ID는 비어 있고 대상은 @P_LOGIN_USER_ID로 받는다.
-- 제한: 직전 발송 후 60초 이내 → 52006(AUTH.OTP_TOO_SOON), 1시간에 5통 초과 → 52007(AUTH.OTP_LIMIT).
-- 사용 중인 계정이 아니거나 이메일이 없으면 50004(MSG.NOT_FOUND). 유효 시간은 5분, 입력 횟수는 새로 센다.
-- 결과: EMAIL_ENC(받는 사람, 암호문), LANG_CD
CREATE PROCEDURE [FW].[USP_AUTH_OTP_ISSUE_EXEC]
  @P_LOGIN_USER_ID VARCHAR(30),
  @P_CODE_HASH     BINARY(32),
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_CODE_HASH IS NULL
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @EMAIL_ENC VARBINARY(512), @LANG VARCHAR(5);

  SELECT @EMAIL_ENC = [EMAIL_ENC], @LANG = [LANG_CD]
    FROM [FW].[TB_USER]
   WHERE [USER_ID] = @P_LOGIN_USER_ID AND [USER_STAT_CD] = 'ACTIVE';

  IF @EMAIL_ENC IS NULL
    THROW 50004, 'MSG.NOT_FOUND', 1;

  BEGIN TRY
    BEGIN TRAN;

    DECLARE @SEND_DT DATETIME2(0), @WINDOW_DT DATETIME2(0), @SEND_CNT SMALLINT;
    SELECT @SEND_DT = [SEND_DT], @WINDOW_DT = [WINDOW_DT], @SEND_CNT = [SEND_CNT]
      FROM [FW].[TB_AUTH_OTP] WITH (UPDLOCK, HOLDLOCK)
     WHERE [USER_ID] = @P_LOGIN_USER_ID;

    IF @SEND_DT IS NULL
    BEGIN
      INSERT INTO [FW].[TB_AUTH_OTP] ([USER_ID], [CODE_HASH], [EXPIRE_DT], [TRY_CNT], [SEND_CNT], [WINDOW_DT], [SEND_DT])
      VALUES (@P_LOGIN_USER_ID, @P_CODE_HASH, DATEADD(MINUTE, 5, @NOW), 0, 1, @NOW, @NOW);
    END
    ELSE
    BEGIN
      IF @SEND_DT > DATEADD(SECOND, -60, @NOW)
        THROW 52006, 'AUTH.OTP_TOO_SOON', 1;

      IF @WINDOW_DT <= DATEADD(HOUR, -1, @NOW)
        SELECT @WINDOW_DT = @NOW, @SEND_CNT = 0;

      IF @SEND_CNT >= 5
        THROW 52007, 'AUTH.OTP_LIMIT', 1;

      UPDATE [FW].[TB_AUTH_OTP]
         SET [CODE_HASH] = @P_CODE_HASH, [EXPIRE_DT] = DATEADD(MINUTE, 5, @NOW), [TRY_CNT] = 0,
             [SEND_CNT] = @SEND_CNT + 1, [WINDOW_DT] = @WINDOW_DT, [SEND_DT] = @NOW
       WHERE [USER_ID] = @P_LOGIN_USER_ID;
    END

    COMMIT;

    SELECT @EMAIL_ENC AS [EMAIL_ENC], @LANG AS [LANG_CD];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
