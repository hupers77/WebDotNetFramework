-- 운영 모니터링 (읽기 전용 현황 한 번에). 프로그램: SYS_MONITOR_INQ
-- 로그 테이블은 최근 24시간(파티션 키 LOG_DT 조건)만 읽어 운영 부하를 주지 않는다. 개인정보(이메일 등)는 돌려주지 않는다.
-- 결과셋 1: 요약 한 행(DB 시각, 접속 중 세션 수, 잠긴 계정 수, 24시간 로그인 실패·오류 건수)
-- 결과셋 2: 캐시 버전, 결과셋 3: 배치 작업 상태, 결과셋 4: 메일 대기열 상태별 건수, 결과셋 5: 레포트 요청 상태별 건수, 결과셋 6: 최근 오류 20건
CREATE PROCEDURE [FW].[USP_MONITOR_GET]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @FROM DATETIME2(3) = DATEADD(HOUR, -24, @NOW);
  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  SELECT @NOW AS [DB_DT],
         (SELECT COUNT(*) FROM [FW].[TB_USER_SESSION] WHERE [END_DT] IS NULL AND [EXPIRE_DT] > @NOW) AS [SESSION_CNT],
         (SELECT COUNT(*) FROM [FW].[TB_USER] WHERE [LOCK_YN] = 'Y') AS [LOCKED_CNT],
         (SELECT COUNT(*) FROM [LOG].[TB_LOGIN_LOG] WHERE [LOG_DT] >= @FROM AND [LOGIN_RESULT_CD] LIKE 'FAIL[_]%') AS [LOGIN_FAIL_CNT],
         (SELECT COUNT(*) FROM [LOG].[TB_ERROR_LOG] WHERE [LOG_DT] >= @FROM) AS [ERROR_CNT];

  SELECT [CACHE_KEY], [VERSION_NO], [UPD_DT] FROM [FW].[TB_CACHE_VERSION] ORDER BY [CACHE_KEY];

  SELECT J.[JOB_ID], J.[JOB_NM], J.[USE_YN], J.[RUNNING_YN], J.[LAST_RUN_DT], J.[LAST_RESULT_CD],
         COALESCE(RL.[CODE_NM], RD.[CODE_NM], J.[LAST_RESULT_CD]) AS [LAST_RESULT_NM], J.[NEXT_RUN_DT],
         IIF(J.[USE_YN] = 'Y' AND J.[RUNNING_YN] = 'N' AND J.[NEXT_RUN_DT] < DATEADD(MINUTE, -10, @NOW), 'Y', 'N') AS [OVERDUE_YN],
         IIF(J.[RUNNING_YN] = 'Y' AND J.[LAST_RUN_DT] < DATEADD(MINUTE, -J.[TIMEOUT_MIN], @NOW), 'Y', 'N') AS [STUCK_YN]
    FROM [FW].[TB_JOB] J
    LEFT JOIN [FW].[TB_CODE_LANG] RL ON RL.[GROUP_CD] = 'JOB_STAT' AND RL.[CODE] = J.[LAST_RESULT_CD] AND RL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] RD ON RD.[GROUP_CD] = 'JOB_STAT' AND RD.[CODE] = J.[LAST_RESULT_CD] AND RD.[LANG_CD] = @DEFAULT_LANG
   ORDER BY J.[JOB_ID];

  SELECT Q.[STAT_CD], COUNT(*) AS [CNT], MIN(Q.[REG_DT]) AS [OLDEST_DT]
    FROM [FW].[TB_MSG_QUEUE] Q
   WHERE Q.[STAT_CD] IN ('READY', 'SENDING', 'FAILED') OR Q.[UPD_DT] >= @FROM
   GROUP BY Q.[STAT_CD]
   ORDER BY Q.[STAT_CD];

  SELECT R.[STATUS_CD], COUNT(*) AS [CNT], MIN(R.[REG_DT]) AS [OLDEST_DT]
    FROM [FW].[TB_REPORT_RUN] R
   WHERE R.[STATUS_CD] IN ('QUEUED', 'RUNNING') OR R.[REG_DT] >= @FROM
   GROUP BY R.[STATUS_CD]
   ORDER BY R.[STATUS_CD];

  SELECT TOP (20) E.[LOG_DT], E.[TRACE_ID], E.[USER_ID], E.[REQUEST_PATH], E.[SOURCE], LEFT(E.[MESSAGE], 300) AS [MESSAGE]
    FROM [LOG].[TB_ERROR_LOG] E
   WHERE E.[LOG_DT] >= @FROM
   ORDER BY E.[LOG_DT] DESC, E.[LOG_ID] DESC;
END
