-- 프로그램 삭제 (삭제 SP 표준 템플릿). 프로그램: SYS_PROGRAM_MGT
-- 잘못 등록한 프로그램만 지운다. 서버 경로(TB_PROGRAM_API)·메뉴·첨부 파일·메시지 템플릿이 하나라도 연결된 프로그램은 지우지 않는다
-- (코드가 쓰는 프로그램은 사용 안 함으로 바꾼다). 기능과 그 역할·사용자 예외 권한도 함께 지운다. 감사 로그를 남기고 권한 캐시(AUTH)를 올린다.
-- 결과: AFFECTED_CNT(프로그램 1 + 지운 기능 수)
CREATE PROCEDURE [FW].[USP_PROGRAM_DEL]
  @P_PROGRAM_ID  VARCHAR(30),
  @P_ROW_VER     BINARY(8),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @VER BINARY(8), @CNT INT = 1;

  BEGIN TRY
    BEGIN TRAN;

    SELECT @VER = [ROW_VER] FROM [FW].[TB_PROGRAM] WITH (UPDLOCK, HOLDLOCK) WHERE [PROGRAM_ID] = @P_PROGRAM_ID;

    IF @VER IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM_API] WHERE [PROGRAM_ID] = @P_PROGRAM_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_MENU] WHERE [PROGRAM_ID] = @P_PROGRAM_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_FILE_GROUP] WHERE [PROGRAM_ID] = @P_PROGRAM_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_MSG_TEMPLATE] WHERE [LINK_PROGRAM_ID] = @P_PROGRAM_ID)
      THROW 50003, 'MSG.PROGRAM_IN_USE', 1;

    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT P.[PROGRAM_ID], P.[MODULE_CD], P.[PROGRAM_NM], P.[URL], P.[PII_YN], P.[USE_YN],
                                            JSON_QUERY('[' + ISNULL((SELECT STRING_AGG(CAST('"' + F.[FUNC_CD] + '"' AS NVARCHAR(MAX)), ',') WITHIN GROUP (ORDER BY F.[FUNC_CD])
                                                                       FROM [FW].[TB_PROGRAM_FUNC] F WHERE F.[PROGRAM_ID] = P.[PROGRAM_ID]), '') + ']') AS [FUNCS]
                                       FROM [FW].[TB_PROGRAM] P WHERE P.[PROGRAM_ID] = @P_PROGRAM_ID
                                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @GRANTS NVARCHAR(MAX) = (SELECT '[' + STRING_AGG(CAST('"' + [ROLE_ID] + ':' + [FUNC_CD] + '"' AS NVARCHAR(MAX)), ',') WITHIN GROUP (ORDER BY [ROLE_ID], [FUNC_CD]) + ']'
                                       FROM [FW].[TB_ROLE_PROGRAM_FUNC] WHERE [PROGRAM_ID] = @P_PROGRAM_ID);

    DELETE FROM [FW].[TB_ROLE_PROGRAM_FUNC] WHERE [PROGRAM_ID] = @P_PROGRAM_ID;
    DELETE FROM [FW].[TB_USER_PROGRAM_FUNC] WHERE [PROGRAM_ID] = @P_PROGRAM_ID;
    DELETE FROM [FW].[TB_PROGRAM_FUNC] WHERE [PROGRAM_ID] = @P_PROGRAM_ID;
    SET @CNT += @@ROWCOUNT;
    DELETE FROM [FW].[TB_PROGRAM] WHERE [PROGRAM_ID] = @P_PROGRAM_ID;

    IF @GRANTS IS NOT NULL
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_ROLE_PROGRAM_FUNC', @P_ACTION_CD = 'D', @P_ROW_KEY = @P_PROGRAM_ID,
        @P_BEFORE_JSON = @GRANTS, @P_AFTER_JSON = NULL,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_PROGRAM', @P_ACTION_CD = 'D', @P_ROW_KEY = @P_PROGRAM_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = NULL,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    UPDATE [FW].[TB_CACHE_VERSION] SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME() WHERE [CACHE_KEY] = 'AUTH';

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT];
END
