-- 내 레포트 생성 요청 목록 (최근 것부터 최대 50건). 지운(EXPIRE_DT가 지난) 요청은 보이지 않는다. 다른 사람의 요청은 보이지 않는다(@P_USER_ID 기준).
-- 프로그램: RPT_RUNS (READ)
CREATE PROCEDURE [FW].[USP_REPORT_RUN_GET_LIST]
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT TOP (50) [RUN_ID], [REPORT_ID], [FORMAT_CD], [STATUS_CD], [ROW_CNT], [FILE_NM], [FILE_SIZE], [ERR_KEY], [ERR_ARG], [REG_DT], [END_DT], [EXPIRE_DT]
    FROM [FW].[TB_REPORT_RUN]
   WHERE [REQ_USER_ID] = @P_USER_ID
     AND ([EXPIRE_DT] IS NULL OR [EXPIRE_DT] > SYSUTCDATETIME())
   ORDER BY [RUN_ID] DESC;
END
