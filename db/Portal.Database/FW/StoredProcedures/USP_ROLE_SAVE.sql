-- 역할 등록·수정 (저장 SP 표준 템플릿). 프로그램: SYS_ROLE_MGT
-- @P_ROW_VER가 NULL이면 등록, 있으면 수정. 역할 ID는 영문 대문자로 시작하는 대문자·숫자·밑줄 2~30자이고 바꿀 수 없다.
-- 규칙: 협력사 역할(COMPANY_TYPE_CD = PARTNER)은 데이터 범위를 전체로 둘 수 없다(협력사는 최대 소속 회사).
--       SYS_ADMIN 역할은 SYS_ADMIN만 고치고, 데이터 범위 전체·본사·사용은 바꿀 수 없다.
--       시스템 역할(SYSTEM_YN = Y)은 사용 안 함으로 바꾸거나 회사 유형을 바꿀 수 없다(코드와 초기 데이터가 쓴다).
--       자기가 가진 역할은 SYS_ADMIN만 고친다(스스로 데이터 범위 넓히기 방지).
--       계정·부서·AD 그룹·위임에 부여됐거나 기능 권한이 있는 역할은 회사 유형을 바꿀 수 없다(부여 규칙이 어긋나므로).
-- 수정하면 권한 캐시(AUTH)를 올린다. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT, NEW_KEY(역할 ID)
CREATE PROCEDURE [FW].[USP_ROLE_SAVE]
  @P_ROLE_ID          VARCHAR(30),
  @P_ROW_VER          BINARY(8)      = NULL,
  @P_ROLE_NM          NVARCHAR(100),
  @P_DESCRIPTION      NVARCHAR(500)  = NULL,
  @P_COMPANY_TYPE_CD  VARCHAR(10)    = NULL,
  @P_DATA_SCOPE_CD    VARCHAR(10),
  @P_SORT_NO          INT            = 0,
  @P_USE_YN           CHAR(1),
  @P_USER_ID          VARCHAR(30),
  @P_LANG_CD          VARCHAR(5),
  @P_CLIENT_IP        VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_ROLE_ID = LTRIM(RTRIM(@P_ROLE_ID));
  SET @P_ROLE_NM = NULLIF(LTRIM(RTRIM(@P_ROLE_NM)), N'');
  SET @P_DESCRIPTION = NULLIF(LTRIM(RTRIM(@P_DESCRIPTION)), N'');
  SET @P_COMPANY_TYPE_CD = NULLIF(@P_COMPANY_TYPE_CD, '');

  -- 입력 검증 (트랜잭션 전)
  IF @P_ROLE_ID IS NULL OR LEN(@P_ROLE_ID) < 2
     OR @P_ROLE_ID COLLATE Latin1_General_BIN LIKE '%[^A-Z0-9_]%' OR LEFT(@P_ROLE_ID, 1) COLLATE Latin1_General_BIN NOT LIKE '[A-Z]'
     OR @P_ROLE_NM IS NULL
     OR (@P_COMPANY_TYPE_CD IS NOT NULL AND @P_COMPANY_TYPE_CD NOT IN ('HQ', 'PARTNER'))
     OR @P_DATA_SCOPE_CD NOT IN ('ALL', 'COMPANY', 'DEPT_SUB', 'DEPT', 'SELF')
     OR @P_USE_YN NOT IN ('Y', 'N') OR @P_SORT_NO < 0
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF @P_COMPANY_TYPE_CD = 'PARTNER' AND @P_DATA_SCOPE_CD = 'ALL'
    THROW 50003, 'MSG.ROLE_PARTNER_SCOPE', 1;

  DECLARE @CALLER_SYS_ADMIN BIT = IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) WHERE [ROLE_ID] = 'SYS_ADMIN'), 1, 0);
  DECLARE @OLD_VER BINARY(8), @OLD_TYPE VARCHAR(10), @SYSTEM_YN CHAR(1);
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF @P_ROW_VER IS NULL
    BEGIN
      IF EXISTS (SELECT 1 FROM [FW].[TB_ROLE] WITH (UPDLOCK, HOLDLOCK) WHERE [ROLE_ID] = @P_ROLE_ID)
        THROW 50001, 'MSG.DUP_CODE', 1;

      INSERT INTO [FW].[TB_ROLE]
        ([ROLE_ID], [ROLE_NM], [DATA_SCOPE_CD], [DESCRIPTION], [COMPANY_TYPE_CD], [SYSTEM_YN], [SORT_NO], [USE_YN], [REG_ID], [UPD_ID])
      VALUES
        (@P_ROLE_ID, @P_ROLE_NM, @P_DATA_SCOPE_CD, @P_DESCRIPTION, @P_COMPANY_TYPE_CD, 'N', @P_SORT_NO, @P_USE_YN, @P_USER_ID, @P_USER_ID);
    END
    ELSE
    BEGIN
      SELECT @OLD_VER = [ROW_VER], @OLD_TYPE = ISNULL([COMPANY_TYPE_CD], '*'), @SYSTEM_YN = [SYSTEM_YN]
        FROM [FW].[TB_ROLE] WITH (UPDLOCK, HOLDLOCK)
       WHERE [ROLE_ID] = @P_ROLE_ID;

      IF @OLD_VER IS NULL
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @OLD_VER <> @P_ROW_VER
        THROW 50002, 'MSG.CONCURRENCY', 1;
      IF @P_ROLE_ID = 'SYS_ADMIN'
         AND (@CALLER_SYS_ADMIN = 0 OR @P_DATA_SCOPE_CD <> 'ALL' OR ISNULL(@P_COMPANY_TYPE_CD, '*') <> 'HQ' OR @P_USE_YN <> 'Y')
        THROW 50003, 'MSG.ROLE_SYS_ADMIN', 1;
      IF @SYSTEM_YN = 'Y' AND (@P_USE_YN <> 'Y' OR ISNULL(@P_COMPANY_TYPE_CD, '*') <> @OLD_TYPE)
        THROW 50003, 'MSG.ROLE_SYSTEM', 1;
      IF @CALLER_SYS_ADMIN = 0 AND EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) M WHERE M.[ROLE_ID] = @P_ROLE_ID)
        THROW 50003, 'MSG.ROLE_SELF', 1;
      IF ISNULL(@P_COMPANY_TYPE_CD, '*') <> @OLD_TYPE
         AND (EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID)
              OR EXISTS (SELECT 1 FROM [FW].[TB_DEPT_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID)
              OR EXISTS (SELECT 1 FROM [FW].[TB_AD_GROUP_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID)
              OR EXISTS (SELECT 1 FROM [FW].[TB_ROLE_DELEGATE] WHERE [ROLE_ID] = @P_ROLE_ID)
              OR EXISTS (SELECT 1 FROM [FW].[TB_ROLE_PROGRAM_FUNC] WHERE [ROLE_ID] = @P_ROLE_ID))
        THROW 50003, 'MSG.ROLE_TYPE_FIXED', 1;

      SET @BEFORE = (SELECT [ROLE_NM], [DESCRIPTION], [COMPANY_TYPE_CD], [DATA_SCOPE_CD], [SORT_NO], [USE_YN]
                       FROM [FW].[TB_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID
                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);

      UPDATE [FW].[TB_ROLE]
         SET [ROLE_NM] = @P_ROLE_NM, [DESCRIPTION] = @P_DESCRIPTION, [COMPANY_TYPE_CD] = @P_COMPANY_TYPE_CD,
             [DATA_SCOPE_CD] = @P_DATA_SCOPE_CD, [SORT_NO] = @P_SORT_NO, [USE_YN] = @P_USE_YN,
             [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
       WHERE [ROLE_ID] = @P_ROLE_ID;

      -- 데이터 범위·사용 여부가 권한 계산에 들어가므로 캐시를 새로 읽게 한다
      UPDATE [FW].[TB_CACHE_VERSION] SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME() WHERE [CACHE_KEY] = 'AUTH';
    END

    SET @AFTER = (SELECT [ROLE_ID], [ROLE_NM], [DESCRIPTION], [COMPANY_TYPE_CD], [DATA_SCOPE_CD], [SYSTEM_YN], [SORT_NO], [USE_YN]
                    FROM [FW].[TB_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID
                    FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @ACTION CHAR(1) = IIF(@P_ROW_VER IS NULL, 'I', 'U');
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_ROLE', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @P_ROLE_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT], @P_ROLE_ID AS [NEW_KEY];
END
