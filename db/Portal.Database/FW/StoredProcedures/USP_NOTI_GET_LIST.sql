-- 내 알림 목록 (최근 것부터). 프로그램: MY_NOTIFICATION. 다른 사람의 알림은 보이지 않는다(@P_USER_ID 기준).
-- 제목·본문은 지금 화면 언어의 템플릿 문구를 주고(없으면 기본 언어), 치환은 애플리케이션이 한다.
-- 누르면 여는 화면(LINK_URL)은 템플릿의 LINK_PROGRAM_ID가 사용 중일 때만 준다.
-- 결과셋 1: 목록, 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_NOTI_GET_LIST]
  @P_UNREAD_YN    CHAR(1)       = 'N',              -- Y면 안 읽은 알림만
  @P_PAGE_NO      INT           = 1,
  @P_PAGE_SIZE    INT           = 20,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 100 THEN 100 ELSE @P_PAGE_SIZE END;

  SELECT N.[NOTI_ID], N.[TEMPLATE_ID], N.[PARAMS_JSON], N.[REG_DT], N.[READ_DT],
         IIF(N.[READ_DT] IS NULL, 'N', 'Y') AS [READ_YN],
         COALESCE(L.[SUBJECT], D.[SUBJECT], T.[TEMPLATE_NM]) AS [SUBJECT], COALESCE(L.[BODY], D.[BODY], N'') AS [BODY],
         P.[PROGRAM_ID] AS [LINK_PROGRAM_ID], P.[URL] AS [LINK_URL]
    FROM [FW].[TB_NOTIFICATION] N
    JOIN [FW].[TB_MSG_TEMPLATE] T ON T.[TEMPLATE_ID] = N.[TEMPLATE_ID]
    LEFT JOIN [FW].[TB_MSG_TEMPLATE_LANG] L ON L.[TEMPLATE_ID] = N.[TEMPLATE_ID] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_MSG_TEMPLATE_LANG] D ON D.[TEMPLATE_ID] = N.[TEMPLATE_ID] AND D.[LANG_CD] = @DEFAULT_LANG
    LEFT JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = T.[LINK_PROGRAM_ID] AND P.[USE_YN] = 'Y'
   WHERE N.[USER_ID] = @P_USER_ID
     AND (@P_UNREAD_YN <> 'Y' OR N.[READ_DT] IS NULL)
   ORDER BY N.[NOTI_ID] DESC
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY;

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_NOTIFICATION]
   WHERE [USER_ID] = @P_USER_ID
     AND (@P_UNREAD_YN <> 'Y' OR [READ_DT] IS NULL);
END
