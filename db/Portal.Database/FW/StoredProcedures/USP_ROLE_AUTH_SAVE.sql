-- 역할 한 개의 기능 권한을 통째로 저장 (화면의 체크 상태 그대로). 프로그램: SYS_ROLE_AUTH_MGT
-- @P_FUNCS: [{"programId":"SYS_USER_MGT","funcCd":"READ"}, ...] 사용 중인 프로그램의 부여할 기능 전부. 사용 안 함 프로그램의 권한은 건드리지 않는다.
-- 규칙: SYS_ADMIN 역할은 코드에서 전부 허용하므로 고치지 않는다. 자기가 가진 역할은 SYS_ADMIN만 고친다(스스로 권한 올리기 방지).
--       조회(READ) 없이 다른 기능만 줄 수 없다. 새로 주는 권한은 역할의 회사 유형에 맞는 프로그램이어야 한다(UFN_PROGRAM_SCOPE).
-- 바뀐 것이 있으면 감사 로그(전후 기능 목록)를 남기고 역할 ROW_VER와 권한 캐시(AUTH)를 올린다.
-- 결과: AFFECTED_CNT(추가+삭제 건수)
CREATE PROCEDURE [FW].[USP_ROLE_AUTH_SAVE]
  @P_ROLE_ID    VARCHAR(30),
  @P_ROW_VER    BINARY(8),
  @P_FUNCS      NVARCHAR(MAX),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_ROW_VER IS NULL OR @P_FUNCS IS NULL OR ISJSON(@P_FUNCS) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NEW TABLE ([PROGRAM_ID] VARCHAR(30) NOT NULL, [FUNC_CD] VARCHAR(20) NOT NULL, PRIMARY KEY ([PROGRAM_ID], [FUNC_CD]));
  BEGIN TRY
    INSERT INTO @NEW ([PROGRAM_ID], [FUNC_CD])
    SELECT [programId], [funcCd]
      FROM OPENJSON(@P_FUNCS) WITH ([programId] VARCHAR(30) '$.programId', [funcCd] VARCHAR(20) '$.funcCd');
  END TRY
  BEGIN CATCH
    THROW 50005, 'MSG.INVALID_INPUT', 1; -- 같은 기능이 두 번 오거나 값이 비었을 때
  END CATCH;

  -- 프로그램이 쓰는 기능이고 사용 중인 프로그램이어야 한다
  IF EXISTS (SELECT 1 FROM @NEW N
              WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM_FUNC] F JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = F.[PROGRAM_ID]
                                 WHERE F.[PROGRAM_ID] = N.[PROGRAM_ID] AND F.[FUNC_CD] = N.[FUNC_CD] AND P.[USE_YN] = 'Y'))
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  IF EXISTS (SELECT 1 FROM @NEW N WHERE N.[FUNC_CD] <> 'READ'
                AND NOT EXISTS (SELECT 1 FROM @NEW R WHERE R.[PROGRAM_ID] = N.[PROGRAM_ID] AND R.[FUNC_CD] = 'READ'))
    THROW 50003, 'MSG.ROLE_AUTH_READ_REQUIRED', 1;

  BEGIN TRY
    BEGIN TRAN;

    DECLARE @OLD_VER BINARY(8), @COMPANY_TYPE VARCHAR(10);
    SELECT @OLD_VER = [ROW_VER], @COMPANY_TYPE = ISNULL([COMPANY_TYPE_CD], '*')
      FROM [FW].[TB_ROLE] WITH (UPDLOCK, HOLDLOCK)
     WHERE [ROLE_ID] = @P_ROLE_ID;

    IF @OLD_VER IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @OLD_VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @P_ROLE_ID = 'SYS_ADMIN'
      THROW 50003, 'MSG.ROLE_AUTH_SYS_ADMIN', 1;
    IF EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) M WHERE M.[ROLE_ID] = @P_ROLE_ID)
       AND NOT EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) M WHERE M.[ROLE_ID] = 'SYS_ADMIN')
      THROW 50003, 'MSG.ROLE_AUTH_SELF', 1;

    DECLARE @OLD TABLE ([PROGRAM_ID] VARCHAR(30) NOT NULL, [FUNC_CD] VARCHAR(20) NOT NULL, PRIMARY KEY ([PROGRAM_ID], [FUNC_CD]));
    INSERT INTO @OLD ([PROGRAM_ID], [FUNC_CD])
    SELECT RF.[PROGRAM_ID], RF.[FUNC_CD]
      FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF
      JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = RF.[PROGRAM_ID]
     WHERE RF.[ROLE_ID] = @P_ROLE_ID AND P.[USE_YN] = 'Y';

    -- 새로 주는 권한만 공개 대상을 본다 (이미 있던 권한은 그대로 둘 수 있다)
    IF EXISTS (SELECT 1 FROM @NEW N
                 JOIN [FW].[UFN_PROGRAM_SCOPE]() S ON S.[PROGRAM_ID] = N.[PROGRAM_ID]
                WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[PROGRAM_ID] = N.[PROGRAM_ID] AND O.[FUNC_CD] = N.[FUNC_CD])
                  AND NOT (@COMPANY_TYPE = '*' OR S.[OPEN_SCOPE_CD] = 'ALL'
                           OR (@COMPANY_TYPE = 'HQ' AND S.[OPEN_SCOPE_CD] = 'EMP')
                           OR (@COMPANY_TYPE = 'PARTNER' AND S.[OPEN_SCOPE_CD] = 'PARTNER')))
      THROW 50003, 'MSG.ROLE_AUTH_SCOPE', 1;

    DECLARE @CNT INT = 0;

    DELETE RF
      FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF
      JOIN @OLD O ON O.[PROGRAM_ID] = RF.[PROGRAM_ID] AND O.[FUNC_CD] = RF.[FUNC_CD]
     WHERE RF.[ROLE_ID] = @P_ROLE_ID
       AND NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[PROGRAM_ID] = O.[PROGRAM_ID] AND N.[FUNC_CD] = O.[FUNC_CD]);
    SET @CNT += @@ROWCOUNT;

    INSERT INTO [FW].[TB_ROLE_PROGRAM_FUNC] ([ROLE_ID], [PROGRAM_ID], [FUNC_CD], [REG_ID], [UPD_ID])
    SELECT @P_ROLE_ID, N.[PROGRAM_ID], N.[FUNC_CD], @P_USER_ID, @P_USER_ID
      FROM @NEW N
     WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[PROGRAM_ID] = N.[PROGRAM_ID] AND O.[FUNC_CD] = N.[FUNC_CD]);
    SET @CNT += @@ROWCOUNT;

    IF @CNT > 0
    BEGIN
      UPDATE [FW].[TB_ROLE] SET [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME() WHERE [ROLE_ID] = @P_ROLE_ID;

      DECLARE @BEFORE NVARCHAR(MAX) = (SELECT JSON_QUERY('[' + ISNULL(STRING_AGG(CAST('"' + [PROGRAM_ID] + ':' + [FUNC_CD] + '"' AS NVARCHAR(MAX)), ',')
                                                         WITHIN GROUP (ORDER BY [PROGRAM_ID], [FUNC_CD]), '') + ']') FROM @OLD);
      DECLARE @AFTER NVARCHAR(MAX) = (SELECT JSON_QUERY('[' + ISNULL(STRING_AGG(CAST('"' + [PROGRAM_ID] + ':' + [FUNC_CD] + '"' AS NVARCHAR(MAX)), ',')
                                                        WITHIN GROUP (ORDER BY [PROGRAM_ID], [FUNC_CD]), '') + ']') FROM @NEW);
      DECLARE @ROW_KEY NVARCHAR(200) = @P_ROLE_ID;
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_ROLE_PROGRAM_FUNC', @P_ACTION_CD = 'U', @P_ROW_KEY = @ROW_KEY,
        @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

      UPDATE [FW].[TB_CACHE_VERSION] SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME() WHERE [CACHE_KEY] = 'AUTH';
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH;

  SELECT @CNT AS [AFFECTED_CNT];
END
