-- 위젯 관리 화면 목록 (사용 안 함 포함). 프로그램: DSH_WIDGET_MGT
-- 결과셋 1: 위젯 설정과 언어별 제목, 결과셋 2: 전체 건수.
CREATE PROCEDURE [FW].[USP_WIDGET_ADMIN_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT W.[WIDGET_CD], W.[TYPE_CD], W.[DATA_SP], W.[PROGRAM_ID],
         (SELECT [WIDGET_NM] FROM [FW].[TB_WIDGET_LANG] WHERE [WIDGET_CD] = W.[WIDGET_CD] AND [LANG_CD] = 'ko') AS [NAME_KO],
         (SELECT [WIDGET_NM] FROM [FW].[TB_WIDGET_LANG] WHERE [WIDGET_CD] = W.[WIDGET_CD] AND [LANG_CD] = 'en') AS [NAME_EN],
         (SELECT [WIDGET_NM] FROM [FW].[TB_WIDGET_LANG] WHERE [WIDGET_CD] = W.[WIDGET_CD] AND [LANG_CD] = 'zh-CN') AS [NAME_ZH],
         W.[SPAN_COLS], W.[CACHE_SEC], W.[SORT_NO], W.[USE_YN], W.[UPD_ID], W.[UPD_DT], W.[ROW_VER]
    FROM [FW].[TB_WIDGET] W
   ORDER BY W.[SORT_NO], W.[WIDGET_CD];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_WIDGET];
END
