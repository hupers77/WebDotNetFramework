-- 게시판 관리 화면 목록 (사용 안 함 포함). 프로그램: BRD_BOARD_MGT
-- 결과셋 1: 게시판별 설정과 언어별 이름, 결과셋 2: 전체 건수.
CREATE PROCEDURE [FW].[USP_BOARD_ADMIN_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT B.[BOARD_CD], B.[PROGRAM_ID], B.[BOARD_TYPE_CD],
         (SELECT [BOARD_NM] FROM [FW].[TB_BOARD_LANG] WHERE [BOARD_CD] = B.[BOARD_CD] AND [LANG_CD] = 'ko') AS [NAME_KO],
         (SELECT [BOARD_NM] FROM [FW].[TB_BOARD_LANG] WHERE [BOARD_CD] = B.[BOARD_CD] AND [LANG_CD] = 'en') AS [NAME_EN],
         (SELECT [BOARD_NM] FROM [FW].[TB_BOARD_LANG] WHERE [BOARD_CD] = B.[BOARD_CD] AND [LANG_CD] = 'zh-CN') AS [NAME_ZH],
         B.[REPLY_YN], B.[COMMENT_YN], B.[ATTACH_YN], B.[ANON_YN], B.[SECRET_YN], B.[PERIOD_YN], B.[PIN_YN], B.[READER_YN],
         B.[SORT_NO], B.[USE_YN], B.[UPD_ID], B.[UPD_DT], B.[ROW_VER]
    FROM [FW].[TB_BOARD] B
   ORDER BY B.[SORT_NO], B.[BOARD_CD];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_BOARD];
END
