-- 협력사 가입 신청 승인·반려 (본사 담당자). 프로그램: SYS_PARTNER_APPROVE, 기능 APPROVE
-- 승인: 신청의 비밀번호 해시로 TB_USER 계정(PARTNER, ACTIVE)을 만들고 협력사 사용자 역할(PARTNER_USER)을 준다.
--       계정 사용 기한은 회사 계약 종료일이다. 신청에 남은 비밀번호 해시는 지운다.
-- 반려: 사유가 필요하고, 비밀번호 해시를 지운다.
-- 협력사 사용자는 처리할 수 없다(없는 신청처럼 응답). 동시에 처리하면 ROW_VER로 막는다.
-- 결과: AFFECTED_CNT, NEW_KEY(승인하면 만든 사용자 ID)
CREATE PROCEDURE [FW].[USP_PARTNER_JOIN_APPROVE_EXEC]
  @P_REQ_ID        BIGINT,
  @P_ROW_VER       BINARY(8),
  @P_APPROVE_YN    CHAR(1),
  @P_REJECT_REASON NVARCHAR(500) = NULL,
  @P_USER_ID       VARCHAR(30),
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_APPROVE_YN NOT IN ('Y', 'N') OR @P_ROW_VER IS NULL
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF @P_APPROVE_YN = 'N' AND NULLIF(LTRIM(RTRIM(@P_REJECT_REASON)), N'') IS NULL
    THROW 50005, 'MSG.JOIN_REJECT_REASON', 1;
  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_USER] WHERE [USER_ID] = @P_USER_ID AND [USER_TYPE_CD] <> 'PARTNER')
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @TODAY DATE = CAST(GETDATE() AS DATE);
  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @COMPANY_CD VARCHAR(10), @REQ_USER_ID VARCHAR(30), @STAT VARCHAR(10), @ROW_VER BINARY(8), @NEW_STAT VARCHAR(10);
  DECLARE @ROW_KEY NVARCHAR(200) = CAST(@P_REQ_ID AS NVARCHAR(20));

  BEGIN TRY
    BEGIN TRAN;

    SELECT @COMPANY_CD = [COMPANY_CD], @REQ_USER_ID = [USER_ID], @STAT = [REQ_STAT_CD], @ROW_VER = [ROW_VER]
      FROM [FW].[TB_PARTNER_JOIN_REQ] WITH (UPDLOCK)
     WHERE [REQ_ID] = @P_REQ_ID;

    IF @@ROWCOUNT = 0
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @STAT <> 'REQUESTED' OR @ROW_VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;

    IF @P_APPROVE_YN = 'Y'
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM [FW].[TB_COMPANY]
                      WHERE [COMPANY_CD] = @COMPANY_CD AND [COMPANY_TYPE_CD] = 'PARTNER' AND [USE_YN] = 'Y'
                        AND ([CONTRACT_END_DT] IS NULL OR [CONTRACT_END_DT] >= @TODAY))
        THROW 50005, 'MSG.JOIN_COMPANY_NOT_FOUND', 1;
      IF EXISTS (SELECT 1 FROM [FW].[TB_USER] WITH (UPDLOCK, HOLDLOCK) WHERE [USER_ID] = @REQ_USER_ID)
        THROW 50001, 'MSG.JOIN_ID_TAKEN', 1;

      INSERT INTO [FW].[TB_USER]
        ([USER_ID], [COMPANY_CD], [USER_NM], [EMAIL_ENC], [USER_TYPE_CD], [PWD_HASH], [PWD_SALT], [PWD_CHG_DT], [PWD_CHG_REQ_YN],
         [ACCOUNT_END_DT], [USER_STAT_CD], [LANG_CD], [REG_ID], [UPD_ID])
      SELECT R.[USER_ID], R.[COMPANY_CD], R.[USER_NM], R.[EMAIL_ENC], 'PARTNER', R.[PWD_HASH], R.[PWD_SALT], R.[REQ_DT], 'N',
             C.[CONTRACT_END_DT], 'ACTIVE', R.[LANG_CD], @P_USER_ID, @P_USER_ID
        FROM [FW].[TB_PARTNER_JOIN_REQ] R
        JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = R.[COMPANY_CD]
       WHERE R.[REQ_ID] = @P_REQ_ID;

      INSERT INTO [FW].[TB_USER_ROLE] ([USER_ID], [ROLE_ID], [REG_ID], [UPD_ID])
      VALUES (@REQ_USER_ID, 'PARTNER_USER', @P_USER_ID, @P_USER_ID);

      DECLARE @USER_AFTER NVARCHAR(MAX) = (SELECT @REQ_USER_ID AS [USER_ID], @COMPANY_CD AS [COMPANY_CD], 'PARTNER' AS [USER_TYPE_CD],
                                                  'ACTIVE' AS [USER_STAT_CD], 'PARTNER_USER' AS [ROLE_ID] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'I', @P_ROW_KEY = @REQ_USER_ID,
        @P_BEFORE_JSON = NULL, @P_AFTER_JSON = @USER_AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    END

    SET @NEW_STAT = CASE @P_APPROVE_YN WHEN 'Y' THEN 'APPROVED' ELSE 'REJECTED' END;
    UPDATE [FW].[TB_PARTNER_JOIN_REQ]
       SET [REQ_STAT_CD] = @NEW_STAT, [PWD_HASH] = NULL, [PWD_SALT] = NULL,
           [PROC_ID] = @P_USER_ID, [PROC_DT] = @NOW,
           [REJECT_REASON] = CASE @P_APPROVE_YN WHEN 'N' THEN LTRIM(RTRIM(@P_REJECT_REASON)) END,
           [UPD_ID] = @P_USER_ID, [UPD_DT] = @NOW
     WHERE [REQ_ID] = @P_REQ_ID;

    DECLARE @AFTER NVARCHAR(MAX) = (SELECT @NEW_STAT AS [REQ_STAT_CD],
                                           CASE @P_APPROVE_YN WHEN 'N' THEN LTRIM(RTRIM(@P_REJECT_REASON)) END AS [REJECT_REASON]
                                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_PARTNER_JOIN_REQ', @P_ACTION_CD = 'U', @P_ROW_KEY = @ROW_KEY,
      @P_BEFORE_JSON = N'{"REQ_STAT_CD":"REQUESTED"}', @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT 1 AS [AFFECTED_CNT], CASE @P_APPROVE_YN WHEN 'Y' THEN @REQ_USER_ID END AS [NEW_KEY];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
