-- 위젯 데이터: 내가 쓴 글 수 (숫자 카드, 삭제한 글과 사용 안 하는 게시판의 글은 빼고 센다).
-- 위젯 SP 공통 결과 열: LABEL, VALUE, TEXT, LINK, DT
CREATE PROCEDURE [FW].[USP_WIDGET_MY_POST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT CAST(NULL AS NVARCHAR(100)) AS [LABEL], CAST(COUNT(*) AS DECIMAL(18, 2)) AS [VALUE],
         CAST(NULL AS NVARCHAR(200)) AS [TEXT], CAST(NULL AS VARCHAR(200)) AS [LINK], CAST(NULL AS DATETIME2(0)) AS [DT]
    FROM [FW].[TB_POST] P
    JOIN [FW].[TB_BOARD] B ON B.[BOARD_CD] = P.[BOARD_CD] AND B.[USE_YN] = 'Y'
   WHERE P.[WRITER_ID] = @P_USER_ID AND P.[DEL_YN] = 'N';
END
