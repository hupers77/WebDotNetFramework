-- 댓글 등록·수정. 프로그램: 게시판의 프로그램 (등록 CREATE, 수정 UPDATE는 애플리케이션이 확인; 수정은 본인 댓글만, 관리자도 남의 댓글은 지우기만 한다)
-- 글은 @P_BOARD_CD 게시판의 글이어야 한다(권한을 확인한 게시판 밖의 글에 댓글을 달거나 고치지 못하게).
-- @P_COMMENT_ID가 NULL이면 등록(글을 볼 수 있어야 하고 게시판 댓글 설정이 켜져 있어야 한다), 있으면 수정(@P_ROW_VER 필요).
-- 댓글을 달면 글 작성자(본인 제외)에게 포털 알림(TPL_BOARD_COMMENT)을 쌓는다.
-- 결과: AFFECTED_CNT, NEW_KEY(댓글 ID)
CREATE PROCEDURE [FW].[USP_COMMENT_SAVE]
  @P_COMMENT_ID   BIGINT        = NULL,
  @P_ROW_VER      BINARY(8)     = NULL,
  @P_BOARD_CD     VARCHAR(30),
  @P_POST_ID      BIGINT,
  @P_CONTENT      NVARCHAR(1000),
  @P_MANAGER_YN   CHAR(1)       = 'N',
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_CONTENT = LTRIM(RTRIM(@P_CONTENT));
  IF NULLIF(@P_CONTENT, N'') IS NULL OR @P_MANAGER_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_POST] P
                   JOIN [FW].[TB_BOARD] B ON B.[BOARD_CD] = P.[BOARD_CD] AND B.[COMMENT_YN] = 'Y'
                   JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, @P_MANAGER_YN) V ON V.[POST_ID] = P.[POST_ID] AND V.[SECRET_OK_YN] = 'Y'
                  WHERE P.[POST_ID] = @P_POST_ID AND P.[BOARD_CD] = @P_BOARD_CD)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @ID BIGINT = @P_COMMENT_ID;

  BEGIN TRY
    BEGIN TRAN;

    IF @P_COMMENT_ID IS NULL
    BEGIN
      INSERT INTO [FW].[TB_POST_COMMENT] ([POST_ID], [CONTENT], [COMPANY_CD], [WRITER_ID], [REG_ID], [UPD_ID])
      SELECT @P_POST_ID, @P_CONTENT, U.[COMPANY_CD], U.[USER_ID], U.[USER_ID], U.[USER_ID]
        FROM [FW].[TB_USER] U
       WHERE U.[USER_ID] = @P_USER_ID AND U.[USER_STAT_CD] = 'ACTIVE';
      SET @ID = SCOPE_IDENTITY();

      -- 글 작성자에게 포털 알림 (본인 글에 본인이 단 댓글은 제외)
      DECLARE @POST_WRITER VARCHAR(30), @POST_TITLE NVARCHAR(200);
      SELECT @POST_WRITER = [WRITER_ID], @POST_TITLE = [TITLE] FROM [FW].[TB_POST] WHERE [POST_ID] = @P_POST_ID;
      IF @POST_WRITER <> @P_USER_ID
      BEGIN
        DECLARE @NOTI_PARAMS NVARCHAR(4000) = (SELECT @POST_TITLE AS [POST_TITLE] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
        EXEC [FW].[USP_MSG_QUEUE_SAVE] @P_TEMPLATE_ID = 'TPL_BOARD_COMMENT', @P_TO_USER_ID = @POST_WRITER, @P_PARAMS_JSON = @NOTI_PARAMS,
             @P_RESULT_YN = 'N', @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
      END
    END
    ELSE
    BEGIN
      DECLARE @VER BINARY(8);
      SELECT @VER = C.[ROW_VER]
        FROM [FW].[TB_POST_COMMENT] C WITH (UPDLOCK, HOLDLOCK)
       WHERE C.[COMMENT_ID] = @P_COMMENT_ID AND C.[POST_ID] = @P_POST_ID AND C.[WRITER_ID] = @P_USER_ID AND C.[DEL_YN] = 'N';
      IF @VER IS NULL
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
        THROW 50002, 'MSG.CONCURRENCY', 1;

      UPDATE [FW].[TB_POST_COMMENT] SET [CONTENT] = @P_CONTENT, [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME() WHERE [COMMENT_ID] = @P_COMMENT_ID;
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT], CAST(@ID AS NVARCHAR(20)) AS [NEW_KEY];
END
