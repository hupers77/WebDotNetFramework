-- 역할 한 개의 기능 권한표 (사용 중인 프로그램 × 프로그램이 쓰는 기능). 프로그램: SYS_ROLE_AUTH_MGT
-- 화면 순서·메뉴명은 애플리케이션이 메뉴 캐시로 정한다.
-- 결과: PROGRAM_ID, PROGRAM_NM, MODULE_CD, OPEN_SCOPE_CD, GRANTABLE_YN(역할의 회사 유형에 줄 수 있는지), FUNC_CD, GRANTED_YN
CREATE PROCEDURE [FW].[USP_ROLE_AUTH_GET_LIST]
  @P_ROLE_ID    VARCHAR(30),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @COMPANY_TYPE VARCHAR(10);
  SELECT @COMPANY_TYPE = ISNULL([COMPANY_TYPE_CD], '*') FROM [FW].[TB_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID;
  IF @COMPANY_TYPE IS NULL
    THROW 50004, 'MSG.NOT_FOUND', 1;

  SELECT P.[PROGRAM_ID], P.[PROGRAM_NM], P.[MODULE_CD], S.[OPEN_SCOPE_CD],
         CASE WHEN @COMPANY_TYPE = '*' OR S.[OPEN_SCOPE_CD] = 'ALL'
                OR (@COMPANY_TYPE = 'HQ' AND S.[OPEN_SCOPE_CD] = 'EMP')
                OR (@COMPANY_TYPE = 'PARTNER' AND S.[OPEN_SCOPE_CD] = 'PARTNER') THEN 'Y' ELSE 'N' END AS [GRANTABLE_YN],
         F.[FUNC_CD],
         IIF(RF.[ROLE_ID] IS NULL, 'N', 'Y') AS [GRANTED_YN]
    FROM [FW].[TB_PROGRAM] P
    JOIN [FW].[UFN_PROGRAM_SCOPE]() S ON S.[PROGRAM_ID] = P.[PROGRAM_ID]
    JOIN [FW].[TB_PROGRAM_FUNC] F ON F.[PROGRAM_ID] = P.[PROGRAM_ID]
    LEFT JOIN [FW].[TB_ROLE_PROGRAM_FUNC] RF ON RF.[ROLE_ID] = @P_ROLE_ID AND RF.[PROGRAM_ID] = F.[PROGRAM_ID] AND RF.[FUNC_CD] = F.[FUNC_CD]
   WHERE P.[USE_YN] = 'Y'
   ORDER BY P.[PROGRAM_ID], F.[FUNC_CD];
END
