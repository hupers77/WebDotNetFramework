-- 설정값 일괄 저장 (저장 SP 표준 템플릿, TVP). 프로그램: SYS_CONFIG_MGT
-- 키 추가·삭제는 하지 않고 값만 바꾼다(키는 초기 데이터가 관리). 값이 실제로 바뀐 행만 반영하고
-- 변경 이력(TB_CONFIG_HIST)과 감사 로그를 남긴 뒤 캐시 버전(CONFIG)을 올려 모든 서버에 반영한다.
-- SECRET 값은 이력·감사 로그에 남기지 않는다(변경 사실만 기록).
-- 결과: AFFECTED_CNT (실제로 바뀐 설정 수)
CREATE PROCEDURE [FW].[USP_CONFIG_SAVE]
  @P_ROWS       [FW].[TVP_CONFIG] READONLY,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF NOT EXISTS (SELECT 1 FROM @P_ROWS)
    THROW 50005, 'MSG.NO_CHANGES', 1;
  IF EXISTS (SELECT 1 FROM @P_ROWS R LEFT JOIN [FW].[TB_CONFIG] C ON C.[CONFIG_KEY] = R.[CONFIG_KEY] WHERE C.[CONFIG_KEY] IS NULL)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @CHANGED TABLE (
    [CONFIG_KEY] VARCHAR(100) PRIMARY KEY, [OLD_VAL] NVARCHAR(2000) NULL, [NEW_VAL] NVARCHAR(2000) NULL, [ENC_YN] CHAR(1) NOT NULL);
  DECLARE @CNT INT;

  BEGIN TRY
    BEGIN TRAN;

    -- 동시성: 조회 시점의 ROW_VER와 같아야 한다
    IF EXISTS (SELECT 1
                 FROM @P_ROWS R
                 JOIN [FW].[TB_CONFIG] C WITH (UPDLOCK) ON C.[CONFIG_KEY] = R.[CONFIG_KEY]
                WHERE C.[ROW_VER] <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;

    UPDATE C
       SET C.[CONFIG_VAL] = R.[CONFIG_VAL], C.[UPD_ID] = @P_USER_ID, C.[UPD_DT] = SYSUTCDATETIME()
    OUTPUT INSERTED.[CONFIG_KEY], DELETED.[CONFIG_VAL], INSERTED.[CONFIG_VAL], INSERTED.[ENC_YN] INTO @CHANGED
      FROM [FW].[TB_CONFIG] C
      JOIN @P_ROWS R ON R.[CONFIG_KEY] = C.[CONFIG_KEY]
     WHERE ISNULL(C.[CONFIG_VAL], N'') COLLATE Latin1_General_BIN2 <> ISNULL(R.[CONFIG_VAL], N'') COLLATE Latin1_General_BIN2
        OR (C.[CONFIG_VAL] IS NULL AND R.[CONFIG_VAL] IS NOT NULL)
        OR (C.[CONFIG_VAL] IS NOT NULL AND R.[CONFIG_VAL] IS NULL);
    SET @CNT = @@ROWCOUNT;

    IF @CNT > 0
    BEGIN
      INSERT INTO [FW].[TB_CONFIG_HIST] ([CONFIG_KEY], [OLD_VAL], [NEW_VAL], [CHG_ID], [CLIENT_IP])
      SELECT [CONFIG_KEY],
             CASE WHEN [ENC_YN] = 'Y' THEN NULL ELSE [OLD_VAL] END,
             CASE WHEN [ENC_YN] = 'Y' THEN NULL ELSE [NEW_VAL] END,
             @P_USER_ID, @P_CLIENT_IP
        FROM @CHANGED;

      DECLARE @BEFORE NVARCHAR(MAX) = (SELECT [CONFIG_KEY], CASE WHEN [ENC_YN] = 'Y' THEN N'***' ELSE [OLD_VAL] END AS [CONFIG_VAL]
                                         FROM @CHANGED FOR JSON PATH, INCLUDE_NULL_VALUES);
      DECLARE @AFTER NVARCHAR(MAX) = (SELECT [CONFIG_KEY], CASE WHEN [ENC_YN] = 'Y' THEN N'***' ELSE [NEW_VAL] END AS [CONFIG_VAL]
                                        FROM @CHANGED FOR JSON PATH, INCLUDE_NULL_VALUES);
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_CONFIG', @P_ACTION_CD = 'U', @P_ROW_KEY = N'CONFIG',
        @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

      UPDATE [FW].[TB_CACHE_VERSION]
         SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME()
       WHERE [CACHE_KEY] = 'CONFIG';
    END

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
