-- 본인 비밀번호 변경. 정책·현재 비밀번호·재사용 검사는 애플리케이션이 끝낸 뒤 새 해시만 넘긴다. 프로그램: MY_PWD_CHG
-- 현재 해시를 이력으로 옮기고 이력은 PWD.HISTORY_COUNT개만 남긴다. 변경 강제 표시를 끈다.
-- 감사 로그에는 변경 사실만 남기고 해시는 기록하지 않는다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_AUTH_PWD_CHANGE_EXEC]
  @P_PWD_HASH   VARBINARY(64),
  @P_PWD_SALT   VARBINARY(16),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_USER_ID IS NULL OR DATALENGTH(@P_PWD_HASH) <> 64 OR DATALENGTH(@P_PWD_SALT) <> 16
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @HISTORY_COUNT INT = ISNULL(TRY_CAST((SELECT [CONFIG_VAL] FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'PWD.HISTORY_COUNT') AS INT), 3);
  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @OLD_HASH VARBINARY(64), @OLD_SALT VARBINARY(16), @NEXT_SEQ INT;

  BEGIN TRY
    BEGIN TRAN;

    SELECT @OLD_HASH = [PWD_HASH], @OLD_SALT = [PWD_SALT]
      FROM [FW].[TB_USER] WITH (UPDLOCK)
     WHERE [USER_ID] = @P_USER_ID;

    IF @@ROWCOUNT = 0
      THROW 50004, 'MSG.NOT_FOUND', 1;

    IF @OLD_HASH IS NOT NULL
    BEGIN
      SELECT @NEXT_SEQ = ISNULL(MAX([SEQ_NO]), 0) + 1 FROM [FW].[TB_USER_PWD_HIST] WHERE [USER_ID] = @P_USER_ID;

      INSERT INTO [FW].[TB_USER_PWD_HIST] ([USER_ID], [SEQ_NO], [PWD_HASH], [PWD_SALT], [REG_ID], [UPD_ID])
      VALUES (@P_USER_ID, @NEXT_SEQ, @OLD_HASH, @OLD_SALT, @P_USER_ID, @P_USER_ID);

      DELETE FROM [FW].[TB_USER_PWD_HIST]
       WHERE [USER_ID] = @P_USER_ID AND [SEQ_NO] <= @NEXT_SEQ - @HISTORY_COUNT;
    END

    UPDATE [FW].[TB_USER]
       SET [PWD_HASH] = @P_PWD_HASH, [PWD_SALT] = @P_PWD_SALT, [PWD_CHG_DT] = @NOW, [PWD_CHG_REQ_YN] = 'N',
           [UPD_ID] = @P_USER_ID, [UPD_DT] = @NOW
     WHERE [USER_ID] = @P_USER_ID;

    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_USER_ID,
      @P_BEFORE_JSON = NULL, @P_AFTER_JSON = N'{"PWD_CHANGED":true}',
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT 1 AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
