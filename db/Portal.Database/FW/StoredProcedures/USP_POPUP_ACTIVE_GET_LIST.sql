-- 지금 홈 화면에 띄울 공지 팝업. 프로그램: DSH_HOME
-- 사용 중이고, 오늘이 기간 안이며, 공개 대상이 내 사용자 유형과 맞는 것. 문구는 화면 언어(없으면 기본 언어).
-- VER_KEY: 팝업 내용이 바뀌면 달라지는 값 (브라우저의 "오늘 하루 보지 않기" 기준)
CREATE PROCEDURE [FW].[USP_POPUP_ACTIVE_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  DECLARE @TYPE VARCHAR(10) = (SELECT [USER_TYPE_CD] FROM [FW].[TB_USER] WHERE [USER_ID] = @P_USER_ID);
  DECLARE @TODAY DATE = CAST(SYSUTCDATETIME() AS DATE);

  SELECT TOP (5) P.[POPUP_ID], COALESCE(L.[TITLE], D.[TITLE]) AS [TITLE], COALESCE(L.[CONTENT], D.[CONTENT]) AS [CONTENT],
         CONVERT(VARCHAR(20), P.[POPUP_ID]) + '-' + CONVERT(VARCHAR(30), P.[UPD_DT], 126) AS [VER_KEY]
    FROM [FW].[TB_POPUP] P
    LEFT JOIN [FW].[TB_POPUP_LANG] L ON L.[POPUP_ID] = P.[POPUP_ID] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_POPUP_LANG] D ON D.[POPUP_ID] = P.[POPUP_ID] AND D.[LANG_CD] = @DEFAULT_LANG
   WHERE P.[USE_YN] = 'Y' AND @TODAY BETWEEN P.[START_DT] AND P.[END_DT]
     AND (P.[OPEN_SCOPE_CD] = 'ALL' OR P.[OPEN_SCOPE_CD] = @TYPE)
     AND COALESCE(L.[TITLE], D.[TITLE]) IS NOT NULL
   ORDER BY P.[START_DT] DESC, P.[POPUP_ID] DESC;
END
