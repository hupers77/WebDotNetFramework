-- 프로그램 등록·수정 (저장 SP 표준 템플릿). 프로그램: SYS_PROGRAM_MGT
-- @P_ROW_VER가 NULL이면 등록, 있으면 수정. 프로그램 ID·모듈·URL은 코드가 정하므로 등록할 때만 넣고 바꿀 수 없다(수정이면 무시).
-- @P_FUNCS: ["READ","CREATE",...] 이 프로그램이 쓰는 기능 전부 (공통코드 FUNC_CD의 사용 중인 코드). 조회(READ)는 꼭 있어야 한다.
-- 규칙: 서버 경로(TB_PROGRAM_API)가 요구하는 기능은 뺄 수 없다(코드가 그 기능으로 권한을 검사하므로).
--       뺀 기능의 역할·사용자 예외 권한은 함께 지운다. 홈과 프로그램 관리 화면은 사용 안 함으로 바꿀 수 없다(다시 켤 화면이 없어진다).
-- 바뀌면 감사 로그(프로그램 행, 기능 전후 목록)를 남기고 권한·메뉴 캐시(AUTH, MENU)를 올린다.
-- 결과: AFFECTED_CNT, NEW_KEY(프로그램 ID)
CREATE PROCEDURE [FW].[USP_PROGRAM_SAVE]
  @P_PROGRAM_ID  VARCHAR(30),
  @P_ROW_VER     BINARY(8)      = NULL,
  @P_MODULE_CD   VARCHAR(20)    = NULL,
  @P_PROGRAM_NM  NVARCHAR(100),
  @P_URL         VARCHAR(300)   = NULL,
  @P_PII_YN      CHAR(1),
  @P_USE_YN      CHAR(1),
  @P_FUNCS       NVARCHAR(MAX),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_PROGRAM_ID = LTRIM(RTRIM(@P_PROGRAM_ID));
  SET @P_MODULE_CD = NULLIF(LTRIM(RTRIM(@P_MODULE_CD)), '');
  SET @P_PROGRAM_NM = NULLIF(LTRIM(RTRIM(@P_PROGRAM_NM)), N'');
  SET @P_URL = NULLIF(LTRIM(RTRIM(@P_URL)), '');

  -- 입력 검증 (트랜잭션 전)
  IF @P_PROGRAM_ID IS NULL OR LEN(@P_PROGRAM_ID) < 2
     OR @P_PROGRAM_ID COLLATE Latin1_General_BIN LIKE '%[^A-Z0-9_]%' OR LEFT(@P_PROGRAM_ID, 1) COLLATE Latin1_General_BIN NOT LIKE '[A-Z]'
     OR @P_PROGRAM_NM IS NULL OR @P_PII_YN NOT IN ('Y', 'N') OR @P_USE_YN NOT IN ('Y', 'N')
     OR @P_FUNCS IS NULL OR ISJSON(@P_FUNCS) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF @P_ROW_VER IS NULL
     AND (@P_MODULE_CD IS NULL OR @P_MODULE_CD COLLATE Latin1_General_BIN LIKE '%[^A-Z0-9]%' OR LEFT(@P_MODULE_CD, 1) COLLATE Latin1_General_BIN NOT LIKE '[A-Z]'
          OR @P_URL IS NULL OR LEFT(@P_URL, 1) <> '/' OR @P_URL LIKE '//%' OR @P_URL LIKE '/\%' OR @P_URL LIKE '%[ <>"'']%')
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF @P_USE_YN = 'N' AND @P_PROGRAM_ID IN ('DSH_HOME', 'SYS_PROGRAM_MGT')
    THROW 50003, 'MSG.PROGRAM_KEEP_USE', 1;

  DECLARE @NEW TABLE ([FUNC_CD] VARCHAR(20) NOT NULL PRIMARY KEY);
  BEGIN TRY
    INSERT INTO @NEW ([FUNC_CD]) SELECT [value] FROM OPENJSON(@P_FUNCS) WHERE [type] = 1;
  END TRY
  BEGIN CATCH
    THROW 50005, 'MSG.INVALID_INPUT', 1; -- 같은 기능이 두 번 왔을 때
  END CATCH;
  IF (SELECT COUNT(*) FROM OPENJSON(@P_FUNCS)) <> (SELECT COUNT(*) FROM @NEW)
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF NOT EXISTS (SELECT 1 FROM @NEW WHERE [FUNC_CD] = 'READ')
    THROW 50003, 'MSG.PROGRAM_READ_REQUIRED', 1;

  DECLARE @OLD_VER BINARY(8), @CNT INT = 0;
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX), @FUNCS_BEFORE NVARCHAR(MAX), @FUNCS_AFTER NVARCHAR(MAX);
  DECLARE @OLD TABLE ([FUNC_CD] VARCHAR(20) NOT NULL PRIMARY KEY);

  BEGIN TRY
    BEGIN TRAN;

    IF @P_ROW_VER IS NULL
    BEGIN
      IF EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM] WITH (UPDLOCK, HOLDLOCK) WHERE [PROGRAM_ID] = @P_PROGRAM_ID)
        THROW 50001, 'MSG.DUP_CODE', 1;
    END
    ELSE
    BEGIN
      SELECT @OLD_VER = [ROW_VER] FROM [FW].[TB_PROGRAM] WITH (UPDLOCK, HOLDLOCK) WHERE [PROGRAM_ID] = @P_PROGRAM_ID;
      IF @OLD_VER IS NULL
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @OLD_VER <> @P_ROW_VER
        THROW 50002, 'MSG.CONCURRENCY', 1;
      INSERT INTO @OLD ([FUNC_CD]) SELECT [FUNC_CD] FROM [FW].[TB_PROGRAM_FUNC] WHERE [PROGRAM_ID] = @P_PROGRAM_ID;
    END

    -- 새로 넣는 기능은 공통코드 FUNC_CD의 사용 중인 코드여야 한다 (이미 쓰던 기능은 코드가 꺼져도 그대로 둘 수 있다)
    IF EXISTS (SELECT 1 FROM @NEW N
                WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[FUNC_CD] = N.[FUNC_CD])
                  AND NOT EXISTS (SELECT 1 FROM [FW].[TB_CODE] C WHERE C.[GROUP_CD] = 'FUNC_CD' AND C.[CODE] = N.[FUNC_CD] AND C.[USE_YN] = 'Y'))
      THROW 50005, 'MSG.INVALID_INPUT', 1;
    IF EXISTS (SELECT 1 FROM @OLD O
                WHERE NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[FUNC_CD] = O.[FUNC_CD])
                  AND EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM_API] A WHERE A.[PROGRAM_ID] = @P_PROGRAM_ID AND A.[FUNC_CD] = O.[FUNC_CD]))
      THROW 50003, 'MSG.PROGRAM_FUNC_IN_USE', 1;

    IF @P_ROW_VER IS NULL
    BEGIN
      INSERT INTO [FW].[TB_PROGRAM] ([PROGRAM_ID], [MODULE_CD], [PROGRAM_NM], [URL], [PII_YN], [USE_YN], [REG_ID], [UPD_ID])
      VALUES (@P_PROGRAM_ID, @P_MODULE_CD, @P_PROGRAM_NM, @P_URL, @P_PII_YN, @P_USE_YN, @P_USER_ID, @P_USER_ID);
      SET @CNT = 1;
    END
    ELSE
    BEGIN
      SET @BEFORE = (SELECT [PROGRAM_NM], [PII_YN], [USE_YN] FROM [FW].[TB_PROGRAM] WHERE [PROGRAM_ID] = @P_PROGRAM_ID
                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
      UPDATE [FW].[TB_PROGRAM]
         SET [PROGRAM_NM] = @P_PROGRAM_NM, [PII_YN] = @P_PII_YN, [USE_YN] = @P_USE_YN,
             [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
       WHERE [PROGRAM_ID] = @P_PROGRAM_ID;
      SET @CNT = 1;
    END

    -- 뺀 기능: 그 기능의 역할·사용자 예외 권한부터 지운다
    DELETE RF FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF
     WHERE RF.[PROGRAM_ID] = @P_PROGRAM_ID AND NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[FUNC_CD] = RF.[FUNC_CD]);
    DELETE UF FROM [FW].[TB_USER_PROGRAM_FUNC] UF
     WHERE UF.[PROGRAM_ID] = @P_PROGRAM_ID AND NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[FUNC_CD] = UF.[FUNC_CD]);
    DELETE F FROM [FW].[TB_PROGRAM_FUNC] F
     WHERE F.[PROGRAM_ID] = @P_PROGRAM_ID AND NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[FUNC_CD] = F.[FUNC_CD]);
    SET @CNT += @@ROWCOUNT;
    INSERT INTO [FW].[TB_PROGRAM_FUNC] ([PROGRAM_ID], [FUNC_CD], [REG_ID], [UPD_ID])
    SELECT @P_PROGRAM_ID, N.[FUNC_CD], @P_USER_ID, @P_USER_ID FROM @NEW N WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[FUNC_CD] = N.[FUNC_CD]);
    SET @CNT += @@ROWCOUNT;

    SET @AFTER = (SELECT [PROGRAM_ID], [MODULE_CD], [PROGRAM_NM], [URL], [PII_YN], [USE_YN] FROM [FW].[TB_PROGRAM] WHERE [PROGRAM_ID] = @P_PROGRAM_ID
                    FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @ACTION CHAR(1) = IIF(@P_ROW_VER IS NULL, 'I', 'U');
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_PROGRAM', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @P_PROGRAM_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    IF EXISTS (SELECT 1 FROM @NEW N WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[FUNC_CD] = N.[FUNC_CD]))
       OR EXISTS (SELECT 1 FROM @OLD O WHERE NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[FUNC_CD] = O.[FUNC_CD]))
    BEGIN
      SET @FUNCS_BEFORE = IIF(@P_ROW_VER IS NULL, NULL,
                              (SELECT '[' + ISNULL(STRING_AGG(CAST('"' + [FUNC_CD] + '"' AS NVARCHAR(MAX)), ',') WITHIN GROUP (ORDER BY [FUNC_CD]), '') + ']' FROM @OLD));
      SET @FUNCS_AFTER = (SELECT '[' + STRING_AGG(CAST('"' + [FUNC_CD] + '"' AS NVARCHAR(MAX)), ',') WITHIN GROUP (ORDER BY [FUNC_CD]) + ']' FROM @NEW);
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_PROGRAM_FUNC', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @P_PROGRAM_ID,
        @P_BEFORE_JSON = @FUNCS_BEFORE, @P_AFTER_JSON = @FUNCS_AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    END

    UPDATE [FW].[TB_CACHE_VERSION] SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME() WHERE [CACHE_KEY] IN ('AUTH', 'MENU');

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT], @P_PROGRAM_ID AS [NEW_KEY];
END
