-- 역할 삭제 (삭제 SP 표준 템플릿). 프로그램: SYS_ROLE_MGT
-- 잘못 만든 역할만 지운다. 시스템 역할, 그리고 계정·부서·AD 그룹·위임 중 하나라도 부여된 역할은 지우지 않는다
-- (먼저 부여를 빼거나 사용 안 함으로 바꾼다). 역할의 기능 권한도 함께 지운다. 감사 로그를 남기고 권한 캐시(AUTH)를 올린다.
-- 결과: AFFECTED_CNT(역할 1 + 지운 기능 권한 수)
CREATE PROCEDURE [FW].[USP_ROLE_DEL]
  @P_ROLE_ID    VARCHAR(30),
  @P_ROW_VER    BINARY(8),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @VER BINARY(8), @SYSTEM_YN CHAR(1), @CNT INT = 1;

  BEGIN TRY
    BEGIN TRAN;

    SELECT @VER = [ROW_VER], @SYSTEM_YN = [SYSTEM_YN]
      FROM [FW].[TB_ROLE] WITH (UPDLOCK, HOLDLOCK)
     WHERE [ROLE_ID] = @P_ROLE_ID;

    IF @VER IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @SYSTEM_YN = 'Y'
      THROW 50003, 'MSG.ROLE_SYSTEM', 1;
    IF EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_DEPT_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_AD_GROUP_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID)
       OR EXISTS (SELECT 1 FROM [FW].[TB_ROLE_DELEGATE] WHERE [ROLE_ID] = @P_ROLE_ID)
      THROW 50003, 'MSG.ROLE_IN_USE', 1;

    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT [ROLE_ID], [ROLE_NM], [DESCRIPTION], [COMPANY_TYPE_CD], [DATA_SCOPE_CD], [SYSTEM_YN], [SORT_NO], [USE_YN]
                                       FROM [FW].[TB_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID
                                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @FUNCS NVARCHAR(MAX) = (SELECT '[' + STRING_AGG(CAST('"' + [PROGRAM_ID] + ':' + [FUNC_CD] + '"' AS NVARCHAR(MAX)), ',')
                                                   WITHIN GROUP (ORDER BY [PROGRAM_ID], [FUNC_CD]) + ']'
                                      FROM [FW].[TB_ROLE_PROGRAM_FUNC] WHERE [ROLE_ID] = @P_ROLE_ID);

    DELETE FROM [FW].[TB_ROLE_PROGRAM_FUNC] WHERE [ROLE_ID] = @P_ROLE_ID;
    SET @CNT += @@ROWCOUNT;
    DELETE FROM [FW].[TB_ROLE] WHERE [ROLE_ID] = @P_ROLE_ID;

    IF @FUNCS IS NOT NULL
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_ROLE_PROGRAM_FUNC', @P_ACTION_CD = 'D', @P_ROW_KEY = @P_ROLE_ID,
        @P_BEFORE_JSON = @FUNCS, @P_AFTER_JSON = NULL,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_ROLE', @P_ACTION_CD = 'D', @P_ROW_KEY = @P_ROLE_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = NULL,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    UPDATE [FW].[TB_CACHE_VERSION] SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME() WHERE [CACHE_KEY] = 'AUTH';

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT];
END
