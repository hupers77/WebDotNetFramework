-- 정리할 요청 목록: 끝나거나 지워서 보관 기간(EXPIRE_DT)이 지난 요청. 만드는 중(RUNNING)인 요청은 제외한다.
-- 결과: RUN_ID, STORED_PATH (파일이 없으면 NULL)
CREATE PROCEDURE [FW].[USP_REPORT_RUN_CLEANUP_GET_LIST]
  @P_BATCH_SIZE   INT = 100,
  @P_USER_ID      VARCHAR(30) = NULL,
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT TOP (CASE WHEN @P_BATCH_SIZE < 1 THEN 1 WHEN @P_BATCH_SIZE > 1000 THEN 1000 ELSE @P_BATCH_SIZE END) [RUN_ID], [STORED_PATH]
    FROM [FW].[TB_REPORT_RUN]
   WHERE [EXPIRE_DT] <= SYSUTCDATETIME() AND [STATUS_CD] <> 'RUNNING'
   ORDER BY [RUN_ID];
END
