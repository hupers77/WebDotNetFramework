-- 레포트 정의 한 건 (레포트 화면이 조건 입력·출력 전에 읽는다). 레포트나 그 프로그램이 사용 안 함이면 0행이다.
-- 권한(READ/PRINT/EXPORT)은 화면이 REPORT_ID(= 프로그램 ID)로 확인한다.
-- 결과: REPORT_ID, DATA_SP, TEMPLATE_VIEW, PARAMS_JSON, ORIENT_CD, APPROVAL_YN, TOTAL_YN, MAX_ROWS, PII_YN
CREATE PROCEDURE [FW].[USP_REPORT_GET]
  @P_REPORT_ID  VARCHAR(30),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT R.[REPORT_ID], R.[DATA_SP], R.[TEMPLATE_VIEW], R.[PARAMS_JSON], R.[ORIENT_CD], R.[APPROVAL_YN], R.[TOTAL_YN], R.[MAX_ROWS], P.[PII_YN]
    FROM [FW].[TB_REPORT] R
    JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = R.[REPORT_ID]
   WHERE R.[REPORT_ID] = @P_REPORT_ID
     AND R.[USE_YN] = 'Y'
     AND P.[USE_YN] = 'Y';
END
