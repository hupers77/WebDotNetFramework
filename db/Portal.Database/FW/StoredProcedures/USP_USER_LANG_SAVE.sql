-- 본인 화면 언어 변경 (헤더 언어 전환). 세션 확인 SP가 TB_USER.LANG_CD를 읽으므로 다음 요청부터 바로 바뀐다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_USER_LANG_SAVE]
  @P_NEW_LANG_CD  VARCHAR(5),
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_USER_ID IS NULL OR NOT EXISTS (SELECT 1 FROM [FW].[TB_LANG] WHERE [LANG_CD] = @P_NEW_LANG_CD AND [USE_YN] = 'Y')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @OLD_LANG_CD VARCHAR(5);

  BEGIN TRY
    BEGIN TRAN;

    SELECT @OLD_LANG_CD = [LANG_CD] FROM [FW].[TB_USER] WITH (UPDLOCK) WHERE [USER_ID] = @P_USER_ID;
    IF @@ROWCOUNT = 0
      THROW 50004, 'MSG.NOT_FOUND', 1;

    UPDATE [FW].[TB_USER]
       SET [LANG_CD] = @P_NEW_LANG_CD, [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
     WHERE [USER_ID] = @P_USER_ID AND [LANG_CD] <> @P_NEW_LANG_CD;

    IF @@ROWCOUNT > 0
    BEGIN
      DECLARE @BEFORE NVARCHAR(100) = (SELECT @OLD_LANG_CD AS [LANG_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
      DECLARE @AFTER NVARCHAR(100) = (SELECT @P_NEW_LANG_CD AS [LANG_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_USER_ID,
        @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    END

    COMMIT;

    SELECT 1 AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
