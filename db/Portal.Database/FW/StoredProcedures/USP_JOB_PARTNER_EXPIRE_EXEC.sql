-- 배치 작업 JOB_PARTNER_EXPIRE: 사용 기한이 지난 협력사 계정을 만료(EXPIRED)로 바꾸고, 기한 전에 안내 메일을 보낸다.
--   기한은 계정 사용 기한(ACCOUNT_END_DT)과 회사 계약 종료일(CONTRACT_END_DT) 중 이른 날이다(로그인도 둘 중 하나가 지나면 막힌다).
--   기한이 오늘부터 PARTNER.EXPIRE_NOTICE_DAYS(기본 7일, 0이면 안내 안 함) 안에 들면 안내 메일(TPL_ACCOUNT_EXPIRE)을 한 번 보낸다.
--   기한을 늘리면 새 기한 기준으로 다시 안내한다. 기한이 지나면 안내를 받았는지와 상관없이 만료로 바꾼다(계약이 끝났으므로).
--   날짜는 서버 현지 날짜(한국 시간) 기준이다. 사용(ACTIVE) 상태인 협력사 계정만 대상이다.
--   만료 계정은 관리자가 기한을 늘린 뒤 사용자 관리에서 '사용'으로 돌리거나, 회사 관리에서 계약 종료일을 늘리면 함께 돌아온다.
-- 결과: PROCESSED_CNT (만료 + 안내 건수)
CREATE PROCEDURE [FW].[USP_JOB_PARTNER_EXPIRE_EXEC]
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME(), @TODAY DATE = CAST(GETDATE() AS DATE), @BY VARCHAR(30) = ISNULL(@P_USER_ID, 'SYSTEM'), @CNT INT = 0;
  DECLARE @NOTICE_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'PARTNER.EXPIRE_NOTICE_DAYS'), 7);
  IF @NOTICE_DAYS < 0 SET @NOTICE_DAYS = 0;

  DECLARE @TARGET TABLE ([USER_ID] VARCHAR(30) PRIMARY KEY, [USER_NM] NVARCHAR(100), [END_DT] DATE, [KIND] CHAR(1));  -- E 만료, N 사전 안내

  INSERT INTO @TARGET ([USER_ID], [USER_NM], [END_DT], [KIND])
  SELECT U.[USER_ID], U.[USER_NM], E.[END_DT],
         CASE WHEN E.[END_DT] < @TODAY THEN 'E'
              WHEN @NOTICE_DAYS > 0 AND E.[END_DT] <= DATEADD(DAY, @NOTICE_DAYS, @TODAY)
                   AND (U.[EXPIRE_NOTICE_DT] IS NULL OR U.[EXPIRE_NOTICE_DT] < DATEADD(DAY, -@NOTICE_DAYS, E.[END_DT])) THEN 'N' END
    FROM [FW].[TB_USER] U
    JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
   CROSS APPLY (SELECT MIN(V.[DT]) AS [END_DT] FROM (VALUES (U.[ACCOUNT_END_DT]), (C.[CONTRACT_END_DT])) V ([DT])) E
   WHERE U.[USER_STAT_CD] = 'ACTIVE'
     AND U.[USER_TYPE_CD] = 'PARTNER'
     AND E.[END_DT] <= DATEADD(DAY, @NOTICE_DAYS, @TODAY);

  DELETE FROM @TARGET WHERE [KIND] IS NULL;  -- 이번 기한으로 이미 안내함

  DECLARE @TO_USER_ID VARCHAR(30), @USER_NM NVARCHAR(100), @END_DT DATE, @KIND CHAR(1), @PARAMS NVARCHAR(4000);
  DECLARE @AUDIT_BEFORE NVARCHAR(200) = (SELECT 'ACTIVE' AS [USER_STAT_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
  DECLARE @AUDIT_AFTER NVARCHAR(200) = (SELECT 'EXPIRED' AS [USER_STAT_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

  DECLARE TARGETS CURSOR LOCAL FAST_FORWARD FOR SELECT [USER_ID], [USER_NM], [END_DT], [KIND] FROM @TARGET ORDER BY [USER_ID];
  OPEN TARGETS;
  FETCH NEXT FROM TARGETS INTO @TO_USER_ID, @USER_NM, @END_DT, @KIND;
  WHILE @@FETCH_STATUS = 0
  BEGIN
    BEGIN TRAN;

    IF @KIND = 'E'
    BEGIN
      -- 그 사이 기한을 늘렸거나 상태가 바뀌었으면 건너뛴다
      UPDATE U
         SET [USER_STAT_CD] = 'EXPIRED', [STAT_CHG_DT] = @NOW, [UPD_ID] = @BY, [UPD_DT] = @NOW
        FROM [FW].[TB_USER] U
        JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
       WHERE U.[USER_ID] = @TO_USER_ID AND U.[USER_STAT_CD] = 'ACTIVE'
         AND (U.[ACCOUNT_END_DT] < @TODAY OR C.[CONTRACT_END_DT] < @TODAY);

      IF @@ROWCOUNT = 1
      BEGIN
        EXEC [LOG].[USP_AUDIT_WRITE]
          @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'U', @P_ROW_KEY = @TO_USER_ID,
          @P_BEFORE_JSON = @AUDIT_BEFORE, @P_AFTER_JSON = @AUDIT_AFTER,
          @P_USER_ID = @BY, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
        SET @CNT += 1;
      END
    END
    ELSE
    BEGIN
      UPDATE [FW].[TB_USER]
         SET [EXPIRE_NOTICE_DT] = @TODAY, [UPD_ID] = @BY, [UPD_DT] = @NOW
       WHERE [USER_ID] = @TO_USER_ID AND [USER_STAT_CD] = 'ACTIVE';

      IF @@ROWCOUNT = 1
      BEGIN
        SET @PARAMS = (SELECT @USER_NM AS [USER_NM], @TO_USER_ID AS [USER_ID], CONVERT(CHAR(10), @END_DT, 23) AS [EXPIRE_DT],
                              CAST(DATEDIFF(DAY, @TODAY, @END_DT) AS VARCHAR(10)) AS [DAYS_LEFT]
                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
        EXEC [FW].[USP_MSG_QUEUE_SAVE] @P_TEMPLATE_ID = 'TPL_ACCOUNT_EXPIRE', @P_TO_USER_ID = @TO_USER_ID, @P_PARAMS_JSON = @PARAMS,
             @P_RESULT_YN = 'N', @P_USER_ID = @BY, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
        SET @CNT += 1;
      END
    END

    COMMIT;
    FETCH NEXT FROM TARGETS INTO @TO_USER_ID, @USER_NM, @END_DT, @KIND;
  END
  CLOSE TARGETS;
  DEALLOCATE TARGETS;

  -- 만료된 계정의 권한 캐시를 버린다
  IF EXISTS (SELECT 1 FROM @TARGET WHERE [KIND] = 'E')
    UPDATE [FW].[TB_CACHE_VERSION]
       SET [VERSION_NO] += 1, [UPD_DT] = @NOW
     WHERE [CACHE_KEY] = 'AUTH';

  SELECT @CNT AS [PROCESSED_CNT];
END
