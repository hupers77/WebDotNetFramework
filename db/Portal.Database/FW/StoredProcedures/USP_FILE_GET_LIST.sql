-- 첨부 묶음의 파일 목록. 결과셋 1: 묶음(PROGRAM_ID, COMPANY_CD, SHARE_YN, CONFIRM_YN), 결과셋 2: 삭제되지 않은 파일.
-- 협력사 사용자는 자기 회사 묶음이나 공유 묶음(SHARE_YN = 'Y')만 볼 수 있고, 아니면 0행이다.
-- 프로그램 권한(READ)은 화면 서버가 결과셋 1의 PROGRAM_ID로 확인한다.
CREATE PROCEDURE [FW].[USP_FILE_GET_LIST]
  @P_FILE_GROUP_ID  BIGINT,
  @P_USER_ID        VARCHAR(30),
  @P_LANG_CD        VARCHAR(5),
  @P_CLIENT_IP      VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @G TABLE ([FILE_GROUP_ID] BIGINT, [PROGRAM_ID] VARCHAR(30), [COMPANY_CD] VARCHAR(10), [SHARE_YN] CHAR(1), [CONFIRM_YN] CHAR(1));

  INSERT INTO @G
  SELECT G.[FILE_GROUP_ID], G.[PROGRAM_ID], G.[COMPANY_CD], G.[SHARE_YN], G.[CONFIRM_YN]
    FROM [FW].[TB_FILE_GROUP] G
    JOIN [FW].[TB_USER] U ON U.[USER_ID] = @P_USER_ID AND U.[USER_STAT_CD] = 'ACTIVE'
   WHERE G.[FILE_GROUP_ID] = @P_FILE_GROUP_ID
     AND (U.[USER_TYPE_CD] <> 'PARTNER' OR G.[COMPANY_CD] = U.[COMPANY_CD] OR G.[SHARE_YN] = 'Y');

  SELECT [FILE_GROUP_ID], [PROGRAM_ID], [COMPANY_CD], [SHARE_YN], [CONFIRM_YN] FROM @G;

  SELECT F.[FILE_ID], F.[ORG_FILE_NM], F.[FILE_EXT], F.[FILE_SIZE], F.[SORT_NO], F.[DOWN_CNT], F.[REG_ID], F.[REG_DT]
    FROM [FW].[TB_FILE] F
    JOIN @G G ON G.[FILE_GROUP_ID] = F.[FILE_GROUP_ID]
   WHERE F.[DEL_YN] = 'N'
   ORDER BY F.[SORT_NO], F.[FILE_ID];
END
