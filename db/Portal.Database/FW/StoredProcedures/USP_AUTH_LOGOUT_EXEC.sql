-- 로그아웃: 세션 종료와 로그인 로그 기록. 이미 끝난 세션이면 아무것도 하지 않는다.
CREATE PROCEDURE [FW].[USP_AUTH_LOGOUT_EXEC]
  @P_SESSION_HASH CHAR(64),
  @P_USER_AGENT   NVARCHAR(300) = NULL,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @SESSION_USER_ID VARCHAR(30), @AUTH_METHOD_CD VARCHAR(10);

  BEGIN TRY
    BEGIN TRAN;

    UPDATE [FW].[TB_USER_SESSION]
       SET [END_DT] = @NOW, [END_REASON_CD] = 'LOGOUT', [UPD_ID] = [USER_ID], [UPD_DT] = @NOW,
           @SESSION_USER_ID = [USER_ID], @AUTH_METHOD_CD = [AUTH_METHOD_CD]
     WHERE [SESSION_ID] = @P_SESSION_HASH AND [END_DT] IS NULL;

    IF @SESSION_USER_ID IS NOT NULL
      EXEC [LOG].[USP_LOGIN_LOG_WRITE]
        @P_LOGIN_USER_ID = @SESSION_USER_ID, @P_LOGIN_RESULT_CD = 'LOGOUT', @P_AUTH_METHOD_CD = @AUTH_METHOD_CD,
        @P_USER_AGENT = @P_USER_AGENT, @P_SESSION_HASH = @P_SESSION_HASH,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
