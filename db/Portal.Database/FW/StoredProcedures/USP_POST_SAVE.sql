-- 게시글 등록·수정 (저장 SP 표준 템플릿). 프로그램: 게시판의 프로그램 (CREATE/UPDATE는 애플리케이션이 확인)
-- @P_POST_ID가 NULL이면 등록(@P_PARENT_POST_ID가 있으면 답글), 있으면 수정(작성자 또는 관리자, @P_ROW_VER 필요).
-- 게시판 설정이 꺼진 항목(비밀글·게시기간·상단 고정·첨부·답글)은 무시하거나 거절한다. 상단 고정·공개 대상 회사는 관리자(@P_MANAGER_YN)만 바꾼다.
-- @P_TARGETS는 회사 코드 JSON 배열(원글만). 첨부 묶음은 같은 트랜잭션에서 확정한다(다른 회사 사용자도 받을 수 있게 공유).
-- 결과: AFFECTED_CNT, NEW_KEY(글 ID)
CREATE PROCEDURE [FW].[USP_POST_SAVE]
  @P_POST_ID         BIGINT        = NULL,
  @P_ROW_VER         BINARY(8)     = NULL,
  @P_BOARD_CD        VARCHAR(30),
  @P_PARENT_POST_ID  BIGINT        = NULL,
  @P_TITLE           NVARCHAR(200),
  @P_CONTENT         NVARCHAR(MAX),
  @P_SECRET_YN       CHAR(1)       = 'N',
  @P_PIN_YN          CHAR(1)       = 'N',
  @P_START_DT        DATE          = NULL,
  @P_END_DT          DATE          = NULL,
  @P_FILE_GROUP_ID   BIGINT        = NULL,
  @P_TARGETS         NVARCHAR(MAX) = NULL,
  @P_MANAGER_YN      CHAR(1)       = 'N',
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_TITLE = LTRIM(RTRIM(@P_TITLE));
  IF NULLIF(@P_TITLE, N'') IS NULL OR NULLIF(LTRIM(RTRIM(@P_CONTENT)), N'') IS NULL
     OR @P_SECRET_YN NOT IN ('Y', 'N') OR @P_PIN_YN NOT IN ('Y', 'N') OR @P_MANAGER_YN NOT IN ('Y', 'N')
     OR (@P_START_DT IS NOT NULL AND @P_END_DT IS NOT NULL AND @P_START_DT > @P_END_DT)
     OR (@P_TARGETS IS NOT NULL AND ISJSON(@P_TARGETS) <> 1)
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @COMPANY VARCHAR(10), @REPLY_YN CHAR(1), @ATTACH_YN CHAR(1), @SECRET_OK CHAR(1), @PIN_OK CHAR(1), @PERIOD_OK CHAR(1), @PROGRAM_ID VARCHAR(30);
  SELECT @REPLY_YN = B.[REPLY_YN], @ATTACH_YN = B.[ATTACH_YN], @SECRET_OK = B.[SECRET_YN], @PIN_OK = B.[PIN_YN], @PERIOD_OK = B.[PERIOD_YN], @PROGRAM_ID = B.[PROGRAM_ID]
    FROM [FW].[TB_BOARD] B
   WHERE B.[BOARD_CD] = @P_BOARD_CD AND B.[USE_YN] = 'Y';
  IF @PROGRAM_ID IS NULL
    THROW 50004, 'MSG.NOT_FOUND', 1;
  SELECT @COMPANY = [COMPANY_CD] FROM [FW].[TB_USER] WHERE [USER_ID] = @P_USER_ID AND [USER_STAT_CD] = 'ACTIVE';
  IF @COMPANY IS NULL
    THROW 50004, 'MSG.NOT_FOUND', 1;

  -- 게시판 설정에 없는 기능은 쓰지 않는다
  SET @P_SECRET_YN = IIF(@SECRET_OK = 'Y', @P_SECRET_YN, 'N');
  IF @PERIOD_OK = 'N'
    SELECT @P_START_DT = NULL, @P_END_DT = NULL;
  IF @ATTACH_YN = 'N'
    SET @P_FILE_GROUP_ID = NULL;

  DECLARE @TARGET TABLE ([COMPANY_CD] VARCHAR(10) NOT NULL PRIMARY KEY);
  IF @P_TARGETS IS NOT NULL
  BEGIN
    INSERT INTO @TARGET ([COMPANY_CD])
    SELECT DISTINCT LTRIM(RTRIM([value])) FROM OPENJSON(@P_TARGETS) WHERE NULLIF(LTRIM(RTRIM([value])), '') IS NOT NULL;
    IF EXISTS (SELECT 1 FROM @TARGET T LEFT JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = T.[COMPANY_CD] WHERE C.[COMPANY_CD] IS NULL)
      THROW 50005, 'MSG.INVALID_INPUT', 1;
  END

  DECLARE @ID BIGINT, @ROOT BIGINT, @DEPTH TINYINT = 0, @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF @P_POST_ID IS NULL
    BEGIN
      IF @P_PARENT_POST_ID IS NOT NULL
      BEGIN
        IF @REPLY_YN = 'N'
          THROW 50003, 'MSG.BOARD_NO_REPLY', 1;

        -- 답글을 달 글은 볼 수 있는 글이어야 한다
        SELECT @ROOT = P.[ROOT_POST_ID], @DEPTH = P.[DEPTH] + 1
          FROM [FW].[TB_POST] P
          JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, @P_MANAGER_YN) V ON V.[POST_ID] = P.[POST_ID] AND V.[SECRET_OK_YN] = 'Y'
         WHERE P.[POST_ID] = @P_PARENT_POST_ID AND P.[BOARD_CD] = @P_BOARD_CD;
        IF @ROOT IS NULL
          THROW 50004, 'MSG.NOT_FOUND', 1;
        IF @DEPTH > 3
          THROW 50003, 'MSG.BOARD_REPLY_DEPTH', 1;
      END

      INSERT INTO [FW].[TB_POST]
        ([BOARD_CD], [ROOT_POST_ID], [PARENT_POST_ID], [DEPTH], [TITLE], [CONTENT], [COMPANY_CD], [WRITER_ID], [SECRET_YN], [PIN_YN],
         [START_DT], [END_DT], [FILE_GROUP_ID], [REG_ID], [UPD_ID])
      VALUES
        (@P_BOARD_CD, @ROOT, @P_PARENT_POST_ID, @DEPTH, @P_TITLE, @P_CONTENT, @COMPANY, @P_USER_ID, @P_SECRET_YN,
         IIF(@PIN_OK = 'Y' AND @P_MANAGER_YN = 'Y' AND @P_PARENT_POST_ID IS NULL, @P_PIN_YN, 'N'),
         @P_START_DT, @P_END_DT, @P_FILE_GROUP_ID, @P_USER_ID, @P_USER_ID);
      SET @ID = SCOPE_IDENTITY();

      IF @ROOT IS NULL
      BEGIN
        UPDATE [FW].[TB_POST] SET [ROOT_POST_ID] = @ID WHERE [POST_ID] = @ID;
        IF @P_MANAGER_YN = 'Y'
          INSERT INTO [FW].[TB_POST_TARGET] ([POST_ID], [COMPANY_CD]) SELECT @ID, [COMPANY_CD] FROM @TARGET;
      END

      SET @AFTER = (SELECT @ID AS [POST_ID], @P_BOARD_CD AS [BOARD_CD], @P_TITLE AS [TITLE], @P_PARENT_POST_ID AS [PARENT_POST_ID] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    END
    ELSE
    BEGIN
      DECLARE @VER BINARY(8), @WRITER VARCHAR(30), @CUR_ROOT BIGINT, @CUR_TITLE NVARCHAR(200), @CUR_PIN CHAR(1), @CUR_PARENT BIGINT;
      SELECT @VER = P.[ROW_VER], @WRITER = P.[WRITER_ID], @CUR_ROOT = P.[ROOT_POST_ID], @CUR_TITLE = P.[TITLE], @CUR_PIN = P.[PIN_YN], @CUR_PARENT = P.[PARENT_POST_ID]
        FROM [FW].[TB_POST] P WITH (UPDLOCK, HOLDLOCK)
       WHERE P.[POST_ID] = @P_POST_ID AND P.[BOARD_CD] = @P_BOARD_CD AND P.[DEL_YN] = 'N';
      IF @WRITER IS NULL OR (@WRITER <> @P_USER_ID AND @P_MANAGER_YN = 'N')
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
        THROW 50002, 'MSG.CONCURRENCY', 1;

      SET @ID = @P_POST_ID;
      SET @BEFORE = (SELECT @CUR_TITLE AS [TITLE], @CUR_PIN AS [PIN_YN] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

      UPDATE [FW].[TB_POST]
         SET [TITLE] = @P_TITLE, [CONTENT] = @P_CONTENT, [SECRET_YN] = @P_SECRET_YN,
             [PIN_YN] = IIF(@PIN_OK = 'Y' AND @P_MANAGER_YN = 'Y' AND @CUR_PARENT IS NULL, @P_PIN_YN, [PIN_YN]),
             [START_DT] = @P_START_DT, [END_DT] = @P_END_DT,
             [FILE_GROUP_ID] = IIF(@ATTACH_YN = 'Y', @P_FILE_GROUP_ID, [FILE_GROUP_ID]),
             [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
       WHERE [POST_ID] = @P_POST_ID;

      IF @P_MANAGER_YN = 'Y' AND @CUR_PARENT IS NULL AND @P_TARGETS IS NOT NULL
      BEGIN
        DELETE FROM [FW].[TB_POST_TARGET] WHERE [POST_ID] = @P_POST_ID;
        INSERT INTO [FW].[TB_POST_TARGET] ([POST_ID], [COMPANY_CD]) SELECT @P_POST_ID, [COMPANY_CD] FROM @TARGET;
      END

      SET @AFTER = (SELECT @ID AS [POST_ID], @P_BOARD_CD AS [BOARD_CD], @P_TITLE AS [TITLE] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    END

    IF @P_FILE_GROUP_ID IS NOT NULL
    BEGIN
      DECLARE @CONFIRMED TABLE ([AFFECTED_CNT] INT);
      INSERT INTO @CONFIRMED
      EXEC [FW].[USP_FILE_GROUP_CONFIRM_EXEC]
        @P_FILE_GROUP_ID = @P_FILE_GROUP_ID, @P_PROGRAM_ID = @PROGRAM_ID, @P_SHARE_YN = 'Y',
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
    END

    DECLARE @KEY NVARCHAR(200) = CAST(@ID AS NVARCHAR(20)), @ACTION CHAR(1) = IIF(@P_POST_ID IS NULL, 'I', 'U');
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_POST', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @KEY,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT], CAST(@ID AS NVARCHAR(20)) AS [NEW_KEY];
END
