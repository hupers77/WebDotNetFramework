-- 요청 하나를 끝낸다: DONE(파일 정보) 또는 FAILED(실패 사유 문구 키). 요청자에게 포털 알림을 보낸다(템플릿 TPL_REPORT_DONE / TPL_REPORT_FAILED).
-- RUNNING이 아닌 요청(이미 끝남)이면 아무것도 하지 않는다. 지운 요청이면 알림을 보내지 않는다. 끝난 요청은 7일 뒤 정리된다.
-- 결과: AFFECTED_CNT (0이면 저장소의 파일을 쓰지 않은 것으로 본다)
CREATE PROCEDURE [FW].[USP_REPORT_RUN_END_EXEC]
  @P_RUN_ID       BIGINT,
  @P_STATUS_CD    VARCHAR(10),
  @P_ROW_CNT      INT           = NULL,
  @P_FILE_NM      NVARCHAR(200) = NULL,
  @P_FILE_SIZE    BIGINT        = NULL,
  @P_STORED_PATH  VARCHAR(100)  = NULL,
  @P_ERR_KEY      VARCHAR(60)   = NULL,
  @P_ERR_ARG      NVARCHAR(100) = NULL,
  @P_USER_ID      VARCHAR(30) = NULL,
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_STATUS_CD NOT IN ('DONE', 'FAILED') OR (@P_STATUS_CD = 'DONE' AND (@P_STORED_PATH IS NULL OR @P_FILE_NM IS NULL))
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME(), @CNT INT, @REPORT_ID VARCHAR(30), @REQ_USER_ID VARCHAR(30), @DELETED BIT, @PARAMS NVARCHAR(4000),
          @TEMPLATE_ID VARCHAR(30) = IIF(@P_STATUS_CD = 'DONE', 'TPL_REPORT_DONE', 'TPL_REPORT_FAILED');

  BEGIN TRY
    BEGIN TRAN;

    UPDATE [FW].[TB_REPORT_RUN]
       SET [STATUS_CD] = @P_STATUS_CD, [ROW_CNT] = @P_ROW_CNT, [FILE_NM] = @P_FILE_NM, [FILE_SIZE] = @P_FILE_SIZE, [STORED_PATH] = @P_STORED_PATH,
           [ERR_KEY] = @P_ERR_KEY, [ERR_ARG] = @P_ERR_ARG, [END_DT] = @NOW, [EXPIRE_DT] = ISNULL([EXPIRE_DT], DATEADD(DAY, 7, @NOW)),
           -- 조건 값과 사유는 끝나면 더 필요 없다
           [PARAMS_JSON] = N'{}', [REASON] = NULL
     WHERE [RUN_ID] = @P_RUN_ID AND [STATUS_CD] = 'RUNNING';

    SET @CNT = @@ROWCOUNT;

    IF @CNT = 1
    BEGIN
      SELECT @REPORT_ID = [REPORT_ID], @REQ_USER_ID = [REQ_USER_ID], @DELETED = IIF([EXPIRE_DT] <= @NOW, 1, 0)
        FROM [FW].[TB_REPORT_RUN]
       WHERE [RUN_ID] = @P_RUN_ID;

      IF @DELETED = 0
      BEGIN
        SET @PARAMS = (SELECT @REPORT_ID AS [REPORT_ID], @P_FILE_NM AS [FILE_NM] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC [FW].[USP_MSG_QUEUE_SAVE]
          @P_TEMPLATE_ID = @TEMPLATE_ID, @P_TO_USER_ID = @REQ_USER_ID, @P_PARAMS_JSON = @PARAMS, @P_RESULT_YN = 'N',
          @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
      END
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT];
END
