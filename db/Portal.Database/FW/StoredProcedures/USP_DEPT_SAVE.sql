-- 부서 등록·수정 (저장 SP 표준 템플릿). 프로그램: SYS_DEPT_MGT
-- @P_ROW_VER가 NULL이면 등록, 있으면 수정. 등록하면 부서 ID를 D000001부터 차례로 부여한다(@P_DEPT_ID는 무시).
-- 부서 역할(@P_ROLES: [{"roleId":"..","inheritYn":"Y|N"}])은 이 목록이 되도록 더하고, 빼고, 상속 여부를 고친다.
-- 규칙: 회사는 데이터 범위 안이어야 하고 수정할 때 바꿀 수 없다. 상위 부서는 같은 회사의 부서여야 하고 자기 자신이나 하위 부서일 수 없다.
--       사용 중인 부서는 사용 안 함 부서 아래에 둘 수 없고, 사용 중인 하위 부서가 있으면 사용 안 함으로 바꿀 수 없다.
--       AD 동기화 부서(AD_OU_PATH 있음)는 이름·상위·사용 여부를 바꿀 수 없다(역할과 정렬 순서만).
--       역할은 COMPANY_TYPE_CD가 비었거나 회사 유형과 같은 사용 중인 것만 줄 수 있고, SYS_ADMIN은 부서로 줄 수 없다(빼는 것은 된다).
-- 역할·상속·상위·사용 여부가 바뀌면 권한 캐시(AUTH)를 갱신한다. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT, NEW_KEY(부서 ID)
CREATE PROCEDURE [FW].[USP_DEPT_SAVE]
  @P_DEPT_ID         VARCHAR(20)    = NULL,
  @P_ROW_VER         BINARY(8)      = NULL,
  @P_COMPANY_CD      VARCHAR(10),
  @P_PARENT_DEPT_ID  VARCHAR(20)    = NULL,
  @P_DEPT_NM         NVARCHAR(100),
  @P_SORT_NO         INT            = 0,
  @P_USE_YN          CHAR(1),
  @P_ROLES           NVARCHAR(MAX)  = N'[]',
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  SET @P_DEPT_NM = NULLIF(LTRIM(RTRIM(@P_DEPT_NM)), N'');
  SET @P_PARENT_DEPT_ID = NULLIF(LTRIM(RTRIM(@P_PARENT_DEPT_ID)), '');

  -- 입력 검증 (트랜잭션 전)
  IF (@P_ROW_VER IS NOT NULL AND NULLIF(LTRIM(RTRIM(@P_DEPT_ID)), '') IS NULL) OR @P_DEPT_NM IS NULL
     OR @P_USE_YN NOT IN ('Y', 'N') OR @P_SORT_NO < 0
     OR ISJSON(@P_ROLES) <> 1 OR LEFT(LTRIM(@P_ROLES), 1) <> '['
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @WANT TABLE ([ROLE_ID] VARCHAR(30) PRIMARY KEY, [INHERIT_YN] CHAR(1) NOT NULL);
  BEGIN TRY
    INSERT INTO @WANT ([ROLE_ID], [INHERIT_YN])
    SELECT [roleId], ISNULL([inheritYn], 'Y')
      FROM OPENJSON(@P_ROLES) WITH ([roleId] VARCHAR(30) '$.roleId', [inheritYn] CHAR(1) '$.inheritYn');
  END TRY
  BEGIN CATCH
    THROW 50005, 'MSG.INVALID_INPUT', 1; -- 같은 역할이 두 번 온 경우 등
  END CATCH
  IF EXISTS (SELECT 1 FROM @WANT WHERE [ROLE_ID] IS NULL OR [INHERIT_YN] NOT IN ('Y', 'N'))
     OR EXISTS (SELECT 1 FROM @WANT W LEFT JOIN [FW].[TB_ROLE] R ON R.[ROLE_ID] = W.[ROLE_ID] WHERE R.[ROLE_ID] IS NULL)
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @COMPANY_TYPE VARCHAR(10), @OLD_COMPANY VARCHAR(10), @OLD_VER BINARY(8), @OLD_PARENT VARCHAR(20), @OLD_USE CHAR(1),
          @OLD_NM NVARCHAR(100), @AD_PATH NVARCHAR(400), @PARENT_USE CHAR(1);
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF @P_ROW_VER IS NOT NULL
    BEGIN
      SELECT @OLD_COMPANY = [COMPANY_CD], @OLD_VER = [ROW_VER], @OLD_PARENT = [PARENT_DEPT_ID], @OLD_USE = [USE_YN],
             @OLD_NM = [DEPT_NM], @AD_PATH = [AD_OU_PATH]
        FROM [FW].[TB_DEPT] WITH (UPDLOCK, HOLDLOCK)
       WHERE [DEPT_ID] = @P_DEPT_ID;
      IF @OLD_COMPANY IS NULL
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @OLD_COMPANY <> @P_COMPANY_CD
        THROW 50005, 'MSG.INVALID_INPUT', 1;
    END

    SET @COMPANY_TYPE = (SELECT C.[COMPANY_TYPE_CD] FROM [FW].[TB_COMPANY] C
                          WHERE C.[COMPANY_CD] = @P_COMPANY_CD
                            AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'SYS_DEPT_MGT') S WHERE S.[COMPANY_CD] = C.[COMPANY_CD]));
    IF @COMPANY_TYPE IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NOT NULL AND @OLD_VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @AD_PATH IS NOT NULL
       AND (@P_DEPT_NM <> @OLD_NM OR @P_USE_YN <> @OLD_USE OR ISNULL(@P_PARENT_DEPT_ID, '') <> ISNULL(@OLD_PARENT, ''))
      THROW 50003, 'MSG.DEPT_AD_MANAGED', 1;

    IF @P_PARENT_DEPT_ID IS NOT NULL
    BEGIN
      SET @PARENT_USE = (SELECT [USE_YN] FROM [FW].[TB_DEPT] WHERE [DEPT_ID] = @P_PARENT_DEPT_ID AND [COMPANY_CD] = @P_COMPANY_CD);
      IF @PARENT_USE IS NULL
        THROW 50005, 'MSG.INVALID_INPUT', 1;
      IF @P_USE_YN = 'Y' AND @PARENT_USE <> 'Y'
        THROW 50003, 'MSG.DEPT_PARENT_UNUSED', 1;
      -- 상위로 고른 부서가 자기 자신이거나 자기 아래에 있으면 순환이 생긴다
      IF @P_ROW_VER IS NOT NULL
      BEGIN
        DECLARE @CYCLE BIT = 0;
        WITH [UP] AS (
          SELECT [DEPT_ID], [PARENT_DEPT_ID], 0 AS [DEPTH] FROM [FW].[TB_DEPT] WHERE [DEPT_ID] = @P_PARENT_DEPT_ID
          UNION ALL
          SELECT P.[DEPT_ID], P.[PARENT_DEPT_ID], U.[DEPTH] + 1
            FROM [UP] U JOIN [FW].[TB_DEPT] P ON P.[DEPT_ID] = U.[PARENT_DEPT_ID]
           WHERE U.[DEPTH] < 30
        )
        SELECT @CYCLE = 1 FROM [UP] WHERE [DEPT_ID] = @P_DEPT_ID;
        IF @CYCLE = 1
          THROW 50003, 'MSG.DEPT_PARENT_CYCLE', 1;
      END
    END

    IF @P_ROW_VER IS NOT NULL AND @P_USE_YN = 'N'
       AND EXISTS (SELECT 1 FROM [FW].[TB_DEPT] WHERE [PARENT_DEPT_ID] = @P_DEPT_ID AND [USE_YN] = 'Y')
      THROW 50003, 'MSG.DEPT_CHILD_IN_USE', 1;
    IF EXISTS (SELECT 1 FROM @WANT W JOIN [FW].[TB_ROLE] R ON R.[ROLE_ID] = W.[ROLE_ID]
                WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_DEPT_ROLE] DR WHERE DR.[DEPT_ID] = @P_DEPT_ID AND DR.[ROLE_ID] = W.[ROLE_ID])
                  AND (R.[USE_YN] <> 'Y' OR R.[ROLE_ID] = 'SYS_ADMIN'
                       OR (R.[COMPANY_TYPE_CD] IS NOT NULL AND R.[COMPANY_TYPE_CD] <> @COMPANY_TYPE)))
      THROW 50003, 'MSG.DEPT_ROLE_TYPE', 1;

    IF @P_ROW_VER IS NULL
    BEGIN
      -- 다음 부서 ID (D + 6자리 일련번호). 동시에 등록해도 겹치지 않게 잠근다
      DECLARE @SEQ INT = 1 + ISNULL((SELECT MAX(TRY_CAST(SUBSTRING([DEPT_ID], 2, 18) AS INT))
                                       FROM [FW].[TB_DEPT] WITH (UPDLOCK, HOLDLOCK)
                                      WHERE [DEPT_ID] LIKE 'D[0-9][0-9][0-9][0-9][0-9][0-9]%'
                                        AND SUBSTRING([DEPT_ID], 2, 18) NOT LIKE '%[^0-9]%'), 0);
      SET @P_DEPT_ID = 'D' + IIF(@SEQ < 1000000, RIGHT('000000' + CAST(@SEQ AS VARCHAR(18)), 6), CAST(@SEQ AS VARCHAR(18)));
      IF EXISTS (SELECT 1 FROM [FW].[TB_DEPT] WHERE [DEPT_ID] = @P_DEPT_ID)
        THROW 50001, 'MSG.DUP_CODE', 1;

      INSERT INTO [FW].[TB_DEPT] ([DEPT_ID], [COMPANY_CD], [PARENT_DEPT_ID], [DEPT_NM], [SORT_NO], [USE_YN], [REG_ID], [UPD_ID])
      VALUES (@P_DEPT_ID, @P_COMPANY_CD, @P_PARENT_DEPT_ID, @P_DEPT_NM, @P_SORT_NO, @P_USE_YN, @P_USER_ID, @P_USER_ID);
    END
    ELSE
    BEGIN
      SET @BEFORE = (SELECT D.[PARENT_DEPT_ID], D.[DEPT_NM], D.[SORT_NO], D.[USE_YN],
                            (SELECT [ROLE_ID], [INHERIT_YN] FROM [FW].[TB_DEPT_ROLE] WHERE [DEPT_ID] = D.[DEPT_ID] ORDER BY [ROLE_ID] FOR JSON PATH) AS [ROLES]
                       FROM [FW].[TB_DEPT] D WHERE D.[DEPT_ID] = @P_DEPT_ID
                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);

      UPDATE [FW].[TB_DEPT]
         SET [PARENT_DEPT_ID] = @P_PARENT_DEPT_ID, [DEPT_NM] = @P_DEPT_NM, [SORT_NO] = @P_SORT_NO, [USE_YN] = @P_USE_YN,
             [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
       WHERE [DEPT_ID] = @P_DEPT_ID;
    END

    -- 부서 역할을 @WANT가 되도록 맞춘다
    DECLARE @ROLE_CHANGES INT = 0;
    DELETE DR FROM [FW].[TB_DEPT_ROLE] DR
     WHERE DR.[DEPT_ID] = @P_DEPT_ID AND NOT EXISTS (SELECT 1 FROM @WANT W WHERE W.[ROLE_ID] = DR.[ROLE_ID]);
    SET @ROLE_CHANGES += @@ROWCOUNT;
    UPDATE DR SET DR.[INHERIT_YN] = W.[INHERIT_YN], DR.[UPD_ID] = @P_USER_ID, DR.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_DEPT_ROLE] DR JOIN @WANT W ON W.[ROLE_ID] = DR.[ROLE_ID]
     WHERE DR.[DEPT_ID] = @P_DEPT_ID AND DR.[INHERIT_YN] <> W.[INHERIT_YN];
    SET @ROLE_CHANGES += @@ROWCOUNT;
    INSERT INTO [FW].[TB_DEPT_ROLE] ([DEPT_ID], [ROLE_ID], [INHERIT_YN], [REG_ID], [UPD_ID])
    SELECT @P_DEPT_ID, W.[ROLE_ID], W.[INHERIT_YN], @P_USER_ID, @P_USER_ID
      FROM @WANT W
     WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_DEPT_ROLE] DR WHERE DR.[DEPT_ID] = @P_DEPT_ID AND DR.[ROLE_ID] = W.[ROLE_ID]);
    SET @ROLE_CHANGES += @@ROWCOUNT;

    SET @AFTER = (SELECT D.[DEPT_ID], D.[COMPANY_CD], D.[PARENT_DEPT_ID], D.[DEPT_NM], D.[SORT_NO], D.[USE_YN],
                         (SELECT [ROLE_ID], [INHERIT_YN] FROM [FW].[TB_DEPT_ROLE] WHERE [DEPT_ID] = D.[DEPT_ID] ORDER BY [ROLE_ID] FOR JSON PATH) AS [ROLES]
                    FROM [FW].[TB_DEPT] D WHERE D.[DEPT_ID] = @P_DEPT_ID
                    FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);
    DECLARE @ACTION CHAR(1) = IIF(@P_ROW_VER IS NULL, 'I', 'U');
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_DEPT', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @P_DEPT_ID,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    IF @ROLE_CHANGES > 0
       OR (@P_ROW_VER IS NOT NULL AND (@OLD_USE <> @P_USE_YN OR ISNULL(@OLD_PARENT, '') <> ISNULL(@P_PARENT_DEPT_ID, '')))
      UPDATE [FW].[TB_CACHE_VERSION]
         SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME()
       WHERE [CACHE_KEY] = 'AUTH';

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT], @P_DEPT_ID AS [NEW_KEY];
END
