-- 공지 팝업 관리 목록 (시작일 최신순). 프로그램: SYS_POPUP_MGT
-- 결과셋 1: 팝업 (제목은 화면 언어, 없으면 기본 언어) + 언어별 제목·내용(수정 화면용), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_POPUP_GET_LIST]
  @P_KEYWORD    NVARCHAR(100) = NULL,
  @P_USE_YN     CHAR(1)       = NULL,
  @P_PAGE_NO    INT           = 1,
  @P_PAGE_SIZE  INT           = 20,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SET @P_KEYWORD = NULLIF(LTRIM(RTRIM(@P_KEYWORD)), N'');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 100 THEN 100 ELSE @P_PAGE_SIZE END;
  IF @P_USE_YN IS NOT NULL AND @P_USE_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  SELECT P.[POPUP_ID], P.[OPEN_SCOPE_CD], CONVERT(CHAR(10), P.[START_DT], 23) AS [START_DT], CONVERT(CHAR(10), P.[END_DT], 23) AS [END_DT], P.[USE_YN],
         COALESCE(L.[TITLE], D.[TITLE], N'') AS [TITLE],
         (SELECT [LANG_CD] AS [langCd], [TITLE] AS [title], [CONTENT] AS [content]
            FROM [FW].[TB_POPUP_LANG] WHERE [POPUP_ID] = P.[POPUP_ID] ORDER BY [LANG_CD] FOR JSON PATH) AS [LANGS_JSON],
         P.[UPD_ID], P.[UPD_DT], P.[ROW_VER]
    FROM [FW].[TB_POPUP] P
    LEFT JOIN [FW].[TB_POPUP_LANG] L ON L.[POPUP_ID] = P.[POPUP_ID] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_POPUP_LANG] D ON D.[POPUP_ID] = P.[POPUP_ID] AND D.[LANG_CD] = @DEFAULT_LANG
   WHERE (@P_USE_YN IS NULL OR P.[USE_YN] = @P_USE_YN)
     AND (@P_KEYWORD IS NULL OR EXISTS (SELECT 1 FROM [FW].[TB_POPUP_LANG] K WHERE K.[POPUP_ID] = P.[POPUP_ID] AND K.[TITLE] LIKE N'%' + @P_KEYWORD + N'%'))
   ORDER BY P.[START_DT] DESC, P.[POPUP_ID] DESC
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_POPUP] P
   WHERE (@P_USE_YN IS NULL OR P.[USE_YN] = @P_USE_YN)
     AND (@P_KEYWORD IS NULL OR EXISTS (SELECT 1 FROM [FW].[TB_POPUP_LANG] K WHERE K.[POPUP_ID] = P.[POPUP_ID] AND K.[TITLE] LIKE N'%' + @P_KEYWORD + N'%'))
  OPTION (RECOMPILE);
END
