-- API 클라이언트 비밀값 (재)발급. 프로그램: SYS_API_CLIENT_MGT
-- 웹서버가 만든 비밀값의 해시·salt만 받는다(원문은 DB에 오지 않는다). 새 비밀값을 저장하면 이전 비밀값은 바로 쓸 수 없다.
-- 감사 로그에는 발급 사실만 남기고 해시는 넣지 않는다. 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_API_CLIENT_SECRET_SET]
  @P_CLIENT_ID    VARCHAR(50),
  @P_ROW_VER      BINARY(8),
  @P_SECRET_HASH  BINARY(64),
  @P_SECRET_SALT  BINARY(16),
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_CLIENT_ID IS NULL OR @P_ROW_VER IS NULL OR @P_SECRET_HASH IS NULL OR @P_SECRET_SALT IS NULL
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @CNT INT = 0, @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    DECLARE @CUR BINARY(8);
    SELECT @CUR = [ROW_VER] FROM [FW].[TB_API_CLIENT] WITH (UPDLOCK) WHERE [CLIENT_ID] = @P_CLIENT_ID;
    IF @CUR IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @CUR <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;

    UPDATE [FW].[TB_API_CLIENT]
       SET [SECRET_HASH] = @P_SECRET_HASH, [SECRET_SALT] = @P_SECRET_SALT, [SECRET_ISSUED_DT] = SYSUTCDATETIME(),
           [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
     WHERE [CLIENT_ID] = @P_CLIENT_ID;
    SET @CNT = @@ROWCOUNT;

    SET @AFTER = (SELECT @P_CLIENT_ID AS [CLIENT_ID], 'SECRET_ISSUED' AS [EVENT] FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_API_CLIENT', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_CLIENT_ID,
      @P_BEFORE_JSON = NULL, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
