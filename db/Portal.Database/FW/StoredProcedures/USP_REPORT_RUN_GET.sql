-- 내 레포트 생성 요청 한 건 (내려받기용, 저장 위치 포함). 남의 요청·지운 요청이면 0행이다.
-- 프로그램: RPT_RUNS (READ)
CREATE PROCEDURE [FW].[USP_REPORT_RUN_GET]
  @P_RUN_ID       BIGINT,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT [RUN_ID], [REPORT_ID], [FORMAT_CD], [STATUS_CD], [FILE_NM], [FILE_SIZE], [STORED_PATH]
    FROM [FW].[TB_REPORT_RUN]
   WHERE [RUN_ID] = @P_RUN_ID
     AND [REQ_USER_ID] = @P_USER_ID
     AND ([EXPIRE_DT] IS NULL OR [EXPIRE_DT] > SYSUTCDATETIME());
END
