-- 배치 작업 JOB_DATA_CLEANUP: 보관 기간이 지난 프레임워크 데이터를 정리한다(개인정보 최소 보관).
--   처리(승인·반려)한 지 PARTNER.JOIN_KEEP_DAYS(기본 30일)가 지난 가입 신청의 암호화 이메일을 지운다.
--   발송을 마친(SENT·FAILED) 지 MSG.KEEP_DAYS(기본 90일)가 지난 메일 대기열 행을 지운다.
--   JOB.HIST_KEEP_DAYS(기본 365일)가 지난 작업 실행 이력을 지운다.
--   NOTIFY.KEEP_DAYS(기본 90일)가 지난 포털 알림을 지운다(읽었는지와 상관없이).
-- 결과: PROCESSED_CNT
CREATE PROCEDURE [FW].[USP_JOB_DATA_CLEANUP_EXEC]
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME(), @CNT INT = 0, @ROWS INT = 1;
  DECLARE @JOIN_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'PARTNER.JOIN_KEEP_DAYS'), 30);
  DECLARE @MSG_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'MSG.KEEP_DAYS'), 90);
  DECLARE @HIST_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'JOB.HIST_KEEP_DAYS'), 365);
  DECLARE @NOTI_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'NOTIFY.KEEP_DAYS'), 90);

  WHILE @ROWS > 0
  BEGIN
    UPDATE TOP (5000) [FW].[TB_PARTNER_JOIN_REQ]
       SET [EMAIL_ENC] = NULL, [UPD_ID] = ISNULL(@P_USER_ID, 'SYSTEM'), [UPD_DT] = @NOW
     WHERE [REQ_STAT_CD] IN ('APPROVED', 'REJECTED')
       AND [EMAIL_ENC] IS NOT NULL
       AND [PROC_DT] < DATEADD(DAY, -@JOIN_DAYS, @NOW);
    SET @ROWS = @@ROWCOUNT;
    SET @CNT += @ROWS;
  END

  SET @ROWS = 1;
  WHILE @ROWS > 0
  BEGIN
    DELETE TOP (5000) FROM [FW].[TB_MSG_QUEUE]
     WHERE [STAT_CD] IN ('SENT', 'FAILED')
       AND [UPD_DT] < DATEADD(DAY, -@MSG_DAYS, @NOW);
    SET @ROWS = @@ROWCOUNT;
    SET @CNT += @ROWS;
  END

  SET @ROWS = 1;
  WHILE @ROWS > 0
  BEGIN
    DELETE TOP (5000) FROM [FW].[TB_JOB_HIST]
     WHERE [START_DT] < DATEADD(DAY, -@HIST_DAYS, @NOW)
       AND [RESULT_CD] <> 'RUNNING';
    SET @ROWS = @@ROWCOUNT;
    SET @CNT += @ROWS;
  END

  SET @ROWS = 1;
  WHILE @ROWS > 0
  BEGIN
    DELETE TOP (5000) FROM [FW].[TB_NOTIFICATION]
     WHERE [REG_DT] < DATEADD(DAY, -@NOTI_DAYS, @NOW);
    SET @ROWS = @@ROWCOUNT;
    SET @CNT += @ROWS;
  END

  SELECT @CNT AS [PROCESSED_CNT];
END
