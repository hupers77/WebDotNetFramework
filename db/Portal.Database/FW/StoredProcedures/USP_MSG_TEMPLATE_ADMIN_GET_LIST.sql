-- 메시지 템플릿 관리 목록 (템플릿은 초기 데이터와 코드가 정하므로 목록은 쪽 나눔 없이 전체). 프로그램: SYS_MSG_TEMPLATE_MGT
-- 결과셋 1: 템플릿(ID 순) + 보내기 기다리는 메일 수, 결과셋 2: 언어별 제목·본문
CREATE PROCEDURE [FW].[USP_MSG_TEMPLATE_ADMIN_GET_LIST]
  @P_KEYWORD    NVARCHAR(100) = NULL,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT T.[TEMPLATE_ID], T.[TEMPLATE_NM], T.[MAIL_YN], T.[PORTAL_YN], T.[USE_YN], T.[FROM_NAME], T.[LINK_PROGRAM_ID],
         (SELECT COUNT(*) FROM [FW].[TB_MSG_QUEUE] Q WHERE Q.[TEMPLATE_ID] = T.[TEMPLATE_ID] AND Q.[STAT_CD] IN ('READY', 'SENDING')) AS [PENDING_CNT],
         T.[UPD_ID], T.[UPD_DT], T.[ROW_VER]
    FROM [FW].[TB_MSG_TEMPLATE] T
   WHERE @P_KEYWORD IS NULL OR T.[TEMPLATE_ID] LIKE '%' + @P_KEYWORD + '%' OR T.[TEMPLATE_NM] LIKE '%' + @P_KEYWORD + '%'
   ORDER BY T.[TEMPLATE_ID]
  OPTION (RECOMPILE);

  SELECT L.[TEMPLATE_ID], L.[LANG_CD], L.[SUBJECT], L.[BODY]
    FROM [FW].[TB_MSG_TEMPLATE_LANG] L
    JOIN [FW].[TB_MSG_TEMPLATE] T ON T.[TEMPLATE_ID] = L.[TEMPLATE_ID]
   WHERE @P_KEYWORD IS NULL OR T.[TEMPLATE_ID] LIKE '%' + @P_KEYWORD + '%' OR T.[TEMPLATE_NM] LIKE '%' + @P_KEYWORD + '%'
   ORDER BY L.[TEMPLATE_ID], L.[LANG_CD]
  OPTION (RECOMPILE);
END
