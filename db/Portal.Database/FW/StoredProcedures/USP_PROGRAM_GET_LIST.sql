-- 프로그램 목록 (프로그램 관리 화면). 프로그램: SYS_PROGRAM_MGT
-- 결과: PROGRAM_ID, MODULE_CD, PROGRAM_NM, URL, PII_YN, USE_YN, FUNCS(사용 기능 쉼표 목록, 공통코드 FUNC_CD 순서),
--       MENU_CNT(연결 메뉴 수), API_CNT(등록된 서버 경로 수), ROLE_CNT(권한을 받은 역할 수), UPD_ID, UPD_DT, ROW_VER
CREATE PROCEDURE [FW].[USP_PROGRAM_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT P.[PROGRAM_ID], P.[MODULE_CD], P.[PROGRAM_NM], P.[URL], P.[PII_YN], P.[USE_YN],
         ISNULL((SELECT STRING_AGG(F.[FUNC_CD], ',') WITHIN GROUP (ORDER BY ISNULL(C.[SORT_NO], 9999), F.[FUNC_CD])
                   FROM [FW].[TB_PROGRAM_FUNC] F
                   LEFT JOIN [FW].[TB_CODE] C ON C.[GROUP_CD] = 'FUNC_CD' AND C.[CODE] = F.[FUNC_CD]
                  WHERE F.[PROGRAM_ID] = P.[PROGRAM_ID]), '') AS [FUNCS],
         (SELECT COUNT(*) FROM [FW].[TB_MENU] M WHERE M.[PROGRAM_ID] = P.[PROGRAM_ID]) AS [MENU_CNT],
         (SELECT COUNT(*) FROM [FW].[TB_PROGRAM_API] A WHERE A.[PROGRAM_ID] = P.[PROGRAM_ID]) AS [API_CNT],
         (SELECT COUNT(DISTINCT RF.[ROLE_ID]) FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF WHERE RF.[PROGRAM_ID] = P.[PROGRAM_ID]) AS [ROLE_CNT],
         P.[UPD_ID], P.[UPD_DT], P.[ROW_VER]
    FROM [FW].[TB_PROGRAM] P
   ORDER BY P.[MODULE_CD], P.[PROGRAM_ID];
END
