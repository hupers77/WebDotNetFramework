-- 레포트 관리 목록 (등록된 레포트 전체, 사용 안 함 포함). 프로그램: RPT_REPORT_MGT
-- 결과셋 1: 레포트(ID 순) + 프로그램 정보 + 지금까지 만든 요청 수, 결과셋 2: 레포트로 등록할 수 있는 프로그램(사용 중이고 아직 레포트가 아닌 것), 결과셋 3: 전체 건수
CREATE PROCEDURE [FW].[USP_REPORT_ADMIN_GET_LIST]
  @P_KEYWORD    NVARCHAR(100) = NULL,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT R.[REPORT_ID], P.[PROGRAM_NM], P.[URL], P.[PII_YN], P.[USE_YN] AS [PROGRAM_USE_YN], R.[DATA_SP], R.[TEMPLATE_VIEW], R.[PARAMS_JSON],
         R.[ORIENT_CD], R.[APPROVAL_YN], R.[TOTAL_YN], R.[MAX_ROWS], R.[USE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_REPORT_RUN] U WHERE U.[REPORT_ID] = R.[REPORT_ID]) AS [RUN_CNT],
         R.[UPD_ID], R.[UPD_DT], R.[ROW_VER]
    FROM [FW].[TB_REPORT] R
    JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = R.[REPORT_ID]
   WHERE @P_KEYWORD IS NULL OR R.[REPORT_ID] LIKE '%' + @P_KEYWORD + '%' OR P.[PROGRAM_NM] LIKE '%' + @P_KEYWORD + '%' OR R.[DATA_SP] LIKE '%' + @P_KEYWORD + '%'
   ORDER BY R.[REPORT_ID]
  OPTION (RECOMPILE);

  SELECT P.[PROGRAM_ID], P.[PROGRAM_NM]
    FROM [FW].[TB_PROGRAM] P
   WHERE P.[USE_YN] = 'Y' AND NOT EXISTS (SELECT 1 FROM [FW].[TB_REPORT] R WHERE R.[REPORT_ID] = P.[PROGRAM_ID])
   ORDER BY P.[PROGRAM_ID];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_REPORT];
END
