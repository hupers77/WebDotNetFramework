-- 배치 작업 JOB_SESSION_CLEANUP: 시간이 지난 세션을 TIMEOUT으로 끝내고, 끝난 지 SESSION.KEEP_DAYS(기본 30일)가 지난 세션 행을 지운다.
-- 로그인·로그아웃 기록은 LOG.TB_LOGIN_LOG에 따로 10년 남는다.
-- 결과: PROCESSED_CNT
CREATE PROCEDURE [FW].[USP_JOB_SESSION_CLEANUP_EXEC]
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME(), @CNT INT = 0, @ROWS INT = 1;
  DECLARE @KEEP_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'SESSION.KEEP_DAYS'), 30);

  WHILE @ROWS > 0
  BEGIN
    UPDATE TOP (5000) [FW].[TB_USER_SESSION]
       SET [END_DT] = [EXPIRE_DT], [END_REASON_CD] = 'TIMEOUT', [UPD_ID] = ISNULL(@P_USER_ID, 'SYSTEM'), [UPD_DT] = @NOW
     WHERE [END_DT] IS NULL
       AND [EXPIRE_DT] <= @NOW;
    SET @ROWS = @@ROWCOUNT;
    SET @CNT += @ROWS;
  END

  SET @ROWS = 1;
  WHILE @ROWS > 0
  BEGIN
    DELETE TOP (5000) FROM [FW].[TB_USER_SESSION]
     WHERE [END_DT] < DATEADD(DAY, -@KEEP_DAYS, @NOW);
    SET @ROWS = @@ROWCOUNT;
    SET @CNT += @ROWS;
  END

  SELECT @CNT AS [PROCESSED_CNT];
END
