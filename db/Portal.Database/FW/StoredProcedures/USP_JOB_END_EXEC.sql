-- 작업 실행을 끝낸다: 이력에 결과를 적고 작업 잠금을 푼다. 멈춘 것으로 보고 다른 Worker가 넘겨받은 실행이면 아무것도 바꾸지 않는다.
-- 실패하면 PORTAL_ADMIN 역할 사용자에게 TPL_JOB_FAILED 메일을 쌓는다. 직전 실행도 실패였으면 다시 보내지 않는다(1분마다 도는 작업이 메일을 쏟아내지 않게).
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_JOB_END_EXEC]
  @P_HIST_ID       BIGINT,
  @P_RESULT_CD     VARCHAR(10),
  @P_PROCESSED_CNT INT = NULL,
  @P_RESULT_MSG    NVARCHAR(1000) = NULL,
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_RESULT_CD NOT IN ('SUCCESS', 'FAILED', 'SKIPPED')
    THROW 50005, 'JOB.INVALID_INPUT', 1;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @ENDED TABLE ([JOB_ID] VARCHAR(30), [JOB_NM] NVARCHAR(100), [PREV_RESULT_CD] VARCHAR(10));
  DECLARE @JOB_ID VARCHAR(30), @CNT INT = 0;

  BEGIN TRY
    BEGIN TRAN;

    UPDATE [FW].[TB_JOB_HIST]
       SET [RESULT_CD] = @P_RESULT_CD, [END_DT] = @NOW, [PROCESSED_CNT] = @P_PROCESSED_CNT, [RESULT_MSG] = LEFT(@P_RESULT_MSG, 1000),
           @JOB_ID = [JOB_ID]
     WHERE [HIST_ID] = @P_HIST_ID
       AND [RESULT_CD] = 'RUNNING';

    SET @CNT = @@ROWCOUNT;

    IF @CNT = 1
      UPDATE [FW].[TB_JOB]
         SET [RUNNING_YN] = 'N', [LOCK_DT] = NULL, [LAST_RESULT_CD] = @P_RESULT_CD, [UPD_DT] = @NOW
      OUTPUT inserted.[JOB_ID], inserted.[JOB_NM], deleted.[LAST_RESULT_CD] INTO @ENDED
       WHERE [JOB_ID] = @JOB_ID
         AND [LAST_HIST_ID] = @P_HIST_ID;

    IF @P_RESULT_CD = 'FAILED' AND EXISTS (SELECT 1 FROM @ENDED WHERE ISNULL([PREV_RESULT_CD], '') <> 'FAILED')
    BEGIN
      DECLARE @PARAMS NVARCHAR(4000) =
        (SELECT [JOB_ID], [JOB_NM], LEFT(ISNULL(@P_RESULT_MSG, N''), 300) AS [RESULT_MSG] FROM @ENDED FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
      DECLARE @TO_USER_ID VARCHAR(30);
      DECLARE ADMINS CURSOR LOCAL FAST_FORWARD FOR
        SELECT U.[USER_ID]
          FROM [FW].[TB_USER] U
         WHERE U.[USER_STAT_CD] = 'ACTIVE'
           AND U.[EMAIL_ENC] IS NOT NULL
           AND EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](U.[USER_ID]) R WHERE R.[ROLE_ID] = 'PORTAL_ADMIN');
      OPEN ADMINS;
      FETCH NEXT FROM ADMINS INTO @TO_USER_ID;
      WHILE @@FETCH_STATUS = 0
      BEGIN
        EXEC [FW].[USP_MSG_QUEUE_SAVE] @P_TEMPLATE_ID = 'TPL_JOB_FAILED', @P_TO_USER_ID = @TO_USER_ID, @P_PARAMS_JSON = @PARAMS,
             @P_RESULT_YN = 'N', @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
        FETCH NEXT FROM ADMINS INTO @TO_USER_ID;
      END
      CLOSE ADMINS;
      DEALLOCATE ADMINS;
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT];
END
