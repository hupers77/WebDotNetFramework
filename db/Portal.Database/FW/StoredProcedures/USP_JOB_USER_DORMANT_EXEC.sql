-- 배치 작업 JOB_USER_DORMANT: 오래 로그인하지 않은 계정을 휴면(DORMANT)으로 바꾼다. 휴면 계정은 로그인할 수 없고 관리자가 사용자 관리에서 '사용'으로 되돌린다.
--   미접속 기간의 기준은 마지막 로그인, 상태를 마지막으로 바꾼 시각(휴면 해제 등), 계정 등록 시각 중 가장 늦은 것이다.
--   USER.DORMANT_DAYS(기본 365일, 0이면 끔)에서 USER.DORMANT_NOTICE_DAYS(기본 30일)를 뺀 날이 지나면 안내 메일(TPL_DORMANT_NOTICE)을 한 번 보내고,
--   안내한 뒤에도 로그인하지 않고 휴면 기준일과 안내 후 USER.DORMANT_NOTICE_DAYS가 모두 지나면 휴면으로 바꾼다(안내 없이 바로 휴면되지 않는다).
--   업무 이메일이 없는 계정도 안내 시각은 남겨 같은 일정으로 휴면된다. 시스템 계정(USER_TYPE_CD = SYSTEM)은 제외한다.
-- 결과: PROCESSED_CNT (휴면 전환 + 안내 건수)
CREATE PROCEDURE [FW].[USP_JOB_USER_DORMANT_EXEC]
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME(), @BY VARCHAR(30) = ISNULL(@P_USER_ID, 'SYSTEM'), @CNT INT = 0;
  DECLARE @DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'USER.DORMANT_DAYS'), 365);
  DECLARE @NOTICE_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'USER.DORMANT_NOTICE_DAYS'), 30);

  IF @DAYS <= 0
  BEGIN
    SELECT 0 AS [PROCESSED_CNT];
    RETURN;
  END

  SET @NOTICE_DAYS = CASE WHEN @NOTICE_DAYS < 0 THEN 0 WHEN @NOTICE_DAYS > @DAYS THEN @DAYS ELSE @NOTICE_DAYS END;

  DECLARE @TARGET TABLE ([USER_ID] VARCHAR(30) PRIMARY KEY, [USER_NM] NVARCHAR(100), [KIND] CHAR(1));  -- D 휴면 전환, N 사전 안내

  INSERT INTO @TARGET ([USER_ID], [USER_NM], [KIND])
  SELECT U.[USER_ID], U.[USER_NM],
         CASE WHEN B.[BASE_DT] < DATEADD(DAY, -@DAYS, @NOW)
                   AND U.[DORMANT_NOTICE_DT] >= B.[BASE_DT] AND U.[DORMANT_NOTICE_DT] <= DATEADD(DAY, -@NOTICE_DAYS, @NOW) THEN 'D'
              WHEN U.[DORMANT_NOTICE_DT] IS NULL OR U.[DORMANT_NOTICE_DT] < B.[BASE_DT] THEN 'N' END
    FROM [FW].[TB_USER] U
   CROSS APPLY (SELECT MAX(V.[DT]) AS [BASE_DT] FROM (VALUES (U.[LAST_LOGIN_DT]), (U.[STAT_CHG_DT]), (U.[REG_DT])) V ([DT])) B
   WHERE U.[USER_STAT_CD] = 'ACTIVE'
     AND U.[USER_TYPE_CD] <> 'SYSTEM'
     AND B.[BASE_DT] < DATEADD(DAY, -(@DAYS - @NOTICE_DAYS), @NOW);

  DELETE FROM @TARGET WHERE [KIND] IS NULL;  -- 이미 안내했고 아직 휴면 시점이 아님

  DECLARE @TO_USER_ID VARCHAR(30), @USER_NM NVARCHAR(100), @KIND CHAR(1), @PARAMS NVARCHAR(4000);
  DECLARE @AUDIT_BEFORE NVARCHAR(200) = (SELECT 'ACTIVE' AS [USER_STAT_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
  DECLARE @AUDIT_AFTER NVARCHAR(200) = (SELECT 'DORMANT' AS [USER_STAT_CD] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

  DECLARE TARGETS CURSOR LOCAL FAST_FORWARD FOR SELECT [USER_ID], [USER_NM], [KIND] FROM @TARGET ORDER BY [USER_ID];
  OPEN TARGETS;
  FETCH NEXT FROM TARGETS INTO @TO_USER_ID, @USER_NM, @KIND;
  WHILE @@FETCH_STATUS = 0
  BEGIN
    BEGIN TRAN;

    IF @KIND = 'D'
    BEGIN
      -- 그 사이 로그인했거나 상태가 바뀌었으면 건너뛴다
      UPDATE [FW].[TB_USER]
         SET [USER_STAT_CD] = 'DORMANT', [STAT_CHG_DT] = @NOW, [DORMANT_NOTICE_DT] = NULL, [UPD_ID] = @BY, [UPD_DT] = @NOW
       WHERE [USER_ID] = @TO_USER_ID AND [USER_STAT_CD] = 'ACTIVE'
         AND (SELECT MAX(V.[DT]) FROM (VALUES ([LAST_LOGIN_DT]), ([STAT_CHG_DT]), ([REG_DT])) V ([DT])) < DATEADD(DAY, -@DAYS, @NOW);

      IF @@ROWCOUNT = 1
      BEGIN
        EXEC [LOG].[USP_AUDIT_WRITE]
          @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = 'U', @P_ROW_KEY = @TO_USER_ID,
          @P_BEFORE_JSON = @AUDIT_BEFORE, @P_AFTER_JSON = @AUDIT_AFTER,
          @P_USER_ID = @BY, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
        SET @CNT += 1;
      END
    END
    ELSE
    BEGIN
      UPDATE [FW].[TB_USER]
         SET [DORMANT_NOTICE_DT] = @NOW, [UPD_ID] = @BY, [UPD_DT] = @NOW
       WHERE [USER_ID] = @TO_USER_ID AND [USER_STAT_CD] = 'ACTIVE';

      IF @@ROWCOUNT = 1
      BEGIN
        SET @PARAMS = (SELECT @USER_NM AS [USER_NM], @TO_USER_ID AS [USER_ID], CAST(@NOTICE_DAYS AS VARCHAR(10)) AS [NOTICE_DAYS]
                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
        EXEC [FW].[USP_MSG_QUEUE_SAVE] @P_TEMPLATE_ID = 'TPL_DORMANT_NOTICE', @P_TO_USER_ID = @TO_USER_ID, @P_PARAMS_JSON = @PARAMS,
             @P_RESULT_YN = 'N', @P_USER_ID = @BY, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
        SET @CNT += 1;
      END
    END

    COMMIT;
    FETCH NEXT FROM TARGETS INTO @TO_USER_ID, @USER_NM, @KIND;
  END
  CLOSE TARGETS;
  DEALLOCATE TARGETS;

  -- 휴면으로 바뀐 계정의 권한 캐시를 버린다
  IF EXISTS (SELECT 1 FROM @TARGET WHERE [KIND] = 'D')
    UPDATE [FW].[TB_CACHE_VERSION]
       SET [VERSION_NO] += 1, [UPD_DT] = @NOW
     WHERE [CACHE_KEY] = 'AUTH';

  SELECT @CNT AS [PROCESSED_CNT];
END
