-- API 클라이언트 한 건 (토큰 발급·호출 확인용). 인증 전에 호출되므로 @P_USER_ID는 비어 있다.
-- ACTIVE_YN: 사용 중이고 사용 기한 안이면 'Y' (DB 시계 기준, 기한 날짜 포함)
-- 결과: 한 행 (없으면 0행)
CREATE PROCEDURE [FW].[USP_API_CLIENT_GET]
  @P_CLIENT_ID  VARCHAR(50),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT C.[CLIENT_ID], C.[CLIENT_NM], C.[SECRET_HASH], C.[SECRET_SALT], C.[API_CODES], C.[ALLOW_IP_LIST], C.[RATE_PER_MIN],
         CASE WHEN C.[USE_YN] = 'Y' AND (C.[EXPIRE_DT] IS NULL OR C.[EXPIRE_DT] >= CONVERT(DATE, SYSUTCDATETIME())) THEN 'Y' ELSE 'N' END AS [ACTIVE_YN]
    FROM [FW].[TB_API_CLIENT] C
   WHERE C.[CLIENT_ID] = @P_CLIENT_ID;
END
