-- 협력사 가입 신청 목록 (목록 SP 표준 템플릿). 프로그램: SYS_PARTNER_APPROVE
-- 협력사 사용자가 부르면 자기 회사 신청만 나온다(본사 사용자는 전체). 이메일은 암호문 그대로 돌려주고 화면에는 가려서 보인다.
-- 결과셋 1: 목록(오래된 신청부터), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_PARTNER_JOIN_GET_LIST]
  @P_REQ_STAT_CD VARCHAR(10)   = NULL,
  @P_KEYWORD     NVARCHAR(100) = NULL,
  @P_PAGE_NO     INT           = 1,
  @P_PAGE_SIZE   INT           = 50,
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @MY_COMPANY_CD VARCHAR(10), @MY_TYPE_CD VARCHAR(10);
  SELECT @MY_COMPANY_CD = [COMPANY_CD], @MY_TYPE_CD = [USER_TYPE_CD] FROM [FW].[TB_USER] WHERE [USER_ID] = @P_USER_ID;
  IF @MY_TYPE_CD IS NULL
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT R.[REQ_ID], R.[COMPANY_CD], C.[COMPANY_NM], C.[BIZ_REG_NO], R.[USER_ID], R.[USER_NM], R.[EMAIL_ENC], R.[LANG_CD],
         R.[REQ_STAT_CD], COALESCE(SL.[CODE_NM], SD.[CODE_NM], R.[REQ_STAT_CD]) AS [REQ_STAT_NM],
         R.[REQ_DT], R.[PROC_ID], R.[PROC_DT], R.[REJECT_REASON], R.[ROW_VER]
    FROM [FW].[TB_PARTNER_JOIN_REQ] R
    JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = R.[COMPANY_CD]
    LEFT JOIN [FW].[TB_CODE_LANG] SL ON SL.[GROUP_CD] = 'JOIN_STAT' AND SL.[CODE] = R.[REQ_STAT_CD] AND SL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] SD ON SD.[GROUP_CD] = 'JOIN_STAT' AND SD.[CODE] = R.[REQ_STAT_CD] AND SD.[LANG_CD] = @DEFAULT_LANG
   WHERE (@MY_TYPE_CD <> 'PARTNER' OR R.[COMPANY_CD] = @MY_COMPANY_CD)
     AND (@P_REQ_STAT_CD IS NULL OR R.[REQ_STAT_CD] = @P_REQ_STAT_CD)
     AND (@P_KEYWORD IS NULL OR R.[USER_ID] LIKE @P_KEYWORD + '%' OR R.[USER_NM] LIKE '%' + @P_KEYWORD + '%' OR C.[COMPANY_NM] LIKE '%' + @P_KEYWORD + '%')
   ORDER BY R.[REQ_DT], R.[REQ_ID]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_PARTNER_JOIN_REQ] R
    JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = R.[COMPANY_CD]
   WHERE (@MY_TYPE_CD <> 'PARTNER' OR R.[COMPANY_CD] = @MY_COMPANY_CD)
     AND (@P_REQ_STAT_CD IS NULL OR R.[REQ_STAT_CD] = @P_REQ_STAT_CD)
     AND (@P_KEYWORD IS NULL OR R.[USER_ID] LIKE @P_KEYWORD + '%' OR R.[USER_NM] LIKE '%' + @P_KEYWORD + '%' OR C.[COMPANY_NM] LIKE '%' + @P_KEYWORD + '%')
  OPTION (RECOMPILE);
END
