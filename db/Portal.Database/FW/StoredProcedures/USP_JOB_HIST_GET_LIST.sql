-- 배치 작업 하나의 실행 이력 (최근 것부터). 프로그램: SYS_JOB_MGT
-- 결과셋 1: 목록, 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_JOB_HIST_GET_LIST]
  @P_JOB_ID       VARCHAR(30),
  @P_PAGE_NO      INT           = 1,
  @P_PAGE_SIZE    INT           = 50,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT H.[HIST_ID], H.[RUN_TYPE_CD], COALESCE(TL.[CODE_NM], TD.[CODE_NM], H.[RUN_TYPE_CD]) AS [RUN_TYPE_NM], H.[RUN_USER_ID], H.[HOST_NM],
         H.[START_DT], H.[END_DT], H.[RESULT_CD], COALESCE(RL.[CODE_NM], RD.[CODE_NM], H.[RESULT_CD]) AS [RESULT_NM], H.[PROCESSED_CNT], H.[RESULT_MSG]
    FROM [FW].[TB_JOB_HIST] H
    LEFT JOIN [FW].[TB_CODE_LANG] TL ON TL.[GROUP_CD] = 'JOB_RUN_TYPE' AND TL.[CODE] = H.[RUN_TYPE_CD] AND TL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] TD ON TD.[GROUP_CD] = 'JOB_RUN_TYPE' AND TD.[CODE] = H.[RUN_TYPE_CD] AND TD.[LANG_CD] = @DEFAULT_LANG
    LEFT JOIN [FW].[TB_CODE_LANG] RL ON RL.[GROUP_CD] = 'JOB_STAT' AND RL.[CODE] = H.[RESULT_CD] AND RL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] RD ON RD.[GROUP_CD] = 'JOB_STAT' AND RD.[CODE] = H.[RESULT_CD] AND RD.[LANG_CD] = @DEFAULT_LANG
   WHERE H.[JOB_ID] = @P_JOB_ID
   ORDER BY H.[START_DT] DESC, H.[HIST_ID] DESC
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY;

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_JOB_HIST] WHERE [JOB_ID] = @P_JOB_ID;
END
