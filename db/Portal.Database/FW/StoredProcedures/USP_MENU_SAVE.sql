-- 메뉴 일괄 저장 (추가·수정·삭제, 한 메뉴 세트). 프로그램: SYS_MENU_MGT
-- @P_ROWS_JSON: [{rowStat(I/U/D), menuKey, parentMenuKey, menuTypeCd(FOLDER/PAGE/LINK/POPUP), programId, linkUrl, iconCd, sortNo,
--                 newWinYn, openScopeCd(ALL/EMP/PARTNER), useYn, rowVer(16진수; U·D 필수), names:[{langCd, menuNm}]}]
-- 규칙: 메뉴 키는 만든 뒤 바꿀 수 없다. 폴더는 프로그램·링크가 없고, 화면·팝업은 사용 중인 프로그램이 있어야 하며,
--       링크는 '/'로 시작하는 내부 주소나 https:// 주소만 쓴다. 부모는 같은 세트의 폴더여야 하고 순환할 수 없다.
--       기본 언어 메뉴명은 꼭 있어야 하고, 하위 메뉴가 남은 메뉴는 지울 수 없다(하위를 함께 지우면 된다). 지울 때 즐겨찾기도 함께 지운다.
-- 수정·삭제는 조회 때의 ROW_VER와 같아야 한다. 변경 내용은 감사 로그에 남기고 메뉴 캐시(MENU)를 올린다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_MENU_SAVE]
  @P_MENU_SET_CD  VARCHAR(10),
  @P_ROWS_JSON    NVARCHAR(MAX),
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_MENU_SET_CD IS NULL OR @P_MENU_SET_CD NOT IN ('PORTAL', 'ADMIN', 'MOBILE') OR ISJSON(@P_ROWS_JSON) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @R TABLE (
    [ROW_STAT] CHAR(1), [MENU_KEY] VARCHAR(50) PRIMARY KEY, [PARENT_KEY] VARCHAR(50), [MENU_TYPE_CD] VARCHAR(10), [PROGRAM_ID] VARCHAR(30),
    [LINK_URL] VARCHAR(500), [ICON_CD] VARCHAR(50), [SORT_NO] INT, [NEW_WIN_YN] CHAR(1), [OPEN_SCOPE_CD] VARCHAR(10), [USE_YN] CHAR(1),
    [ROW_VER] BINARY(8), [NAMES_JSON] NVARCHAR(MAX));
  INSERT INTO @R
  SELECT [rowStat], [menuKey], NULLIF([parentMenuKey], ''), [menuTypeCd], NULLIF([programId], ''), NULLIF([linkUrl], ''), NULLIF([iconCd], ''),
         ISNULL([sortNo], 0), ISNULL([newWinYn], 'N'), ISNULL([openScopeCd], 'ALL'), ISNULL([useYn], 'Y'), CONVERT(BINARY(8), [rowVer], 2), [names]
    FROM OPENJSON(@P_ROWS_JSON) WITH (
      [rowStat] CHAR(1), [menuKey] VARCHAR(50), [parentMenuKey] VARCHAR(50), [menuTypeCd] VARCHAR(10), [programId] VARCHAR(30),
      [linkUrl] VARCHAR(500), [iconCd] VARCHAR(50), [sortNo] INT, [newWinYn] CHAR(1), [openScopeCd] VARCHAR(10), [useYn] CHAR(1),
      [rowVer] VARCHAR(16), [names] NVARCHAR(MAX) AS JSON);

  IF NOT EXISTS (SELECT 1 FROM @R)
    THROW 50005, 'MSG.NO_CHANGES', 1;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  DECLARE @N TABLE ([MENU_KEY] VARCHAR(50), [LANG_CD] VARCHAR(5), [MENU_NM] NVARCHAR(100), PRIMARY KEY ([MENU_KEY], [LANG_CD]));
  BEGIN TRY
    INSERT INTO @N
    SELECT R.[MENU_KEY], J.[langCd], LTRIM(RTRIM(J.[menuNm]))
      FROM @R R
     CROSS APPLY OPENJSON(R.[NAMES_JSON]) WITH ([langCd] VARCHAR(5), [menuNm] NVARCHAR(100)) J
     WHERE R.[ROW_STAT] IN ('I', 'U') AND NULLIF(LTRIM(RTRIM(J.[menuNm])), N'') IS NOT NULL;
  END TRY
  BEGIN CATCH
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  END CATCH

  -- 입력 검증 (트랜잭션 전)
  IF EXISTS (SELECT 1 FROM @R WHERE [ROW_STAT] NOT IN ('I', 'U', 'D') OR [MENU_KEY] IS NULL OR [MENU_KEY] COLLATE Latin1_General_BIN LIKE '%[^A-Za-z0-9_.-]%'
                                   OR ([ROW_STAT] IN ('U', 'D') AND [ROW_VER] IS NULL))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R
              WHERE [ROW_STAT] IN ('I', 'U')
                AND ([MENU_TYPE_CD] NOT IN ('FOLDER', 'PAGE', 'LINK', 'POPUP') OR [MENU_TYPE_CD] IS NULL
                     OR [NEW_WIN_YN] NOT IN ('Y', 'N') OR [USE_YN] NOT IN ('Y', 'N') OR [OPEN_SCOPE_CD] NOT IN ('ALL', 'EMP', 'PARTNER')
                     OR [SORT_NO] NOT BETWEEN 0 AND 100000 OR [PARENT_KEY] = [MENU_KEY]
                     OR ([MENU_TYPE_CD] = 'FOLDER' AND ([PROGRAM_ID] IS NOT NULL OR [LINK_URL] IS NOT NULL))
                     OR ([MENU_TYPE_CD] IN ('PAGE', 'POPUP') AND ([PROGRAM_ID] IS NULL OR [LINK_URL] IS NOT NULL))
                     OR ([MENU_TYPE_CD] = 'LINK' AND ([LINK_URL] IS NULL OR [PROGRAM_ID] IS NOT NULL
                         OR NOT ([LINK_URL] LIKE '/%' AND [LINK_URL] NOT LIKE '//%' AND [LINK_URL] NOT LIKE '/\%' OR [LINK_URL] LIKE 'https://%')
                         OR [LINK_URL] LIKE '%[ <>"'']%' OR [LINK_URL] LIKE '%[%]0[0-9A-Fa-f]%'))))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = R.[PROGRAM_ID]
              WHERE R.[ROW_STAT] IN ('I', 'U') AND R.[PROGRAM_ID] IS NOT NULL AND (P.[PROGRAM_ID] IS NULL OR P.[USE_YN] <> 'Y'))
    THROW 50004, 'MSG.NOT_FOUND', 1;
  -- 기본 언어 메뉴명 필수, 사용 중인 언어만
  IF EXISTS (SELECT 1 FROM @R R WHERE R.[ROW_STAT] IN ('I', 'U') AND NOT EXISTS (SELECT 1 FROM @N N WHERE N.[MENU_KEY] = R.[MENU_KEY] AND N.[LANG_CD] = @DEFAULT_LANG))
     OR EXISTS (SELECT 1 FROM @N N LEFT JOIN [FW].[TB_LANG] L ON L.[LANG_CD] = N.[LANG_CD] AND L.[USE_YN] = 'Y' WHERE L.[LANG_CD] IS NULL)
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_MENU] M ON M.[MENU_KEY] = R.[MENU_KEY] WHERE R.[ROW_STAT] = 'I')
    THROW 50001, 'MSG.DUP_MENU_KEY', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_MENU] M ON M.[MENU_KEY] = R.[MENU_KEY] AND M.[MENU_SET_CD] = @P_MENU_SET_CD
              WHERE R.[ROW_STAT] IN ('U', 'D') AND M.[MENU_ID] IS NULL)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @CNT INT = 0, @CNT_ROW INT;
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_MENU] M WITH (UPDLOCK) ON M.[MENU_KEY] = R.[MENU_KEY]
                WHERE R.[ROW_STAT] IN ('U', 'D') AND M.[ROW_VER] <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;

    SET @BEFORE = (SELECT M.[MENU_KEY], M.[MENU_TYPE_CD], M.[PROGRAM_ID], M.[LINK_URL], M.[SORT_NO], M.[OPEN_SCOPE_CD], M.[USE_YN]
                     FROM [FW].[TB_MENU] M JOIN @R R ON R.[MENU_KEY] = M.[MENU_KEY] FOR JSON PATH);

    -- 삭제 대상 (하위 메뉴가 남는지는 부모 연결을 바꾼 뒤에 확인한다)
    DECLARE @DEL TABLE ([MENU_ID] INT PRIMARY KEY);
    INSERT INTO @DEL SELECT M.[MENU_ID] FROM @R R JOIN [FW].[TB_MENU] M ON M.[MENU_KEY] = R.[MENU_KEY] WHERE R.[ROW_STAT] = 'D';
    -- 추가 (부모는 아래에서 한꺼번에 연결)
    INSERT INTO [FW].[TB_MENU] ([MENU_KEY], [MENU_SET_CD], [OPEN_SCOPE_CD], [MENU_TYPE_CD], [PROGRAM_ID], [LINK_URL], [ICON_CD], [SORT_NO], [NEW_WIN_YN], [USE_YN], [REG_ID], [UPD_ID])
    SELECT [MENU_KEY], @P_MENU_SET_CD, [OPEN_SCOPE_CD], [MENU_TYPE_CD], [PROGRAM_ID], [LINK_URL], [ICON_CD], [SORT_NO], [NEW_WIN_YN], [USE_YN], @P_USER_ID, @P_USER_ID
      FROM @R WHERE [ROW_STAT] = 'I';
    SET @CNT_ROW = @@ROWCOUNT; SET @CNT += @CNT_ROW;

    UPDATE M
       SET M.[OPEN_SCOPE_CD] = R.[OPEN_SCOPE_CD], M.[MENU_TYPE_CD] = R.[MENU_TYPE_CD], M.[PROGRAM_ID] = R.[PROGRAM_ID], M.[LINK_URL] = R.[LINK_URL],
           M.[ICON_CD] = R.[ICON_CD], M.[SORT_NO] = R.[SORT_NO], M.[NEW_WIN_YN] = R.[NEW_WIN_YN], M.[USE_YN] = R.[USE_YN],
           M.[UPD_ID] = @P_USER_ID, M.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_MENU] M JOIN @R R ON R.[MENU_KEY] = M.[MENU_KEY]
     WHERE R.[ROW_STAT] = 'U';
    SET @CNT_ROW = @@ROWCOUNT; SET @CNT += @CNT_ROW;

    -- 부모 연결: 같은 세트의 폴더만
    IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_MENU] P ON P.[MENU_KEY] = R.[PARENT_KEY]
                WHERE R.[ROW_STAT] IN ('I', 'U') AND R.[PARENT_KEY] IS NOT NULL
                  AND (P.[MENU_ID] IS NULL OR P.[MENU_SET_CD] <> @P_MENU_SET_CD OR P.[MENU_TYPE_CD] <> 'FOLDER' OR P.[MENU_ID] IN (SELECT [MENU_ID] FROM @DEL)))
      THROW 50005, 'MSG.INVALID_INPUT', 1;
    UPDATE M
       SET M.[PARENT_MENU_ID] = P.[MENU_ID]
      FROM [FW].[TB_MENU] M
      JOIN @R R ON R.[MENU_KEY] = M.[MENU_KEY] AND R.[ROW_STAT] IN ('I', 'U')
      LEFT JOIN [FW].[TB_MENU] P ON P.[MENU_KEY] = R.[PARENT_KEY]
     WHERE ISNULL(M.[PARENT_MENU_ID], 0) <> ISNULL(P.[MENU_ID], 0);

    IF EXISTS (SELECT 1 FROM [FW].[TB_MENU] C WHERE C.[PARENT_MENU_ID] IN (SELECT [MENU_ID] FROM @DEL) AND C.[MENU_ID] NOT IN (SELECT [MENU_ID] FROM @DEL))
      THROW 50001, 'MSG.MENU_HAS_CHILD', 1;

    -- 순환 확인: 위로 거슬러 올라가 끝나지 않으면 순환
    ;WITH UP AS (
      SELECT M.[MENU_ID], M.[PARENT_MENU_ID], 1 AS [D] FROM [FW].[TB_MENU] M WHERE M.[MENU_SET_CD] = @P_MENU_SET_CD AND M.[PARENT_MENU_ID] IS NOT NULL
      UNION ALL
      SELECT UP.[MENU_ID], M.[PARENT_MENU_ID], UP.[D] + 1 FROM UP JOIN [FW].[TB_MENU] M ON M.[MENU_ID] = UP.[PARENT_MENU_ID] WHERE M.[PARENT_MENU_ID] IS NOT NULL AND UP.[D] < 50
    )
    SELECT @CNT_ROW = COUNT(*) FROM UP WHERE UP.[D] >= 50 OPTION (MAXRECURSION 100);
    IF @CNT_ROW > 0
      THROW 50005, 'MSG.INVALID_INPUT', 1;

    -- 메뉴명: 저장하는 메뉴는 보낸 언어로 맞춘다(보내지 않은 언어는 지운다)
    DELETE T FROM [FW].[TB_MENU_LANG] T
      JOIN [FW].[TB_MENU] M ON M.[MENU_ID] = T.[MENU_ID]
      JOIN @R R ON R.[MENU_KEY] = M.[MENU_KEY] AND R.[ROW_STAT] = 'U'
     WHERE NOT EXISTS (SELECT 1 FROM @N N WHERE N.[MENU_KEY] = R.[MENU_KEY] AND N.[LANG_CD] = T.[LANG_CD]);
    UPDATE T SET T.[MENU_NM] = N.[MENU_NM], T.[UPD_ID] = @P_USER_ID, T.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_MENU_LANG] T
      JOIN [FW].[TB_MENU] M ON M.[MENU_ID] = T.[MENU_ID]
      JOIN @N N ON N.[MENU_KEY] = M.[MENU_KEY] AND N.[LANG_CD] = T.[LANG_CD]
     WHERE T.[MENU_NM] <> N.[MENU_NM];
    INSERT INTO [FW].[TB_MENU_LANG] ([MENU_ID], [LANG_CD], [MENU_NM], [REG_ID], [UPD_ID])
    SELECT M.[MENU_ID], N.[LANG_CD], N.[MENU_NM], @P_USER_ID, @P_USER_ID
      FROM @N N JOIN [FW].[TB_MENU] M ON M.[MENU_KEY] = N.[MENU_KEY]
     WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_MENU_LANG] T WHERE T.[MENU_ID] = M.[MENU_ID] AND T.[LANG_CD] = N.[LANG_CD]);

    -- 삭제 (같이 지우는 하위가 있어도 부모 연결을 먼저 끊고 한 번에 지운다)
    UPDATE [FW].[TB_MENU] SET [PARENT_MENU_ID] = NULL WHERE [MENU_ID] IN (SELECT [MENU_ID] FROM @DEL);
    DELETE FROM [FW].[TB_USER_FAVORITE] WHERE [MENU_ID] IN (SELECT [MENU_ID] FROM @DEL);
    DELETE FROM [FW].[TB_MENU_LANG] WHERE [MENU_ID] IN (SELECT [MENU_ID] FROM @DEL);
    DELETE FROM [FW].[TB_MENU] WHERE [MENU_ID] IN (SELECT [MENU_ID] FROM @DEL);
    SET @CNT_ROW = @@ROWCOUNT; SET @CNT += @CNT_ROW;

    SET @AFTER = (SELECT R.[ROW_STAT], R.[MENU_KEY], R.[PARENT_KEY], R.[MENU_TYPE_CD], R.[PROGRAM_ID], R.[LINK_URL], R.[SORT_NO], R.[OPEN_SCOPE_CD], R.[USE_YN]
                    FROM @R R FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_MENU', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_MENU_SET_CD,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    UPDATE [FW].[TB_CACHE_VERSION]
       SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME()
     WHERE [CACHE_KEY] = 'MENU';

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
