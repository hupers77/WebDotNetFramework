-- 설정 하나의 변경 이력 (최근 순, 목록 SP 표준 템플릿). 프로그램: SYS_CONFIG_MGT
-- SECRET은 이력에 값이 없다(OLD_VAL, NEW_VAL 모두 NULL). 결과셋 1: 목록, 결과셋 2: 전체 건수.
CREATE PROCEDURE [FW].[USP_CONFIG_HIST_GET_LIST]
  @P_CONFIG_KEY  VARCHAR(100),
  @P_PAGE_NO     INT         = 1,
  @P_PAGE_SIZE   INT         = 50,
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT [HIST_ID], [OLD_VAL], [NEW_VAL], [CHG_ID], [CHG_DT], [CLIENT_IP]
    FROM [FW].[TB_CONFIG_HIST]
   WHERE [CONFIG_KEY] = @P_CONFIG_KEY
   ORDER BY [CHG_DT] DESC, [HIST_ID] DESC
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY;

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_CONFIG_HIST] WHERE [CONFIG_KEY] = @P_CONFIG_KEY;
END
