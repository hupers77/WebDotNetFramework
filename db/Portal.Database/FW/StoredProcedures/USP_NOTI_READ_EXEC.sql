-- 내 알림을 읽음으로 표시한다. @P_NOTI_ID가 NULL이면 안 읽은 알림 전부. 다른 사람의 알림은 바뀌지 않는다.
-- 개인 알림함이라 감사 로그는 남기지 않는다. 프로그램: MY_NOTIFICATION
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_NOTI_READ_EXEC]
  @P_NOTI_ID      BIGINT        = NULL,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_USER_ID IS NULL
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  UPDATE [FW].[TB_NOTIFICATION]
     SET [READ_DT] = SYSUTCDATETIME()
   WHERE [USER_ID] = @P_USER_ID
     AND [READ_DT] IS NULL
     AND (@P_NOTI_ID IS NULL OR [NOTI_ID] = @P_NOTI_ID);

  SELECT @@ROWCOUNT AS [AFFECTED_CNT];
END
