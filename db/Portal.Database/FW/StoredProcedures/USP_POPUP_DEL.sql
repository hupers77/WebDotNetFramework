-- 공지 팝업 삭제. 프로그램: SYS_POPUP_MGT. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_POPUP_DEL]
  @P_POPUP_ID    BIGINT,
  @P_ROW_VER     BINARY(8),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  BEGIN TRY
    BEGIN TRAN;

    DECLARE @VER BINARY(8) = (SELECT [ROW_VER] FROM [FW].[TB_POPUP] WITH (UPDLOCK, HOLDLOCK) WHERE [POPUP_ID] = @P_POPUP_ID);
    IF @VER IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;

    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT P.[POPUP_ID], P.[OPEN_SCOPE_CD], P.[START_DT], P.[END_DT], P.[USE_YN],
                                            (SELECT [LANG_CD], [TITLE], [CONTENT] FROM [FW].[TB_POPUP_LANG] WHERE [POPUP_ID] = P.[POPUP_ID] FOR JSON PATH) AS [LANGS]
                                       FROM [FW].[TB_POPUP] P WHERE P.[POPUP_ID] = @P_POPUP_ID FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

    DELETE FROM [FW].[TB_POPUP_LANG] WHERE [POPUP_ID] = @P_POPUP_ID;
    DELETE FROM [FW].[TB_POPUP] WHERE [POPUP_ID] = @P_POPUP_ID;

    DECLARE @KEY NVARCHAR(100) = CONVERT(NVARCHAR(20), @P_POPUP_ID);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_POPUP', @P_ACTION_CD = 'D', @P_ROW_KEY = @KEY,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = NULL,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT 1 AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
