-- 내 알림을 지운다. @P_NOTI_IDS는 알림 번호 JSON 배열([1,2,3], 최대 100건). 다른 사람의 알림 번호는 무시한다.
-- 개인 알림함이라 감사 로그는 남기지 않는다. 프로그램: MY_NOTIFICATION (DELETE)
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_NOTI_DEL]
  @P_NOTI_IDS     NVARCHAR(4000),
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_USER_ID IS NULL OR ISJSON(@P_NOTI_IDS) = 0 OR LEFT(LTRIM(@P_NOTI_IDS), 1) <> '['
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @IDS TABLE ([NOTI_ID] BIGINT PRIMARY KEY);
  INSERT INTO @IDS ([NOTI_ID])
  SELECT DISTINCT TRY_CAST([value] AS BIGINT) FROM OPENJSON(@P_NOTI_IDS) WHERE TRY_CAST([value] AS BIGINT) IS NOT NULL;

  IF NOT EXISTS (SELECT 1 FROM @IDS) OR (SELECT COUNT(*) FROM @IDS) > 100
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DELETE N
    FROM [FW].[TB_NOTIFICATION] N
    JOIN @IDS I ON I.[NOTI_ID] = N.[NOTI_ID]
   WHERE N.[USER_ID] = @P_USER_ID;

  SELECT @@ROWCOUNT AS [AFFECTED_CNT];
END
