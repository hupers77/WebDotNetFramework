-- 휴일·달력 일괄 저장 (추가·수정·삭제). 프로그램: SYS_HOLIDAY_MGT
-- @P_ROWS_JSON: [{rowStat(I/U/D), holidayDt('yyyy-MM-dd'), holidayNm, workYn, rowVer(16진수; U·D 필수)}]
-- 수정·삭제는 조회 때의 ROW_VER와 같아야 한다. 변경 내용은 감사 로그에 남는다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_HOLIDAY_SAVE]
  @P_ROWS_JSON  NVARCHAR(MAX),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF ISJSON(@P_ROWS_JSON) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @R TABLE (
    [ROW_STAT] CHAR(1), [HOLIDAY_DT] DATE PRIMARY KEY, [HOLIDAY_NM] NVARCHAR(100), [WORK_YN] CHAR(1), [ROW_VER] BINARY(8));
  INSERT INTO @R
  SELECT [rowStat], TRY_CONVERT(DATE, [holidayDt], 23), [holidayNm], [workYn], CONVERT(BINARY(8), [rowVer], 2)
    FROM OPENJSON(@P_ROWS_JSON) WITH (
      [rowStat] CHAR(1), [holidayDt] VARCHAR(10), [holidayNm] NVARCHAR(100), [workYn] CHAR(1), [rowVer] VARCHAR(16));

  IF NOT EXISTS (SELECT 1 FROM @R)
    THROW 50005, 'MSG.NO_CHANGES', 1;
  IF EXISTS (SELECT 1 FROM @R WHERE [ROW_STAT] NOT IN ('I', 'U', 'D') OR [HOLIDAY_DT] IS NULL OR [HOLIDAY_DT] NOT BETWEEN '1990-01-01' AND '2100-12-31'
                                   OR ([ROW_STAT] IN ('I', 'U') AND (ISNULL([HOLIDAY_NM], N'') = N'' OR [WORK_YN] NOT IN ('Y', 'N') OR [WORK_YN] IS NULL))
                                   OR ([ROW_STAT] IN ('U', 'D') AND [ROW_VER] IS NULL))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_HOLIDAY] H ON H.[HOLIDAY_DT] = R.[HOLIDAY_DT] WHERE R.[ROW_STAT] = 'I')
    THROW 50001, 'MSG.DUP_HOLIDAY', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_HOLIDAY] H ON H.[HOLIDAY_DT] = R.[HOLIDAY_DT] WHERE R.[ROW_STAT] IN ('U', 'D') AND H.[HOLIDAY_DT] IS NULL)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @CNT INT = 0, @N INT;
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_HOLIDAY] H WITH (UPDLOCK) ON H.[HOLIDAY_DT] = R.[HOLIDAY_DT]
                WHERE R.[ROW_STAT] IN ('U', 'D') AND H.[ROW_VER] <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;

    SET @BEFORE = (SELECT CONVERT(CHAR(10), H.[HOLIDAY_DT], 23) AS [HOLIDAY_DT], H.[HOLIDAY_NM], H.[WORK_YN]
                     FROM [FW].[TB_HOLIDAY] H JOIN @R R ON R.[HOLIDAY_DT] = H.[HOLIDAY_DT] FOR JSON PATH);

    INSERT INTO [FW].[TB_HOLIDAY] ([HOLIDAY_DT], [HOLIDAY_NM], [WORK_YN], [REG_ID], [UPD_ID])
    SELECT [HOLIDAY_DT], [HOLIDAY_NM], [WORK_YN], @P_USER_ID, @P_USER_ID FROM @R WHERE [ROW_STAT] = 'I';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    UPDATE H
       SET H.[HOLIDAY_NM] = R.[HOLIDAY_NM], H.[WORK_YN] = R.[WORK_YN], H.[UPD_ID] = @P_USER_ID, H.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_HOLIDAY] H JOIN @R R ON R.[HOLIDAY_DT] = H.[HOLIDAY_DT]
     WHERE R.[ROW_STAT] = 'U';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    DELETE H
      FROM [FW].[TB_HOLIDAY] H JOIN @R R ON R.[HOLIDAY_DT] = H.[HOLIDAY_DT]
     WHERE R.[ROW_STAT] = 'D';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    SET @AFTER = (SELECT R.[ROW_STAT], CONVERT(CHAR(10), R.[HOLIDAY_DT], 23) AS [HOLIDAY_DT], R.[HOLIDAY_NM], R.[WORK_YN] FROM @R R FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_HOLIDAY', @P_ACTION_CD = 'U', @P_ROW_KEY = N'HOLIDAY',
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
