-- 게시글 삭제 (표시만 한다, 삭제 SP 표준 템플릿). 프로그램: 게시판의 프로그램 (DELETE는 애플리케이션이 확인)
-- 작성자 본인 또는 관리자(@P_MANAGER_YN)만. 원글을 지우면 답글과 댓글은 보이지 않게 된다(원글 아래 답글도 함께 삭제 표시).
-- 결과: AFFECTED_CNT (삭제 표시한 글 수)
CREATE PROCEDURE [FW].[USP_POST_DEL]
  @P_POST_ID      BIGINT,
  @P_ROW_VER      BINARY(8),
  @P_BOARD_CD     VARCHAR(30),
  @P_MANAGER_YN   CHAR(1)     = 'N',
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_MANAGER_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @VER BINARY(8), @WRITER VARCHAR(30), @ROOT BIGINT, @TITLE NVARCHAR(200), @CNT INT;

  BEGIN TRY
    BEGIN TRAN;

    SELECT @VER = P.[ROW_VER], @WRITER = P.[WRITER_ID], @ROOT = P.[ROOT_POST_ID], @TITLE = P.[TITLE]
      FROM [FW].[TB_POST] P WITH (UPDLOCK, HOLDLOCK)
     WHERE P.[POST_ID] = @P_POST_ID AND P.[BOARD_CD] = @P_BOARD_CD AND P.[DEL_YN] = 'N';

    IF @WRITER IS NULL OR (@WRITER <> @P_USER_ID AND @P_MANAGER_YN = 'N')
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;

    -- 원글이면 같은 글타래 전체, 답글이면 그 글과 그 아래 답글
    ;WITH [TREE] AS (
      SELECT [POST_ID] FROM [FW].[TB_POST] WHERE [POST_ID] = @P_POST_ID
      UNION ALL
      SELECT C.[POST_ID] FROM [TREE] T JOIN [FW].[TB_POST] C ON C.[PARENT_POST_ID] = T.[POST_ID] WHERE C.[DEL_YN] = 'N'
    )
    UPDATE P SET P.[DEL_YN] = 'Y', P.[UPD_ID] = @P_USER_ID, P.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_POST] P
      JOIN [TREE] T ON T.[POST_ID] = P.[POST_ID];
    SET @CNT = @@ROWCOUNT;

    DECLARE @KEY NVARCHAR(200) = CAST(@P_POST_ID AS NVARCHAR(20));
    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT @P_POST_ID AS [POST_ID], @P_BOARD_CD AS [BOARD_CD], @TITLE AS [TITLE], @CNT AS [DELETED_CNT] FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_POST', @P_ACTION_CD = 'D', @P_ROW_KEY = @KEY,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = NULL,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT];
END
