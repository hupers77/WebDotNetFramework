-- 공지 팝업 저장 (추가/수정). 프로그램: SYS_POPUP_MGT
-- @P_POPUP_ID가 NULL이면 추가, 아니면 수정(@P_ROW_VER 필수). @P_LANGS_JSON: [{langCd, title, content}] — 기본 언어는 반드시 있어야 하고,
-- 등록된 언어만 허용한다. 수정하면 그 팝업의 언어별 문구를 이 값으로 바꾼다. 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT, NEW_KEY (팝업 ID)
CREATE PROCEDURE [FW].[USP_POPUP_SAVE]
  @P_POPUP_ID       BIGINT        = NULL,
  @P_ROW_VER        BINARY(8)     = NULL,
  @P_OPEN_SCOPE_CD  VARCHAR(10),
  @P_START_DT       DATE,
  @P_END_DT         DATE,
  @P_USE_YN         CHAR(1),
  @P_LANGS_JSON     NVARCHAR(MAX),
  @P_USER_ID        VARCHAR(30),
  @P_LANG_CD        VARCHAR(5),
  @P_CLIENT_IP      VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_OPEN_SCOPE_CD NOT IN ('ALL', 'EMP', 'PARTNER') OR @P_USE_YN NOT IN ('Y', 'N') OR @P_START_DT IS NULL OR @P_END_DT IS NULL
     OR @P_START_DT > @P_END_DT OR ISJSON(@P_LANGS_JSON) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @L TABLE ([LANG_CD] VARCHAR(5) PRIMARY KEY, [TITLE] NVARCHAR(100), [CONTENT] NVARCHAR(2000));
  INSERT INTO @L SELECT [langCd], LTRIM(RTRIM([title])), LTRIM(RTRIM([content]))
    FROM OPENJSON(@P_LANGS_JSON) WITH ([langCd] VARCHAR(5), [title] NVARCHAR(100), [content] NVARCHAR(2000));

  IF EXISTS (SELECT 1 FROM @L WHERE ISNULL([TITLE], N'') = N'' OR ISNULL([CONTENT], N'') = N'')
     OR EXISTS (SELECT 1 FROM @L X LEFT JOIN [FW].[TB_LANG] G ON G.[LANG_CD] = X.[LANG_CD] WHERE G.[LANG_CD] IS NULL)
     OR NOT EXISTS (SELECT 1 FROM @L X JOIN [FW].[TB_LANG] G ON G.[LANG_CD] = X.[LANG_CD] AND G.[DEFAULT_YN] = 'Y')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @ID BIGINT = @P_POPUP_ID, @CNT INT = 0, @BEFORE NVARCHAR(MAX) = NULL, @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF @ID IS NULL
    BEGIN
      INSERT INTO [FW].[TB_POPUP] ([OPEN_SCOPE_CD], [START_DT], [END_DT], [USE_YN], [REG_ID], [UPD_ID])
      VALUES (@P_OPEN_SCOPE_CD, @P_START_DT, @P_END_DT, @P_USE_YN, @P_USER_ID, @P_USER_ID);
      SET @ID = SCOPE_IDENTITY();
    END
    ELSE
    BEGIN
      DECLARE @VER BINARY(8) = (SELECT [ROW_VER] FROM [FW].[TB_POPUP] WITH (UPDLOCK, HOLDLOCK) WHERE [POPUP_ID] = @ID);
      IF @VER IS NULL
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
        THROW 50002, 'MSG.CONCURRENCY', 1;

      SET @BEFORE = (SELECT P.[POPUP_ID], P.[OPEN_SCOPE_CD], P.[START_DT], P.[END_DT], P.[USE_YN],
                            (SELECT [LANG_CD], [TITLE], [CONTENT] FROM [FW].[TB_POPUP_LANG] WHERE [POPUP_ID] = P.[POPUP_ID] FOR JSON PATH) AS [LANGS]
                       FROM [FW].[TB_POPUP] P WHERE P.[POPUP_ID] = @ID FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

      UPDATE [FW].[TB_POPUP]
         SET [OPEN_SCOPE_CD] = @P_OPEN_SCOPE_CD, [START_DT] = @P_START_DT, [END_DT] = @P_END_DT, [USE_YN] = @P_USE_YN,
             [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
       WHERE [POPUP_ID] = @ID;
    END
    SET @CNT = 1;

    MERGE [FW].[TB_POPUP_LANG] AS T
    USING @L AS S ON T.[POPUP_ID] = @ID AND T.[LANG_CD] = S.[LANG_CD]
    WHEN MATCHED THEN UPDATE SET T.[TITLE] = S.[TITLE], T.[CONTENT] = S.[CONTENT], T.[UPD_ID] = @P_USER_ID, T.[UPD_DT] = SYSUTCDATETIME()
    WHEN NOT MATCHED BY TARGET THEN INSERT ([POPUP_ID], [LANG_CD], [TITLE], [CONTENT], [REG_ID], [UPD_ID]) VALUES (@ID, S.[LANG_CD], S.[TITLE], S.[CONTENT], @P_USER_ID, @P_USER_ID)
    WHEN NOT MATCHED BY SOURCE AND T.[POPUP_ID] = @ID THEN DELETE;

    SET @AFTER = (SELECT P.[POPUP_ID], P.[OPEN_SCOPE_CD], P.[START_DT], P.[END_DT], P.[USE_YN],
                         (SELECT [LANG_CD], [TITLE], [CONTENT] FROM [FW].[TB_POPUP_LANG] WHERE [POPUP_ID] = P.[POPUP_ID] FOR JSON PATH) AS [LANGS]
                    FROM [FW].[TB_POPUP] P WHERE P.[POPUP_ID] = @ID FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    DECLARE @KEY NVARCHAR(100) = CONVERT(NVARCHAR(20), @ID), @ACTION CHAR(1) = IIF(@P_POPUP_ID IS NULL, 'I', 'U');
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_POPUP', @P_ACTION_CD = @ACTION, @P_ROW_KEY = @KEY,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT], CONVERT(VARCHAR(20), @ID) AS [NEW_KEY];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
