-- 설치 직후 초기 관리자 계정(sysadmin, 초기 데이터 정의서 2장) 생성 또는 비상 시 비밀번호 재설정.
-- 설치 도구가 임시 비밀번호를 무작위로 만들어 해시만 넘기고, 원문은 화면에 1회만 출력한다.
-- 다음 로그인 때 변경을 강제하며 잠금도 푼다. 재설정은 감사 로그에 남는다.
-- 결과: CREATED_YN ('Y' 새로 만듦, 'N' 재설정)
CREATE PROCEDURE [FW].[USP_AUTH_ADMIN_INIT_EXEC]
  @P_PWD_HASH   VARBINARY(64),
  @P_PWD_SALT   VARBINARY(16),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF DATALENGTH(@P_PWD_HASH) <> 64 OR DATALENGTH(@P_PWD_SALT) <> 16
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @ADMIN_ID VARCHAR(30) = 'sysadmin';
  DECLARE @ACTOR VARCHAR(30) = ISNULL(@P_USER_ID, 'SYSTEM');
  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @CREATED_YN CHAR(1) = 'N';

  BEGIN TRY
    BEGIN TRAN;

    IF NOT EXISTS (SELECT 1 FROM [FW].[TB_USER] WITH (UPDLOCK, HOLDLOCK) WHERE [USER_ID] = @ADMIN_ID)
    BEGIN
      INSERT INTO [FW].[TB_USER]
        ([USER_ID], [COMPANY_CD], [USER_NM], [USER_TYPE_CD], [PWD_HASH], [PWD_SALT], [PWD_CHG_DT], [PWD_CHG_REQ_YN], [REG_ID], [UPD_ID])
      VALUES
        (@ADMIN_ID, 'HQ', N'System Administrator', 'SYSTEM', @P_PWD_HASH, @P_PWD_SALT, @NOW, 'Y', @ACTOR, @ACTOR);
      SET @CREATED_YN = 'Y';
    END
    ELSE
    BEGIN
      UPDATE [FW].[TB_USER]
         SET [PWD_HASH] = @P_PWD_HASH, [PWD_SALT] = @P_PWD_SALT, [PWD_CHG_DT] = @NOW, [PWD_CHG_REQ_YN] = 'Y',
             [LOGIN_FAIL_CNT] = 0, [LOCK_YN] = 'N', [LOCK_DT] = NULL, [USER_STAT_CD] = 'ACTIVE',
             [UPD_ID] = @ACTOR, [UPD_DT] = @NOW
       WHERE [USER_ID] = @ADMIN_ID;

      -- 열려 있던 세션은 모두 끊는다
      UPDATE [FW].[TB_USER_SESSION]
         SET [END_DT] = @NOW, [END_REASON_CD] = 'DISABLED', [UPD_ID] = @ACTOR, [UPD_DT] = @NOW
       WHERE [USER_ID] = @ADMIN_ID AND [END_DT] IS NULL;
    END

    IF NOT EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] WHERE [USER_ID] = @ADMIN_ID AND [ROLE_ID] = 'SYS_ADMIN')
      INSERT INTO [FW].[TB_USER_ROLE] ([USER_ID], [ROLE_ID], [START_DT], [REG_ID], [UPD_ID])
      VALUES (@ADMIN_ID, 'SYS_ADMIN', '1900-01-01', @ACTOR, @ACTOR);
    ELSE
      UPDATE [FW].[TB_USER_ROLE]
         SET [START_DT] = '1900-01-01', [END_DT] = '9999-12-31', [UPD_ID] = @ACTOR, [UPD_DT] = @NOW
       WHERE [USER_ID] = @ADMIN_ID AND [ROLE_ID] = 'SYS_ADMIN'
         AND ([START_DT] > CAST(GETDATE() AS DATE) OR [END_DT] < CAST(GETDATE() AS DATE));

    DECLARE @ACTION_CD CHAR(1) = CASE WHEN @CREATED_YN = 'Y' THEN 'I' ELSE 'U' END;
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_USER', @P_ACTION_CD = @ACTION_CD, @P_ROW_KEY = @ADMIN_ID,
      @P_BEFORE_JSON = NULL, @P_AFTER_JSON = N'{"ADMIN_INIT":true}',
      @P_USER_ID = @ACTOR, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CREATED_YN AS [CREATED_YN];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
