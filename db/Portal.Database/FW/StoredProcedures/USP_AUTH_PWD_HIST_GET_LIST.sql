-- 비밀번호 변경 전 확인용: 현재 사용자(@P_USER_ID)의 현재 해시(SEQ_NO 0)와 최근 이력 해시.
-- 다른 사용자의 해시는 조회할 수 없다. 재사용 검사는 애플리케이션이 같은 해시 함수로 한다. 프로그램: MY_PWD_CHG
-- 결과: SEQ_NO, PWD_HASH, PWD_SALT (현재 비밀번호 + 직전 PWD.HISTORY_COUNT개)
CREATE PROCEDURE [FW].[USP_AUTH_PWD_HIST_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @HISTORY_COUNT INT = ISNULL(TRY_CAST((SELECT [CONFIG_VAL] FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'PWD.HISTORY_COUNT') AS INT), 3);

  SELECT 0 AS [SEQ_NO], [PWD_HASH], [PWD_SALT]
    FROM [FW].[TB_USER]
   WHERE [USER_ID] = @P_USER_ID AND [PWD_HASH] IS NOT NULL
  UNION ALL
  SELECT [SEQ_NO], [PWD_HASH], [PWD_SALT]
    FROM (SELECT TOP (@HISTORY_COUNT) [SEQ_NO], [PWD_HASH], [PWD_SALT]
            FROM [FW].[TB_USER_PWD_HIST]
           WHERE [USER_ID] = @P_USER_ID
           ORDER BY [SEQ_NO] DESC) H
   ORDER BY [SEQ_NO];
END
