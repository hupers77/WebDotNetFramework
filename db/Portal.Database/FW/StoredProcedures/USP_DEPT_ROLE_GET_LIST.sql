-- 부서 한 곳의 역할 선택지 (부서 관리 화면 오른쪽). 프로그램: SYS_DEPT_MGT
-- 사용 중인 역할 전부와 이 부서에 준 역할(하위 부서 상속 여부 포함)을 돌려준다.
-- 줄 수 있는 역할: COMPANY_TYPE_CD가 비었거나 부서 회사 유형과 같은 것. SYS_ADMIN은 부서로 줄 수 없다(비상 계정에 직접만).
-- 결과: ROLE_ID, ROLE_NM, DESCRIPTION, COMPANY_TYPE_CD, ASSIGNED_YN, INHERIT_YN, ASSIGNABLE_YN
CREATE PROCEDURE [FW].[USP_DEPT_ROLE_GET_LIST]
  @P_DEPT_ID     VARCHAR(20),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @COMPANY_TYPE VARCHAR(10) = (
    SELECT C.[COMPANY_TYPE_CD]
      FROM [FW].[TB_DEPT] D
      JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = D.[COMPANY_CD]
     WHERE D.[DEPT_ID] = @P_DEPT_ID
       AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'SYS_DEPT_MGT') S WHERE S.[COMPANY_CD] = D.[COMPANY_CD]));
  IF @COMPANY_TYPE IS NULL
    THROW 50004, 'MSG.NOT_FOUND', 1;

  SELECT R.[ROLE_ID], R.[ROLE_NM], R.[DESCRIPTION], R.[COMPANY_TYPE_CD],
         IIF(DR.[ROLE_ID] IS NULL, 'N', 'Y') AS [ASSIGNED_YN],
         ISNULL(DR.[INHERIT_YN], 'Y') AS [INHERIT_YN],
         IIF(R.[USE_YN] = 'Y' AND R.[ROLE_ID] <> 'SYS_ADMIN'
             AND (R.[COMPANY_TYPE_CD] IS NULL OR R.[COMPANY_TYPE_CD] = @COMPANY_TYPE), 'Y', 'N') AS [ASSIGNABLE_YN]
    FROM [FW].[TB_ROLE] R
    LEFT JOIN [FW].[TB_DEPT_ROLE] DR ON DR.[DEPT_ID] = @P_DEPT_ID AND DR.[ROLE_ID] = R.[ROLE_ID]
   WHERE R.[USE_YN] = 'Y' OR DR.[ROLE_ID] IS NOT NULL
   ORDER BY R.[SORT_NO], R.[ROLE_ID];
END
