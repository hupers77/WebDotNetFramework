-- API 클라이언트 일괄 저장 (추가·수정·삭제). 프로그램: SYS_API_CLIENT_MGT
-- @P_ROWS_JSON: [{rowStat(I/U/D), clientId, clientNm, apiCodes, allowIpList, ratePerMin, expireDt('yyyy-MM-dd'), useYn, rowVer(16진수; U·D 필수)}]
-- 비밀값은 여기서 다루지 않는다(USP_API_CLIENT_SECRET_SET). 새 클라이언트는 비밀값이 없어 토큰을 받을 수 없다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_API_CLIENT_SAVE]
  @P_ROWS_JSON  NVARCHAR(MAX),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF ISJSON(@P_ROWS_JSON) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @R TABLE (
    [ROW_STAT] CHAR(1), [CLIENT_ID] VARCHAR(50) PRIMARY KEY, [CLIENT_NM] NVARCHAR(100), [API_CODES] VARCHAR(1000), [ALLOW_IP_LIST] VARCHAR(1000),
    [RATE_PER_MIN] INT, [EXPIRE_DT] DATE, [EXPIRE_TXT] VARCHAR(10), [USE_YN] CHAR(1), [ROW_VER] BINARY(8));
  INSERT INTO @R
  SELECT [rowStat], [clientId], [clientNm], ISNULL([apiCodes], ''), NULLIF([allowIpList], ''), [ratePerMin],
         TRY_CONVERT(DATE, [expireDt], 23), NULLIF([expireDt], ''), [useYn], CONVERT(BINARY(8), [rowVer], 2)
    FROM OPENJSON(@P_ROWS_JSON) WITH (
      [rowStat] CHAR(1), [clientId] VARCHAR(50), [clientNm] NVARCHAR(100), [apiCodes] VARCHAR(1000), [allowIpList] VARCHAR(1000),
      [ratePerMin] INT, [expireDt] VARCHAR(10), [useYn] CHAR(1), [rowVer] VARCHAR(16));

  IF NOT EXISTS (SELECT 1 FROM @R)
    THROW 50005, 'MSG.NO_CHANGES', 1;
  IF EXISTS (SELECT 1 FROM @R WHERE [ROW_STAT] NOT IN ('I', 'U', 'D') OR [CLIENT_ID] IS NULL OR [CLIENT_ID] LIKE '%[^A-Za-z0-9._-]%'
                                   OR ([ROW_STAT] IN ('I', 'U') AND (ISNULL([CLIENT_NM], N'') = N'' OR [USE_YN] NOT IN ('Y', 'N') OR [USE_YN] IS NULL
                                        OR ([RATE_PER_MIN] IS NOT NULL AND [RATE_PER_MIN] NOT BETWEEN 1 AND 100000)
                                        OR ([EXPIRE_TXT] IS NOT NULL AND [EXPIRE_DT] IS NULL)))
                                   OR ([ROW_STAT] IN ('U', 'D') AND [ROW_VER] IS NULL))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_API_CLIENT] C ON C.[CLIENT_ID] = R.[CLIENT_ID] WHERE R.[ROW_STAT] = 'I')
    THROW 50001, 'MSG.DUP_API_CLIENT', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_API_CLIENT] C ON C.[CLIENT_ID] = R.[CLIENT_ID] WHERE R.[ROW_STAT] IN ('U', 'D') AND C.[CLIENT_ID] IS NULL)
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @CNT INT = 0, @N INT;
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_API_CLIENT] C WITH (UPDLOCK) ON C.[CLIENT_ID] = R.[CLIENT_ID]
                WHERE R.[ROW_STAT] IN ('U', 'D') AND C.[ROW_VER] <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;

    SET @BEFORE = (SELECT C.[CLIENT_ID], C.[CLIENT_NM], C.[API_CODES], C.[ALLOW_IP_LIST], C.[RATE_PER_MIN], CONVERT(CHAR(10), C.[EXPIRE_DT], 23) AS [EXPIRE_DT], C.[USE_YN]
                     FROM [FW].[TB_API_CLIENT] C JOIN @R R ON R.[CLIENT_ID] = C.[CLIENT_ID] FOR JSON PATH);

    INSERT INTO [FW].[TB_API_CLIENT] ([CLIENT_ID], [CLIENT_NM], [API_CODES], [ALLOW_IP_LIST], [RATE_PER_MIN], [EXPIRE_DT], [USE_YN], [REG_ID], [UPD_ID])
    SELECT [CLIENT_ID], [CLIENT_NM], [API_CODES], [ALLOW_IP_LIST], [RATE_PER_MIN], [EXPIRE_DT], [USE_YN], @P_USER_ID, @P_USER_ID FROM @R WHERE [ROW_STAT] = 'I';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    UPDATE C
       SET C.[CLIENT_NM] = R.[CLIENT_NM], C.[API_CODES] = R.[API_CODES], C.[ALLOW_IP_LIST] = R.[ALLOW_IP_LIST], C.[RATE_PER_MIN] = R.[RATE_PER_MIN],
           C.[EXPIRE_DT] = R.[EXPIRE_DT], C.[USE_YN] = R.[USE_YN], C.[UPD_ID] = @P_USER_ID, C.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_API_CLIENT] C JOIN @R R ON R.[CLIENT_ID] = C.[CLIENT_ID]
     WHERE R.[ROW_STAT] = 'U';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    DELETE C
      FROM [FW].[TB_API_CLIENT] C JOIN @R R ON R.[CLIENT_ID] = C.[CLIENT_ID]
     WHERE R.[ROW_STAT] = 'D';
    SET @N = @@ROWCOUNT; SET @CNT += @N;

    SET @AFTER = (SELECT R.[ROW_STAT], R.[CLIENT_ID], R.[CLIENT_NM], R.[API_CODES], R.[ALLOW_IP_LIST], R.[RATE_PER_MIN], R.[EXPIRE_TXT] AS [EXPIRE_DT], R.[USE_YN] FROM @R R FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_API_CLIENT', @P_ACTION_CD = 'U', @P_ROW_KEY = N'API_CLIENT',
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
