-- 회사 삭제 (삭제 SP 표준 템플릿). 프로그램: SYS_COMPANY_MGT
-- 잘못 등록한 협력사만 지운다. 본사, 그리고 계정·부서·가입 신청·첨부 파일이 하나라도 있는 회사는 지우지 않는다
-- (기록을 남겨야 하므로 사용 안 함으로 바꾼다). 감사 로그를 남긴다.
-- 결과: AFFECTED_CNT
CREATE PROCEDURE [FW].[USP_COMPANY_DEL]
  @P_COMPANY_CD  VARCHAR(10),
  @P_ROW_VER     BINARY(8),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @TYPE VARCHAR(10), @VER BINARY(8);

  BEGIN TRY
    BEGIN TRAN;

    SELECT @TYPE = [COMPANY_TYPE_CD], @VER = [ROW_VER]
      FROM [FW].[TB_COMPANY] WITH (UPDLOCK, HOLDLOCK)
     WHERE [COMPANY_CD] = @P_COMPANY_CD;

    IF @TYPE IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF @P_ROW_VER IS NULL OR @VER <> @P_ROW_VER
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @TYPE = 'HQ'
      THROW 50003, 'MSG.COMPANY_HQ_RULE', 1;
    IF EXISTS (SELECT 1 FROM [FW].[TB_USER] WHERE [COMPANY_CD] = @P_COMPANY_CD)
       OR EXISTS (SELECT 1 FROM [FW].[TB_DEPT] WHERE [COMPANY_CD] = @P_COMPANY_CD)
       OR EXISTS (SELECT 1 FROM [FW].[TB_PARTNER_JOIN_REQ] WHERE [COMPANY_CD] = @P_COMPANY_CD)
       OR EXISTS (SELECT 1 FROM [FW].[TB_FILE_GROUP] WHERE [COMPANY_CD] = @P_COMPANY_CD)
      THROW 50003, 'MSG.COMPANY_IN_USE', 1;

    DECLARE @BEFORE NVARCHAR(MAX) = (SELECT [COMPANY_CD], [COMPANY_NM], [COMPANY_TYPE_CD], [BIZ_REG_NO], [ALLOW_IP_LIST], [CONTRACT_END_DT], [SORT_NO], [USE_YN]
                                       FROM [FW].[TB_COMPANY] WHERE [COMPANY_CD] = @P_COMPANY_CD
                                       FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES);

    DELETE FROM [FW].[TB_COMPANY] WHERE [COMPANY_CD] = @P_COMPANY_CD;

    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_COMPANY', @P_ACTION_CD = 'D', @P_ROW_KEY = @P_COMPANY_CD,
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = NULL,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT 1 AS [AFFECTED_CNT];
END
