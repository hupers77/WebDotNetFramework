-- 첨부 파일 한 건 등록. FileService가 저장소에 내용을 쓴 뒤 호출한다(실패하면 FileService가 저장한 내용을 지운다).
-- 묶음 ID가 없으면 새 임시 묶음(CONFIRM_YN = 'N')을 올린 사용자의 회사로 만들고, 있으면 그 묶음에 추가한다.
-- 확장자는 공통코드 FILE_EXT(사용 중)만, 크기·개수는 설정 FILE.MAX_SIZE_MB·FILE.MAX_COUNT까지 허용한다.
-- 협력사 사용자는 자기 회사 묶음에만 추가할 수 있다. 프로그램 권한(CREATE/UPDATE)은 호출 전에 화면 서버가 확인한다.
-- 결과: FILE_GROUP_ID, FILE_ID
CREATE PROCEDURE [FW].[USP_FILE_SAVE]
  @P_FILE_GROUP_ID  BIGINT         = NULL,
  @P_PROGRAM_ID     VARCHAR(30),
  @P_ORG_FILE_NM    NVARCHAR(200),
  @P_FILE_EXT       VARCHAR(10),
  @P_FILE_SIZE      BIGINT,
  @P_STORED_PATH    VARCHAR(100),
  @P_CONTENT_HASH   CHAR(64),
  @P_USER_ID        VARCHAR(30),
  @P_LANG_CD        VARCHAR(5),
  @P_CLIENT_IP      VARCHAR(45)    = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @COMPANY_CD VARCHAR(10), @USER_TYPE_CD VARCHAR(10);
  SELECT @COMPANY_CD = [COMPANY_CD], @USER_TYPE_CD = [USER_TYPE_CD]
    FROM [FW].[TB_USER]
   WHERE [USER_ID] = @P_USER_ID AND [USER_STAT_CD] = 'ACTIVE';

  IF @COMPANY_CD IS NULL OR NULLIF(LTRIM(@P_ORG_FILE_NM), N'') IS NULL OR @P_FILE_SIZE IS NULL OR @P_FILE_SIZE <= 0
     OR NULLIF(@P_STORED_PATH, '') IS NULL OR @P_CONTENT_HASH IS NULL
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM] WHERE [PROGRAM_ID] = @P_PROGRAM_ID)
    THROW 50004, 'MSG.NOT_FOUND', 1;
  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_CODE]
                  WHERE [GROUP_CD] = 'FILE_EXT' AND [CODE] = LOWER(@P_FILE_EXT) AND [USE_YN] = 'Y'
                    AND CAST(SYSUTCDATETIME() AS DATE) BETWEEN [START_DT] AND [END_DT])
    THROW 50005, 'MSG.FILE_EXT_DENIED', 1;

  DECLARE @MAX_SIZE_MB BIGINT = TRY_CAST((SELECT [CONFIG_VAL] FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'FILE.MAX_SIZE_MB') AS BIGINT);
  DECLARE @MAX_COUNT INT = TRY_CAST((SELECT [CONFIG_VAL] FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'FILE.MAX_COUNT') AS INT);
  IF @P_FILE_SIZE > ISNULL(@MAX_SIZE_MB, 0) * 1048576
    THROW 50005, 'MSG.FILE_TOO_LARGE', 1;

  DECLARE @FILE_ID BIGINT;

  BEGIN TRY
    BEGIN TRAN;

    IF @P_FILE_GROUP_ID IS NULL
    BEGIN
      INSERT INTO [FW].[TB_FILE_GROUP] ([PROGRAM_ID], [COMPANY_CD], [REG_ID], [UPD_ID])
      VALUES (@P_PROGRAM_ID, @COMPANY_CD, @P_USER_ID, @P_USER_ID);
      SET @P_FILE_GROUP_ID = SCOPE_IDENTITY();
    END
    ELSE
    BEGIN
      -- 같은 프로그램의 묶음이어야 하고, 협력사는 자기 회사 묶음에만 추가한다 (없는 것처럼 응답해 존재를 드러내지 않는다)
      IF NOT EXISTS (SELECT 1 FROM [FW].[TB_FILE_GROUP] WITH (UPDLOCK)
                      WHERE [FILE_GROUP_ID] = @P_FILE_GROUP_ID AND [PROGRAM_ID] = @P_PROGRAM_ID
                        AND (@USER_TYPE_CD <> 'PARTNER' OR [COMPANY_CD] = @COMPANY_CD))
        THROW 50004, 'MSG.NOT_FOUND', 1;
      IF (SELECT COUNT(*) FROM [FW].[TB_FILE] WHERE [FILE_GROUP_ID] = @P_FILE_GROUP_ID AND [DEL_YN] = 'N') >= ISNULL(@MAX_COUNT, 0)
        THROW 50005, 'MSG.FILE_COUNT_EXCEEDED', 1;

      UPDATE [FW].[TB_FILE_GROUP] SET [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME() WHERE [FILE_GROUP_ID] = @P_FILE_GROUP_ID;
    END

    INSERT INTO [FW].[TB_FILE] ([FILE_GROUP_ID], [ORG_FILE_NM], [FILE_EXT], [FILE_SIZE], [STORED_PATH], [CONTENT_HASH], [SORT_NO], [REG_ID], [UPD_ID])
    SELECT @P_FILE_GROUP_ID, @P_ORG_FILE_NM, LOWER(@P_FILE_EXT), @P_FILE_SIZE, @P_STORED_PATH, LOWER(@P_CONTENT_HASH),
           ISNULL((SELECT MAX([SORT_NO]) FROM [FW].[TB_FILE] WHERE [FILE_GROUP_ID] = @P_FILE_GROUP_ID), 0) + 10,
           @P_USER_ID, @P_USER_ID;
    SET @FILE_ID = SCOPE_IDENTITY();

    COMMIT;

    SELECT @P_FILE_GROUP_ID AS [FILE_GROUP_ID], @FILE_ID AS [FILE_ID];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
