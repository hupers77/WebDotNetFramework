-- 사용자 한 명의 예외 권한을 통째로 저장 (화면의 목록 그대로). 프로그램: SYS_USER_AUTH_MGT
-- @P_ROWS: [{"programId":"SYS_CODE_MGT","funcCd":"EXPORT","grantType":"GRANT","endDt":"2026-12-31"}, ...] 사용 중인 프로그램의 예외 권한 전부.
--          사용 안 함 프로그램의 예외 권한은 건드리지 않는다.
-- 규칙: 대상은 현재 사용자의 데이터 범위 안이어야 한다(밖이면 없는 것으로 본다). 자기 예외 권한은 SYS_ADMIN만 고친다(스스로 권한 올리기 방지).
--       시스템 관리자는 코드에서 모든 권한을 가지므로 예외 권한을 두지 않는다. 기능은 프로그램이 쓰는 기능이어야 한다.
--       새로 넣거나 바꾼 행은 종료일이 오늘 이후여야 하고, 추가 허용(GRANT)은 대상의 회사 유형에 열린 화면이어야 한다(차단은 어디든 된다).
-- 동시성: 조회 때 받은 VERSION(UFN_USER_AUTH_VERSION)과 같아야 한다.
-- 바뀐 것이 있으면 감사 로그(전후 목록)를 남기고 권한 캐시(AUTH)를 올린다.
-- 결과: AFFECTED_CNT(추가+삭제+변경 건수)
CREATE PROCEDURE [FW].[USP_USER_AUTH_SAVE]
  @P_TARGET_USER_ID  VARCHAR(30),
  @P_VERSION         BINARY(32),
  @P_ROWS            NVARCHAR(MAX),
  @P_USER_ID         VARCHAR(30),
  @P_LANG_CD         VARCHAR(5),
  @P_CLIENT_IP       VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF @P_VERSION IS NULL OR @P_ROWS IS NULL OR ISJSON(@P_ROWS) <> 1 OR LEFT(LTRIM(@P_ROWS), 1) <> '['
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @NEW TABLE ([PROGRAM_ID] VARCHAR(30) NOT NULL, [FUNC_CD] VARCHAR(20) NOT NULL, [GRANT_TYPE] CHAR(5) NOT NULL, [END_DT] DATE NOT NULL,
                      PRIMARY KEY ([PROGRAM_ID], [FUNC_CD]));
  BEGIN TRY
    INSERT INTO @NEW ([PROGRAM_ID], [FUNC_CD], [GRANT_TYPE], [END_DT])
    SELECT [programId], [funcCd], [grantType], [endDt]
      FROM OPENJSON(@P_ROWS) WITH ([programId] VARCHAR(30) '$.programId', [funcCd] VARCHAR(20) '$.funcCd',
                                   [grantType] CHAR(5) '$.grantType', [endDt] DATE '$.endDt');
  END TRY
  BEGIN CATCH
    THROW 50005, 'MSG.INVALID_INPUT', 1; -- 같은 기능이 두 번 오거나 값이 비었을 때
  END CATCH;
  IF EXISTS (SELECT 1 FROM @NEW WHERE [GRANT_TYPE] NOT IN ('GRANT', 'DENY'))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @NEW N
              WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM_FUNC] F JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = F.[PROGRAM_ID]
                                 WHERE F.[PROGRAM_ID] = N.[PROGRAM_ID] AND F.[FUNC_CD] = N.[FUNC_CD] AND P.[USE_YN] = 'Y'))
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @CALLER_SYS_ADMIN BIT = IIF(EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_USER_ID) WHERE [ROLE_ID] = 'SYS_ADMIN'), 1, 0);
  DECLARE @COMPANY_TYPE VARCHAR(10), @TODAY DATE = CAST(GETDATE() AS DATE), @CNT INT = 0;
  DECLARE @OLD TABLE ([PROGRAM_ID] VARCHAR(30) NOT NULL, [FUNC_CD] VARCHAR(20) NOT NULL, [GRANT_TYPE] CHAR(5) NOT NULL, [END_DT] DATE NOT NULL,
                      PRIMARY KEY ([PROGRAM_ID], [FUNC_CD]));

  BEGIN TRY
    BEGIN TRAN;

    -- 대상 계정을 잠가 같은 사람의 예외 권한을 동시에 저장하지 못하게 한다
    SELECT @COMPANY_TYPE = C.[COMPANY_TYPE_CD]
      FROM [FW].[TB_USER] U WITH (UPDLOCK, HOLDLOCK)
      JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
     WHERE U.[USER_ID] = @P_TARGET_USER_ID
       AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'SYS_USER_AUTH_MGT') S
                   WHERE S.[COMPANY_CD] = U.[COMPANY_CD] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                     AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID]));

    IF @COMPANY_TYPE IS NULL
      THROW 50004, 'MSG.NOT_FOUND', 1;
    IF (SELECT [VERSION] FROM [FW].[UFN_USER_AUTH_VERSION](@P_TARGET_USER_ID)) <> @P_VERSION
      THROW 50002, 'MSG.CONCURRENCY', 1;
    IF @P_TARGET_USER_ID = @P_USER_ID AND @CALLER_SYS_ADMIN = 0
      THROW 50003, 'MSG.USER_AUTH_SELF', 1;
    IF EXISTS (SELECT 1 FROM [FW].[TB_USER_ROLE] WHERE [USER_ID] = @P_TARGET_USER_ID AND [ROLE_ID] = 'SYS_ADMIN')
       OR EXISTS (SELECT 1 FROM [FW].[UFN_USER_ROLES](@P_TARGET_USER_ID) WHERE [ROLE_ID] = 'SYS_ADMIN')
      THROW 50003, 'MSG.USER_AUTH_SYS_ADMIN', 1;

    INSERT INTO @OLD ([PROGRAM_ID], [FUNC_CD], [GRANT_TYPE], [END_DT])
    SELECT UF.[PROGRAM_ID], UF.[FUNC_CD], UF.[GRANT_TYPE], UF.[END_DT]
      FROM [FW].[TB_USER_PROGRAM_FUNC] UF
      JOIN [FW].[TB_PROGRAM] P ON P.[PROGRAM_ID] = UF.[PROGRAM_ID]
     WHERE UF.[USER_ID] = @P_TARGET_USER_ID AND P.[USE_YN] = 'Y';

    -- 새로 넣거나 바꾼 행만 종료일·공개 대상을 본다 (그대로 둔 행은 지난 것도 둘 수 있다)
    DECLARE @CHANGED TABLE ([PROGRAM_ID] VARCHAR(30) NOT NULL, [FUNC_CD] VARCHAR(20) NOT NULL, [GRANT_TYPE] CHAR(5) NOT NULL, [END_DT] DATE NOT NULL);
    INSERT INTO @CHANGED
    SELECT N.* FROM @NEW N
     WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[PROGRAM_ID] = N.[PROGRAM_ID] AND O.[FUNC_CD] = N.[FUNC_CD]
                                              AND O.[GRANT_TYPE] = N.[GRANT_TYPE] AND O.[END_DT] = N.[END_DT]);
    IF EXISTS (SELECT 1 FROM @CHANGED WHERE [END_DT] < @TODAY)
      THROW 50003, 'MSG.USER_AUTH_END_PAST', 1;
    IF EXISTS (SELECT 1 FROM @CHANGED N
                 JOIN [FW].[UFN_PROGRAM_SCOPE]() S ON S.[PROGRAM_ID] = N.[PROGRAM_ID]
                WHERE N.[GRANT_TYPE] = 'GRANT'
                  AND NOT (S.[OPEN_SCOPE_CD] = 'ALL' OR (@COMPANY_TYPE = 'HQ' AND S.[OPEN_SCOPE_CD] = 'EMP')
                           OR (@COMPANY_TYPE = 'PARTNER' AND S.[OPEN_SCOPE_CD] = 'PARTNER')))
      THROW 50003, 'MSG.USER_AUTH_SCOPE', 1;

    DELETE UF FROM [FW].[TB_USER_PROGRAM_FUNC] UF
      JOIN @OLD O ON O.[PROGRAM_ID] = UF.[PROGRAM_ID] AND O.[FUNC_CD] = UF.[FUNC_CD]
     WHERE UF.[USER_ID] = @P_TARGET_USER_ID
       AND NOT EXISTS (SELECT 1 FROM @NEW N WHERE N.[PROGRAM_ID] = O.[PROGRAM_ID] AND N.[FUNC_CD] = O.[FUNC_CD]);
    SET @CNT += @@ROWCOUNT;

    UPDATE UF
       SET [GRANT_TYPE] = C.[GRANT_TYPE], [END_DT] = C.[END_DT], [UPD_ID] = @P_USER_ID, [UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_USER_PROGRAM_FUNC] UF
      JOIN @CHANGED C ON C.[PROGRAM_ID] = UF.[PROGRAM_ID] AND C.[FUNC_CD] = UF.[FUNC_CD]
     WHERE UF.[USER_ID] = @P_TARGET_USER_ID;
    SET @CNT += @@ROWCOUNT;

    INSERT INTO [FW].[TB_USER_PROGRAM_FUNC] ([USER_ID], [PROGRAM_ID], [FUNC_CD], [GRANT_TYPE], [END_DT], [REG_ID], [UPD_ID])
    SELECT @P_TARGET_USER_ID, C.[PROGRAM_ID], C.[FUNC_CD], C.[GRANT_TYPE], C.[END_DT], @P_USER_ID, @P_USER_ID
      FROM @CHANGED C
     WHERE NOT EXISTS (SELECT 1 FROM @OLD O WHERE O.[PROGRAM_ID] = C.[PROGRAM_ID] AND O.[FUNC_CD] = C.[FUNC_CD]);
    SET @CNT += @@ROWCOUNT;

    IF @CNT > 0
    BEGIN
      DECLARE @BEFORE NVARCHAR(MAX) = (SELECT '[' + ISNULL(STRING_AGG(CAST('"' + [PROGRAM_ID] + ':' + [FUNC_CD] + ':' + RTRIM([GRANT_TYPE]) + ':' + CONVERT(CHAR(10), [END_DT], 23) + '"' AS NVARCHAR(MAX)), ',')
                                                              WITHIN GROUP (ORDER BY [PROGRAM_ID], [FUNC_CD]), '') + ']' FROM @OLD);
      DECLARE @AFTER NVARCHAR(MAX) = (SELECT '[' + ISNULL(STRING_AGG(CAST('"' + [PROGRAM_ID] + ':' + [FUNC_CD] + ':' + RTRIM([GRANT_TYPE]) + ':' + CONVERT(CHAR(10), [END_DT], 23) + '"' AS NVARCHAR(MAX)), ',')
                                                             WITHIN GROUP (ORDER BY [PROGRAM_ID], [FUNC_CD]), '') + ']' FROM @NEW);
      EXEC [LOG].[USP_AUDIT_WRITE]
        @P_TABLE_NM = 'FW.TB_USER_PROGRAM_FUNC', @P_ACTION_CD = 'U', @P_ROW_KEY = @P_TARGET_USER_ID,
        @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
        @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

      UPDATE [FW].[TB_CACHE_VERSION] SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME() WHERE [CACHE_KEY] = 'AUTH';
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH

  SELECT @CNT AS [AFFECTED_CNT];
END
