-- 위젯 데이터: 내 안 읽은 알림 수 (숫자 카드). 위젯 SP 공통 결과 열: LABEL, VALUE, TEXT, LINK, DT
CREATE PROCEDURE [FW].[USP_WIDGET_NOTI_UNREAD]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT CAST(NULL AS NVARCHAR(100)) AS [LABEL], CAST(COUNT(*) AS DECIMAL(18, 2)) AS [VALUE],
         CAST(NULL AS NVARCHAR(200)) AS [TEXT], CAST(NULL AS VARCHAR(200)) AS [LINK], CAST(NULL AS DATETIME2(0)) AS [DT]
    FROM [FW].[TB_NOTIFICATION]
   WHERE [USER_ID] = @P_USER_ID AND [READ_DT] IS NULL;
END
