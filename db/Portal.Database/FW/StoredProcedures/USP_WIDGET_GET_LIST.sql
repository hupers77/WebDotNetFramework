-- 홈 화면에 올릴 수 있는 위젯 목록 (사용 중인 것만, 제목은 화면 언어). 프로그램: DSH_HOME
-- 위젯별 읽기 권한(PROGRAM_ID)은 애플리케이션이 현재 사용자 권한으로 거른다.
-- 결과: WIDGET_CD, WIDGET_NM, TYPE_CD, DATA_SP, PROGRAM_ID, LINK_URL, ICON_CD, SPAN_COLS, CACHE_SEC
CREATE PROCEDURE [FW].[USP_WIDGET_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  SELECT W.[WIDGET_CD], COALESCE(L.[WIDGET_NM], D.[WIDGET_NM], W.[WIDGET_CD]) AS [WIDGET_NM], W.[TYPE_CD], W.[DATA_SP],
         W.[PROGRAM_ID], W.[LINK_URL], W.[ICON_CD], W.[SPAN_COLS], W.[CACHE_SEC]
    FROM [FW].[TB_WIDGET] W
    LEFT JOIN [FW].[TB_WIDGET_LANG] L ON L.[WIDGET_CD] = W.[WIDGET_CD] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_WIDGET_LANG] D ON D.[WIDGET_CD] = W.[WIDGET_CD] AND D.[LANG_CD] = @DEFAULT_LANG
   WHERE W.[USE_YN] = 'Y'
   ORDER BY W.[SORT_NO], W.[WIDGET_CD];
END
