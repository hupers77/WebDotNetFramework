-- 사용자 목록 (목록 SP 표준 템플릿). 프로그램: SYS_USER_MGT(본사 관리자), PTN_USER_MGT(협력사 관리자)
-- 보이는 사용자는 @P_PROGRAM_ID의 데이터 범위(UFN_DATA_SCOPE)로 거른다: 포털 관리자는 전체, 협력사 관리자는 자기 회사만.
-- 검색어는 사용자 ID·이름 일부. 이메일 등 개인정보는 돌려주지 않는다(2단계 인증은 등록 여부만).
-- 결과셋 1: 목록(회사 정렬 순서, 회사, 사용자 ID 순), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_USER_GET_LIST]
  @P_PROGRAM_ID     VARCHAR(30),
  @P_KEYWORD        NVARCHAR(100) = NULL,
  @P_COMPANY_CD     VARCHAR(10)   = NULL,
  @P_USER_TYPE_CD   VARCHAR(10)   = NULL,
  @P_USER_STAT_CD   VARCHAR(10)   = NULL,
  @P_LOCK_YN        CHAR(1)       = NULL,
  @P_PAGE_NO        INT           = 1,
  @P_PAGE_SIZE      INT           = 50,
  @P_USER_ID        VARCHAR(30),
  @P_LANG_CD        VARCHAR(5),
  @P_CLIENT_IP      VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_PROGRAM_ID NOT IN ('SYS_USER_MGT', 'PTN_USER_MGT')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT U.[USER_ID], U.[USER_NM], U.[COMPANY_CD], C.[COMPANY_NM], C.[COMPANY_TYPE_CD], U.[DEPT_ID], D.[DEPT_NM],
         U.[USER_TYPE_CD], COALESCE(TL.[CODE_NM], TD.[CODE_NM], U.[USER_TYPE_CD]) AS [USER_TYPE_NM],
         U.[USER_STAT_CD], COALESCE(SL.[CODE_NM], SD.[CODE_NM], U.[USER_STAT_CD]) AS [USER_STAT_NM],
         U.[LOCK_YN], U.[LOGIN_FAIL_CNT], U.[ACCOUNT_END_DT],
         IIF(U.[MFA_SECRET_ENC] IS NULL, 'N', 'Y') AS [MFA_YN], IIF(U.[PWD_HASH] IS NULL, 'N', 'Y') AS [PWD_YN],
         U.[LAST_LOGIN_DT], U.[PWD_CHG_DT],
         (SELECT STRING_AGG(UR.[ROLE_ID], ',') WITHIN GROUP (ORDER BY R.[SORT_NO], UR.[ROLE_ID])
            FROM [FW].[TB_USER_ROLE] UR JOIN [FW].[TB_ROLE] R ON R.[ROLE_ID] = UR.[ROLE_ID]
           WHERE UR.[USER_ID] = U.[USER_ID]) AS [ROLE_IDS],
         U.[UPD_ID], U.[UPD_DT], U.[ROW_VER]
    FROM [FW].[TB_USER] U
    JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
    LEFT JOIN [FW].[TB_DEPT] D ON D.[DEPT_ID] = U.[DEPT_ID]
    LEFT JOIN [FW].[TB_CODE_LANG] TL ON TL.[GROUP_CD] = 'USER_TYPE' AND TL.[CODE] = U.[USER_TYPE_CD] AND TL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] TD ON TD.[GROUP_CD] = 'USER_TYPE' AND TD.[CODE] = U.[USER_TYPE_CD] AND TD.[LANG_CD] = @DEFAULT_LANG
    LEFT JOIN [FW].[TB_CODE_LANG] SL ON SL.[GROUP_CD] = 'USER_STAT' AND SL.[CODE] = U.[USER_STAT_CD] AND SL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] SD ON SD.[GROUP_CD] = 'USER_STAT' AND SD.[CODE] = U.[USER_STAT_CD] AND SD.[LANG_CD] = @DEFAULT_LANG
   WHERE (@P_KEYWORD IS NULL OR U.[USER_ID] LIKE '%' + @P_KEYWORD + '%' OR U.[USER_NM] LIKE '%' + @P_KEYWORD + '%')
     AND (@P_COMPANY_CD IS NULL OR U.[COMPANY_CD] = @P_COMPANY_CD)
     AND (@P_USER_TYPE_CD IS NULL OR U.[USER_TYPE_CD] = @P_USER_TYPE_CD)
     AND (@P_USER_STAT_CD IS NULL OR U.[USER_STAT_CD] = @P_USER_STAT_CD)
     AND (@P_LOCK_YN IS NULL OR U.[LOCK_YN] = @P_LOCK_YN)
     AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, @P_PROGRAM_ID) S
                 WHERE S.[COMPANY_CD] = U.[COMPANY_CD] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID]))
   ORDER BY CASE WHEN C.[COMPANY_TYPE_CD] = 'HQ' THEN 0 ELSE 1 END, C.[SORT_NO], C.[COMPANY_NM], U.[USER_ID]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_USER] U
   WHERE (@P_KEYWORD IS NULL OR U.[USER_ID] LIKE '%' + @P_KEYWORD + '%' OR U.[USER_NM] LIKE '%' + @P_KEYWORD + '%')
     AND (@P_COMPANY_CD IS NULL OR U.[COMPANY_CD] = @P_COMPANY_CD)
     AND (@P_USER_TYPE_CD IS NULL OR U.[USER_TYPE_CD] = @P_USER_TYPE_CD)
     AND (@P_USER_STAT_CD IS NULL OR U.[USER_STAT_CD] = @P_USER_STAT_CD)
     AND (@P_LOCK_YN IS NULL OR U.[LOCK_YN] = @P_LOCK_YN)
     AND EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, @P_PROGRAM_ID) S
                 WHERE S.[COMPANY_CD] = U.[COMPANY_CD] AND (S.[DEPT_ID] IS NULL OR S.[DEPT_ID] = U.[DEPT_ID])
                   AND (S.[USER_ID] IS NULL OR S.[USER_ID] = U.[USER_ID]))
  OPTION (RECOMPILE);
END
