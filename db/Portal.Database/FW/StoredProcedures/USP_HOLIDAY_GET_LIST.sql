-- 휴일·달력 목록 (한 해). 프로그램: SYS_HOLIDAY_MGT
-- 결과셋 1: 등록된 날짜(날짜순), 결과셋 2: 전체 건수. WEEKDAY_NO: 0=일 … 6=토 (DATEFIRST와 무관)
CREATE PROCEDURE [FW].[USP_HOLIDAY_GET_LIST]
  @P_YEAR       INT,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_YEAR IS NULL OR @P_YEAR NOT BETWEEN 1990 AND 2100
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @FROM DATE = DATEFROMPARTS(@P_YEAR, 1, 1), @TO DATE = DATEFROMPARTS(@P_YEAR, 12, 31);

  SELECT CONVERT(CHAR(10), H.[HOLIDAY_DT], 23) AS [HOLIDAY_DT], H.[HOLIDAY_NM], H.[WORK_YN],
         DATEDIFF(DAY, '19000107', H.[HOLIDAY_DT]) % 7 AS [WEEKDAY_NO], H.[UPD_ID], H.[UPD_DT], H.[ROW_VER]
    FROM [FW].[TB_HOLIDAY] H
   WHERE H.[HOLIDAY_DT] BETWEEN @FROM AND @TO
   ORDER BY H.[HOLIDAY_DT];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_HOLIDAY] WHERE [HOLIDAY_DT] BETWEEN @FROM AND @TO;
END
