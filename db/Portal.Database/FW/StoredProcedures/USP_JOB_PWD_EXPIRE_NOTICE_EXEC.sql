-- 배치 작업 JOB_PWD_EXPIRE_NOTICE: 비밀번호 변경 주기가 곧 끝나는 계정에 안내(TPL_PWD_EXPIRE, 메일·포털 알림)를 보낸다.
--   만료 시각은 마지막 변경 시각(PWD_CHG_DT) + PWD.EXPIRE_DAYS(기본 90일, 0이면 만료 없음 → 아무것도 하지 않음)이다.
--   만료까지 PWD.EXPIRE_NOTICE_DAYS(기본 7일, 0이면 안내 안 함) 안으로 들어온 계정에 변경 주기마다 한 번 보낸다(비밀번호를 바꾸면 다음 주기에 다시 안내).
--   이미 만료된 계정은 로그인할 때 변경 화면으로 보내므로 안내하지 않는다. 변경이 강제된 계정(PWD_CHG_REQ_YN = 'Y')도 마찬가지다.
--   비밀번호가 있는 사용(ACTIVE) 계정만 대상이다(AD 전용 계정과 시스템 계정 제외). 만료일은 서버 현지 날짜(한국 시간)로 보낸다.
-- 결과: PROCESSED_CNT (안내 건수)
CREATE PROCEDURE [FW].[USP_JOB_PWD_EXPIRE_NOTICE_EXEC]
  @P_USER_ID       VARCHAR(30) = NULL,
  @P_LANG_CD       VARCHAR(5),
  @P_CLIENT_IP     VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME(), @UTC_OFFSET_MIN INT = DATEDIFF(MINUTE, SYSUTCDATETIME(), SYSDATETIME()), @BY VARCHAR(30) = ISNULL(@P_USER_ID, 'SYSTEM'), @CNT INT = 0;
  DECLARE @EXPIRE_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'PWD.EXPIRE_DAYS'), 90);
  DECLARE @NOTICE_DAYS INT = ISNULL((SELECT TRY_CAST([CONFIG_VAL] AS INT) FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'PWD.EXPIRE_NOTICE_DAYS'), 7);

  IF @EXPIRE_DAYS <= 0 OR @NOTICE_DAYS <= 0
  BEGIN
    SELECT 0 AS [PROCESSED_CNT];
    RETURN;
  END

  DECLARE @TARGET TABLE ([USER_ID] VARCHAR(30) PRIMARY KEY, [USER_NM] NVARCHAR(100), [EXPIRE_DT] CHAR(10), [DAYS_LEFT] INT);

  INSERT INTO @TARGET ([USER_ID], [USER_NM], [EXPIRE_DT], [DAYS_LEFT])
  SELECT U.[USER_ID], U.[USER_NM],
         CONVERT(CHAR(10), DATEADD(MINUTE, @UTC_OFFSET_MIN, X.[EXPIRE_AT]), 23),
         CEILING(DATEDIFF(MINUTE, @NOW, X.[EXPIRE_AT]) / 1440.0)
    FROM [FW].[TB_USER] U
   CROSS APPLY (SELECT DATEADD(DAY, @EXPIRE_DAYS, U.[PWD_CHG_DT]) AS [EXPIRE_AT]) X
   WHERE U.[USER_STAT_CD] = 'ACTIVE'
     AND U.[USER_TYPE_CD] <> 'SYSTEM'
     AND U.[PWD_HASH] IS NOT NULL
     AND U.[PWD_CHG_REQ_YN] = 'N'
     AND U.[PWD_CHG_DT] IS NOT NULL
     AND X.[EXPIRE_AT] > @NOW
     AND X.[EXPIRE_AT] <= DATEADD(DAY, @NOTICE_DAYS, @NOW)
     AND (U.[PWD_EXPIRE_NOTICE_DT] IS NULL OR U.[PWD_EXPIRE_NOTICE_DT] < U.[PWD_CHG_DT]);

  DECLARE @TO_USER_ID VARCHAR(30), @USER_NM NVARCHAR(100), @EXPIRE_DT CHAR(10), @DAYS_LEFT INT, @PARAMS NVARCHAR(4000);

  DECLARE TARGETS CURSOR LOCAL FAST_FORWARD FOR SELECT [USER_ID], [USER_NM], [EXPIRE_DT], [DAYS_LEFT] FROM @TARGET ORDER BY [USER_ID];
  OPEN TARGETS;
  FETCH NEXT FROM TARGETS INTO @TO_USER_ID, @USER_NM, @EXPIRE_DT, @DAYS_LEFT;
  WHILE @@FETCH_STATUS = 0
  BEGIN
    BEGIN TRAN;

    -- 그 사이 비밀번호를 바꿨으면 건너뛴다
    UPDATE [FW].[TB_USER]
       SET [PWD_EXPIRE_NOTICE_DT] = @NOW, [UPD_ID] = @BY, [UPD_DT] = @NOW
     WHERE [USER_ID] = @TO_USER_ID
       AND [USER_STAT_CD] = 'ACTIVE'
       AND ([PWD_EXPIRE_NOTICE_DT] IS NULL OR [PWD_EXPIRE_NOTICE_DT] < [PWD_CHG_DT])
       AND DATEADD(DAY, @EXPIRE_DAYS, [PWD_CHG_DT]) <= DATEADD(DAY, @NOTICE_DAYS, @NOW);

    IF @@ROWCOUNT = 1
    BEGIN
      SET @PARAMS = (SELECT @USER_NM AS [USER_NM], @TO_USER_ID AS [USER_ID], @EXPIRE_DT AS [EXPIRE_DT], CAST(@DAYS_LEFT AS VARCHAR(10)) AS [DAYS_LEFT]
                     FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
      EXEC [FW].[USP_MSG_QUEUE_SAVE] @P_TEMPLATE_ID = 'TPL_PWD_EXPIRE', @P_TO_USER_ID = @TO_USER_ID, @P_PARAMS_JSON = @PARAMS,
           @P_RESULT_YN = 'N', @P_USER_ID = @BY, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;
      SET @CNT += 1;
    END

    COMMIT;
    FETCH NEXT FROM TARGETS INTO @TO_USER_ID, @USER_NM, @EXPIRE_DT, @DAYS_LEFT;
  END
  CLOSE TARGETS;
  DEALLOCATE TARGETS;

  SELECT @CNT AS [PROCESSED_CNT];
END
