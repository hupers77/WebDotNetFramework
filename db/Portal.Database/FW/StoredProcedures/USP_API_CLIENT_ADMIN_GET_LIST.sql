-- API 클라이언트 목록 (관리 화면). 프로그램: SYS_API_CLIENT_MGT
-- 결과셋 1: 클라이언트(ID순, 비밀값 해시는 내보내지 않고 발급 여부만), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_API_CLIENT_ADMIN_GET_LIST]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT C.[CLIENT_ID], C.[CLIENT_NM], C.[API_CODES], C.[ALLOW_IP_LIST], C.[RATE_PER_MIN],
         CONVERT(CHAR(10), C.[EXPIRE_DT], 23) AS [EXPIRE_DT], C.[USE_YN],
         CASE WHEN C.[SECRET_HASH] IS NULL THEN 'N' ELSE 'Y' END AS [SECRET_YN], C.[SECRET_ISSUED_DT],
         C.[UPD_ID], C.[UPD_DT], C.[ROW_VER]
    FROM [FW].[TB_API_CLIENT] C
   ORDER BY C.[CLIENT_ID];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_API_CLIENT];
END
