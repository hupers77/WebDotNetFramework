-- 위젯 설정 일괄 저장 (수정만). 프로그램: DSH_WIDGET_MGT
-- @P_ROWS_JSON: [{widgetCd, nameKo, nameEn, nameZh, spanCols, cacheSec, sortNo, useYn, rowVer(16진수)}]
-- 위젯 추가·삭제와 데이터 SP·유형·권한 프로그램 변경은 하지 않는다(SP와 짝이라 개발 배포로만 바꾼다). 동시성은 ROW_VER로 확인한다.
-- 결과: AFFECTED_CNT (처리한 위젯 수)
CREATE PROCEDURE [FW].[USP_WIDGET_SAVE]
  @P_ROWS_JSON  NVARCHAR(MAX),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF ISJSON(@P_ROWS_JSON) <> 1
    THROW 50003, 'MSG.INVALID_INPUT', 1;

  DECLARE @R TABLE (
    [WIDGET_CD] VARCHAR(30) PRIMARY KEY, [NAME_KO] NVARCHAR(100), [NAME_EN] NVARCHAR(100), [NAME_ZH] NVARCHAR(100),
    [SPAN_COLS] INT, [CACHE_SEC] INT, [SORT_NO] INT, [USE_YN] CHAR(1), [ROW_VER] BINARY(8));
  INSERT INTO @R
  SELECT [widgetCd], [nameKo], [nameEn], [nameZh], [spanCols], [cacheSec], [sortNo], [useYn], CONVERT(BINARY(8), [rowVer], 2)
    FROM OPENJSON(@P_ROWS_JSON) WITH (
      [widgetCd] VARCHAR(30), [nameKo] NVARCHAR(100), [nameEn] NVARCHAR(100), [nameZh] NVARCHAR(100),
      [spanCols] INT, [cacheSec] INT, [sortNo] INT, [useYn] CHAR(1), [rowVer] VARCHAR(16));

  IF NOT EXISTS (SELECT 1 FROM @R)
    THROW 50005, 'MSG.NO_CHANGES', 1;
  IF EXISTS (SELECT 1 FROM @R R LEFT JOIN [FW].[TB_WIDGET] W ON W.[WIDGET_CD] = R.[WIDGET_CD] WHERE W.[WIDGET_CD] IS NULL)
    THROW 50004, 'MSG.NOT_FOUND', 1;
  IF EXISTS (SELECT 1 FROM @R WHERE ISNULL([NAME_KO], N'') = N'' OR ISNULL([NAME_EN], N'') = N'' OR ISNULL([NAME_ZH], N'') = N''
                                   OR [SPAN_COLS] NOT BETWEEN 1 AND 12 OR [CACHE_SEC] NOT BETWEEN 0 AND 86400
                                   OR [SORT_NO] IS NULL OR [USE_YN] NOT IN ('Y', 'N') OR [USE_YN] IS NULL)
    THROW 50003, 'MSG.INVALID_INPUT', 1;

  DECLARE @CNT INT = 0;
  DECLARE @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF EXISTS (SELECT 1 FROM @R R JOIN [FW].[TB_WIDGET] W WITH (UPDLOCK) ON W.[WIDGET_CD] = R.[WIDGET_CD] WHERE W.[ROW_VER] <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;

    SET @BEFORE = (SELECT W.[WIDGET_CD], W.[SPAN_COLS], W.[CACHE_SEC], W.[SORT_NO], W.[USE_YN]
                     FROM [FW].[TB_WIDGET] W JOIN @R R ON R.[WIDGET_CD] = W.[WIDGET_CD] FOR JSON PATH);

    UPDATE W
       SET W.[SPAN_COLS] = R.[SPAN_COLS], W.[CACHE_SEC] = R.[CACHE_SEC], W.[SORT_NO] = R.[SORT_NO], W.[USE_YN] = R.[USE_YN],
           W.[UPD_ID] = @P_USER_ID, W.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_WIDGET] W JOIN @R R ON R.[WIDGET_CD] = W.[WIDGET_CD];
    SET @CNT = @@ROWCOUNT;

    MERGE [FW].[TB_WIDGET_LANG] AS T
    USING (SELECT R.[WIDGET_CD], V.[LANG_CD], V.[WIDGET_NM]
             FROM @R R CROSS APPLY (VALUES ('ko', R.[NAME_KO]), ('en', R.[NAME_EN]), ('zh-CN', R.[NAME_ZH])) V ([LANG_CD], [WIDGET_NM])) AS S
       ON T.[WIDGET_CD] = S.[WIDGET_CD] AND T.[LANG_CD] = S.[LANG_CD]
    WHEN MATCHED AND T.[WIDGET_NM] <> S.[WIDGET_NM] THEN UPDATE SET T.[WIDGET_NM] = S.[WIDGET_NM], T.[UPD_ID] = @P_USER_ID, T.[UPD_DT] = SYSUTCDATETIME()
    WHEN NOT MATCHED THEN INSERT ([WIDGET_CD], [LANG_CD], [WIDGET_NM], [REG_ID], [UPD_ID]) VALUES (S.[WIDGET_CD], S.[LANG_CD], S.[WIDGET_NM], @P_USER_ID, @P_USER_ID);

    SET @AFTER = (SELECT R.[WIDGET_CD], R.[SPAN_COLS], R.[CACHE_SEC], R.[SORT_NO], R.[USE_YN], R.[NAME_KO], R.[NAME_EN], R.[NAME_ZH] FROM @R R FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_WIDGET', @P_ACTION_CD = 'U', @P_ROW_KEY = N'WIDGET',
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
