-- 위젯 데이터: 공지사항 최근 5건 (목록). 글 보기 규칙(게시기간·공개 대상 회사)은 목록 화면과 같다(UFN_POST_VISIBLE, 관리자 아님).
-- 위젯 SP 공통 결과 열: LABEL, VALUE, TEXT(제목), LINK(글 보기 주소), DT
CREATE PROCEDURE [FW].[USP_WIDGET_NOTICE_RECENT]
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT TOP (5) CAST(NULL AS NVARCHAR(100)) AS [LABEL], CAST(NULL AS DECIMAL(18, 2)) AS [VALUE],
         CAST(P.[TITLE] AS NVARCHAR(200)) AS [TEXT], CAST('/Board/Notice/View/' + CONVERT(VARCHAR(20), P.[POST_ID]) AS VARCHAR(200)) AS [LINK],
         P.[REG_DT] AS [DT]
    FROM [FW].[TB_POST] P
    JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, 'N') V ON V.[POST_ID] = P.[POST_ID]
   WHERE P.[BOARD_CD] = 'Notice' AND P.[ROOT_POST_ID] = P.[POST_ID] AND V.[SECRET_OK_YN] = 'Y'
   ORDER BY P.[PIN_YN] DESC, P.[POST_ID] DESC;
END
