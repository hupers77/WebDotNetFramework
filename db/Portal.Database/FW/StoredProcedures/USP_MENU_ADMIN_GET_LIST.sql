-- 메뉴 관리 목록 (한 메뉴 세트 전체, 사용 안 함 포함). 프로그램: SYS_MENU_MGT
-- 트리 순서(부모 아래 정렬 번호 순)로 돌려주며, DEPTH는 최상위가 1이다. 부모는 바뀌지 않는 MENU_KEY로 가리킨다.
-- 결과셋 1: 메뉴, 결과셋 2: 메뉴명(언어별), 결과셋 3: 선택할 수 있는 프로그램(사용 중), 결과셋 4: 전체 건수
CREATE PROCEDURE [FW].[USP_MENU_ADMIN_GET_LIST]
  @P_MENU_SET_CD  VARCHAR(10),
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_MENU_SET_CD IS NULL OR @P_MENU_SET_CD NOT IN ('PORTAL', 'ADMIN', 'MOBILE')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  ;WITH T AS (
    SELECT M.[MENU_ID], 1 AS [DEPTH], CONVERT(VARCHAR(900), RIGHT('0000000000' + CONVERT(VARCHAR(10), M.[SORT_NO] + 1000000), 10) + RIGHT('0000000000' + CONVERT(VARCHAR(10), M.[MENU_ID]), 10)) AS [PATH]
      FROM [FW].[TB_MENU] M
     WHERE M.[MENU_SET_CD] = @P_MENU_SET_CD AND M.[PARENT_MENU_ID] IS NULL
    UNION ALL
    SELECT C.[MENU_ID], T.[DEPTH] + 1, CONVERT(VARCHAR(900), T.[PATH] + RIGHT('0000000000' + CONVERT(VARCHAR(10), C.[SORT_NO] + 1000000), 10) + RIGHT('0000000000' + CONVERT(VARCHAR(10), C.[MENU_ID]), 10))
      FROM T
      JOIN [FW].[TB_MENU] C ON C.[PARENT_MENU_ID] = T.[MENU_ID] AND C.[MENU_SET_CD] = @P_MENU_SET_CD
     WHERE T.[DEPTH] < 20
  )
  SELECT M.[MENU_KEY], P.[MENU_KEY] AS [PARENT_MENU_KEY], M.[MENU_SET_CD], M.[MENU_TYPE_CD], M.[PROGRAM_ID], M.[LINK_URL], M.[ICON_CD],
         M.[SORT_NO], M.[NEW_WIN_YN], M.[OPEN_SCOPE_CD], M.[USE_YN], T.[DEPTH], M.[UPD_ID], M.[UPD_DT], M.[ROW_VER]
    FROM T
    JOIN [FW].[TB_MENU] M ON M.[MENU_ID] = T.[MENU_ID]
    LEFT JOIN [FW].[TB_MENU] P ON P.[MENU_ID] = M.[PARENT_MENU_ID]
   ORDER BY T.[PATH]
  OPTION (MAXRECURSION 30);

  SELECT M.[MENU_KEY], N.[LANG_CD], N.[MENU_NM]
    FROM [FW].[TB_MENU_LANG] N
    JOIN [FW].[TB_MENU] M ON M.[MENU_ID] = N.[MENU_ID]
   WHERE M.[MENU_SET_CD] = @P_MENU_SET_CD;

  SELECT P.[PROGRAM_ID], P.[PROGRAM_NM], P.[URL]
    FROM [FW].[TB_PROGRAM] P
   WHERE P.[USE_YN] = 'Y'
   ORDER BY P.[PROGRAM_ID];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM [FW].[TB_MENU] WHERE [MENU_SET_CD] = @P_MENU_SET_CD;
END
