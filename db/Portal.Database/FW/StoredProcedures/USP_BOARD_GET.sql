-- 게시판 한 곳의 설정과 이름 (게시판 화면이 가장 먼저 부른다). 프로그램: 그 게시판의 프로그램 (권한은 애플리케이션이 확인)
-- 사용 안 하는 게시판은 0행. 이름은 화면 언어(없으면 기본 언어).
-- 결과: BOARD_CD, PROGRAM_ID, BOARD_TYPE_CD, BOARD_NM, REPLY_YN, COMMENT_YN, ATTACH_YN, ANON_YN, SECRET_YN, PERIOD_YN, PIN_YN, READER_YN
CREATE PROCEDURE [FW].[USP_BOARD_GET]
  @P_BOARD_CD    VARCHAR(30),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  SELECT B.[BOARD_CD], B.[PROGRAM_ID], B.[BOARD_TYPE_CD], COALESCE(L.[BOARD_NM], D.[BOARD_NM], B.[BOARD_CD]) AS [BOARD_NM],
         B.[REPLY_YN], B.[COMMENT_YN], B.[ATTACH_YN], B.[ANON_YN], B.[SECRET_YN], B.[PERIOD_YN], B.[PIN_YN], B.[READER_YN]
    FROM [FW].[TB_BOARD] B
    LEFT JOIN [FW].[TB_BOARD_LANG] L ON L.[BOARD_CD] = B.[BOARD_CD] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_BOARD_LANG] D ON D.[BOARD_CD] = B.[BOARD_CD] AND D.[LANG_CD] = @DEFAULT_LANG
   WHERE B.[BOARD_CD] = @P_BOARD_CD AND B.[USE_YN] = 'Y';
END
