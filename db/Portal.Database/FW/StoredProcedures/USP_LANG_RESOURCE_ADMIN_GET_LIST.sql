-- 다국어 문구 관리 목록 (키 단위 쪽 나눔). 프로그램: SYS_LANG_MGT
-- 검색어는 키·문구 일부, @P_RES_TYPE는 LABEL/MSG/BTN/TOOLTIP, @P_MISSING_YN = 'Y'면 사용 중인 언어 중 빠진 문구가 있는 키만.
-- 결과셋 1: 고른 쪽의 키별·언어별 문구(키 순), KEY_VER는 그 키의 언어 행 중 가장 큰 ROW_VER(저장할 때 동시성 확인용)
-- 결과셋 2: 검색 조건에 맞는 전체 키 수
CREATE PROCEDURE [FW].[USP_LANG_RESOURCE_ADMIN_GET_LIST]
  @P_KEYWORD      NVARCHAR(100) = NULL,
  @P_RES_TYPE     VARCHAR(10)   = NULL,
  @P_MISSING_YN   CHAR(1)       = NULL,
  @P_PAGE_NO      INT           = 1,
  @P_PAGE_SIZE    INT           = 50,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 200 THEN 200 ELSE @P_PAGE_SIZE END;
  IF @P_RES_TYPE IS NOT NULL AND @P_RES_TYPE NOT IN ('LABEL', 'MSG', 'BTN', 'TOOLTIP')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @LANG_CNT INT = (SELECT COUNT(*) FROM [FW].[TB_LANG] WHERE [USE_YN] = 'Y');
  DECLARE @K TABLE ([RES_KEY] VARCHAR(100) PRIMARY KEY);

  INSERT INTO @K
  SELECT R.[RES_KEY]
    FROM [FW].[TB_LANG_RESOURCE] R
    JOIN [FW].[TB_LANG] L ON L.[LANG_CD] = R.[LANG_CD] AND L.[USE_YN] = 'Y'
   GROUP BY R.[RES_KEY]
  HAVING (@P_MISSING_YN IS NULL OR @P_MISSING_YN <> 'Y' OR COUNT(*) < @LANG_CNT)
     AND (@P_RES_TYPE IS NULL OR MAX(IIF(R.[RES_TYPE] = @P_RES_TYPE, 1, 0)) = 1)
     AND (@P_KEYWORD IS NULL OR R.[RES_KEY] LIKE '%' + @P_KEYWORD + '%' OR MAX(IIF(R.[RES_TEXT] LIKE '%' + @P_KEYWORD + '%', 1, 0)) = 1)
  OPTION (RECOMPILE);

  SELECT R.[RES_KEY], R.[LANG_CD], R.[RES_TEXT], R.[RES_TYPE], V.[KEY_VER]
    FROM (SELECT [RES_KEY] FROM @K ORDER BY [RES_KEY] OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY) P
    JOIN [FW].[TB_LANG_RESOURCE] R ON R.[RES_KEY] = P.[RES_KEY]
    JOIN (SELECT [RES_KEY], MAX([ROW_VER]) AS [KEY_VER] FROM [FW].[TB_LANG_RESOURCE] GROUP BY [RES_KEY]) V ON V.[RES_KEY] = R.[RES_KEY]
   ORDER BY R.[RES_KEY], R.[LANG_CD];

  SELECT COUNT(*) AS [TOTAL_CNT] FROM @K;
END
