-- 프로그램 한 개의 기능(버튼) 목록 (프로그램 관리 화면 오른쪽). 프로그램: SYS_PROGRAM_MGT
-- 공통코드 FUNC_CD의 사용 중인 기능 전부와, 코드에서 빠졌지만 이 프로그램이 아직 쓰는 기능을 돌려준다.
-- 결과: FUNC_CD, USED_YN(이 프로그램이 쓰는 기능), API_CNT(이 기능을 요구하는 서버 경로 수, 있으면 뺄 수 없다), ROLE_CNT(이 기능을 받은 역할 수)
CREATE PROCEDURE [FW].[USP_PROGRAM_FUNC_GET_LIST]
  @P_PROGRAM_ID  VARCHAR(30),
  @P_USER_ID     VARCHAR(30),
  @P_LANG_CD     VARCHAR(5),
  @P_CLIENT_IP   VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  SELECT K.[FUNC_CD],
         IIF(F.[FUNC_CD] IS NULL, 'N', 'Y') AS [USED_YN],
         (SELECT COUNT(*) FROM [FW].[TB_PROGRAM_API] A WHERE A.[PROGRAM_ID] = @P_PROGRAM_ID AND A.[FUNC_CD] = K.[FUNC_CD]) AS [API_CNT],
         (SELECT COUNT(*) FROM [FW].[TB_ROLE_PROGRAM_FUNC] RF WHERE RF.[PROGRAM_ID] = @P_PROGRAM_ID AND RF.[FUNC_CD] = K.[FUNC_CD]) AS [ROLE_CNT]
    FROM (SELECT [CODE] AS [FUNC_CD], [SORT_NO] FROM [FW].[TB_CODE] WHERE [GROUP_CD] = 'FUNC_CD' AND [USE_YN] = 'Y'
          UNION
          SELECT [FUNC_CD], 9999 FROM [FW].[TB_PROGRAM_FUNC] X
           WHERE X.[PROGRAM_ID] = @P_PROGRAM_ID
             AND NOT EXISTS (SELECT 1 FROM [FW].[TB_CODE] C WHERE C.[GROUP_CD] = 'FUNC_CD' AND C.[CODE] = X.[FUNC_CD] AND C.[USE_YN] = 'Y')) K
    LEFT JOIN [FW].[TB_PROGRAM_FUNC] F ON F.[PROGRAM_ID] = @P_PROGRAM_ID AND F.[FUNC_CD] = K.[FUNC_CD]
   WHERE EXISTS (SELECT 1 FROM [FW].[TB_PROGRAM] P WHERE P.[PROGRAM_ID] = @P_PROGRAM_ID)
   ORDER BY K.[SORT_NO], K.[FUNC_CD];
END
