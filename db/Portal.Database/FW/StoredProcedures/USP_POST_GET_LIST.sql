-- 게시글 목록 (원글 최신순, 상단 고정이 먼저, 답글은 원글 아래 시간순). 프로그램: 게시판의 프로그램 (READ는 애플리케이션이 확인)
-- 비밀글은 볼 수 없는 사람에게 제목을 주지 않는다(TITLE = NULL, SECRET_YN = 'Y'). 익명 게시판은 관리자와 본인 외에게 작성자를 주지 않는다.
-- @P_SEARCH_TYPE: TITLE / CONTENT / TITLE_CONTENT / WRITER. 검색어가 있으면 비밀글 중 볼 수 없는 글은 제목·내용으로는 찾지 않는다.
-- 결과셋 1: 목록, 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_POST_GET_LIST]
  @P_BOARD_CD     VARCHAR(30),
  @P_SEARCH_TYPE  VARCHAR(20)   = 'TITLE_CONTENT',
  @P_KEYWORD      NVARCHAR(100) = NULL,
  @P_MANAGER_YN   CHAR(1)       = 'N',
  @P_PAGE_NO      INT           = 1,
  @P_PAGE_SIZE    INT           = 20,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF @P_SEARCH_TYPE NOT IN ('TITLE', 'CONTENT', 'TITLE_CONTENT', 'WRITER') OR @P_MANAGER_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF NOT EXISTS (SELECT 1 FROM [FW].[TB_BOARD] WHERE [BOARD_CD] = @P_BOARD_CD AND [USE_YN] = 'Y')
    THROW 50004, 'MSG.NOT_FOUND', 1;

  SET @P_KEYWORD = NULLIF(LTRIM(RTRIM(@P_KEYWORD)), N'');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 100 THEN 100 ELSE @P_PAGE_SIZE END;

  SELECT P.[POST_ID], P.[ROOT_POST_ID], P.[PARENT_POST_ID], P.[DEPTH],
         IIF(V.[SECRET_OK_YN] = 'Y', P.[TITLE], NULL) AS [TITLE],
         P.[SECRET_YN], P.[PIN_YN], P.[COMPANY_CD], P.[VIEW_CNT],
         IIF(B.[ANON_YN] = 'Y' AND V.[MINE_YN] = 'N' AND @P_MANAGER_YN = 'N', NULL, W.[USER_NM]) AS [WRITER_NM],
         V.[MINE_YN],
         IIF(P.[FILE_GROUP_ID] IS NULL, 'N', 'Y') AS [HAS_FILE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_POST_COMMENT] C WHERE C.[POST_ID] = P.[POST_ID] AND C.[DEL_YN] = 'N') AS [COMMENT_CNT],
         P.[START_DT], P.[END_DT], P.[REG_DT]
    FROM [FW].[TB_POST] P
    JOIN [FW].[TB_BOARD] B ON B.[BOARD_CD] = P.[BOARD_CD]
    JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, @P_MANAGER_YN) V ON V.[POST_ID] = P.[POST_ID]
    JOIN [FW].[TB_USER] W ON W.[USER_ID] = P.[WRITER_ID]
   WHERE P.[BOARD_CD] = @P_BOARD_CD
     AND (@P_KEYWORD IS NULL
          OR (@P_SEARCH_TYPE = 'WRITER' AND (B.[ANON_YN] = 'N' OR @P_MANAGER_YN = 'Y') AND W.[USER_NM] LIKE N'%' + @P_KEYWORD + N'%')
          OR (V.[SECRET_OK_YN] = 'Y'
              AND ((@P_SEARCH_TYPE IN ('TITLE', 'TITLE_CONTENT') AND P.[TITLE] LIKE N'%' + @P_KEYWORD + N'%')
                   OR (@P_SEARCH_TYPE IN ('CONTENT', 'TITLE_CONTENT') AND P.[CONTENT] LIKE N'%' + @P_KEYWORD + N'%'))))
   ORDER BY IIF(P.[ROOT_POST_ID] = P.[POST_ID], P.[PIN_YN], 'N') DESC, P.[ROOT_POST_ID] DESC, P.[POST_ID]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY;

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_POST] P
    JOIN [FW].[TB_BOARD] B ON B.[BOARD_CD] = P.[BOARD_CD]
    JOIN [FW].[UFN_POST_VISIBLE](@P_USER_ID, @P_MANAGER_YN) V ON V.[POST_ID] = P.[POST_ID]
    JOIN [FW].[TB_USER] W ON W.[USER_ID] = P.[WRITER_ID]
   WHERE P.[BOARD_CD] = @P_BOARD_CD
     AND (@P_KEYWORD IS NULL
          OR (@P_SEARCH_TYPE = 'WRITER' AND (B.[ANON_YN] = 'N' OR @P_MANAGER_YN = 'Y') AND W.[USER_NM] LIKE N'%' + @P_KEYWORD + N'%')
          OR (V.[SECRET_OK_YN] = 'Y'
              AND ((@P_SEARCH_TYPE IN ('TITLE', 'TITLE_CONTENT') AND P.[TITLE] LIKE N'%' + @P_KEYWORD + N'%')
                   OR (@P_SEARCH_TYPE IN ('CONTENT', 'TITLE_CONTENT') AND P.[CONTENT] LIKE N'%' + @P_KEYWORD + N'%'))));
END
