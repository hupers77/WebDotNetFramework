-- 다국어 문구 일괄 저장 (키 단위 추가·수정·삭제). 프로그램: SYS_LANG_MGT
-- @P_ROWS_JSON: [{rowStat(I/U/D), resKey, resType(LABEL/MSG/BTN/TOOLTIP), rowVer(16진수; U·D 필수, 조회한 KEY_VER), texts:[{langCd, resText}]}]
-- 규칙: 키는 대문자·숫자·밑줄을 점으로 이은 형식이고 만든 뒤 바꿀 수 없다. 기본 언어 문구는 꼭 있어야 한다(없는 언어는 기본 언어로 대신 보인다).
--       삭제는 그 키의 모든 언어를 지운다. 코드가 쓰는 키를 지우면 화면에 키가 그대로 보이므로 확인은 화면에서 한 번 더 받는다.
-- 수정·삭제는 조회 때의 KEY_VER와 같아야 한다. 변경 내용은 감사 로그에 남기고 문구 캐시(LANG)를 올린다.
-- 결과: AFFECTED_CNT (처리한 키 수)
CREATE PROCEDURE [FW].[USP_LANG_RESOURCE_SAVE]
  @P_ROWS_JSON  NVARCHAR(MAX),
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  IF ISJSON(@P_ROWS_JSON) <> 1
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  DECLARE @R TABLE ([ROW_STAT] CHAR(1), [RES_KEY] VARCHAR(100) PRIMARY KEY, [RES_TYPE] VARCHAR(10), [ROW_VER] BINARY(8), [TEXTS_JSON] NVARCHAR(MAX));
  DECLARE @T TABLE ([RES_KEY] VARCHAR(100), [LANG_CD] VARCHAR(5), [RES_TEXT] NVARCHAR(1000), PRIMARY KEY ([RES_KEY], [LANG_CD]));
  BEGIN TRY
    INSERT INTO @R
    SELECT [rowStat], [resKey], [resType], CONVERT(BINARY(8), [rowVer], 2), [texts]
      FROM OPENJSON(@P_ROWS_JSON) WITH ([rowStat] CHAR(1), [resKey] VARCHAR(100), [resType] VARCHAR(10), [rowVer] VARCHAR(16), [texts] NVARCHAR(MAX) AS JSON);

    INSERT INTO @T
    SELECT R.[RES_KEY], J.[langCd], LTRIM(RTRIM(J.[resText]))
      FROM @R R
     CROSS APPLY OPENJSON(R.[TEXTS_JSON]) WITH ([langCd] VARCHAR(5), [resText] NVARCHAR(1000)) J
     WHERE R.[ROW_STAT] IN ('I', 'U') AND NULLIF(LTRIM(RTRIM(J.[resText])), N'') IS NOT NULL;
  END TRY
  BEGIN CATCH
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  END CATCH

  IF NOT EXISTS (SELECT 1 FROM @R)
    THROW 50005, 'MSG.NO_CHANGES', 1;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');

  IF EXISTS (SELECT 1 FROM @R WHERE [ROW_STAT] NOT IN ('I', 'U', 'D') OR [RES_KEY] IS NULL OR [RES_KEY] NOT LIKE '%.%'
                                  OR [RES_KEY] COLLATE Latin1_General_BIN LIKE '%[^A-Z0-9_.]%' OR [RES_KEY] LIKE '.%' OR [RES_KEY] LIKE '%.' OR [RES_KEY] LIKE '%..%'
                                  OR ([ROW_STAT] IN ('I', 'U') AND ([RES_TYPE] IS NULL OR [RES_TYPE] NOT IN ('LABEL', 'MSG', 'BTN', 'TOOLTIP')))
                                  OR ([ROW_STAT] IN ('U', 'D') AND [ROW_VER] IS NULL))
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R R WHERE R.[ROW_STAT] IN ('I', 'U') AND NOT EXISTS (SELECT 1 FROM @T T WHERE T.[RES_KEY] = R.[RES_KEY] AND T.[LANG_CD] = @DEFAULT_LANG))
     OR EXISTS (SELECT 1 FROM @T T LEFT JOIN [FW].[TB_LANG] L ON L.[LANG_CD] = T.[LANG_CD] AND L.[USE_YN] = 'Y' WHERE L.[LANG_CD] IS NULL)
    THROW 50005, 'MSG.INVALID_INPUT', 1;
  IF EXISTS (SELECT 1 FROM @R R WHERE R.[ROW_STAT] = 'I' AND EXISTS (SELECT 1 FROM [FW].[TB_LANG_RESOURCE] X WHERE X.[RES_KEY] = R.[RES_KEY]))
    THROW 50001, 'MSG.DUP_LANG_KEY', 1;
  IF EXISTS (SELECT 1 FROM @R R WHERE R.[ROW_STAT] IN ('U', 'D') AND NOT EXISTS (SELECT 1 FROM [FW].[TB_LANG_RESOURCE] X WHERE X.[RES_KEY] = R.[RES_KEY]))
    THROW 50004, 'MSG.NOT_FOUND', 1;

  DECLARE @CNT INT, @BEFORE NVARCHAR(MAX), @AFTER NVARCHAR(MAX);

  BEGIN TRY
    BEGIN TRAN;

    IF EXISTS (SELECT 1 FROM @R R
                WHERE R.[ROW_STAT] IN ('U', 'D')
                  AND (SELECT MAX(X.[ROW_VER]) FROM [FW].[TB_LANG_RESOURCE] X WITH (UPDLOCK, HOLDLOCK) WHERE X.[RES_KEY] = R.[RES_KEY]) <> R.[ROW_VER])
      THROW 50002, 'MSG.CONCURRENCY', 1;

    SET @BEFORE = (SELECT X.[RES_KEY], X.[LANG_CD], X.[RES_TEXT], X.[RES_TYPE] FROM [FW].[TB_LANG_RESOURCE] X JOIN @R R ON R.[RES_KEY] = X.[RES_KEY] FOR JSON PATH);

    DELETE X FROM [FW].[TB_LANG_RESOURCE] X
      JOIN @R R ON R.[RES_KEY] = X.[RES_KEY]
     WHERE R.[ROW_STAT] = 'D'
        OR (R.[ROW_STAT] = 'U' AND NOT EXISTS (SELECT 1 FROM @T T WHERE T.[RES_KEY] = X.[RES_KEY] AND T.[LANG_CD] = X.[LANG_CD]));

    UPDATE X
       SET X.[RES_TEXT] = T.[RES_TEXT], X.[RES_TYPE] = R.[RES_TYPE], X.[UPD_ID] = @P_USER_ID, X.[UPD_DT] = SYSUTCDATETIME()
      FROM [FW].[TB_LANG_RESOURCE] X
      JOIN @R R ON R.[RES_KEY] = X.[RES_KEY] AND R.[ROW_STAT] = 'U'
      JOIN @T T ON T.[RES_KEY] = X.[RES_KEY] AND T.[LANG_CD] = X.[LANG_CD]
     WHERE X.[RES_TEXT] <> T.[RES_TEXT] OR X.[RES_TYPE] <> R.[RES_TYPE];

    INSERT INTO [FW].[TB_LANG_RESOURCE] ([RES_KEY], [LANG_CD], [RES_TEXT], [RES_TYPE], [REG_ID], [UPD_ID])
    SELECT T.[RES_KEY], T.[LANG_CD], T.[RES_TEXT], R.[RES_TYPE], @P_USER_ID, @P_USER_ID
      FROM @T T JOIN @R R ON R.[RES_KEY] = T.[RES_KEY]
     WHERE NOT EXISTS (SELECT 1 FROM [FW].[TB_LANG_RESOURCE] X WHERE X.[RES_KEY] = T.[RES_KEY] AND X.[LANG_CD] = T.[LANG_CD]);

    SELECT @CNT = COUNT(*) FROM @R;

    SET @AFTER = (SELECT R.[ROW_STAT], R.[RES_KEY], R.[RES_TYPE], JSON_QUERY((SELECT T.[LANG_CD], T.[RES_TEXT] FROM @T T WHERE T.[RES_KEY] = R.[RES_KEY] FOR JSON PATH)) AS [TEXTS]
                    FROM @R R FOR JSON PATH);
    EXEC [LOG].[USP_AUDIT_WRITE]
      @P_TABLE_NM = 'FW.TB_LANG_RESOURCE', @P_ACTION_CD = 'U', @P_ROW_KEY = N'LANG_RESOURCE',
      @P_BEFORE_JSON = @BEFORE, @P_AFTER_JSON = @AFTER,
      @P_USER_ID = @P_USER_ID, @P_LANG_CD = @P_LANG_CD, @P_CLIENT_IP = @P_CLIENT_IP;

    UPDATE [FW].[TB_CACHE_VERSION]
       SET [VERSION_NO] += 1, [UPD_DT] = SYSUTCDATETIME()
     WHERE [CACHE_KEY] = 'LANG';

    COMMIT;

    SELECT @CNT AS [AFFECTED_CNT];
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK;
    THROW;
  END CATCH
END
