-- 회사 한 곳의 부서 전부 (트리 화면용, 쪽 나눔 없음). 프로그램: SYS_DEPT_MGT
-- 화면이 PARENT_DEPT_ID로 트리를 만든다. 회사는 데이터 범위(UFN_DATA_SCOPE) 안이어야 하고, 범위 밖이면 0행.
-- @P_INCLUDE_UNUSED_YN = 'N'이면 사용 중인 부서만 (사용 안 함 부서 아래의 부서도 함께 빠진다).
-- AD_YN = 'Y'는 AD 동기화로 만든 부서(이름·상위·사용 여부를 동기화가 정한다).
-- 결과: DEPT_ID, COMPANY_CD, PARENT_DEPT_ID, DEPT_NM, AD_YN, SORT_NO, USE_YN, USER_CNT(이 부서 소속 계정), CHILD_CNT, ROLE_IDS, UPD_ID, UPD_DT, ROW_VER
CREATE PROCEDURE [FW].[USP_DEPT_GET_LIST]
  @P_COMPANY_CD          VARCHAR(10),
  @P_INCLUDE_UNUSED_YN   CHAR(1)     = 'N',
  @P_USER_ID             VARCHAR(30),
  @P_LANG_CD             VARCHAR(5),
  @P_CLIENT_IP           VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  IF NULLIF(LTRIM(RTRIM(@P_COMPANY_CD)), '') IS NULL OR @P_INCLUDE_UNUSED_YN NOT IN ('Y', 'N')
    THROW 50005, 'MSG.INVALID_INPUT', 1;

  WITH [VISIBLE] AS (
    SELECT D.[DEPT_ID], 0 AS [DEPTH]
      FROM [FW].[TB_DEPT] D
     WHERE D.[COMPANY_CD] = @P_COMPANY_CD AND D.[PARENT_DEPT_ID] IS NULL
       AND (@P_INCLUDE_UNUSED_YN = 'Y' OR D.[USE_YN] = 'Y')
    UNION ALL
    SELECT C.[DEPT_ID], V.[DEPTH] + 1
      FROM [VISIBLE] V
      JOIN [FW].[TB_DEPT] C ON C.[PARENT_DEPT_ID] = V.[DEPT_ID]
     WHERE (@P_INCLUDE_UNUSED_YN = 'Y' OR C.[USE_YN] = 'Y') AND V.[DEPTH] < 20
  )
  SELECT D.[DEPT_ID], D.[COMPANY_CD], D.[PARENT_DEPT_ID], D.[DEPT_NM], IIF(D.[AD_OU_PATH] IS NULL, 'N', 'Y') AS [AD_YN],
         D.[SORT_NO], D.[USE_YN],
         (SELECT COUNT(*) FROM [FW].[TB_USER] U WHERE U.[DEPT_ID] = D.[DEPT_ID]) AS [USER_CNT],
         (SELECT COUNT(*) FROM [FW].[TB_DEPT] C WHERE C.[PARENT_DEPT_ID] = D.[DEPT_ID]) AS [CHILD_CNT],
         (SELECT STRING_AGG(DR.[ROLE_ID], ',') WITHIN GROUP (ORDER BY DR.[ROLE_ID]) FROM [FW].[TB_DEPT_ROLE] DR WHERE DR.[DEPT_ID] = D.[DEPT_ID]) AS [ROLE_IDS],
         D.[UPD_ID], D.[UPD_DT], D.[ROW_VER]
    FROM [VISIBLE] V
    JOIN [FW].[TB_DEPT] D ON D.[DEPT_ID] = V.[DEPT_ID]
   WHERE EXISTS (SELECT 1 FROM [FW].[UFN_DATA_SCOPE](@P_USER_ID, 'SYS_DEPT_MGT') S WHERE S.[COMPANY_CD] = D.[COMPANY_CD])
   ORDER BY V.[DEPTH], D.[SORT_NO], D.[DEPT_NM], D.[DEPT_ID];
END
