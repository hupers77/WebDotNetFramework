-- 요청마다 세션 확인 (인증 미들웨어). 살아 있는 세션이면 비활동 만료 시각을 연장하고 사용자 정보를 돌려준다.
-- 쓰기를 줄이려고 마지막 접근 후 1분이 지났을 때만 갱신한다. @P_TOUCH_YN = 'N'(헤더 알림 배지처럼 사용자가 하지 않은 백그라운드 요청)이면
-- 확인만 하고 연장하지 않는다(화면을 켜 두기만 해도 자동 로그아웃이 되지 않는 일이 없도록). 세션이 없거나 끝났으면 END_REASON_CD만 있는 행을 돌려준다
-- (공통코드 LOGIN_RESULT: KICKED 다른 곳에서 로그인, LOGOUT, TIMEOUT 비활동 만료, DISABLED 계정 잠김·사용 기간 끝남.
-- 행이 없으면 알 수 없는 세션).
-- 결과: USER_ID, COMPANY_CD, DEPT_ID, USER_TYPE_CD, USER_NM, LANG_CD, TIMEZONE_ID, PWD_CHG_REQ_YN, PWD_CHG_DT, EXPIRE_DT, END_REASON_CD
CREATE PROCEDURE [FW].[USP_AUTH_SESSION_CHECK_EXEC]
  @P_SESSION_HASH CHAR(64),
  @P_TOUCH_YN     CHAR(1)     = 'Y',
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @IDLE_MINUTES INT = ISNULL(TRY_CAST((SELECT [CONFIG_VAL] FROM [FW].[TB_CONFIG] WHERE [CONFIG_KEY] = 'SESSION.IDLE_MINUTES') AS INT), 30);
  DECLARE @NOW DATETIME2(0) = SYSUTCDATETIME();
  DECLARE @TODAY DATE = CAST(GETDATE() AS DATE);
  DECLARE @SESSION_USER_ID VARCHAR(30), @END_DT DATETIME2(0), @END_REASON_CD VARCHAR(20), @EXPIRE_DT DATETIME2(0), @LAST_ACCESS_DT DATETIME2(0);

  SELECT @SESSION_USER_ID = [USER_ID], @END_DT = [END_DT], @END_REASON_CD = [END_REASON_CD],
         @EXPIRE_DT = [EXPIRE_DT], @LAST_ACCESS_DT = [LAST_ACCESS_DT]
    FROM [FW].[TB_USER_SESSION]
   WHERE [SESSION_ID] = @P_SESSION_HASH;

  IF @SESSION_USER_ID IS NULL
    RETURN;

  IF @END_DT IS NULL AND @EXPIRE_DT <= @NOW
    SET @END_REASON_CD = 'TIMEOUT';

  -- 로그인 이후 잠기거나 사용 기간이 끝난 계정은 세션을 끊는다
  IF @END_REASON_CD IS NULL
     AND NOT EXISTS (SELECT 1
                       FROM [FW].[TB_USER] U
                       JOIN [FW].[TB_COMPANY] C ON C.[COMPANY_CD] = U.[COMPANY_CD]
                      WHERE U.[USER_ID] = @SESSION_USER_ID
                        AND U.[USER_STAT_CD] = 'ACTIVE' AND U.[LOCK_YN] = 'N' AND C.[USE_YN] = 'Y'
                        AND ISNULL(U.[ACCOUNT_END_DT], '9999-12-31') >= @TODAY
                        AND ISNULL(C.[CONTRACT_END_DT], '9999-12-31') >= @TODAY)
    SET @END_REASON_CD = 'DISABLED';

  IF @END_REASON_CD IS NOT NULL
  BEGIN
    IF @END_DT IS NULL
      UPDATE [FW].[TB_USER_SESSION]
         SET [END_DT] = @NOW, [END_REASON_CD] = @END_REASON_CD, [UPD_ID] = 'SYSTEM', [UPD_DT] = @NOW
       WHERE [SESSION_ID] = @P_SESSION_HASH AND [END_DT] IS NULL;

    SELECT CAST(NULL AS VARCHAR(30)) AS [USER_ID], @END_REASON_CD AS [END_REASON_CD];
    RETURN;
  END

  IF @P_TOUCH_YN = 'Y' AND @LAST_ACCESS_DT < DATEADD(MINUTE, -1, @NOW)
  BEGIN
    SET @EXPIRE_DT = DATEADD(MINUTE, @IDLE_MINUTES, @NOW);
    UPDATE [FW].[TB_USER_SESSION]
       SET [LAST_ACCESS_DT] = @NOW, [EXPIRE_DT] = @EXPIRE_DT
     WHERE [SESSION_ID] = @P_SESSION_HASH AND [END_DT] IS NULL;
  END

  SELECT U.[USER_ID], U.[COMPANY_CD], U.[DEPT_ID], U.[USER_TYPE_CD], U.[USER_NM], U.[LANG_CD], U.[TIMEZONE_ID],
         U.[PWD_CHG_REQ_YN], U.[PWD_CHG_DT], @EXPIRE_DT AS [EXPIRE_DT], CAST(NULL AS VARCHAR(20)) AS [END_REASON_CD]
    FROM [FW].[TB_USER] U
   WHERE U.[USER_ID] = @SESSION_USER_ID;
END
