-- 공통코드 목록 (목록 SP 표준 템플릿). 프로그램: SYS_CODE_MGT
-- 결과셋 1: 목록, 결과셋 2: 전체 건수. 명칭은 사용자 언어 → 기본 언어 순으로 대체한다.
CREATE PROCEDURE [FW].[USP_CODE_GET_LIST]
  @P_GROUP_CD   VARCHAR(30),
  @P_KEYWORD    NVARCHAR(100) = NULL,
  @P_USE_YN     CHAR(1)       = NULL,
  @P_PAGE_NO    INT           = 1,
  @P_PAGE_SIZE  INT           = 50,
  @P_USER_ID    VARCHAR(30),
  @P_LANG_CD    VARCHAR(5),
  @P_CLIENT_IP  VARCHAR(45)   = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT C.[CODE],
         COALESCE(L.[CODE_NM], LD.[CODE_NM], C.[CODE]) AS [CODE_NM],
         C.[PARENT_CODE], C.[SORT_NO],
         C.[ATTR1], C.[ATTR2], C.[ATTR3], C.[ATTR4], C.[ATTR5],
         C.[START_DT], C.[END_DT], C.[USE_YN], C.[ROW_VER]
    FROM [FW].[TB_CODE] C
    LEFT JOIN [FW].[TB_CODE_LANG] L  ON L.[GROUP_CD] = C.[GROUP_CD] AND L.[CODE] = C.[CODE] AND L.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] LD ON LD.[GROUP_CD] = C.[GROUP_CD] AND LD.[CODE] = C.[CODE] AND LD.[LANG_CD] = @DEFAULT_LANG
   WHERE C.[GROUP_CD] = @P_GROUP_CD
     AND (@P_USE_YN IS NULL OR C.[USE_YN] = @P_USE_YN)
     AND (@P_KEYWORD IS NULL OR C.[CODE] LIKE @P_KEYWORD + '%' OR L.[CODE_NM] LIKE '%' + @P_KEYWORD + '%')
   ORDER BY C.[SORT_NO], C.[CODE]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_CODE] C
    LEFT JOIN [FW].[TB_CODE_LANG] L ON L.[GROUP_CD] = C.[GROUP_CD] AND L.[CODE] = C.[CODE] AND L.[LANG_CD] = @P_LANG_CD
   WHERE C.[GROUP_CD] = @P_GROUP_CD
     AND (@P_USE_YN IS NULL OR C.[USE_YN] = @P_USE_YN)
     AND (@P_KEYWORD IS NULL OR C.[CODE] LIKE @P_KEYWORD + '%' OR L.[CODE_NM] LIKE '%' + @P_KEYWORD + '%')
  OPTION (RECOMPILE);
END
