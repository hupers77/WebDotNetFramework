-- 배치 작업 목록 (목록 SP 표준 템플릿). 프로그램: SYS_JOB_MGT
-- 결과셋 1: 목록(작업 ID 순), 결과셋 2: 전체 건수
CREATE PROCEDURE [FW].[USP_JOB_GET_LIST]
  @P_KEYWORD      NVARCHAR(100) = NULL,
  @P_PAGE_NO      INT           = 1,
  @P_PAGE_SIZE    INT           = 50,
  @P_USER_ID      VARCHAR(30),
  @P_LANG_CD      VARCHAR(5),
  @P_CLIENT_IP    VARCHAR(45) = NULL
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @DEFAULT_LANG VARCHAR(5) = (SELECT TOP (1) [LANG_CD] FROM [FW].[TB_LANG] WHERE [DEFAULT_YN] = 'Y');
  SET @P_PAGE_NO = CASE WHEN @P_PAGE_NO < 1 THEN 1 ELSE @P_PAGE_NO END;
  SET @P_PAGE_SIZE = CASE WHEN @P_PAGE_SIZE < 1 THEN 1 WHEN @P_PAGE_SIZE > 500 THEN 500 ELSE @P_PAGE_SIZE END;

  SELECT J.[JOB_ID], J.[JOB_NM], J.[JOB_TYPE_CD], J.[JOB_TARGET], J.[CRON_EXPR], J.[TIMEOUT_MIN], J.[DESCRIPTION], J.[USE_YN],
         J.[NEXT_RUN_DT], J.[RUN_REQ_YN], J.[RUN_REQ_ID], J.[RUNNING_YN], J.[LAST_RUN_DT], J.[LAST_RESULT_CD],
         COALESCE(RL.[CODE_NM], RD.[CODE_NM], J.[LAST_RESULT_CD]) AS [LAST_RESULT_NM], J.[EDIT_VER]
    FROM [FW].[TB_JOB] J
    LEFT JOIN [FW].[TB_CODE_LANG] RL ON RL.[GROUP_CD] = 'JOB_STAT' AND RL.[CODE] = J.[LAST_RESULT_CD] AND RL.[LANG_CD] = @P_LANG_CD
    LEFT JOIN [FW].[TB_CODE_LANG] RD ON RD.[GROUP_CD] = 'JOB_STAT' AND RD.[CODE] = J.[LAST_RESULT_CD] AND RD.[LANG_CD] = @DEFAULT_LANG
   WHERE (@P_KEYWORD IS NULL OR J.[JOB_ID] LIKE '%' + @P_KEYWORD + '%' OR J.[JOB_NM] LIKE '%' + @P_KEYWORD + '%')
   ORDER BY J.[JOB_ID]
  OFFSET (@P_PAGE_NO - 1) * @P_PAGE_SIZE ROWS FETCH NEXT @P_PAGE_SIZE ROWS ONLY
  OPTION (RECOMPILE);

  SELECT COUNT(*) AS [TOTAL_CNT]
    FROM [FW].[TB_JOB] J
   WHERE (@P_KEYWORD IS NULL OR J.[JOB_ID] LIKE '%' + @P_KEYWORD + '%' OR J.[JOB_NM] LIKE '%' + @P_KEYWORD + '%')
  OPTION (RECOMPILE);
END
