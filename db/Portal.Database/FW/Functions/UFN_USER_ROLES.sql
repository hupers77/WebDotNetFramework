-- 사용자의 유효 역할(설계서 6장 권한 평가 규칙 1):
-- 직접 부여 ∪ 부서 역할(상위 부서의 INHERIT_YN='Y' 역할 상속, 사용 중이고 유효기간 안의 부서가 준 것만) ∪ AD 그룹 역할 ∪ 위임받은 역할. 유효기간 안의 사용 중인 역할만.
-- 날짜 비교는 업무 기준일(서버 로컬 날짜)로 한다.
CREATE FUNCTION [FW].[UFN_USER_ROLES] (@P_USER_ID VARCHAR(30))
RETURNS TABLE
AS
RETURN
  WITH [DEPT_PATH] AS (
    SELECT D.[DEPT_ID], D.[PARENT_DEPT_ID], 0 AS [DEPTH]
      FROM [FW].[TB_USER] U
      JOIN [FW].[TB_DEPT] D ON D.[DEPT_ID] = U.[DEPT_ID]
     WHERE U.[USER_ID] = @P_USER_ID
    UNION ALL
    SELECT P.[DEPT_ID], P.[PARENT_DEPT_ID], C.[DEPTH] + 1
      FROM [DEPT_PATH] C
      JOIN [FW].[TB_DEPT] P ON P.[DEPT_ID] = C.[PARENT_DEPT_ID]
     WHERE C.[DEPTH] < 20
  ),
  [ROLES] AS (
    SELECT UR.[ROLE_ID]
      FROM [FW].[TB_USER_ROLE] UR
     WHERE UR.[USER_ID] = @P_USER_ID
       AND CAST(GETDATE() AS DATE) BETWEEN UR.[START_DT] AND UR.[END_DT]
    UNION
    SELECT DR.[ROLE_ID]
      FROM [DEPT_PATH] DP
      JOIN [FW].[TB_DEPT] D ON D.[DEPT_ID] = DP.[DEPT_ID]
      JOIN [FW].[TB_DEPT_ROLE] DR ON DR.[DEPT_ID] = DP.[DEPT_ID]
     WHERE (DP.[DEPTH] = 0 OR DR.[INHERIT_YN] = 'Y')
       AND D.[USE_YN] = 'Y' AND CAST(GETDATE() AS DATE) BETWEEN D.[START_DT] AND D.[END_DT]
       AND CAST(GETDATE() AS DATE) BETWEEN DR.[START_DT] AND DR.[END_DT]
    UNION
    SELECT GR.[ROLE_ID]
      FROM [FW].[TB_USER_AD_GROUP] UG
      JOIN [FW].[TB_AD_GROUP_ROLE] GR ON GR.[AD_GROUP_SID] = UG.[AD_GROUP_SID]
     WHERE UG.[USER_ID] = @P_USER_ID
       AND CAST(GETDATE() AS DATE) BETWEEN GR.[START_DT] AND GR.[END_DT]
    UNION
    SELECT RD.[ROLE_ID]
      FROM [FW].[TB_ROLE_DELEGATE] RD
     WHERE RD.[TO_USER_ID] = @P_USER_ID
       AND CAST(GETDATE() AS DATE) BETWEEN RD.[START_DT] AND RD.[END_DT]
  )
  SELECT R.[ROLE_ID], RL.[DATA_SCOPE_CD]
    FROM [ROLES] R
    JOIN [FW].[TB_ROLE] RL ON RL.[ROLE_ID] = R.[ROLE_ID]
    JOIN [FW].[TB_USER] U ON U.[USER_ID] = @P_USER_ID
   WHERE RL.[USE_YN] = 'Y'
     AND U.[USER_STAT_CD] = 'ACTIVE';
