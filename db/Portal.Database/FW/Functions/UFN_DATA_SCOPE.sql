-- 데이터 범위(설계서 6장 규칙 5, 개발 표준 가이드 6장). 회사 소유 데이터를 다루는 모든 목록·단건 SP가 조인한다.
--   반환 행: COMPANY_CD는 항상 값이 있고, DEPT_ID/USER_ID가 NULL이면 그 조건으로 거르지 않는다. 권한이 없으면 0행.
--   유효 역할 중 프로그램에 READ가 있는 역할의 가장 넓은 범위를 쓴다. SYS_ADMIN은 전체.
--   협력사 사용자는 역할과 관계없이 최대 '소속 회사'까지만 본다.
CREATE FUNCTION [FW].[UFN_DATA_SCOPE] (@P_USER_ID VARCHAR(30), @P_PROGRAM_ID VARCHAR(30))
RETURNS TABLE
AS
RETURN
  WITH [U] AS (
    SELECT [USER_ID], [COMPANY_CD], [DEPT_ID], [USER_TYPE_CD]
      FROM [FW].[TB_USER]
     WHERE [USER_ID] = @P_USER_ID
       AND [USER_STAT_CD] = 'ACTIVE'
  ),
  [GRANTED] AS (
    SELECT CASE R.[DATA_SCOPE_CD]
             WHEN 'ALL' THEN 5 WHEN 'COMPANY' THEN 4 WHEN 'DEPT_SUB' THEN 3 WHEN 'DEPT' THEN 2 ELSE 1
           END AS [SCOPE_RANK]
      FROM [FW].[UFN_USER_ROLES](@P_USER_ID) R
     WHERE R.[ROLE_ID] = 'SYS_ADMIN'
        OR EXISTS (SELECT 1 FROM [FW].[TB_ROLE_PROGRAM_FUNC] F
                    WHERE F.[ROLE_ID] = R.[ROLE_ID] AND F.[PROGRAM_ID] = @P_PROGRAM_ID AND F.[FUNC_CD] = 'READ')
  ),
  [S] AS (
    SELECT U.[USER_ID], U.[COMPANY_CD], U.[DEPT_ID],
           CASE WHEN U.[USER_TYPE_CD] = 'PARTNER' AND MAX(G.[SCOPE_RANK]) > 4 THEN 4 ELSE MAX(G.[SCOPE_RANK]) END AS [SCOPE_RANK]
      FROM [U] U
      CROSS JOIN [GRANTED] G
     GROUP BY U.[USER_ID], U.[COMPANY_CD], U.[DEPT_ID], U.[USER_TYPE_CD]
  ),
  [SUB_DEPT] AS (
    SELECT D.[DEPT_ID], 0 AS [DEPTH]
      FROM [S] S
      JOIN [FW].[TB_DEPT] D ON D.[DEPT_ID] = S.[DEPT_ID]
     WHERE S.[SCOPE_RANK] = 3
    UNION ALL
    SELECT C.[DEPT_ID], P.[DEPTH] + 1
      FROM [SUB_DEPT] P
      JOIN [FW].[TB_DEPT] C ON C.[PARENT_DEPT_ID] = P.[DEPT_ID]
     WHERE P.[DEPTH] < 20
  )
  SELECT C.[COMPANY_CD], CAST(NULL AS VARCHAR(20)) AS [DEPT_ID], CAST(NULL AS VARCHAR(30)) AS [USER_ID]
    FROM [S] S
    CROSS JOIN [FW].[TB_COMPANY] C
   WHERE S.[SCOPE_RANK] = 5
  UNION ALL
  SELECT S.[COMPANY_CD], NULL, NULL FROM [S] S WHERE S.[SCOPE_RANK] = 4
  UNION ALL
  SELECT S.[COMPANY_CD], D.[DEPT_ID], NULL FROM [S] S CROSS JOIN [SUB_DEPT] D WHERE S.[SCOPE_RANK] = 3
  UNION ALL
  SELECT S.[COMPANY_CD], S.[DEPT_ID], NULL FROM [S] S WHERE S.[SCOPE_RANK] = 2 AND S.[DEPT_ID] IS NOT NULL
  UNION ALL
  SELECT S.[COMPANY_CD], NULL, S.[USER_ID] FROM [S] S WHERE S.[SCOPE_RANK] = 1;
