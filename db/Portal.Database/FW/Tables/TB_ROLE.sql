CREATE TABLE [FW].[TB_ROLE] (

  [ROLE_ID]        VARCHAR(30)    NOT NULL,
  [ROLE_NM]        NVARCHAR(100)  NOT NULL,
  [DATA_SCOPE_CD]  VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_ROLE_DATA_SCOPE_CD] DEFAULT ('SELF'),    -- ALL/COMPANY/DEPT_SUB/DEPT/SELF
  [DESCRIPTION]    NVARCHAR(500)  NULL,
  [SYSTEM_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_ROLE_SYSTEM_YN] DEFAULT ('N'),       -- Y면 삭제 불가
  [SORT_NO]        INT            NOT NULL CONSTRAINT [DF_TB_ROLE_SORT_NO] DEFAULT (0),
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_ROLE_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_ROLE_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_ROLE_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_ROLE_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_ROLE_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_ROLE] PRIMARY KEY CLUSTERED ([ROLE_ID])
);
