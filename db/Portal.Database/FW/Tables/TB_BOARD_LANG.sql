CREATE TABLE [FW].[TB_BOARD_LANG] (

  [BOARD_CD]       VARCHAR(30)    NOT NULL,
  [LANG_CD]        VARCHAR(5)     NOT NULL,
  [BOARD_NM]       NVARCHAR(100)  NOT NULL,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_BOARD_LANG_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_BOARD_LANG_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_BOARD_LANG_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_BOARD_LANG_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT [PK_TB_BOARD_LANG] PRIMARY KEY CLUSTERED ([BOARD_CD], [LANG_CD]),
  CONSTRAINT [FK_TB_BOARD_LANG_TB_BOARD] FOREIGN KEY ([BOARD_CD]) REFERENCES [FW].[TB_BOARD] ([BOARD_CD]),
  CONSTRAINT [FK_TB_BOARD_LANG_TB_LANG] FOREIGN KEY ([LANG_CD]) REFERENCES [FW].[TB_LANG] ([LANG_CD])
);
