-- 부서 부여 역할 (INHERIT_YN = Y면 하위 부서에도 적용)
CREATE TABLE [FW].[TB_DEPT_ROLE] (
  [DEPT_ID]        VARCHAR(20)    NOT NULL,
  [ROLE_ID]        VARCHAR(30)    NOT NULL,
  [INHERIT_YN]     CHAR(1)        NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_INHERIT_YN] DEFAULT ('Y'),
  [START_DT]       DATE           NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_START_DT] DEFAULT (CONVERT(DATE, GETDATE())),
  [END_DT]         DATE           NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_END_DT] DEFAULT ('9999-12-31'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_DEPT_ROLE_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_DEPT_ROLE] PRIMARY KEY CLUSTERED ([DEPT_ID], [ROLE_ID])
);
GO
CREATE INDEX [IX_TB_DEPT_ROLE_ROLE] ON [FW].[TB_DEPT_ROLE] ([ROLE_ID]);
GO
ALTER TABLE [FW].[TB_DEPT_ROLE] ADD CONSTRAINT [FK_TB_DEPT_ROLE_TB_DEPT] FOREIGN KEY ([DEPT_ID]) REFERENCES [FW].[TB_DEPT] ([DEPT_ID]);
GO
ALTER TABLE [FW].[TB_DEPT_ROLE] ADD CONSTRAINT [FK_TB_DEPT_ROLE_TB_ROLE] FOREIGN KEY ([ROLE_ID]) REFERENCES [FW].[TB_ROLE] ([ROLE_ID]);
