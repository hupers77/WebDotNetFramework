-- 템플릿의 언어별 제목·본문. 치환 변수는 {{USER_NM}}처럼 쓰고, 보낼 때 값을 HTML 인코딩해 넣는다
-- 받는 사람 언어의 행이 없으면 기본 언어 행을 쓴다
CREATE TABLE [FW].[TB_MSG_TEMPLATE_LANG] (

  [TEMPLATE_ID]    VARCHAR(30)    NOT NULL,
  [LANG_CD]        VARCHAR(5)     NOT NULL,
  [SUBJECT]        NVARCHAR(200)  NOT NULL,             -- 메일 제목 (글자 그대로, 줄바꿈 불가)
  [BODY]           NVARCHAR(4000) NOT NULL,             -- 메일 본문 (HTML)
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_LANG_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_LANG_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_LANG_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_LANG_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_MSG_TEMPLATE_LANG] PRIMARY KEY CLUSTERED ([TEMPLATE_ID], [LANG_CD]),
  CONSTRAINT [FK_TB_MSG_TEMPLATE_LANG_TEMPLATE] FOREIGN KEY ([TEMPLATE_ID]) REFERENCES [FW].[TB_MSG_TEMPLATE] ([TEMPLATE_ID]),
  CONSTRAINT [FK_TB_MSG_TEMPLATE_LANG_LANG] FOREIGN KEY ([LANG_CD]) REFERENCES [FW].[TB_LANG] ([LANG_CD])
);
