-- 위젯 제목 (언어별)
CREATE TABLE [FW].[TB_WIDGET_LANG] (

  [WIDGET_CD]      VARCHAR(30)    NOT NULL,
  [LANG_CD]        VARCHAR(5)     NOT NULL,
  [WIDGET_NM]      NVARCHAR(100)  NOT NULL,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_WIDGET_LANG_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_WIDGET_LANG_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_WIDGET_LANG_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_WIDGET_LANG_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT [PK_TB_WIDGET_LANG] PRIMARY KEY CLUSTERED ([WIDGET_CD], [LANG_CD]),
  CONSTRAINT [FK_TB_WIDGET_LANG_TB_WIDGET] FOREIGN KEY ([WIDGET_CD]) REFERENCES [FW].[TB_WIDGET] ([WIDGET_CD]),
