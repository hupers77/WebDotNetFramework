CREATE TABLE [FW].[TB_USER_ROLE] (
  [USER_ID]        VARCHAR(30)    NOT NULL,
  [ROLE_ID]        VARCHAR(30)    NOT NULL,
  [START_DT]       DATE           NOT NULL CONSTRAINT [DF_TB_USER_ROLE_START_DT] DEFAULT (CONVERT(DATE, GETDATE())),
  [END_DT]         DATE           NOT NULL CONSTRAINT [DF_TB_USER_ROLE_END_DT] DEFAULT ('9999-12-31'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_ROLE_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_ROLE_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_ROLE_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_ROLE_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_USER_ROLE] PRIMARY KEY CLUSTERED ([USER_ID], [ROLE_ID])
);
GO
