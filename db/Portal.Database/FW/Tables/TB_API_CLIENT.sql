-- 외부 API 클라이언트 (수신). 비밀값은 해시(PBKDF2)로만 저장하고 발급 때 한 번만 보여 준다.
-- API_CODES: 호출을 허용한 API 코드(쉼표 구분, 예: PING,ORDER_GET). 코드는 API마다 코드에서 정한다.
CREATE TABLE [FW].[TB_API_CLIENT] (

  [CLIENT_ID]         VARCHAR(50)    NOT NULL,
  [CLIENT_NM]         NVARCHAR(100)  NOT NULL,
  [SECRET_HASH]       BINARY(64)     NULL,                 -- NULL이면 비밀값 미발급(토큰을 받을 수 없다)
  [SECRET_SALT]       BINARY(16)     NULL,
  [SECRET_ISSUED_DT]  DATETIME2(0)   NULL,
  [API_CODES]         VARCHAR(1000)  NOT NULL CONSTRAINT [DF_TB_API_CLIENT_API_CODES] DEFAULT (''),
  [ALLOW_IP_LIST]     VARCHAR(1000)  NULL,                 -- CIDR/IP 쉼표 구분. NULL이면 제한 없음
  [RATE_PER_MIN]      INT            NULL,                 -- NULL이면 설정 API.DEFAULT_RATE_PER_MIN
  [EXPIRE_DT]         DATE           NULL,                 -- 이 날짜(포함)까지 사용. NULL이면 기한 없음
  [USE_YN]            CHAR(1)        NOT NULL CONSTRAINT [DF_TB_API_CLIENT_USE_YN] DEFAULT ('Y'),
  [REG_ID]            VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_API_CLIENT_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]            DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_API_CLIENT_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]            VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_API_CLIENT_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]            DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_API_CLIENT_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]           ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_API_CLIENT] PRIMARY KEY CLUSTERED ([CLIENT_ID]),
  CONSTRAINT [CK_TB_API_CLIENT_ID] CHECK ([CLIENT_ID] NOT LIKE '%[^A-Za-z0-9._-]%'),
  CONSTRAINT [CK_TB_API_CLIENT_RATE] CHECK ([RATE_PER_MIN] IS NULL OR [RATE_PER_MIN] BETWEEN 1 AND 100000),
  CONSTRAINT [CK_TB_API_CLIENT_SECRET] CHECK (([SECRET_HASH] IS NULL AND [SECRET_SALT] IS NULL) OR ([SECRET_HASH] IS NOT NULL AND [SECRET_SALT] IS NOT NULL)),
  CONSTRAINT [CK_TB_API_CLIENT_USE_YN] CHECK ([USE_YN] IN ('Y', 'N'))
);
