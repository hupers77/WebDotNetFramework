-- 글 단위 공개 대상 협력사. 행이 없으면 게시판을 볼 수 있는 모든 회사에 공개, 있으면 본사와 여기 적힌 회사만 본다.
CREATE TABLE [FW].[TB_POST_TARGET] (

  [POST_ID]        BIGINT         NOT NULL,
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,
  CONSTRAINT [PK_TB_POST_TARGET] PRIMARY KEY CLUSTERED ([POST_ID], [COMPANY_CD]),
  CONSTRAINT [FK_TB_POST_TARGET_TB_POST] FOREIGN KEY ([POST_ID]) REFERENCES [FW].[TB_POST] ([POST_ID]),
  CONSTRAINT [FK_TB_POST_TARGET_TB_COMPANY] FOREIGN KEY ([COMPANY_CD]) REFERENCES [FW].[TB_COMPANY] ([COMPANY_CD])
);
