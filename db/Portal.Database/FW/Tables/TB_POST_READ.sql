-- 조회자 기록 (READER_YN 게시판). 사용자마다 처음 본 시각과 본 횟수를 둔다.
CREATE TABLE [FW].[TB_POST_READ] (

  [POST_ID]        BIGINT         NOT NULL,
  [USER_ID]        VARCHAR(30)    NOT NULL,
  [FIRST_DT]       DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POST_READ_FIRST_DT] DEFAULT (SYSUTCDATETIME()),
  [LAST_DT]        DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POST_READ_LAST_DT] DEFAULT (SYSUTCDATETIME()),
  [READ_CNT]       INT            NOT NULL CONSTRAINT [DF_TB_POST_READ_READ_CNT] DEFAULT (1),
  CONSTRAINT [PK_TB_POST_READ] PRIMARY KEY CLUSTERED ([POST_ID], [USER_ID]),
  CONSTRAINT [FK_TB_POST_READ_TB_POST] FOREIGN KEY ([POST_ID]) REFERENCES [FW].[TB_POST] ([POST_ID]),
  CONSTRAINT [FK_TB_POST_READ_TB_USER] FOREIGN KEY ([USER_ID]) REFERENCES [FW].[TB_USER] ([USER_ID])
);
