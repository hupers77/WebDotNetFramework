-- 공지 팝업 제목·내용 (언어별)
CREATE TABLE [FW].[TB_POPUP_LANG] (

  [POPUP_ID]       BIGINT         NOT NULL,
  [LANG_CD]        VARCHAR(5)     NOT NULL,
  [TITLE]          NVARCHAR(100)  NOT NULL,
  [CONTENT]        NVARCHAR(2000) NOT NULL,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POPUP_LANG_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POPUP_LANG_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POPUP_LANG_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POPUP_LANG_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT [PK_TB_POPUP_LANG] PRIMARY KEY CLUSTERED ([POPUP_ID], [LANG_CD]),
  CONSTRAINT [FK_TB_POPUP_LANG_TB_POPUP] FOREIGN KEY ([POPUP_ID]) REFERENCES [FW].[TB_POPUP] ([POPUP_ID]),
  CONSTRAINT [FK_TB_POPUP_LANG_TB_LANG] FOREIGN KEY ([LANG_CD]) REFERENCES [FW].[TB_LANG] ([LANG_CD])
);
