-- 외부 인증 계정(AD 등)과 포털 사용자 연결
CREATE TABLE [FW].[TB_USER_LOGIN_MAP] (

  [PROVIDER_CD]    VARCHAR(10)    NOT NULL,             -- AD
  [EXTERNAL_ID]    VARCHAR(100)   NOT NULL,             -- AD objectSid
  [EXTERNAL_LOGIN] VARCHAR(100)   NOT NULL,             -- sAMAccountName
  [USER_ID]        VARCHAR(30)    NOT NULL,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_LOGIN_MAP_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_LOGIN_MAP_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_LOGIN_MAP_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_LOGIN_MAP_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_USER_LOGIN_MAP] PRIMARY KEY CLUSTERED ([PROVIDER_CD], [EXTERNAL_ID])
);
GO
CREATE UNIQUE INDEX [UX_TB_USER_LOGIN_MAP_USER] ON [FW].[TB_USER_LOGIN_MAP] ([PROVIDER_CD], [USER_ID]);
GO
ALTER TABLE [FW].[TB_USER_LOGIN_MAP] ADD CONSTRAINT [FK_TB_USER_LOGIN_MAP_TB_USER] FOREIGN KEY ([USER_ID]) REFERENCES [FW].[TB_USER] ([USER_ID]);
