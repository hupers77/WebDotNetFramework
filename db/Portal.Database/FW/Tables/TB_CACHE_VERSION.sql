-- 캐시 버전. 값을 바꾸는 SP가 해당 키의 버전을 올리면 웹서버가 5초 안에 캐시를 비운다
CREATE TABLE [FW].[TB_CACHE_VERSION] (

  [CACHE_KEY]      VARCHAR(50)    NOT NULL,             -- MENU, AUTH, CODE, LANG, CONFIG
  [VERSION_NO]     BIGINT         NOT NULL CONSTRAINT [DF_TB_CACHE_VERSION_VERSION_NO] DEFAULT (1),
  [UPD_DT]         DATETIME2(3)   NOT NULL CONSTRAINT [DF_TB_CACHE_VERSION_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT [PK_TB_CACHE_VERSION] PRIMARY KEY CLUSTERED ([CACHE_KEY])
);
