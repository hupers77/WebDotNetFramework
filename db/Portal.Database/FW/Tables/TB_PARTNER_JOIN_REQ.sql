-- 협력사 계정 가입 신청 (설계서 5장: 협력사 담당자 가입 신청 → 본사 승인 → 계정 활성화)
-- 승인하면 TB_USER에 계정을 만들고 비밀번호 해시를 옮긴 뒤 여기서는 지운다. 반려해도 비밀번호 해시는 지운다.
-- 이메일은 업무용만 받고 애플리케이션에서 암호화한다(개인정보 최소 저장).
CREATE TABLE [FW].[TB_PARTNER_JOIN_REQ] (

  [REQ_ID]         BIGINT         IDENTITY (1, 1) NOT NULL,
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,
  [USER_ID]        VARCHAR(30)    NOT NULL,             -- 희망 ID
  [USER_NM]        NVARCHAR(100)  NOT NULL,
  [EMAIL_ENC]      VARBINARY(512) NULL,                 -- 업무용 이메일, 애플리케이션에서 암호화
  [LANG_CD]        VARCHAR(5)     NOT NULL,
  [PWD_HASH]       VARBINARY(64)  NULL,                 -- 처리하면 NULL
  [PWD_SALT]       VARBINARY(16)  NULL,
  [REQ_STAT_CD]    VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_PARTNER_JOIN_REQ_REQ_STAT_CD] DEFAULT ('REQUESTED'), -- 공통코드 JOIN_STAT
  [REQ_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PARTNER_JOIN_REQ_REQ_DT] DEFAULT (SYSUTCDATETIME()),
  [PROC_ID]        VARCHAR(30)    NULL,                 -- 승인·반려한 사용자
  [PROC_DT]        DATETIME2(0)   NULL,
  [REJECT_REASON]  NVARCHAR(500)  NULL,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_PARTNER_JOIN_REQ_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PARTNER_JOIN_REQ_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_PARTNER_JOIN_REQ_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PARTNER_JOIN_REQ_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_PARTNER_JOIN_REQ] PRIMARY KEY CLUSTERED ([REQ_ID]),
  CONSTRAINT [CK_TB_PARTNER_JOIN_REQ_STAT] CHECK ([REQ_STAT_CD] IN ('REQUESTED', 'APPROVED', 'REJECTED'))
);
GO
-- 같은 ID로 동시에 두 건을 신청할 수 없다
CREATE UNIQUE INDEX [UX_TB_PARTNER_JOIN_REQ_USER_REQUESTED] ON [FW].[TB_PARTNER_JOIN_REQ] ([USER_ID]) WHERE [REQ_STAT_CD] = 'REQUESTED';
GO
CREATE INDEX [IX_TB_PARTNER_JOIN_REQ_STAT_DT] ON [FW].[TB_PARTNER_JOIN_REQ] ([REQ_STAT_CD], [REQ_DT]);
GO
ALTER TABLE [FW].[TB_PARTNER_JOIN_REQ] ADD CONSTRAINT [FK_TB_PARTNER_JOIN_REQ_TB_COMPANY] FOREIGN KEY ([COMPANY_CD]) REFERENCES [FW].[TB_COMPANY] ([COMPANY_CD]);
GO
ALTER TABLE [FW].[TB_PARTNER_JOIN_REQ] ADD CONSTRAINT [FK_TB_PARTNER_JOIN_REQ_TB_LANG] FOREIGN KEY ([LANG_CD]) REFERENCES [FW].[TB_LANG] ([LANG_CD]);
