-- 외부 API 송신 대상. 코드는 주소를 쓰지 않고 TARGET_KEY만 쓴다(IOutboundApiClient).
-- 인증 비밀값(BASIC 비밀번호, BEARER 토큰, API_KEY 값)은 AUTH_SECRET_ENC에 암호화(Data Protection)해 저장하고 화면으로 내보내지 않는다.
-- ALLOW_PRIVATE_YN: 사내망(사설 IP) 대상이면 'Y'. 'N'이면 사설·내부 대역으로 해석되는 주소는 호출하지 않는다(SSRF 방지). http는 'Y'일 때만 허용.
CREATE TABLE [FW].[TB_API_OUTBOUND] (

  [TARGET_KEY]        VARCHAR(30)    NOT NULL,
  [TARGET_NM]         NVARCHAR(100)  NOT NULL,
  [BASE_URL]          VARCHAR(500)   NOT NULL,
  [AUTH_TYPE_CD]      VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_AUTH_TYPE_CD] DEFAULT ('NONE'),  -- NONE/BASIC/BEARER/API_KEY
  [AUTH_HEADER]       VARCHAR(50)    NULL,                 -- API_KEY일 때 헤더 이름
  [AUTH_USER]         NVARCHAR(100)  NULL,                 -- BASIC일 때 사용자
  [AUTH_SECRET_ENC]   NVARCHAR(2000) NULL,
  [TIMEOUT_SEC]       INT            NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_TIMEOUT_SEC] DEFAULT (30),
  [RETRY_COUNT]       INT            NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_RETRY_COUNT] DEFAULT (2),
  [ALLOW_PRIVATE_YN]  CHAR(1)        NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_ALLOW_PRIVATE_YN] DEFAULT ('N'),
  [USE_YN]            CHAR(1)        NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_USE_YN] DEFAULT ('Y'),
  [REG_ID]            VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]            DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]            VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]            DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_API_OUTBOUND_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]           ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_API_OUTBOUND] PRIMARY KEY CLUSTERED ([TARGET_KEY]),
  CONSTRAINT [CK_TB_API_OUTBOUND_KEY] CHECK ([TARGET_KEY] NOT LIKE '%[^A-Z0-9_]%'),
  CONSTRAINT [CK_TB_API_OUTBOUND_URL] CHECK ([BASE_URL] LIKE 'https://%' OR ([BASE_URL] LIKE 'http://%' AND [ALLOW_PRIVATE_YN] = 'Y')),
  CONSTRAINT [CK_TB_API_OUTBOUND_AUTH] CHECK ([AUTH_TYPE_CD] IN ('NONE', 'BASIC', 'BEARER', 'API_KEY')),
  CONSTRAINT [CK_TB_API_OUTBOUND_TIMEOUT] CHECK ([TIMEOUT_SEC] BETWEEN 1 AND 300),
  CONSTRAINT [CK_TB_API_OUTBOUND_RETRY] CHECK ([RETRY_COUNT] BETWEEN 0 AND 5),
  CONSTRAINT [CK_TB_API_OUTBOUND_PRIVATE] CHECK ([ALLOW_PRIVATE_YN] IN ('Y', 'N')),
  CONSTRAINT [CK_TB_API_OUTBOUND_USE_YN] CHECK ([USE_YN] IN ('Y', 'N'))
);
