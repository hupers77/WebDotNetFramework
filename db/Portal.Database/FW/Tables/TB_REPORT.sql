-- 레포트 (설계서 11장 '레포트'). 행 하나를 등록하면 조건 입력·미리보기·PDF·엑셀 화면(/Rpt/Viewer/Index/{REPORT_ID})이 생긴다.
-- REPORT_ID는 그 레포트의 프로그램 ID와 같다(권한·메뉴·접근 기록을 프로그램 단위로 건다). 조회는 READ, PDF는 PRINT, 엑셀은 EXPORT.
-- 데이터 SP는 '스키마.USP_RPT_대상_GET_LIST' 형식만 실행하고, 결과셋 하나(컬럼 그대로 표로 그림)와 @P_MAX_ROWS를 받는다.
-- PARAMS_JSON: 조건 정의 [{"name":"P_MONTH","type":"MONTH","required":true,"labelKey":"LBL.MONTH","default":"PREV_MONTH"}]
--   type은 DATE/MONTH/TEXT, default는 TODAY/THIS_MONTH/PREV_MONTH(사용자 날짜 기준) 또는 비움. 이름은 데이터 SP의 파라미터 이름(@ 제외)이다.
-- 개인정보가 들어 있는 레포트는 프로그램의 PII_YN = 'Y'로 표시한다(미리보기는 조회, PDF·엑셀은 사유를 받아 다운로드로 접속기록에 남긴다).
CREATE TABLE [FW].[TB_REPORT] (
  [REPORT_ID]      VARCHAR(30)    NOT NULL,             -- = TB_PROGRAM.PROGRAM_ID (예: RPT_LOG_MONTHLY)
  [DATA_SP]        VARCHAR(128)   NOT NULL,             -- LOG.USP_RPT_ACCESS_MONTHLY_GET_LIST
  [TEMPLATE_VIEW]  VARCHAR(50)    NULL,                 -- Areas/Rpt/Views/Templates의 Razor 뷰 이름. NULL이면 기본 표(Default)
  [PARAMS_JSON]    NVARCHAR(2000) NULL,
  [ORIENT_CD]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_REPORT_ORIENT_CD] DEFAULT ('P'),     -- P 세로 / L 가로 (A4)
  [APPROVAL_YN]    CHAR(1)        NOT NULL CONSTRAINT [DF_TB_REPORT_APPROVAL_YN] DEFAULT ('N'),   -- 결재란(담당·검토·승인) 표시
  [TOTAL_YN]       CHAR(1)        NOT NULL CONSTRAINT [DF_TB_REPORT_TOTAL_YN] DEFAULT ('N'),      -- 숫자 컬럼 합계 행 표시
  [MAX_ROWS]       INT            NOT NULL CONSTRAINT [DF_TB_REPORT_MAX_ROWS] DEFAULT (5000),     -- 넘으면 조건을 좁혀 달라고 한다
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_REPORT_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_REPORT_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_REPORT_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_REPORT_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_REPORT_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_REPORT] PRIMARY KEY CLUSTERED ([REPORT_ID]),
  CONSTRAINT [CK_TB_REPORT_DATA_SP] CHECK ([DATA_SP] LIKE '[A-Z]%.USP[_]RPT[_]%[_]GET[_]LIST'),
  CONSTRAINT [CK_TB_REPORT_PARAMS_JSON] CHECK ([PARAMS_JSON] IS NULL OR ISJSON([PARAMS_JSON]) = 1),
  CONSTRAINT [CK_TB_REPORT_ORIENT_CD] CHECK ([ORIENT_CD] IN ('P', 'L')),
  CONSTRAINT [CK_TB_REPORT_APPROVAL_YN] CHECK ([APPROVAL_YN] IN ('Y', 'N')),
  CONSTRAINT [CK_TB_REPORT_TOTAL_YN] CHECK ([TOTAL_YN] IN ('Y', 'N')),
  CONSTRAINT [CK_TB_REPORT_MAX_ROWS] CHECK ([MAX_ROWS] BETWEEN 1 AND 100000),
  CONSTRAINT [CK_TB_REPORT_USE_YN] CHECK ([USE_YN] IN ('Y', 'N'))
);
GO
ALTER TABLE [FW].[TB_REPORT] ADD CONSTRAINT [FK_TB_REPORT_TB_PROGRAM] FOREIGN KEY ([REPORT_ID]) REFERENCES [FW].[TB_PROGRAM] ([PROGRAM_ID]);
