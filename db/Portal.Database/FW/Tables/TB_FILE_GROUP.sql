-- 첨부 묶음. 업무 데이터는 FILE_GROUP_ID 하나로 첨부를 연결한다.
-- 업로드 직후에는 임시(CONFIRM_YN = 'N')이고, 업무 저장 SP가 USP_FILE_GROUP_CONFIRM_EXEC로 확정한다(확정되지 않은 묶음은 정리 작업이 지운다).
CREATE TABLE [FW].[TB_FILE_GROUP] (

  [FILE_GROUP_ID]  BIGINT         IDENTITY(1,1) NOT NULL,
  [PROGRAM_ID]     VARCHAR(30)    NOT NULL,                                                          -- 권한 기준 프로그램
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,                                                          -- 올린 사용자의 회사 (협력사 격리 기준)
  [SHARE_YN]       CHAR(1)        NOT NULL CONSTRAINT [DF_TB_FILE_GROUP_SHARE_YN] DEFAULT ('N'),     -- Y면 다른 회사 사용자도 받을 수 있다 (공지 첨부 등)
  [CONFIRM_YN]     CHAR(1)        NOT NULL CONSTRAINT [DF_TB_FILE_GROUP_CONFIRM_YN] DEFAULT ('N'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_FILE_GROUP_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_FILE_GROUP_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_FILE_GROUP_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_FILE_GROUP_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_FILE_GROUP] PRIMARY KEY CLUSTERED ([FILE_GROUP_ID]),
  CONSTRAINT [CK_TB_FILE_GROUP_SHARE_YN] CHECK ([SHARE_YN] IN ('Y', 'N')),
  CONSTRAINT [CK_TB_FILE_GROUP_CONFIRM_YN] CHECK ([CONFIRM_YN] IN ('Y', 'N'))
);
GO
CREATE INDEX [IX_TB_FILE_GROUP_CONFIRM] ON [FW].[TB_FILE_GROUP] ([CONFIRM_YN], [REG_DT]);
GO
ALTER TABLE [FW].[TB_FILE_GROUP] ADD CONSTRAINT [FK_TB_FILE_GROUP_TB_PROGRAM] FOREIGN KEY ([PROGRAM_ID]) REFERENCES [FW].[TB_PROGRAM] ([PROGRAM_ID]);
GO
ALTER TABLE [FW].[TB_FILE_GROUP] ADD CONSTRAINT [FK_TB_FILE_GROUP_TB_COMPANY] FOREIGN KEY ([COMPANY_CD]) REFERENCES [FW].[TB_COMPANY] ([COMPANY_CD]);
