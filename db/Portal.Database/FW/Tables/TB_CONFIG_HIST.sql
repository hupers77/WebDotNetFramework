-- 설정 변경 이력 (SECRET 값은 남기지 않음)
CREATE TABLE [FW].[TB_CONFIG_HIST] (

  [HIST_ID]        BIGINT IDENTITY(1,1) NOT NULL,
  [CONFIG_KEY]     VARCHAR(100)   NOT NULL,
  [OLD_VAL]        NVARCHAR(2000) NULL,
  [NEW_VAL]        NVARCHAR(2000) NULL,
  [CHG_ID]         VARCHAR(30)    NOT NULL,
  [CHG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_CONFIG_HIST_CHG_DT] DEFAULT (SYSUTCDATETIME()),
  [CLIENT_IP]      VARCHAR(45)    NULL,
  CONSTRAINT [PK_TB_CONFIG_HIST] PRIMARY KEY CLUSTERED ([HIST_ID])
);
GO
CREATE INDEX [IX_TB_CONFIG_HIST_KEY] ON [FW].[TB_CONFIG_HIST] ([CONFIG_KEY], [CHG_DT]);
