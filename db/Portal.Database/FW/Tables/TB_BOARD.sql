-- 게시판 마스터. 게시판 하나가 프로그램 하나에 대응하고(권한은 프로그램에 건다), 설정으로 기능을 켜고 끈다.
-- 화면 주소는 /Board/{BOARD_CD}이며 프로그램 URL과 같다.
CREATE TABLE [FW].[TB_BOARD] (

  [BOARD_CD]       VARCHAR(30)    NOT NULL,
  [PROGRAM_ID]     VARCHAR(30)    NOT NULL,                                                          -- 권한 기준 프로그램 (게시판마다 하나)
  [BOARD_TYPE_CD]  VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_BOARD_BOARD_TYPE_CD] DEFAULT ('NORMAL'), -- 공통코드 BOARD_TYPE
  [REPLY_YN]       CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_REPLY_YN] DEFAULT ('N'),          -- 답글
  [COMMENT_YN]     CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_COMMENT_YN] DEFAULT ('N'),        -- 댓글
  [ATTACH_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_ATTACH_YN] DEFAULT ('Y'),         -- 첨부
  [ANON_YN]        CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_ANON_YN] DEFAULT ('N'),           -- 익명 (관리자 외에는 작성자를 숨긴다)
  [SECRET_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_SECRET_YN] DEFAULT ('N'),         -- 비밀글
  [PERIOD_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_PERIOD_YN] DEFAULT ('N'),         -- 게시기간
  [PIN_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_PIN_YN] DEFAULT ('N'),            -- 상단 고정
  [READER_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_READER_YN] DEFAULT ('N'),         -- 조회자 목록
  [SORT_NO]        INT            NOT NULL CONSTRAINT [DF_TB_BOARD_SORT_NO] DEFAULT (0),
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_BOARD_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_BOARD_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_BOARD_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_BOARD_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_BOARD_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_BOARD] PRIMARY KEY CLUSTERED ([BOARD_CD]),
  CONSTRAINT [CK_TB_BOARD_FLAGS] CHECK ([REPLY_YN] IN ('Y', 'N') AND [COMMENT_YN] IN ('Y', 'N') AND [ATTACH_YN] IN ('Y', 'N') AND [ANON_YN] IN ('Y', 'N')
                                        AND [SECRET_YN] IN ('Y', 'N') AND [PERIOD_YN] IN ('Y', 'N') AND [PIN_YN] IN ('Y', 'N') AND [READER_YN] IN ('Y', 'N')),
  CONSTRAINT [CK_TB_BOARD_USE_YN] CHECK ([USE_YN] IN ('Y', 'N'))
);
GO
CREATE UNIQUE INDEX [UX_TB_BOARD_PROGRAM] ON [FW].[TB_BOARD] ([PROGRAM_ID]);
GO
ALTER TABLE [FW].[TB_BOARD] ADD CONSTRAINT [FK_TB_BOARD_TB_PROGRAM] FOREIGN KEY ([PROGRAM_ID]) REFERENCES [FW].[TB_PROGRAM] ([PROGRAM_ID]);
