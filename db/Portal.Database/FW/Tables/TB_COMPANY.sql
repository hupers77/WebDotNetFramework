-- 회사 (본사/협력사). 협력사별 접속 허용 IP 대역은 ALLOW_IP_LIST(CIDR, 쉼표 구분)
CREATE TABLE [FW].[TB_COMPANY] (

  [COMPANY_CD]     VARCHAR(10)    NOT NULL,
  [COMPANY_NM]     NVARCHAR(100)  NOT NULL,
  [COMPANY_TYPE_CD] VARCHAR(10)   NOT NULL,             -- 공통코드 COMPANY_TYPE: HQ/PARTNER
  [BIZ_REG_NO]     VARCHAR(20)    NULL,                 -- 사업자등록번호 (법인 정보, 개인정보 아님)
  [ALLOW_IP_LIST]  VARCHAR(1000)  NULL,                 -- NULL이면 제한 없음
  [CONTRACT_END_DT] DATE          NULL,                 -- 계약 종료일 (협력사)
  [SORT_NO]        INT            NOT NULL CONSTRAINT [DF_TB_COMPANY_SORT_NO] DEFAULT (0),
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_COMPANY_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_COMPANY_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_COMPANY_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_COMPANY_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_COMPANY_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_COMPANY] PRIMARY KEY CLUSTERED ([COMPANY_CD])
);
