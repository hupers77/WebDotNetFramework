-- 휴일·영업일 달력. 평일이 휴일이면 WORK_YN = 'N', 주말에 일하는 날(대체 근무일)이면 WORK_YN = 'Y'로 등록한다.
-- 등록이 없는 날은 토·일만 쉬는 날이다. 영업일 판단은 FW.UFN_IS_BUSINESS_DAY를 쓴다.
CREATE TABLE [FW].[TB_HOLIDAY] (

  [HOLIDAY_DT]     DATE           NOT NULL,
  [HOLIDAY_NM]     NVARCHAR(100)  NOT NULL,
  [WORK_YN]        CHAR(1)        NOT NULL CONSTRAINT [DF_TB_HOLIDAY_WORK_YN] DEFAULT ('N'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_HOLIDAY_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_HOLIDAY_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_HOLIDAY_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_HOLIDAY_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_HOLIDAY] PRIMARY KEY CLUSTERED ([HOLIDAY_DT]),
  CONSTRAINT [CK_TB_HOLIDAY_WORK_YN] CHECK ([WORK_YN] IN ('Y', 'N'))
);
