-- 공지 팝업. 기간(시작일~종료일, 포함) 안에 사용 중이고 공개 대상(OPEN_SCOPE_CD)이 맞는 사용자의 홈 화면에 뜬다.
-- 제목·내용은 언어별로 TB_POPUP_LANG에 둔다 (내용은 글자만 보여 주므로 HTML을 받지 않는다).
CREATE TABLE [FW].[TB_POPUP] (

  [POPUP_ID]       BIGINT         NOT NULL IDENTITY(1, 1),
  [OPEN_SCOPE_CD]  VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_POPUP_OPEN_SCOPE_CD] DEFAULT ('ALL'),  -- 공통코드 OPEN_SCOPE: ALL/EMP/PARTNER (사용자 유형과 비교)
  [START_DT]       DATE           NOT NULL,
  [END_DT]         DATE           NOT NULL,
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_POPUP_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POPUP_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POPUP_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POPUP_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POPUP_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_POPUP] PRIMARY KEY CLUSTERED ([POPUP_ID]),
  CONSTRAINT [CK_TB_POPUP_OPEN_SCOPE_CD] CHECK ([OPEN_SCOPE_CD] IN ('ALL', 'EMP', 'PARTNER')),
  CONSTRAINT [CK_TB_POPUP_PERIOD] CHECK ([START_DT] <= [END_DT]),
  CONSTRAINT [CK_TB_POPUP_USE_YN] CHECK ([USE_YN] IN ('Y', 'N'))
);
GO
CREATE INDEX [IX_TB_POPUP_PERIOD] ON [FW].[TB_POPUP] ([USE_YN], [START_DT], [END_DT]);
