-- 화면·메시지 문구 (언어별). 키 체계는 개발 표준 가이드 7장
CREATE TABLE [FW].[TB_LANG_RESOURCE] (

  [RES_KEY]        VARCHAR(100)   NOT NULL,             -- BTN.SAVE, MSG.SAVED, SYS.USER.TITLE
  [LANG_CD]        VARCHAR(5)     NOT NULL,
  [RES_TEXT]       NVARCHAR(1000) NOT NULL,
  [RES_TYPE]       VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_LANG_RESOURCE_RES_TYPE] DEFAULT ('LABEL'),   -- LABEL/MSG/BTN/TOOLTIP,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_LANG_RESOURCE_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_LANG_RESOURCE_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_LANG_RESOURCE_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_LANG_RESOURCE_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_LANG_RESOURCE] PRIMARY KEY CLUSTERED ([RES_KEY], [LANG_CD])
);
GO
CREATE INDEX [IX_TB_LANG_RESOURCE_LANG] ON [FW].[TB_LANG_RESOURCE] ([LANG_CD]) INCLUDE ([RES_TEXT]);
GO
ALTER TABLE [FW].[TB_LANG_RESOURCE] ADD CONSTRAINT [FK_TB_LANG_RESOURCE_TB_LANG] FOREIGN KEY ([LANG_CD]) REFERENCES [FW].[TB_LANG] ([LANG_CD]);
