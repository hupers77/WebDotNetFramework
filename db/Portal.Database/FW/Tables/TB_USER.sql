-- 사용자 계정. 개인정보는 저장하지 않는다: 이름과 업무 이메일(암호화)만 둔다
CREATE TABLE [FW].[TB_USER] (

  [USER_ID]        VARCHAR(30)    NOT NULL,
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,
  [DEPT_ID]        VARCHAR(20)    NULL,
  [USER_NM]        NVARCHAR(100)  NOT NULL,
  [EMAIL_ENC]      VARBINARY(512) NULL,                 -- 업무용 이메일만, 애플리케이션에서 AES-256-GCM 암호화
  [USER_TYPE_CD]   VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_USER_USER_TYPE_CD] DEFAULT ('EMP'),     -- EMP/PARTNER/SYSTEM
  [PWD_HASH]       VARBINARY(64)  NULL,                 -- AD 전용 계정은 NULL
  [PWD_SALT]       VARBINARY(16)  NULL,
  [PWD_CHG_DT]     DATETIME2(0)   NULL,
  [PWD_CHG_REQ_YN] CHAR(1)        NOT NULL CONSTRAINT [DF_TB_USER_PWD_CHG_REQ_YN] DEFAULT ('N'),       -- 최초 로그인·초기화 후 변경 강제
  [LOGIN_FAIL_CNT] TINYINT        NOT NULL CONSTRAINT [DF_TB_USER_LOGIN_FAIL_CNT] DEFAULT (0),
  [LOCK_YN]        CHAR(1)        NOT NULL CONSTRAINT [DF_TB_USER_LOCK_YN] DEFAULT ('N'),
  [LOCK_DT]        DATETIME2(0)   NULL,
  [ACCOUNT_END_DT] DATE           NULL,                 -- 협력사 계약 종료일(지나면 자동 잠금)
  [USER_STAT_CD]   VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_USER_USER_STAT_CD] DEFAULT ('ACTIVE'),  -- 공통코드 USER_STAT
  [LANG_CD]        VARCHAR(5)     NOT NULL CONSTRAINT [DF_TB_USER_LANG_CD] DEFAULT ('ko'),
  [TIMEZONE_ID]    VARCHAR(50)    NOT NULL CONSTRAINT [DF_TB_USER_TIMEZONE_ID] DEFAULT ('Korea Standard Time'),
  [MFA_SECRET_ENC] VARBINARY(256) NULL,                 -- TOTP 비밀키, 애플리케이션에서 암호화 (등록 전 NULL)
  [MFA_LAST_STEP]  BIGINT         NULL,                 -- 마지막으로 쓴 TOTP 시간 단계 (같은 코드 재사용 방지)
  [LAST_LOGIN_DT]  DATETIME2(0)   NULL,
  [STAT_CHG_DT]    DATETIME2(0)   NULL,                 -- 상태를 마지막으로 바꾼 시각 (휴면 해제 후 다시 바로 휴면되지 않게 미접속 기간 기준에 쓴다)
  [DORMANT_NOTICE_DT] DATETIME2(0) NULL,                -- 휴면 전환 사전 안내를 보낸 시각 (JOB_USER_DORMANT)
  [EXPIRE_NOTICE_DT] DATE        NULL,                 -- 계정 만료 사전 안내를 보낸 날 (JOB_PARTNER_EXPIRE, 사용 기한을 늘리면 새 기한 기준으로 다시 안내)
  [PWD_EXPIRE_NOTICE_DT] DATETIME2(0) NULL,             -- 비밀번호 만료 사전 안내를 보낸 시각 (JOB_PWD_EXPIRE_NOTICE, 비밀번호를 바꾸면 다음 주기에 다시 안내)
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_USER] PRIMARY KEY CLUSTERED ([USER_ID])
);
GO
CREATE INDEX [IX_TB_USER_COMPANY_DEPT] ON [FW].[TB_USER] ([COMPANY_CD], [DEPT_ID]);
GO
ALTER TABLE [FW].[TB_USER] ADD CONSTRAINT [FK_TB_USER_TB_COMPANY] FOREIGN KEY ([COMPANY_CD]) REFERENCES [FW].[TB_COMPANY] ([COMPANY_CD]);
GO
ALTER TABLE [FW].[TB_USER] ADD CONSTRAINT [FK_TB_USER_TB_LANG] FOREIGN KEY ([LANG_CD]) REFERENCES [FW].[TB_LANG] ([LANG_CD]);
