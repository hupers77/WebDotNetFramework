-- 포털 알림함 (헤더 배지, 내 정보 > 알림함). USP_MSG_QUEUE_SAVE가 템플릿의 포털 채널(PORTAL_YN = 'Y')이 켜져 있고 받는 사람이 포털 사용자일 때 쌓는다.
-- 문구는 저장하지 않고 템플릿 ID와 치환값만 둔다(볼 때 보는 사람의 화면 언어로 만든다).
-- NOTIFY.KEEP_DAYS(기본 90일)가 지나면 정리 작업(JOB_DATA_CLEANUP)이 지운다.
CREATE TABLE [FW].[TB_NOTIFICATION] (

  [NOTI_ID]        BIGINT         IDENTITY (1, 1) NOT NULL,
  [USER_ID]        VARCHAR(30)    NOT NULL,             -- 받는 사람
  [TEMPLATE_ID]    VARCHAR(30)    NOT NULL,
  [PARAMS_JSON]    NVARCHAR(4000) NULL,                 -- 치환값 (메일과 같다). 비밀번호·인증 번호는 넣지 않는다
  [READ_DT]        DATETIME2(0)   NULL,                 -- 읽은 시각 (NULL이면 안 읽음)
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_NOTIFICATION_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_NOTIFICATION_REG_DT] DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT [PK_TB_NOTIFICATION] PRIMARY KEY CLUSTERED ([NOTI_ID]),
  CONSTRAINT [FK_TB_NOTIFICATION_USER] FOREIGN KEY ([USER_ID]) REFERENCES [FW].[TB_USER] ([USER_ID]),
  CONSTRAINT [FK_TB_NOTIFICATION_TEMPLATE] FOREIGN KEY ([TEMPLATE_ID]) REFERENCES [FW].[TB_MSG_TEMPLATE] ([TEMPLATE_ID]),
  CONSTRAINT [CK_TB_NOTIFICATION_PARAMS] CHECK ([PARAMS_JSON] IS NULL OR ISJSON([PARAMS_JSON]) = 1)
);
GO
-- 내 알림 목록(최근 것부터)과 안 읽은 수
CREATE INDEX [IX_TB_NOTIFICATION_USER] ON [FW].[TB_NOTIFICATION] ([USER_ID], [NOTI_ID] DESC) INCLUDE ([READ_DT]);
GO
-- 정리 작업
CREATE INDEX [IX_TB_NOTIFICATION_REG_DT] ON [FW].[TB_NOTIFICATION] ([REG_DT]);
