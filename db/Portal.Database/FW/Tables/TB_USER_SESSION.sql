-- 활성 세션. 앱 풀 재시작에도 로그인을 유지하고 중복 로그인·강제 로그아웃을 처리한다
CREATE TABLE [FW].[TB_USER_SESSION] (

  [SESSION_ID]     CHAR(64)       NOT NULL,             -- 무작위 256비트 값의 SHA-256 (원문은 쿠키에만)
  [USER_ID]        VARCHAR(30)    NOT NULL,
  [LOGIN_DT]       DATETIME2(0)   NOT NULL,
  [LAST_ACCESS_DT] DATETIME2(0)   NOT NULL,
  [EXPIRE_DT]      DATETIME2(0)   NOT NULL,
  [CLIENT_IP]      VARCHAR(45)    NULL,
  [USER_AGENT]     NVARCHAR(300)  NULL,
  [AUTH_METHOD_CD] VARCHAR(10)    NOT NULL,             -- FORM/AD/AD_LDAP
  [END_DT]         DATETIME2(0)   NULL,                 -- 로그아웃·강제 종료 시각
  [END_REASON_CD]  VARCHAR(20)    NULL,                 -- 공통코드 LOGIN_RESULT (LOGOUT/KICKED 등),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_SESSION_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_SESSION_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_USER_SESSION_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_USER_SESSION_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_USER_SESSION] PRIMARY KEY CLUSTERED ([SESSION_ID])
);
GO
CREATE INDEX [IX_TB_USER_SESSION_USER] ON [FW].[TB_USER_SESSION] ([USER_ID]) INCLUDE ([END_DT], [EXPIRE_DT]);
GO
CREATE INDEX [IX_TB_USER_SESSION_EXPIRE] ON [FW].[TB_USER_SESSION] ([EXPIRE_DT]) WHERE [END_DT] IS NULL;
GO
ALTER TABLE [FW].[TB_USER_SESSION] ADD CONSTRAINT [FK_TB_USER_SESSION_TB_USER] FOREIGN KEY ([USER_ID]) REFERENCES [FW].[TB_USER] ([USER_ID]);
