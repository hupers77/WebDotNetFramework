-- 부서 트리. 유효기간으로 조직 개편 이력을 보존한다
CREATE TABLE [FW].[TB_DEPT] (

  [DEPT_ID]        VARCHAR(20)    NOT NULL,
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,
  [PARENT_DEPT_ID] VARCHAR(20)    NULL,
  [DEPT_NM]        NVARCHAR(100)  NOT NULL,
  [AD_OU_PATH]     NVARCHAR(400)  NULL,                 -- AD 동기화 원본 OU
  [SORT_NO]        INT            NOT NULL CONSTRAINT [DF_TB_DEPT_SORT_NO] DEFAULT (0),
  [START_DT]       DATE           NOT NULL CONSTRAINT [DF_TB_DEPT_START_DT] DEFAULT ('1900-01-01'),
  [END_DT]         DATE           NOT NULL CONSTRAINT [DF_TB_DEPT_END_DT] DEFAULT ('9999-12-31'),
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_DEPT_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_DEPT_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_DEPT_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_DEPT_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_DEPT_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_DEPT] PRIMARY KEY CLUSTERED ([DEPT_ID])
);
GO
CREATE INDEX [IX_TB_DEPT_PARENT] ON [FW].[TB_DEPT] ([COMPANY_CD], [PARENT_DEPT_ID], [SORT_NO]);
GO
ALTER TABLE [FW].[TB_DEPT] ADD CONSTRAINT [FK_TB_DEPT_TB_COMPANY] FOREIGN KEY ([COMPANY_CD]) REFERENCES [FW].[TB_COMPANY] ([COMPANY_CD]);
