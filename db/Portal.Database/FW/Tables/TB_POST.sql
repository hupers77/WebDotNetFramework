-- 게시글. 답글은 ROOT_POST_ID(원글)와 PARENT_POST_ID(바로 위 글)로 이어지고 DEPTH가 들여쓰기 단계다.
-- 내용(CONTENT)은 저장 전에 서버 HTML 화이트리스트 필터를 거친 HTML이다. 삭제는 표시만 한다(DEL_YN).
-- 작성자는 계정 ID와 회사만 두고 이름은 보여 줄 때 계정에서 읽는다(개인정보를 따로 저장하지 않는다).
CREATE TABLE [FW].[TB_POST] (

  [POST_ID]        BIGINT         IDENTITY(1,1) NOT NULL,
  [BOARD_CD]       VARCHAR(30)    NOT NULL,
  [ROOT_POST_ID]   BIGINT         NULL,                                                              -- 원글 ID (원글은 자기 자신)
  [PARENT_POST_ID] BIGINT         NULL,                                                              -- 답글이 달린 글
  [DEPTH]          TINYINT        NOT NULL CONSTRAINT [DF_TB_POST_DEPTH] DEFAULT (0),
  [TITLE]          NVARCHAR(200)  NOT NULL,
  [CONTENT]        NVARCHAR(MAX)  NOT NULL,
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,                                                          -- 작성자의 회사
  [WRITER_ID]      VARCHAR(30)    NOT NULL,
  [SECRET_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_POST_SECRET_YN] DEFAULT ('N'),
  [PIN_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_POST_PIN_YN] DEFAULT ('N'),
  [START_DT]       DATE           NULL,                                                              -- 게시기간 (PERIOD_YN 게시판)
  [END_DT]         DATE           NULL,
  [FILE_GROUP_ID]  BIGINT         NULL,
  [IMAGE_GROUP_ID] BIGINT         NULL,                                                              -- 본문 사진 묶음 (첨부 목록에는 보이지 않는다)
  [VIEW_CNT]       INT            NOT NULL CONSTRAINT [DF_TB_POST_VIEW_CNT] DEFAULT (0),
  [DEL_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_POST_DEL_YN] DEFAULT ('N'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POST_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POST_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POST_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POST_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_POST] PRIMARY KEY CLUSTERED ([POST_ID]),
  CONSTRAINT [CK_TB_POST_FLAGS] CHECK ([SECRET_YN] IN ('Y', 'N') AND [PIN_YN] IN ('Y', 'N') AND [DEL_YN] IN ('Y', 'N')),
  CONSTRAINT [CK_TB_POST_PERIOD] CHECK ([START_DT] IS NULL OR [END_DT] IS NULL OR [START_DT] <= [END_DT])
);
GO
-- 목록: 게시판별 원글 순서 (상단 고정이 먼저)
CREATE INDEX [IX_TB_POST_BOARD] ON [FW].[TB_POST] ([BOARD_CD], [DEL_YN], [PIN_YN], [ROOT_POST_ID] DESC);
GO
CREATE INDEX [IX_TB_POST_ROOT] ON [FW].[TB_POST] ([ROOT_POST_ID]);
GO
CREATE INDEX [IX_TB_POST_WRITER] ON [FW].[TB_POST] ([WRITER_ID]);
GO
