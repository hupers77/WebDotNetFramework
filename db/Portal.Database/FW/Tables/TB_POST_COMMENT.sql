-- 댓글. 삭제는 표시만 하고(DEL_YN) 목록에서는 빼서 보여 준다.
CREATE TABLE [FW].[TB_POST_COMMENT] (

  [COMMENT_ID]     BIGINT         IDENTITY(1,1) NOT NULL,
  [POST_ID]        BIGINT         NOT NULL,
  [CONTENT]        NVARCHAR(1000) NOT NULL,                                                          -- 글자만 (HTML 아님)
  [COMPANY_CD]     VARCHAR(10)    NOT NULL,
  [WRITER_ID]      VARCHAR(30)    NOT NULL,
  [DEL_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_POST_COMMENT_DEL_YN] DEFAULT ('N'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POST_COMMENT_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POST_COMMENT_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_POST_COMMENT_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_POST_COMMENT_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_POST_COMMENT] PRIMARY KEY CLUSTERED ([COMMENT_ID]),
  CONSTRAINT [CK_TB_POST_COMMENT_DEL_YN] CHECK ([DEL_YN] IN ('Y', 'N')),
  CONSTRAINT [FK_TB_POST_COMMENT_TB_POST] FOREIGN KEY ([POST_ID]) REFERENCES [FW].[TB_POST] ([POST_ID]),
  CONSTRAINT [FK_TB_POST_COMMENT_TB_COMPANY] FOREIGN KEY ([COMPANY_CD]) REFERENCES [FW].[TB_COMPANY] ([COMPANY_CD]),
  CONSTRAINT [FK_TB_POST_COMMENT_TB_USER] FOREIGN KEY ([WRITER_ID]) REFERENCES [FW].[TB_USER] ([USER_ID])
);
GO
CREATE INDEX [IX_TB_POST_COMMENT_POST] ON [FW].[TB_POST_COMMENT] ([POST_ID], [DEL_YN], [COMMENT_ID]);
