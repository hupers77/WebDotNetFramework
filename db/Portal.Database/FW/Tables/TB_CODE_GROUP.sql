-- 공통코드 그룹. 추가 속성 5개의 의미를 그룹별로 정의한다
CREATE TABLE [FW].[TB_CODE_GROUP] (

  [GROUP_CD]       VARCHAR(30)    NOT NULL,
  [GROUP_NM]       NVARCHAR(100)  NOT NULL,             -- 관리용 기본명
  [SYSTEM_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_SYSTEM_YN] DEFAULT ('N'),       -- Y면 코드값 추가·삭제 불가
  [ALLOW_ADD_YN]   CHAR(1)        NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_ALLOW_ADD_YN] DEFAULT ('Y'),       -- 시스템 그룹 중 값 추가를 허용(FUNC_CD, FILE_EXT)
  [ATTR1_NM]       NVARCHAR(50)   NULL,
  [ATTR2_NM]       NVARCHAR(50)   NULL,
  [ATTR3_NM]       NVARCHAR(50)   NULL,
  [ATTR4_NM]       NVARCHAR(50)   NULL,
  [ATTR5_NM]       NVARCHAR(50)   NULL,
  [SORT_NO]        INT            NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_SORT_NO] DEFAULT (0),
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_CODE_GROUP_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_CODE_GROUP] PRIMARY KEY CLUSTERED ([GROUP_CD])
);
