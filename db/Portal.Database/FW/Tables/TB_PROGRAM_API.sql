-- 요청 경로(Action/API) → 프로그램 + 기능 매핑. 권한 필터와 권한 매트릭스 테스트의 기준
CREATE TABLE [FW].[TB_PROGRAM_API] (

  [HTTP_METHOD]    VARCHAR(10)    NOT NULL,
  [ROUTE_PATTERN]  VARCHAR(300)   NOT NULL,
  [PROGRAM_ID]     VARCHAR(30)    NOT NULL,
  [FUNC_CD]        VARCHAR(20)    NOT NULL,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_PROGRAM_API_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PROGRAM_API_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_PROGRAM_API_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PROGRAM_API_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_PROGRAM_API] PRIMARY KEY CLUSTERED ([HTTP_METHOD], [ROUTE_PATTERN])
);
GO
CREATE INDEX [IX_TB_PROGRAM_API_PROGRAM] ON [FW].[TB_PROGRAM_API] ([PROGRAM_ID]);
GO
ALTER TABLE [FW].[TB_PROGRAM_API] ADD CONSTRAINT [FK_TB_PROGRAM_API_TB_PROGRAM_FUNC] FOREIGN KEY ([PROGRAM_ID], [FUNC_CD]) REFERENCES [FW].[TB_PROGRAM_FUNC] ([PROGRAM_ID], [FUNC_CD]);
