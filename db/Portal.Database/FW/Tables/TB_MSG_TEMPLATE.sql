-- 메일·포털 알림 템플릿 (초기 데이터 정의서 7장). 본문은 언어별로 TB_MSG_TEMPLATE_LANG에 둔다
CREATE TABLE [FW].[TB_MSG_TEMPLATE] (

  [TEMPLATE_ID]    VARCHAR(30)    NOT NULL,             -- TPL_PARTNER_APPROVED
  [TEMPLATE_NM]    NVARCHAR(100)  NOT NULL,             -- 관리용 이름
  [MAIL_YN]        CHAR(1)        NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_MAIL_YN] DEFAULT ('Y'),   -- 메일로 보내는지
  [PORTAL_YN]      CHAR(1)        NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_PORTAL_YN] DEFAULT ('N'), -- 포털 알림으로 보내는지
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_USE_YN] DEFAULT ('Y'),    -- N이면 쌓지 않는다
  [LINK_PROGRAM_ID] VARCHAR(30)   NULL,                 -- 포털 알림을 누르면 여는 화면 (없으면 알림만 읽음 처리)
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_MSG_TEMPLATE_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_MSG_TEMPLATE] PRIMARY KEY CLUSTERED ([TEMPLATE_ID]),
  CONSTRAINT [FK_TB_MSG_TEMPLATE_LINK_PROGRAM] FOREIGN KEY ([LINK_PROGRAM_ID]) REFERENCES [FW].[TB_PROGRAM] ([PROGRAM_ID])
);
