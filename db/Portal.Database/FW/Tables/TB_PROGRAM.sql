-- 프로그램(화면). 권한은 메뉴가 아닌 프로그램에 건다
CREATE TABLE [FW].[TB_PROGRAM] (

  [PROGRAM_ID]     VARCHAR(30)    NOT NULL,             -- <모듈>_<대상>_<유형>, 예: SYS_USER_MGT
  [MODULE_CD]      VARCHAR(20)    NOT NULL,
  [PROGRAM_NM]     NVARCHAR(100)  NOT NULL,             -- 관리용 기본명 (화면 표시는 메뉴명)
  [URL]            VARCHAR(300)   NOT NULL,             -- /Sys/User/Index
  [PII_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_PROGRAM_PII_YN] DEFAULT ('N'),       -- 개인정보 처리 화면(접속기록 대상)
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_PROGRAM_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_PROGRAM_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PROGRAM_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_PROGRAM_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_PROGRAM_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_PROGRAM] PRIMARY KEY CLUSTERED ([PROGRAM_ID])
);
