-- 메뉴 트리 (무제한 단계, 화면 표시는 권장 4단계)
CREATE TABLE [FW].[TB_MENU] (

  [MENU_ID]        INT IDENTITY(1,1) NOT NULL,
  [MENU_KEY]       VARCHAR(50)    NOT NULL,             -- 시드·배포 간 메뉴를 식별하는 고정 키
  [MENU_SET_CD]    VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_MENU_MENU_SET_CD] DEFAULT ('PORTAL'),  -- PORTAL/ADMIN/MOBILE
  [OPEN_SCOPE_CD]  VARCHAR(10)    NOT NULL CONSTRAINT [DF_TB_MENU_OPEN_SCOPE_CD] DEFAULT ('ALL'),     -- ALL/EMP/PARTNER
  [PARENT_MENU_ID] INT            NULL,
  [MENU_TYPE_CD]   VARCHAR(10)    NOT NULL,             -- FOLDER/PAGE/LINK/POPUP
  [PROGRAM_ID]     VARCHAR(30)    NULL,
  [LINK_URL]       VARCHAR(500)   NULL,
  [ICON_CD]        VARCHAR(50)    NULL,
  [SORT_NO]        INT            NOT NULL CONSTRAINT [DF_TB_MENU_SORT_NO] DEFAULT (0),
  [NEW_WIN_YN]     CHAR(1)        NOT NULL CONSTRAINT [DF_TB_MENU_NEW_WIN_YN] DEFAULT ('N'),
  [USE_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_MENU_USE_YN] DEFAULT ('Y'),
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_MENU_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_MENU_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_MENU_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_MENU_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_MENU] PRIMARY KEY CLUSTERED ([MENU_ID])
);
GO
CREATE UNIQUE INDEX [UX_TB_MENU_KEY] ON [FW].[TB_MENU] ([MENU_KEY]);
GO
CREATE INDEX [IX_TB_MENU_PARENT] ON [FW].[TB_MENU] ([MENU_SET_CD], [PARENT_MENU_ID], [SORT_NO]);
GO
ALTER TABLE [FW].[TB_MENU] ADD CONSTRAINT [FK_TB_MENU_PARENT] FOREIGN KEY ([PARENT_MENU_ID]) REFERENCES [FW].[TB_MENU] ([MENU_ID]);
GO
ALTER TABLE [FW].[TB_MENU] ADD CONSTRAINT [FK_TB_MENU_TB_PROGRAM] FOREIGN KEY ([PROGRAM_ID]) REFERENCES [FW].[TB_PROGRAM] ([PROGRAM_ID]);
