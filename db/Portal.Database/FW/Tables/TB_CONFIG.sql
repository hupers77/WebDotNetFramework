-- 시스템 설정값 (정책·기능 스위치). 서버마다 다른 값은 appsettings에 둔다
CREATE TABLE [FW].[TB_CONFIG] (

  [CONFIG_KEY]     VARCHAR(100)   NOT NULL,             -- SESSION.IDLE_MINUTES
  [CONFIG_VAL]     NVARCHAR(2000) NULL,
  [VAL_TYPE_CD]    VARCHAR(10)    NOT NULL,             -- STRING/INT/BOOL/JSON/SECRET
  [ENC_YN]         CHAR(1)        NOT NULL CONSTRAINT [DF_TB_CONFIG_ENC_YN] DEFAULT ('N'),       -- SECRET은 애플리케이션에서 암호화해 저장
  [CATEGORY_CD]    VARCHAR(20)    NOT NULL,
  [DESCRIPTION]    NVARCHAR(500)  NULL,
  [RESTART_YN]     CHAR(1)        NOT NULL CONSTRAINT [DF_TB_CONFIG_RESTART_YN] DEFAULT ('N'),       -- 재기동 필요 여부,
  [REG_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_CONFIG_REG_ID] DEFAULT ('SYSTEM'),
  [REG_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_CONFIG_REG_DT] DEFAULT (SYSUTCDATETIME()),
  [UPD_ID]         VARCHAR(30)    NOT NULL CONSTRAINT [DF_TB_CONFIG_UPD_ID] DEFAULT ('SYSTEM'),
  [UPD_DT]         DATETIME2(0)   NOT NULL CONSTRAINT [DF_TB_CONFIG_UPD_DT] DEFAULT (SYSUTCDATETIME()),
  [ROW_VER]        ROWVERSION     NOT NULL,
  CONSTRAINT [PK_TB_CONFIG] PRIMARY KEY CLUSTERED ([CONFIG_KEY])
);
